# где лежит таблица — печатается в каждом отказе, чтобы не искать
FILE = os.path.abspath(__file__)


def _norm(name):
    return (name or "").strip().upper().replace("Ё", "Е").replace("  ", " ")


def _aliases():
    """{нормализованный синоним: имя канала}. Собирается из таблицы, а не
    пишется вторым списком."""
    out = {}
    for ch, rec in KANALY.items():
        out[_norm(ch)] = ch
        for al in rec.get("alias", ()):
            out[_norm(al)] = ch
    return out


def kanal(name):
    """Имя канала по тому, что пришло из пути. Не узнан — None.

    Порядок сверки детерминированный: точное совпадение синонима, затем
    самый ДЛИННЫЙ синоним, с которого начинается пришедшая строка («ОЛЬКА
    НОВОСТИ» → ОЛЬКА), затем — для совместимости с прежним префиксным
    поиском — самый длинный синоним, НАЧАЛО которого равно пришедшей
    строке (не короче четырёх знаков, inache «П» ловила бы два канала).
    """
    key = _norm(name)
    if not key:
        return None
    al = _aliases()
    if key in al:
        return al[key]
    for a in sorted(al, key=len, reverse=True):
        if key.startswith(a):
            return al[a]
    if len(key) >= 4:
        for a in sorted(al, key=len, reverse=True):
            if a.startswith(key):
                return al[a]
    return None


def spisok():
    """Имена каналов таблицы одной строкой — для текста отказа."""
    return " · ".join(KANALY)


def _otkaz(name, pole):
    raise NetKanala(
        "канал «%s» не в палитре каналов — нет цвета «%s».\n"
        "   Таблица: %s\n"
        "   Есть: %s\n"
        "   Добавь каналу ОДНУ строку в словарь KANALY — цвет подхватят "
        "сразу субтитры, дашборд упаковки, надпись из-под маски и "
        "рисованные кадры. Цвет не придумывать: взять закреплённый его "
        "словом." % (name or "<пусто>", pole, FILE, spisok()))


def _rec(name, pole, strict=True):
    ch = kanal(name)
    if ch is None:
        if strict:
            _otkaz(name, pole)
        return None
    return KANALY[ch]


def subtitry(name):
    """(плашка, текст) субтитров, hex без «#». Неизвестный канал — ОТКАЗ.

    Молчаливого умолчания здесь нет намеренно: субтитры вжигаются в клипы
    последним слоем, правок после `ship.sh` не бывает.
    """
    return tuple(_rec(name, "плашка субтитров")["subtitry"])


def dash(name, tiho=False):
    """(акцент, фон) карточки канала в дашборде упаковки, «#rrggbb».
    Неизвестный канал — нейтральная серая пара и голос в stderr."""
    rec = _rec(name, "цвет карточки дашборда", strict=False)
    if rec is None:
        if not tiho:
            print("!! канал «%s» не в палитре (%s) — карточка серая"
                  % (name, FILE), file=sys.stderr)
        return ("#9a9aa2", "#17171a")
    return tuple(rec["dash"])


def accent(name, inache=(185, 37, 38), tiho=False):
    """Цвет акцента канала (r,g,b). Неизвестный канал — прежний красный и
    голос в stderr: красный ничьим фирменным цветом не является."""
    rec = _rec(name, "акцент канала", strict=False)
    if rec is None:
        if name and not tiho:
            print("!! канал «%s» не в палитре (%s) — акцент красный"
                  % (name, FILE), file=sys.stderr)
        return inache
    return tuple(rec["accent"])


def fon(name, tiho=False):
    """(INK, INK_MID) — заливка кадра и центр виньетки рисованных кадров."""
    rec = _rec(name, "фон рисованных кадров", strict=False)
    if rec is None:
        if name and not tiho:
            print("!! канал «%s» не в палитре (%s) — фон ПЛАНЕТЫ"
                  % (name, FILE), file=sys.stderr)
        return tuple(KANALY["ПЛАНЕТА"]["fon"])
    return tuple(rec["fon"])


def series(name, tiho=False):
    """Роли данных канала — список (r,g,b). Первый белый, последний серый."""
    rec = _rec(name, "цвета данных", strict=False)
    if rec is None:
        if name and not tiho:
            print("!! канал «%s» не в палитре (%s) — серии ПЛАНЕТЫ"
                  % (name, FILE), file=sys.stderr)
        return list(KANALY["ПЛАНЕТА"]["series"])
    return list(rec["series"])


def prevyu(name):
    """Гамма надписей превью или None, если его слова по каналу ещё нет.
    None — повод СПРОСИТЬ, а не подставить гамму другого канала."""
    rec = _rec(name, "гамма превью", strict=False)
    if rec is None:
        return None
    g = rec.get("prevyu")
    return tuple(g) if g else None


