REP_Z = 8.4
REP_ЦИКЛ = 2.2             # как часто подсветка переходит к следующей


def плитка_тех(кто, что, acc, w=560, h=0):
    """Плитка реплики: кто сверху мелко, реплика крупно, полоса акцента.

    ВЫСОТА СЧИТАЕТСЯ ПО ЧИСЛУ СТРОК РЕПЛИКИ (13.11, по кадру): при
    фиксированных 340 px короткая реплика оставляла под собой пустую
    половину плитки, и стена читалась набором пустых рамок.
    """
    def сделать():
        S = 2
        f2_ = zc.font("ArialBlack.ttf", int(38 * S))
        d0 = ImageDraw.Draw(Image.new("RGBA", (8, 8)))
        строк = 1
        тек_ = ""
        for сл in str(что).split():
            проба = (тек_ + " " + сл).strip()
            if тек_ and d0.textlength(проба, font=f2_) > (w - 52) * S:
                строк += 1
                тек_ = сл
            else:
                тек_ = проба
        hh = h or int(96 + 46 * min(строк, 4) + 18)
        img = Image.new("RGBA", (w * S, hh * S), (19, 20, 23, 244))
        d = ImageDraw.Draw(img)
        d.rectangle([0, 0, w * S, int(9 * S)], fill=tuple(acc) + (255,))
        d.rectangle([0, 0, w * S - 1, hh * S - 1],
                    outline=(38, 40, 45, 255), width=int(2 * S))
        f1 = zc.font("Arimo-Bold.ttf", int(27 * S))
        d.text((int(26 * S), int(26 * S)), str(кто).upper(), font=f1,
               fill=tuple(_светлее(acc, 0.30)) + (255,))
        слова = str(что).split()
        строки_, тек = [], ""
        f2 = zc.font("ArialBlack.ttf", int(38 * S))
        d0 = ImageDraw.Draw(Image.new("RGBA", (8, 8)))
        for сл in слова:
            проба = (тек + " " + сл).strip()
            if тек and d0.textlength(проба, font=f2) > (w - 52) * S:
                строки_.append(тек)
                тек = сл
            else:
                тек = проба
        if тек:
            строки_.append(тек)
        y = int(80 * S)
        for ln in строки_[:4]:
            d.text((int(26 * S), y), ln, font=f2, fill=(236, 237, 240, 255))
            y += int(46 * S)
        return img.resize((w, hh), Image.LANCZOS)
    return _кэш(("плитка", str(кто), str(что), tuple(acc), w, h), сделать)


def repliki(out=None, t=None, text="", repliki_=(), source="", channel="",
            watermark="", dur=0.0, sfx=None, **_):
    """Мозаика реплик. Вход: «КТО|что сказал» по одной строке на лицо."""
    tt = 3.0 if t is None else float(t)
    acc, ink, mid = пал(channel)
    cam = zc.Cam(x=0.22 * math.sin(tt * 0.16), y=1.56, z=0.035 * tt)
    img = зал(cam, acc, ink, mid, шаг=3.0, даль=38.0)

    пары = []
    for r in (repliki_ or ()):
        s = str(r)
        кто, _, что = s.partition("|")
        пары.append((кто.strip() or "сторона", что.strip() or s.strip()))
    пары = пары[:6]
    n = max(1, len(пары))
    кол = 3 if n > 4 else (2 if n > 1 else 1)
    ряд = int(math.ceil(n / float(кол)))
    tex0 = плитка_тех(*пары[0], acc=acc) if пары else None
    if tex0 is None:
        знак(img, watermark)
        im = img.convert("RGB")
        return im.save(out, quality=92) or out if out else im

    # РАЗМЕР ПЛИТКИ СЧИТАЕТСЯ ОТ СЕТКИ, А НЕ ЗАДАЁТСЯ ЧИСЛОМ: при шести
    # плитках она вдвое мельче, чем при двух, и зазор между ними одинаков.
    # РАВНЯЕМ ПЛИТКИ ПО ШИРИНЕ, А НЕ ПО ВЫСОТЕ (13.11, по кадру). Высота
    # плитки зависит от числа строк реплики, поэтому одинаковая ВЫСОТА даёт
    # разную ширину — нижний ряд уехал за оба края кадра. Ширина у всех одна,
    # высота у каждой своя, ряды равняются по верхней кромке.
    w_px = 0.86 * W / кол - 26
    w = w_px * (REP_Z - cam.z) / zc.F
    высоты_пл, тексты = [], []
    for кто, что in пары:
        тек = плитка_тех(кто, что, acc=acc)
        тексты.append(тек)
        высоты_пл.append(w * тек.size[1] / float(тек.size[0]))
    ряд_h = [max(высоты_пл[r * кол:(r + 1) * кол] or [0.1])
             for r in range(ряд)]
    зазор_x = w * 0.075
    зазор_y = max(ряд_h) * 0.16
    верх_мира = _в_мир(cam, W / 2.0, 0.255 * H, REP_Z)[1]
    актив = int((tt - 1.6) / REP_ЦИКЛ) % n if tt > 1.6 else -1
    for i, (кто, что) in enumerate(пары):
        r, c = i // кол, i % кол
        в_ряду = min(кол, n - r * кол)
        x = (c - (в_ряду - 1) / 2.0) * (w + зазор_x)
        y_верх = верх_мира - sum(ряд_h[:r]) - r * зазор_y
        y = y_верх - высоты_пл[i] / 2.0
        пр = дол(tt, 0.15 + 0.16 * i, 0.47 + 0.16 * i)
        if пр <= 0:
            continue
        # перелёт 12% и осадка — те же числа, что у наклеек белого зала
        к = 1.0 + 0.12 * math.sin(math.pi * zc.clamp01(пр))
        свой = (i == актив)
        тек = тексты[i]
        hh = высоты_пл[i] * к * (1.045 if свой else 1.0)
        билборд(img, cam, тек, (x, y, REP_Z), hh,
                opacity=min(1.0, пр * 1.5) * (1.0 if свой else 0.72))
        if свой:
            # подсветка активной: рамка акцента вокруг её четырёхугольника
            ww = hh * тек.size[0] / float(тек.size[1])
            углы = zc.quad((x, y, REP_Z), ww * 1.02, hh * 1.03)
            pts = [cam.proj(p) for p in углы]
            ImageDraw.Draw(img, "RGBA").line(
                [(p[0], p[1]) for p in pts] + [(pts[0][0], pts[0][1])],
                fill=tuple(_светлее(acc, 0.25)) + (235,), width=4)
        _ev(sfx, 0.15 + 0.16 * i, "label")

    стр = строки(text, строк=1, знаков=26)
    if стр:
        надпись_сверху(img, текст_тех(стр, fsize=96, color=(238, 239, 242),
                                      acc=acc), плавно(дол(tt, 0.0, 0.7)),
                       доля_h=0.11)
    источник(img, source)
    знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


