def _центром(куски, зазор=10):
    """Несколько строк-картинок → один блок, строки выровнены ПО ЦЕНТРУ."""
    w = max(k.size[0] for k in куски)
    h = sum(k.size[1] for k in куски) + зазор * (len(куски) - 1)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    y = 0
    for k in куски:
        img.alpha_composite(k, (int((w - k.size[0]) / 2), y))
        y += k.size[1] + зазор
    return img


def prolog(out=None, t=None, text="", kick="", source="", channel="",
           watermark="", dur=0.0, sfx=None, **_):
    """Заголовок темы выходит из темноты. Ни одного найденного кадра."""
    tt = 2.2 if t is None else float(t)
    acc, ink, mid = пал(channel)
    img = Image.new("RGBA", (W, H), tuple(_темнее(ink, 0.35)) + (255,))
    слой = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой, "RGBA")
    # ЛУЧ СВЕРХУ: он и «вынимает» заголовок из темноты
    k = плавно(дол(tt, 0.0, 1.5))
    ds.polygon([(W * 0.30, -40), (W * 0.52, -40),
                (W * 0.78, H * 0.86), (W * 0.18, H * 0.86)],
               fill=tuple(_светлее(acc, 0.55)) + (int(46 * k),))
    ds.ellipse([W * 0.5 - 420, H * 0.46 - 150, W * 0.5 + 420, H * 0.46 + 150],
               fill=tuple(_светлее(acc, 0.45)) + (int(88 * k),))
    _пыль(слой, zc.Cam(x=0.0, y=1.5, z=0.0), tt, acc, n=30, seed=31)
    img = свечение(img, слой, радиус=60, сила=0.95)

    стр = строки(text, строк=3, знаков=16)
    if стр:
        # СТРОКИ ЗАГОЛОВКА — ПО ЦЕНТРУ КАЖДАЯ. Общий набор `text_tex`
        # равняет строки по левому краю: в зале это уместно (надпись стоит
        # на полу), в титре — нет, титр обязан быть симметричным.
        tex = _кэш(("пролог", tuple(стр), tuple(acc)), lambda: _центром(
            [текст_тех([ln], fsize=150, color=(243, 244, 246), acc=acc)
             for ln in стр]))
        доля = min(0.80 * W / tex.size[0], 0.40 * H / tex.size[1])
        w = max(4, int(tex.size[0] * доля))
        h = max(4, int(tex.size[1] * доля))
        м = tex.resize((w, h), Image.LANCZOS)
        # ВЫХОД ИЗ ТЕМНОТЫ: подъём на 70 px и проявление. Размывки на кадр
        # по-прежнему одна (та, что у свечения) — заголовок не размываем,
        # иначе кадр стоил бы вдвое.
        ход = плавно(дол(tt, 0.35, 1.6))
        сл = м.copy()
        сл.putalpha(сл.split()[3].point(lambda v: int(v * ход)))
        y = int(H * 0.46 - h / 2 + (1.0 - ход) * 70)
        img.alpha_composite(сл, (int((W - w) / 2), y))
        # черта акцента под заголовком — растёт из центра
        ч = плавно(дол(tt, 1.0, 1.9))
        if ч > 0:
            d = ImageDraw.Draw(img, "RGBA")
            пол = int(W * 0.21 * ч)
            yy = y + h + 34
            d.rectangle([W / 2 - пол, yy, W / 2 + пол, yy + 7],
                        fill=tuple(acc) + (240,))
        _ev(sfx, 0.35, "accent")
        _ev(sfx, 1.0, "label")

    if kick:
        f = zc.font("Arimo-Bold.ttf", 34)
        d = ImageDraw.Draw(img, "RGBA")
        b = d.textbbox((0, 0), str(kick).upper(), font=f)
        a = плавно(дол(tt, 1.4, 2.2))
        d.text(((W - (b[2] - b[0])) / 2 - b[0], H * 0.22), str(kick).upper(),
               font=f, fill=tuple(_светлее(acc, 0.35)) + (int(235 * a),))

    источник(img, source)
    знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


