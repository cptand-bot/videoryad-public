# ---------------------------------------------------------------------------
# КТО НА КОГО НАЖИМАЕТ. Не граф связей (связь — это линия, она ничего не
# говорит о том, кто сильнее), а МЕХАНИКА: блоки стоят на полу, между ними
# идут стрелы усилия, и тот, на кого давят, ПРИСЕДАЕТ под нажимом. Вход —
# пары «кто → на кого» словами. Ни чисел, ни долей.
