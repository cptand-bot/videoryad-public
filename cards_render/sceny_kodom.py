def плашка_тех(заголовок, подпись="", acc=(205, 170, 95), ширина=760,
               кегль=46, кегль_под=30, темп=(18, 18, 21)):
    """Плашка-табличка: полоса акцента слева, строка и подпись под ней."""
    def сделать():
        S = 2                                            # двойной размер: PIL не сглаживает
        f1 = zc.font("ArialBlack.ttf", кегль * S)
        f2 = zc.font("Arimo-Bold.ttf", max(1, кегль_под) * S)
        d0 = ImageDraw.Draw(Image.new("RGBA", (8, 8)))
        b1 = d0.textbbox((0, 0), str(заголовок).upper(), font=f1)
        b2 = d0.textbbox((0, 0), str(подпись), font=f2) if подпись else (0, 0, 0, 0)
        pad = int(26 * S)
        wt = max(b1[2] - b1[0], b2[2] - b2[0]) + pad * 2 + int(34 * S)
        ht = (b1[3] - b1[1]) + (int(14 * S) + (b2[3] - b2[1]) if подпись else 0) + pad * 2
        wt = max(wt, int(ширина * S * 0.5))
        img = Image.new("RGBA", (int(wt), int(ht)), tuple(темп) + (238,))
        d = ImageDraw.Draw(img)
        d.rectangle([0, 0, int(14 * S), ht], fill=tuple(acc) + (255,))
        x = int(34 * S) + pad
        y = pad
        d.text((x - b1[0], y - b1[1]), str(заголовок).upper(), font=f1,
               fill=(240, 241, 243, 255))
        if подпись:
            y += (b1[3] - b1[1]) + int(14 * S)
            d.text((x - b2[0], y - b2[1]), str(подпись), font=f2,
                   fill=tuple(_светлее(acc, 0.25)) + (255,))
        return img.resize((max(4, img.size[0] // S), max(4, img.size[1] // S)),
                          Image.LANCZOS)
    return _кэш(("плашка", str(заголовок), str(подпись), tuple(acc), ширина,
                 кегль, кегль_под), сделать)


def надпись_сверху(img, tex, прозрачность, доля_w=0.70, доля_h=0.19):
    """Фраза сцены вверху кадра: ужимается по ШИРИНЕ И ВЫСОТЕ сразу.

    Было (13.11, по кадру `relsy`): масштаб брался только по ширине, и
    двухстрочная фраза занимала 40% кадра — на длинной сцене она давит на
    всё остальное. Теперь доля задана обеими сторонами, меньший масштаб и
    побеждает.
    """
    if прозрачность <= 0:
        return
    k = min(доля_w * W / float(tex.size[0]), доля_h * H / float(tex.size[1]))
    w = max(4, int(tex.size[0] * k))
    h = max(4, int(tex.size[1] * k))
    сл = tex.resize((w, h), Image.LANCZOS)
    сл.putalpha(сл.split()[3].point(lambda v: int(v * zc.clamp01(прозрачность))))
    img.alpha_composite(сл, (int((W - w) / 2), int(SAFE * H)))


def _короб(cam, углы):
    pts = [cam.proj(p) for p in углы]
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def _в_мир(cam, x_scr, y_scr, z):
    dz = max(0.3, z - cam.z)
    return (cam.x + (x_scr - W / 2.0) * dz / zc.F,
            cam.y - (y_scr - H / 2.0) * dz / zc.F)


def вписать(cam, z, аспект, доля_w, доля_h):
    ключ = ("вписать", round(z - cam.z, 2), round(cam.y, 2), round(аспект, 3),
            доля_w, доля_h)
    if ключ not in _КЭШ:
        _КЭШ[ключ] = _вписать(cam, z, аспект, доля_w, доля_h)
    return _КЭШ[ключ]


def _вписать(cam, z, аспект, доля_w, доля_h):
    """Высота объекта в метрах, при которой он займёт свою долю кадра.

    ШИРИНА МЕРИТСЯ ПРОЕКЦИЕЙ, А НЕ ПРИКИДЫВАЕТСЯ: русские слова длиннее
    английских, и первая же проба боевым текстом на зале дала надпись за
    краем кадра. Меряем экранную коробку и ужимаем, пока не влезет.
    """
    h = 1.0
    for _ in range(26):
        углы = zc.quad((cam.x, cam.y, z), h * аспект, h)
        x0, y0, x1, y1 = _короб(cam, углы)
        kw = (x1 - x0) / (доля_w * W)
        kh = (y1 - y0) / (доля_h * H)
        k = max(kw, kh)
        if abs(k - 1.0) < 0.02:
            break
        h /= max(0.25, k)
    return h


def билборд(img, cam, tex, центр, высота, opacity=1.0, yaw=0.0):
    """Плоская картинка, стоящая в пространстве лицом к камере."""
    w = высота * tex.size[0] / float(tex.size[1])
    углы = zc.quad(центр, w, высота, yaw=yaw)
    zc.paste_quad(img, tex, [cam.proj(p) for p in углы], opacity=opacity)
    return углы


def отражение(img, cam, tex, центр, высота, сила=0.16, yaw=0.0):
    """Отражение в полу-глянце. Пол у нас тёмный, поэтому сила маленькая."""
    w = высота * tex.size[0] / float(tex.size[1])
    низ = центр[1] - высота / 2.0
    цz = центр[2]
    углы = zc.quad((центр[0], низ - высота / 2.0, цz), w, высота, yaw=yaw)
    def сделать():
        q = tex.transpose(Image.FLIP_TOP_BOTTOM).filter(ImageFilter.GaussianBlur(12))
        q.putalpha(q.split()[3].point(lambda v: int(v * сила)))
        return q
    t = _кэш(("отраж", id(tex), round(сила, 3)), сделать)
    zc.paste_quad(img, t, [cam.proj(p) for p in углы])


