def _фон(ink, mid):
    """Подложка-градиент: от камеры не зависит, поэтому считается один раз."""
    def сделать():
        g = np.zeros((H, W, 3), np.float32)
        yy = (np.arange(H) / float(H))[:, None]
        k = np.clip(1.0 - np.abs(yy - 0.46) * 2.1, 0, 1) ** 1.6
        for i in range(3):
            g[..., i] = ink[i] + (mid[i] - ink[i]) * k
        return Image.fromarray(g.astype(np.uint8), "RGB").convert("RGBA")
    return _кэш(("фон", ink, mid), сделать).copy()


def _полигон(d, cam, точки, fill):
    p = [cam.proj(q) for q in точки]
    d.polygon([(q[0], q[1]) for q in p], fill=fill)


def _тона(ink, mid, свет):
    """Базовые тона зала с поправкой на `свет`.

    СВЕТЛЕЕ ДЕЛАЕТСЯ НЕ ВЕСЬ ЗАЛ, А ОТДЕЛЬНЫЙ ВИД (13.11). Его правка
    «посветлее немножко расцветки» касалась прохода; трибуну он принял в
    прежней темноте тем же сообщением, и менять её нельзя — утверждённое
    не трогаем. Поэтому `свет` идёт доводом, а не новой константой.
    """
    пол = _светлее(_темнее(mid, 0.45), свет * 0.55)
    потолок = _светлее(_темнее(ink, 0.25), свет * 0.45)
    стена = _светлее(tuple(ink), свет * 0.42)
    return пол, потолок, стена


def _статика(acc, ink, mid, cam_y, стены, потолок, даль, свет=0.0):
    """Фон, пол, потолок и стены — ОДНОЙ КАРТИНКОЙ НА ВЕСЬ КЛИП.

    Они не зависят от того, сколько камера проехала: стена x=±WALL бесконечна
    вдоль z, и её проекция при неизменной высоте взгляда ровно та же. Двигаются
    только швы пола и рёбра — они стоят на АБСОЛЮТНЫХ отметках z. Замер 13.11:
    перерисовка статики стоила 0,08 с на кадр, то есть больше минуты на клип.
    """
    def сделать():
        cam = zc.Cam(x=0.0, y=cam_y, z=0.0)
        img = _фон(ink, mid)
        d = ImageDraw.Draw(img, "RGBA")
        п, пт, ст = _тона(ink, mid, свет)
        d.rectangle([0, H / 2.0, W, H], fill=п + (255,))
        if потолок:
            d.rectangle([0, 0, W, H / 2.0], fill=пт + (255,))
        if стены:
            for sx in (-1, 1):
                _полигон(d, cam, [(sx * WALL, CEIL, 1.0),
                                  (sx * WALL, CEIL, даль),
                                  (sx * WALL, 0.0, даль),
                                  (sx * WALL, 0.0, 1.0)], ст + (255,))
        return img
    return _кэш(("статика", tuple(ink), tuple(mid), round(cam_y, 2), стены,
                 потолок, даль, round(свет, 3)), сделать)


def зал(cam, acc, ink, mid, шаг=3.0, стены=True, потолок=True, сетка=True,
        даль=52.0, свет=0.0):
    """Тёмный павильон: статика из кэша + ПЕРИОДИЧНЫЕ швы пола и рёбра стен.

    Швы и рёбра и дают зрителю ощущение движения: без них тёмный коридор на
    экране стоит на месте, сколько бы метров камера ни проехала.
    """
    img = _статика(acc, ink, mid, cam.y, стены, потолок, даль, свет).copy()
    d = ImageDraw.Draw(img, "RGBA")
    пол, _пт, стена = _тона(ink, mid, свет)
    z0 = math.floor((cam.z + 1.0) / шаг) * шаг
    for i in range(int(даль / шаг) + 2):
        zz = z0 + i * шаг
        if zz - cam.z < 0.6:
            continue
        k = max(0.0, 1.0 - (zz - cam.z) / даль)
        if сетка:
            # ШВЫ ТЯНЕМ ШИРЕ СТЕН (13.11, осмотр кадра: нижняя четверть
            # кадра была плоской серой полосой без геометрии). Вблизи
            # камеры отрезок от стены до стены уже уходит за края кадра, и
            # пол перестаёт читаться полом ровно там, где он крупнее всего.
            a = cam.proj((-WALL * 2.6, 0.0, zz))
            b = cam.proj((WALL * 2.6, 0.0, zz))
            d.line([(a[0], a[1]), (b[0], b[1])],
                   fill=_светлее(пол, 0.10 + 0.22 * k) + (255,), width=2)
        if стены:
            for sx in (-1, 1):
                a = cam.proj((sx * WALL, 0.0, zz))
                b = cam.proj((sx * WALL, CEIL, zz))
                d.line([(a[0], a[1]), (b[0], b[1])],
                       fill=_светлее(стена, 0.06 + 0.16 * k) + (255,), width=2)
    return img


def gor_y(cam):
    """Экранная высота линии пола у горизонта — зависит только от взгляда."""
    return H / 2.0


def свечение(img, слой, радиус=38, сила=1.0):
    """ОДНА размывка на кадр — И ТА НА УМЕНЬШЕННОЙ КОПИИ.

    Замер 13.11: размывка радиусом 50 по полному кадру плюс сложение в numpy
    стоили 0,22 с — две трети цены кадра, то есть ТРИ ЛИШНИХ МИНУТЫ на клип
    в 30 с. В свечении деталей нет по определению: считаем его втрое мельче,
    там же приводим альфу, и обратно растягиваем уже готовое. Сложение —
    `ImageChops.add` (код на C), а не поэлементно в numpy.
    """
    if слой is None:
        return img
    k = 3
    м = слой.resize((W // k, H // k), Image.BILINEAR)
    м = м.filter(ImageFilter.GaussianBlur(max(1.0, радиус / float(k))))
    a = np.asarray(м, np.float32)
    rgb = np.clip(a[..., :3] * (a[..., 3:4] / 255.0) * сила, 0, 255).astype(np.uint8)
    g = Image.fromarray(rgb, "RGB").resize((W, H), Image.BILINEAR)
    return ImageChops.add(img.convert("RGB"), g).convert("RGBA")


def подол(img, ink, доля=0.22, сила=0.72):
    """Тень у нижнего края кадра.

    Зачем (13.11, осмотр кадра): у светлого зала нижняя четверть кадра
    становится плоской светлой полосой, и в ней тонут подпись источника и
    знак канала. Тень и возвращает глубину, и поднимает читаемость подписи.
    Считается один раз на канал и накладывается готовой.
    """
    def сделать():
        h = int(H * доля)
        g = np.zeros((h, 1), np.float32)
        g[:, 0] = np.linspace(0.0, 1.0, h) ** 1.6
        a = (g * 255 * сила).astype(np.uint8)
        сл = Image.fromarray(np.repeat(a, W, axis=1), "L")
        слой = Image.new("RGBA", (W, h), tuple(_темнее(ink, 0.55)) + (0,))
        слой.putalpha(сл)
        return слой
    img.alpha_composite(_кэш(("подол", tuple(ink), доля, сила), сделать),
                        (0, H - int(H * доля)))


