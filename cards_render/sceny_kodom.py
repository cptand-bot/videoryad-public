# 3 · ХРОНОЛЕНТА-РЕЛЬС  (`card:relsy`)
# ---------------------------------------------------------------------------
# Горизонтальная лента времени: камера едет вдоль, вехи-таблички ВСТАЮТ по
# очереди из положения лёжа. Вход — список событий СЛОВАМИ, без дат и чисел
# (его слово 13.11: «если диаграмма требует чисел, то может какими-то
# событиями их можно продемонстрировать»). Закрывает весь абзац «как это
# развивалось» — то есть 3-5 сцен подряд.
# ===========================================================================
RELS_V = 1.30               # м/с вдоль ленты
RELS_ПЕРВАЯ = 9.0          # где первая веха
RELS_УХОД = 5.2            # ближе этого веха уходит за край кадра
# ОКНО ВИДИМОСТИ СВЕРЕНО С ШАГОМ (13.11, по клипу: на 20-й секунде лента шла
# пустой). Веха видна от 16,4 м до 5,2 м — это 11,2 м, или 8,6 с при 1,3 м/с,
# а шаг между вехами при четырёх событиях и 30 секундах равен 9,2 с. То есть
# следующая появляется почти в тот момент, когда уходит прежняя.
RELS_Y = 0.72               # высота ленты над полом
RELS_X = 0.0                # ЛЕНТА ПО ОСИ ВЗГЛЯДА (13.11, по кадру).
# Первый заход ставил ленту сбоку (x=0,75) при камере в x=-1,65 — и она
# уходила за правый нижний угол: прямая вдоль z сходится В ЦЕНТР кадра
# независимо от смещения, поэтому ближний её конец улетает тем дальше, чем
# больше смещение. Камера теперь идёт почти над лентой и чуть левее.
RELS_СМЕЩ = -0.62           # насколько камера левее ленты
RELS_БЛИЖЕ = 3.2            # ближе этого лента не рисуется


def _лента(img, cam, acc, ширина=1.70, даль=46.0, шаг=1.30):
    """Лента времени: полотно вдоль z, светлая кромка и поперечины.

    Поперечины стоят на АБСОЛЮТНЫХ отметках z — они и показывают, что
    камера едет, а не стоит.
    """
    d = ImageDraw.Draw(img, "RGBA")
    x0, x1 = RELS_X - ширина / 2, RELS_X + ширина / 2
    z0, z1 = cam.z + RELS_БЛИЖЕ, cam.z + даль
    _полигон(d, cam, [(x0, RELS_Y, z1), (x1, RELS_Y, z1),
                      (x1, RELS_Y, z0), (x0, RELS_Y, z0)],
             tuple(_темнее(acc, 0.72)) + (255,))
    for xx in (x0, x1):
        a = cam.proj((xx, RELS_Y, z0))
        b = cam.proj((xx, RELS_Y, z1))
        d.line([(a[0], a[1]), (b[0], b[1])],
               fill=tuple(_светлее(acc, 0.20)) + (235,), width=3)
    zz0 = math.floor((cam.z + 1.0) / шаг) * шаг
    for i in range(int(даль / шаг) + 2):
        zz = zz0 + i * шаг
        if zz - cam.z < RELS_БЛИЖЕ:
            continue
        k = max(0.0, 1.0 - (zz - cam.z) / даль)
        a = cam.proj((x0, RELS_Y, zz))
        b = cam.proj((x1, RELS_Y, zz))
        d.line([(a[0], a[1]), (b[0], b[1])],
               fill=tuple(_темнее(acc, 0.35 + 0.35 * (1 - k))) + (255,), width=2)


def _веха(img, cam, tex, z, h, угол, acc, opacity=1.0, сдвиг=0.0):
    """Табличка-веха: встаёт из положения лёжа на ленте.

    `угол` 0 — лежит на ленте (уходит от камеры), 90° — стоит. Углы считаем
    в пространстве, а не поворотом картинки: иначе табличка не стояла бы на
    ленте, а висела бы над ней.
    """
    w = h * tex.size[0] / float(tex.size[1])
    a = math.radians(угол)
    y_в = RELS_Y + h * math.sin(a)
    z_в = z + h * math.cos(a)
    cx = RELS_X + сдвиг
    углы = [(cx - w / 2, y_в, z_в), (cx + w / 2, y_в, z_в),
            (cx + w / 2, RELS_Y, z), (cx - w / 2, RELS_Y, z)]
    zc.paste_quad(img, tex, [cam.proj(q) for q in углы], opacity=opacity)
    # ножка-свечение у основания: видно, что веха стоит НА ленте
    p = cam.proj((cx, RELS_Y + 0.01, z))
    r = max(2, int(0.05 * zc.F / max(0.6, z - cam.z)))
    ImageDraw.Draw(img, "RGBA").ellipse(
        [p[0] - r * 2.2, p[1] - r * 0.45, p[0] + r * 2.2, p[1] + r * 0.45],
        fill=tuple(_светлее(acc, 0.35)) + (int(150 * opacity),))


def relsy(out=None, t=None, text="", sobytiya=(), source="", channel="",
          watermark="", dur=0.0, sfx=None, **_):
    """Лента времени: камера едет вдоль, вехи встают по очереди."""
    tt = 8.0 if t is None else float(t)
    acc, ink, mid = пал(channel)
    cam = zc.Cam(x=RELS_СМЕЩ, y=2.08, z=RELS_V * tt)
    img = зал(cam, acc, ink, mid, шаг=3.2, потолок=False, даль=50.0)
    слой = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой, "RGBA")
    p = cam.proj((RELS_X, RELS_Y + 0.7, cam.z + 34.0))  # отблеск впереди
    ds.ellipse([p[0] - 200, p[1] - 90, p[0] + 200, p[1] + 90],
               fill=tuple(_светлее(acc, 0.45)) + (120,))
    _пыль(слой, cam, tt, acc, n=26, seed=19)
    img = свечение(img, слой, радиус=44, сила=0.85)
    _лента(img, cam, acc)

    соб = [str(x).strip() for x in (sobytiya or ()) if str(x).strip()][:6]
    # ШАГ ВЕХ — ОТ ДЛИТЕЛЬНОСТИ (13.11, та же правка, что у прохода): при
    # постоянных 7 м четыре вехи кончались на 23-й секунде тридцатисекундной
    # сцены.
    дальняя = RELS_V * (max(6.0, float(dur or 24.0)) - 1.2) + RELS_УХОД
    шаг_в = max(5.5, (дальняя - RELS_ПЕРВАЯ) / max(1, len(соб) - 1))
    for i, с in enumerate(соб):
        z_k = RELS_ПЕРВАЯ + шаг_в * i
        d_k = z_k - cam.z
        if d_k < RELS_УХОД or d_k > 21.0:
            continue
        tex = плашка_тех(с, "", acc=acc, кегль=38, кегль_под=0, ширина=560)
        h = вписать(zc.Cam(x=RELS_СМЕЩ, y=2.08, z=0.0), 10.0,
                    tex.size[0] / float(tex.size[1]), 0.23, 0.12)
        # ВСТАЁТ ЗАРАНЕЕ, А НЕ ПЕРЕД НОСОМ: подъём начинается за 17 м и
        # занимает 2,5 м пути (≈1,9 с) — зритель успевает прочесть обе
        # соседние вехи, пока едет между ними.
        подъём = плавно(zc.clamp01((16.4 - d_k) / 2.4))
        ухо = zc.clamp01((d_k - RELS_УХОД) / 2.0)
        _веха(img, cam, tex, z_k, h, 90.0 * подъём, acc,
              opacity=min(1.0, подъём * 1.6) * плавно(ухо),
              сдвиг=(-1.0 if i % 2 == 0 else 1.0) * 0.55)
        _ev(sfx, max(0.0, (z_k - 16.4) / RELS_V), "label")

    стр = строки(text, строк=2, знаков=20)
    if стр:
        tex_t = текст_тех(стр, fsize=104, color=(238, 239, 242), acc=acc)
        надпись_сверху(img, tex_t, плавно(дол(tt, 0.2, 1.1)))
        _ev(sfx, 0.2, "accent")

    источник(img, source)
    знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


