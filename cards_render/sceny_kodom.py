# 2 · ДЛИННЫЙ ПРОХОД  (`card:prohod`)
# ---------------------------------------------------------------------------
# ГЛАВНЫЙ ВИД ПО СКОРОСТИ: один клип 25-40 с вместо 3-4 найденных сцен.
# Тёмная анфилада, камера едет вперёд непрерывно, по стенам ОДНА ЗА ДРУГОЙ
# проявляются плашки-тезисы, в конце коридора — проём со светом канала.
# Вход: фраза сцены + 3-5 коротких тезисов. Ни чисел, ни мест не требует.
# ===========================================================================
# ЕГО ПРАВКА ПО КЛИПУ 13.11: «номер 2 то же самое, чуть быстрее. И
# посветлее немножко расцветки». Скорость 1,15 → 1,55 м/с: за 32 секунды
# камера проходит 49,6 м вместо 36,8. Раскладка тезисов считается ОТ
# СКОРОСТИ И ДЛИТЕЛЬНОСТИ, поэтому она подстроилась сама — правки не
# потребовалось. Окно чтения тезиса при этом 7,4 м / 1,55 = 4,8 с.
PROH_V = 1.55               # м/с
PROH_СВЕТ = 0.42            # насколько зал светлее базового (только проход)
# ПЕРВЫЙ ТЕЗИС СТОИТ ДАЛЬШЕ ОКНА ВИДИМОСТИ (13.11, вторая правка по
# раскладке). При 11 м он оказывался в кадре уже готовым на нулевой секунде
# и уходил через 1,9 с — зритель не успевал прочесть. С 20 м он
# проявляется, как все остальные, и живёт в кадре 7-9 секунд.
PROH_ПЕРВЫЙ = 20.0         # где первый тезис
PROH_УХОД = 8.0            # ближе этого плашка уже вышла бы за край кадра
PROH_ВИДНО = 23.0          # с какого расстояния плашка начинает проявляться


def _колонна(img, cam, x, z, acc, ширина=0.55, глубина=0.75, свет=0.0):
    """Колонна у стены: передняя грань и внутренняя — отсюда объём."""
    d = ImageDraw.Draw(img, "RGBA")
    sx = 1 if x > 0 else -1
    перед = [(x - ширина / 2, CEIL, z), (x + ширина / 2, CEIL, z),
             (x + ширина / 2, 0.0, z), (x - ширина / 2, 0.0, z)]
    бок = [(x - sx * ширина / 2, CEIL, z), (x - sx * ширина / 2, CEIL, z + глубина),
           (x - sx * ширина / 2, 0.0, z + глубина), (x - sx * ширина / 2, 0.0, z)]
    k = max(0.0, 1.0 - (z - cam.z) / 46.0)
    _с = 1.0 + свет * 1.15
    _полигон(d, cam, бок, (min(255, int((26 + 22 * k) * _с)),
                           min(255, int((27 + 23 * k) * _с)),
                           min(255, int((30 + 26 * k) * _с)), 255))
    _полигон(d, cam, перед, (min(255, int((38 + 34 * k) * _с)),
                             min(255, int((39 + 35 * k) * _с)),
                             min(255, int((43 + 38 * k) * _с)), 255))
    # световая полоса на ребре — в гамме канала
    a = cam.proj((x + sx * ширина / 2, CEIL * 0.92, z))
    b = cam.proj((x + sx * ширина / 2, 0.22, z))
    d.line([(a[0], a[1]), (b[0], b[1])],
           fill=tuple(_темнее(acc, 0.35)) + (int(90 + 90 * k),), width=2)


def prohod(out=None, t=None, text="", tezisy=(), source="", channel="",
           watermark="", dur=0.0, sfx=None, **_):
    """Тёмная анфилада: камера едет вперёд, тезисы проявляются по одному."""
    tt = 6.0 if t is None else float(t)
    acc, ink, mid = пал(channel)
    cam = zc.Cam(x=0.0, y=1.58, z=PROH_V * tt)
    img = зал(cam, acc, ink, mid, шаг=2.4, даль=56.0, свет=PROH_СВЕТ)
    for i in range(14):                                  # колонны по обе стороны
        zz = math.floor((cam.z + 1.5) / 4.6) * 4.6 + i * 4.6
        if zz - cam.z < 0.9:
            continue
        for sx in (-1, 1):
            _колонна(img, cam, sx * (WALL - 1.05), zz, acc, свет=PROH_СВЕТ)

    слой = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой, "RGBA")
    # ШАГ ТЕЗИСОВ СЧИТАЕТСЯ ОТ ДЛИТЕЛЬНОСТИ СЦЕНЫ (13.11, по готовому клипу).
    # При постоянном шаге 8 м четыре тезиса кончались на 25-й секунде, и
    # последние 6 секунд камера ехала по ПУСТОМУ коридору — то есть клип
    # врал о том, сколько сцен закрывает. Теперь последний тезис уходит из
    # кадра за 1,2 с до конца, сколько бы их ни было и какой бы длины ни
    # была сцена.
    тезисов = max(1, len([x for x in (tezisy or ()) if str(x).strip()]))
    дальний = PROH_V * (max(6.0, float(dur or 24.0)) - 1.2) + PROH_УХОД
    шаг_т = max(6.0, (дальний - PROH_ПЕРВЫЙ) / max(1, тезисов - 1))
    # ШАГ НЕ БОЛЬШЕ ОКНА ВИДИМОСТИ (13.11, второй заход). После ускорения
    # камеры до 1,55 м/с четыре тезиса встали через 14,9 м, а окно от
    # появления до ухода было 8,6 м — на 24-й секунде в кадре не оказалось
    # НИ ОДНОГО тезиса (осмотр кадра). Лечим с двух сторон: окно расширено
    # (плашка проявляется ещё за 23 м, маленькой вдали — это и выглядит как
    # приближение), а шаг сверху ограничен этим окном.
    шаг_т = min(шаг_т, (PROH_ВИДНО - PROH_УХОД) * 0.92)
    конец = PROH_ПЕРВЫЙ + шаг_т * (тезисов - 1) + 8.0
    p = cam.proj((0.0, 1.6, конец))
    r = max(40.0, 260.0 * zc.F / max(60.0, (конец - cam.z) * zc.F / 9.0))
    ds.ellipse([p[0] - r, p[1] - r * 1.25, p[0] + r, p[1] + r * 1.25],
               fill=tuple(_светлее(acc, 0.55)) + (160,))
    # ОТБЛЕСК ДАЛЬНЕГО СВЕТА НА ПОЛУ: без него нижняя треть кадра — пустая
