def _светлее(c, k):
    return tuple(min(255, int(v + (255 - v) * k)) for v in c[:3])


def _темнее(c, k):
    return tuple(max(0, int(v * (1.0 - k))) for v in c[:3])


def строки(text, строк=2, знаков=17):
    """Фраза сцены → строки заглавными. Рвём по словам (общий приём с залом)."""
    слова = [w for w in str(text or "").upper().split() if w]
    if not слова:
        return []
    ширина = max(знаков, int(math.ceil(len(" ".join(слова)) / float(строк))))
    out, тек = [], ""
    for w in слова:
        проба = (тек + " " + w).strip()
        if тек and len(проба) > ширина:
            out.append(тек)
            тек = w
        else:
            тек = проба
    if тек:
        out.append(тек)
    if len(out) > строк:
        out = out[:строк - 1] + [" ".join(out[строк - 1:])]
    return out


