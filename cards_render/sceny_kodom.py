def _суша():
    """Контуры стран, упрощённые ОДИН РАЗ: [(имя по-русски, кольцо), …].

    Полные контуры — 3 МБ и десятки тысяч точек; рисовать их 540 раз подряд
    нельзя. Прореживаем до ~90 точек на кольцо и выбрасываем мелкие острова:
    на шаре радиусом 400 px они всё равно меньше пикселя, а времени стоят
    столько же, сколько материк.
    """
    def сделать():
        путь = _гео_путь()
        if not путь:
            print("  глобус: нет geo/countries.geojson — рисую без суши",
                  file=sys.stderr)
            return []
        import json as _j
        данные = _j.load(open(путь, encoding="utf-8"))
        out = []
        for f in данные.get("features", []):
            св = f.get("properties") or {}
            имя = (св.get("NAME_RU") or св.get("NAME") or "").strip()
            г = f.get("geometry") or {}
            тип = г.get("type")
            куски = ([г.get("coordinates")] if тип == "Polygon"
                     else (г.get("coordinates") or []))
            for кусок in куски:
                if not кусок:
                    continue
                кольцо = кусок[0]
                if len(кольцо) < 8:
                    continue
                арр = np.array(кольцо, np.float32)
                ш = арр[:, 0].max() - арр[:, 0].min()
                в = арр[:, 1].max() - арр[:, 1].min()
                if max(ш, в) < 1.6:            # мелкий остров — пропускаем
                    continue
                шаг = max(1, len(арр) // 90)
                out.append((имя, arr_rad(арр[::шаг])))
        return out
    return _кэш(("суша",), сделать)


def arr_rad(a):
    """Градусы → радианы один раз, на этапе подготовки."""
    return np.radians(a.astype(np.float32))


def _на_шар(кольцо, lon0, R, cx, cy, lat0=0.0):
    """Кольцо (радианы) → экранные точки и признак «перед нами».

    Точки за лимбом не выбрасываем, а ПРИЖИМАЕМ К ЛИМБУ: иначе страна,
    наполовину ушедшая за край шара, теряла половину контура и получала
    рваный край прямо посреди материка.
    """
    la = кольцо[:, 0] - math.radians(lon0)
    fi = кольцо[:, 1]
    cf = np.cos(fi)
    x = cf * np.sin(la)
    y = np.sin(fi)
    z = cf * np.cos(la)
    # НАКЛОН ПО ШИРОТЕ (13.11, по кадру: Европа оказалась у верхнего края, а
    # в центре диска — Северная Африка). Без него шар всегда смотрит
    # экватором, и всё, что севернее 40°, уезжает к полюсу. Поворот вокруг
    # оси X ставит названную широту ровно в центр диска.
    if lat0:
        c0, s0 = math.cos(lat0), math.sin(lat0)
        y, z = y * c0 - z * s0, y * s0 + z * c0
    видно = z > 0.0
    r = np.sqrt(x * x + y * y)
    r = np.where(r < 1e-6, 1e-6, r)
    k = np.where(видно, 1.0, 1.0 / r)          # за лимбом — на сам лимб
    return cx + R * x * k, cy - R * y * k, видно


def _точка_шара(lon, lat, lon0, R, cx, cy, lat0=0.0):
    """(долгота, широта) → экранная точка и видимость (перед нами ли)."""
    a = math.radians(lon - lon0)
    b = math.radians(lat)
    x = math.cos(b) * math.sin(a)
    y = math.sin(b)
    z = math.cos(b) * math.cos(a)
    if lat0:
        c0, s0 = math.cos(lat0), math.sin(lat0)
        y, z = y * c0 - z * s0, y * s0 + z * c0
    return (cx + R * x, cy - R * y, z)


def globus(out=None, t=None, text="", region="", source="", channel="",
           watermark="", dur=0.0, sfx=None, **_):
    """Шар с подсвеченным сектором. `region` — слово, не координаты."""
    tt = 4.0 if t is None else float(t)
    acc, ink, mid = пал(channel)
    img = _фон(ink, mid)
    R = 398.0 * (1.0 + 0.055 * плавно(дол(tt, 0.0, max(6.0, float(dur or 18.0)))))
    cx, cy = W * 0.645, H * 0.545
    слой = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой, "RGBA")
    ds.ellipse([cx - R * 1.22, cy - R * 1.22, cx + R * 1.22, cy + R * 1.22],
               fill=tuple(_светлее(acc, 0.35)) + (46,))
    _пыль(слой, zc.Cam(x=0.0, y=1.5, z=0.0), tt, acc, n=22, seed=41)
    img = свечение(img, слой, радиус=56, сила=0.85)

    шар = _шар(R, acc, ink)
    img.alpha_composite(шар, (int(cx - R), int(cy - R)))
    d = ImageDraw.Draw(img, "RGBA")

    # ЧТО ПОДСВЕЧИВАЕМ. Сначала ищем НАЗВАННЫЕ СТРАНЫ в контурах — его
    # правка 13.11: «нельзя ли сделать там, чтобы карта была какая-то, чтобы
    # там подсвечивался тот регион, о котором будет говориться». Не нашли
    # страну (сказано «Ближний Восток», «весь регион») — подсвечиваем
    # СЕКТОР по грубой таблице, как раньше. Координат вид по-прежнему не
    # требует: вход — слово.
    хочу = []
    for кусок in str(region or "").replace(",", " ").split():
        к = кусок.strip(" .«»\"").upper().replace("Ё", "Е")
        if len(к) > 2:
            хочу.append(ГЛОБ_АЛИАС.get(к, к))
    цел_ые = str(region or "").strip().upper().replace("Ё", "Е")
    if цел_ые:
        хочу.insert(0, ГЛОБ_АЛИАС.get(цел_ые, цел_ые))
    суша = _суша()
    свои = []
    for _i, (имя, кольцо) in enumerate(суша):
        н = имя.upper().replace("Ё", "Е")
        if not н:
            continue
        for w in хочу:
            if н == w or н.startswith(w) or w.startswith(н):
                свои.append((_i, кольцо))
                break
    # ЗАМОРСКИЕ ВЛАДЕНИЯ ОТСЕКАЕМ (13.11, по кадру: вместе с Францией
    # подсветилась Гвиана в Южной Америке — формально верно, а на экране
    # читается как ошибка). Оставляем кольца вокруг САМОГО КРУПНОГО из
    # найденных: всё, что дальше 38° от него, к сцене отношения не имеет.
    if len(свои) > 1:
        # ГЛАВНОЕ КОЛЬЦО — ПО ПЛОЩАДИ, А НЕ ПО ЧИСЛУ ТОЧЕК (13.11, по кадру:
        # глобус развернулся на Южную Америку). Прореживание режет ВСЕ
        # кольца до ~90 точек, поэтому «самое длинное» после него ничего не
        # значит — Гвиана оказалась не меньше материковой Франции и увела
        # поворот за океан. Площадь рамки такого вырождения не имеет.
        def _площадь(к):
            return float((к[:, 0].max() - к[:, 0].min())
                         * (к[:, 1].max() - к[:, 1].min()))
        главное = max(свои, key=lambda п: _площадь(п[1]))
        ц = главное[1].mean(axis=0)
        свои = [(и, к) for и, к in свои
                if abs(math.degrees(float(к.mean(axis=0)[0] - ц[0]))) < 38.0
                and abs(math.degrees(float(к.mean(axis=0)[1] - ц[1]))) < 38.0]

    # поворот: названное должно смотреть на нас В СЕРЕДИНЕ сцены
    середина = max(6.0, float(dur or 18.0)) / 2.0
    if свои:
        все = np.concatenate([к for _, к in свои])
        центр_lon = float(np.degrees(np.arctan2(
            np.mean(np.sin(все[:, 0])), np.mean(np.cos(все[:, 0])))))
        центр_lat = float(np.degrees(np.mean(все[:, 1])))
        сек = None
    else:
        ключ = str(region or "").strip().lower()
        сек = None
        for k, v in СЕКТОРЫ.items():
            if k and k in ключ:
                сек = v
                break
        if сек is None:
            сек = (10, 120, 25, 65)
        центр_lon = (сек[0] + сек[1]) / 2.0
        центр_lat = (сек[2] + сек[3]) / 2.0
    lon0 = центр_lon - ГЛОБ_СКОРОСТЬ * (середина - tt)
    # НАКЛОН ограничен ±52°: дальше шар смотрит полюсом и перестаёт
    # читаться глобусом.
    lat0 = math.radians(max(-52.0, min(52.0, центр_lat)))

    появ = плавно(дол(tt, 0.5, 1.6))
    пульс = 0.80 + 0.20 * math.sin(tt * 1.25)
    # РАМКА СЕКТОРА СЧИТАЕТСЯ ДО СУШИ: по ней решаем, какую землю подсветить.
    рамка = None
    if сек is not None:
        _la, _lb, _ta, _tb = сек
        _dl = (_lb - _la) * 0.14
        _db = (_tb - _ta) * 0.14
        рамка = (_la - _dl, _lb + _dl,
                 max(-82.0, _ta - _db), min(82.0, _tb + _db))
    # СУША. Рисуется всегда — это и есть «какая-то карта» вместо голого шара.
    тон_суши = _светлее(ink, 0.30)
    # ОТБОР ПО НОМЕРУ КОЛЬЦА, А НЕ ПО ИМЕНИ (13.11, по кадру: Гвиану
    # отсеяли из `свои`, но в отрисовке сверка шла по ИМЕНИ «Франция» — и
    # она подсвечивалась снова. У страны колец много, и отсев обязан
    # действовать на то же, что рисуется.)
    свои_номера = {и for и, _ in свои}
    for _i, (имя, кольцо) in enumerate(суша):
        xs, ys, видно = _на_шар(кольцо, lon0, R, cx, cy, lat0)
        if not видно.any():
            continue
        точки = list(zip(xs.tolist(), ys.tolist()))
        if len(точки) < 3:
            continue
        свой = _i in свои_номера
        в_секторе = False
        if рамка is not None and not свой:
            # ПОДСВЕЧИВАЕМ ЗЕМЛЮ, А НЕ ВОДУ (13.11, осмотр кадра: «сама
            # Аравия остаётся серо-бурой, а золотом светятся больше
            # акватории»). Полупрозрачная заливка поверх всего ложится и на
            # море, и на сушу одинаково, а море темнее — вот оно и
            # вспыхивало ярче. Он просил подсветить МЕСТНОСТЬ, поэтому
            # страна, попавшая в рамку, получает свой тон ещё до заливки.
            _ц = кольцо.mean(axis=0)
            _цl = math.degrees(float(_ц[0]))
            _цb = math.degrees(float(_ц[1]))
            в_секторе = (рамка[0] <= _цl <= рамка[1]
                         and рамка[2] <= _цb <= рамка[3])
        if свой:
            c = tuple(_светлее(acc, 0.10)) + (int(236 * появ * пульс),)
            d.polygon(точки, fill=c,
                      outline=tuple(_светлее(acc, 0.70)) + (int(250 * появ),))
        elif в_секторе:
            с = tuple(int(тон_суши[i] * 0.42 + _светлее(acc, 0.05)[i] * 0.58)
                      for i in range(3))
            d.polygon(точки, fill=с + (240,),
                      outline=tuple(_светлее(acc, 0.45)) + (205,))
        else:
            d.polygon(точки, fill=тон_суши + (236,),
                      outline=_светлее(ink, 0.46) + (190,))
    if свои:
        _ev(sfx, 0.5, "accent")

    if рамка is not None:
        lon_a, lon_b, lat_a, lat_b = рамка
        шаг_lon = max(4.0, (lon_b - lon_a) / 10.0)
        шаг_lat = max(3.0, (lat_b - lat_a) / 7.0)
        if появ > 0:
            # ЗАЛИВКА СЕКТОРА — ОТДЕЛЬНЫМ СЛОЕМ (13.11, мина PIL из шапки
            # файла, она же мина 1 движка зала): `ImageDraw.Draw(img,
            # "RGBA")` по RGBA-холсту НЕ СМЕШИВАЕТ по альфе — сколько ни
            # понижай прозрачность, заливка остаётся сплошной. Осмотр кадра
            # это и показал: суша под сектором не проступала ни при 92, ни
            # при 58. Рисуем в свой слой и кладём `alpha_composite`.
            сл_сек = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            dс = ImageDraw.Draw(сл_сек, "RGBA")
            lo = lon_a
            while lo < lon_b - 1e-6:
                la = lat_a
                while la < lat_b - 1e-6:
                    углы = [_точка_шара(lo, la, lon0, R, cx, cy, lat0),
                            _точка_шара(min(lo + шаг_lon, lon_b), la, lon0,
                                        R, cx, cy, lat0),
                            _точка_шара(min(lo + шаг_lon, lon_b),
                                        min(la + шаг_lat, lat_b), lon0,
                                        R, cx, cy, lat0),
                            _точка_шара(lo, min(la + шаг_lat, lat_b), lon0,
                                        R, cx, cy, lat0)]
                    if all(p[2] > 0.02 for p in углы):
                        dс.polygon([(p[0], p[1]) for p in углы],
                                   fill=tuple(_светлее(acc, 0.15))
                                   + (int(54 * появ * пульс),))
                    la += шаг_lat
                lo += шаг_lon
            # КАЙМА ЗАМЫКАЕТСЯ ТОЧНО В УГЛАХ (13.11, осмотр кадра: нижняя и
            # правая грани шли ступеньками). `np.arange` не включает конец
            # отрезка, и если ширина сектора не кратна шагу, сторона не
            # доходила до угла — отсюда разрывы. `linspace` кладёт ровно N
            # точек ОТ и ДО, углы совпадают по построению.
            _ш = max(2, int(abs(lon_b - lon_a) / 2.0) + 1)
            _в = max(2, int(abs(lat_b - lat_a) / 2.0) + 1)
            _lons = np.linspace(lon_a, lon_b, _ш)
            _lats = np.linspace(lat_a, lat_b, _в)
            for сторона in (
                    [(lo2, lat_a) for lo2 in _lons],
                    [(lo2, lat_b) for lo2 in _lons],
                    [(lon_a, la2) for la2 in _lats],
                    [(lon_b, la2) for la2 in _lats]):
                пред = None
                for lo2, la2 in сторона:
                    p = _точка_шара(float(lo2), float(la2), lon0, R, cx,
                                    cy, lat0)
                    if пред is not None and p[2] > 0.02 and пред[2] > 0.02:
                        dс.line([(пред[0], пред[1]), (p[0], p[1])],
                                fill=tuple(_светлее(acc, 0.72))
                                + (int(252 * появ),), width=4)
                    пред = p
            img.alpha_composite(сл_сек)
            _ev(sfx, 0.5, "accent")

    # сетка: меридианы и параллели — поверх сектора, тонкие
    for lon in range(-180, 180, 20):
        пред = None
        for lat in range(-80, 81, 5):
            p = _точка_шара(lon, lat, lon0, R, cx, cy, lat0)
            if пред is not None and p[2] > 0.02 and пред[2] > 0.02:
                d.line([(пред[0], пред[1]), (p[0], p[1])],
                       fill=tuple(_светлее(ink, 0.42)) + (95,), width=1)
            пред = p
    for lat in range(-60, 61, 20):
        пред = None
        for lon in range(-180, 181, 5):
            p = _точка_шара(lon, lat, lon0, R, cx, cy, lat0)
            if пред is not None and p[2] > 0.02 and пред[2] > 0.02:
                d.line([(пред[0], пред[1]), (p[0], p[1])],
                       fill=tuple(_светлее(ink, 0.42)) + (95,), width=1)
            пред = p

    стр = строки(text, строк=2, знаков=15)
    if стр:
        tex = текст_тех(стр, fsize=104, color=(238, 239, 242), acc=acc)
        k = min(0.345 * W / tex.size[0], 0.28 * H / tex.size[1])
        м = tex.resize((max(4, int(tex.size[0] * k)),
                        max(4, int(tex.size[1] * k))), Image.LANCZOS)
        a = плавно(дол(tt, 0.1, 0.9))
        сл = м.copy()
        сл.putalpha(сл.split()[3].point(lambda v: int(v * a)))
        img.alpha_composite(сл, (int(SAFE * W), int(0.26 * H)))
    if region:
        pl = плашка_тех(region,
                        "названы в сцене" if свои else "регион целиком",
                        acc=acc, кегль=38,
                        кегль_под=26, ширина=520)
        a = плавно(дол(tt, 1.2, 2.0))
        if a > 0:
            сл = pl.copy()
            сл.putalpha(сл.split()[3].point(lambda v: int(v * a)))
            img.alpha_composite(сл, (int(SAFE * W), int(H * 0.60)))
        _ev(sfx, 1.2, "label")
    источник(img, source)
    знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


