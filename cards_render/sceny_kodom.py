TRIB_ФИГУРА = 1.78          # рост фигуры, м
TRIB_Z = 7.2                # где она стоит
# СКОРОСТЬ НАЕЗДА — ЕГО ПРАВКА ПО КЛИПУ 13.11: «только надо чуть-чуть
# быстрее это сделать, чтобы вот эти вот менялись вот эти полосочки, как бы
# приближение». «Полосочки» — швы пола и рёбра стен: они стоят на
# абсолютных отметках z, и скорость их смены И ЕСТЬ ощущение приближения.
# Было 0,075 м/с — за 18 секунд камера проезжала 1,35 м, то есть движение
# почти не читалось. Стало 0,17 м/с: 3,1 м за сцену. Без тряски, ход
# равномерный — правило «только медленный зум» не нарушено.
TRIB_ДОЛЛИ = 0.17           # м/с


def _фигура_тех(acc, px=560):
    """Силуэт без лица: голова, шея, плечи, корпус + контровой ореол.

    Рисуется в двойном размере и ужимается LANCZOS — PIL не сглаживает.
    Лица нет ПО ПОСТРОЕНИЮ: это не стилизованный портрет, а тёмная масса,
    и никакого сходства с конкретным человеком в ней нет.
    """
    def сделать():
        S, w, h = 2, px, int(px * 1.62)
        im = Image.new("RGBA", (w * S, h * S), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        cx = w * S / 2.0
        hh = h * S
        тело = (16, 16, 19, 255)
        # ПЛЕЧИ УЖЕ, ЧЕМ В ПЕРВОМ ЗАХОДЕ (13.11, по кадру): при ширине 2,16
        # головы силуэт читался плитой, а не человеком. Ширина плеч — 0,46
        # ширины кадра текстуры, корпус к низу чуть сужается, плечо покатое
        # (три точки, а не угол).
        rh = 0.082 * hh                                   # полуширина головы
        d.ellipse([cx - rh, 0.055 * hh, cx + rh, 0.055 * hh + rh * 2.25],
                  fill=тело)
        d.rectangle([cx - rh * 0.40, 0.055 * hh + rh * 1.85,
                     cx + rh * 0.40, 0.30 * hh], fill=тело)
        пл = 0.235 * w * S                                # полуширина плеч
        низ = 0.205 * w * S
        d.polygon([(cx - rh * 0.46, 0.272 * hh),
                   (cx - пл * 0.62, 0.300 * hh),
                   (cx - пл * 0.93, 0.350 * hh),
                   (cx - пл, 0.410 * hh),
                   (cx - низ, 1.0 * hh),
                   (cx + низ, 1.0 * hh),
                   (cx + пл, 0.410 * hh),
                   (cx + пл * 0.93, 0.350 * hh),
                   (cx + пл * 0.62, 0.300 * hh),
                   (cx + rh * 0.46, 0.272 * hh)], fill=тело)
        # контровой ореол: та же форма акцентом, размытая, ПОД фигурой
        ор = Image.new("RGBA", im.size, (0, 0, 0, 0))
        ор.paste(Image.new("RGBA", im.size, tuple(_светлее(acc, 0.35)) + (255,)),
                 (0, 0), im.split()[3])
        ор = ор.filter(ImageFilter.GaussianBlur(int(0.018 * h * S)))
        a = ор.split()[3].point(lambda v: int(min(255, v * 1.45)))
        ор.putalpha(a)
        ор.alpha_composite(im)
        return ор.resize((w, h), Image.LANCZOS)
    return _кэш(("фигура", tuple(acc), px), сделать)


def _трибуна(img, cam, x, z, acc, ширина=1.50, высота=1.10, глубина=0.55):
    """Сама трибуна: короб перед фигурой. Без неё силуэт уходил плитой в
    нижний край кадра (13.11, по первому же кадру) — теперь фигура видна от
    груди, как на любом подходе к микрофону."""
    d = ImageDraw.Draw(img, "RGBA")
    перед = [(x - ширина / 2, высота, z), (x + ширина / 2, высота, z),
             (x + ширина / 2, 0.0, z), (x - ширина / 2, 0.0, z)]
    верх = [(x - ширина / 2, высота, z - глубина),
            (x + ширина / 2, высота, z - глубина),
            (x + ширина / 2, высота, z), (x - ширина / 2, высота, z)]
    _полигон(d, cam, верх, (40, 41, 46, 255))
    _полигон(d, cam, перед, (27, 28, 32, 255))
    a = cam.proj((x - ширина / 2, высота, z))
    b = cam.proj((x + ширина / 2, высота, z))
    d.line([(a[0], a[1]), (b[0], b[1])],
           fill=tuple(_темнее(acc, 0.25)) + (205,), width=3)
    # плашка на передней грани — без неё короб читался пустой плитой
    _полигон(d, cam, [(x - 0.30, высота * 0.72, z), (x + 0.30, высота * 0.72, z),
                      (x + 0.30, высота * 0.40, z), (x - 0.30, высота * 0.40, z)],
             tuple(_темнее(acc, 0.55)) + (255,))


def _микрофон(img, cam, x, z, acc, h=1.38):
    """Стойка с микрофоном: рисуется прямо в кадре, текстура ей не нужна."""
    d = ImageDraw.Draw(img, "RGBA")
    a = cam.proj((x, 0.02, z))
    b = cam.proj((x, h, z))
    d.line([(a[0], a[1]), (b[0], b[1])], fill=(58, 60, 66, 255),
           width=max(2, int(0.012 * zc.F / max(0.5, z - cam.z))))
    # голова микрофона — небольшой наклонный овал
    c = cam.proj((x + 0.045, h + 0.07, z - 0.05))
    r = max(3, int(0.050 * zc.F / max(0.5, z - cam.z)))
    d.ellipse([c[0] - r, c[1] - r * 1.25, c[0] + r, c[1] + r * 1.25],
              fill=(44, 46, 52, 255), outline=tuple(_темнее(acc, 0.45)) + (255,),
              width=2)


def _пыль(слой, cam, t, acc, n=34, seed=11):
    """Медленная пыль в луче: точки на слое свечения, один общий блюр."""
    rng = np.random.default_rng(seed)
    d = ImageDraw.Draw(слой, "RGBA")
    for i in range(n):
        x = float(rng.uniform(-3.2, 3.2))
        y = float(rng.uniform(0.4, 3.4))
        z0 = float(rng.uniform(3.0, 18.0))
        z = z0 + math.sin(t * 0.16 + i) * 0.35
        yy = y + math.sin(t * 0.21 + i * 1.7) * 0.10
        p = cam.proj((x, yy, z))
        if p[2] < 0.6:
            continue
        r = max(1, int(2.4 * zc.F / (p[2] * 160)))
        a = int(70 + 60 * math.sin(t * 0.7 + i * 2.1))
        d.ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r],
                  fill=tuple(_светлее(acc, 0.55)) + (max(20, a),))


