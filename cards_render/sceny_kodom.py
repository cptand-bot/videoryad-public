MEH_Z = 9.6                 # где стоит ряд блоков
MEH_ЦИКЛ = 2.6              # сколько длится один нажим


def _пары(pary):
    """«А>Б» → список пар и порядок узлов. Разделитель любой из > → ->."""
    пары, узлы = [], []
    for p in (pary or ()):
        тек = str(p).replace("→", ">").replace("->", ">")
        части = [c.strip() for c in тек.split(">") if c.strip()]
        if len(части) < 2:
            continue
        for ч in части:
            if ч not in узлы:
                узлы.append(ч)
        for i in range(len(части) - 1):
            пары.append((части[i], части[i + 1]))
    return пары, узлы


def узел_тех(слово, acc, px=440):
    """Блок-узел: панель с полосой акцента сверху и словом внутри.

    Плашкой-полосой (`плашка_тех`) узел не рисуется: у неё соотношение 5:1,
    и ряд таких «блоков» на кадре читался сплошной лентой, а стрелы шли
    прямо по надписям (13.11, по первому кадру). Панель 3:2 стоит на полу
    блоком, и между блоками остаётся место для стрелы.
    """
    def сделать():
        S = 2
        w, h = px * S, int(px * 0.68) * S
        img = Image.new("RGBA", (w, h), (20, 21, 24, 240))
        d = ImageDraw.Draw(img)
        d.rectangle([0, 0, w, int(14 * S)], fill=tuple(acc) + (255,))
        слова = str(слово).upper().split()
        строки_ = []
        тек = ""
        for сл in слова:
            проба = (тек + " " + сл).strip()
            if тек and len(проба) > 11:
                строки_.append(тек)
                тек = сл
            else:
                тек = проба
        if тек:
            строки_.append(тек)
        строки_ = строки_[:2]
        # КЕГЛЬ ПОДБИРАЕТСЯ ПО ШРИФТУ, А НЕ ПО ЧИСЛУ БУКВ (13.11, по кадру:
        # «ПОДРЯДЧИК» вылезал за панель). Меряем строку и ужимаем, пока не
        # влезет в панель с полями.
        d0 = ImageDraw.Draw(Image.new("RGBA", (8, 8)))
        поле = int(26 * S)
        кегль = int(62 * S)
        while кегль > int(22 * S):
            f = zc.font("ArialBlack.ttf", кегль)
            шир = max(d0.textlength(x, font=f) for x in строки_)
            if шир <= w - поле * 2:
                break
            кегль = int(кегль * 0.92)
        f = zc.font("ArialBlack.ttf", кегль)
        высота = len(строки_) * кегль * 1.08
        y = (h + int(14 * S)) / 2.0 - высота / 2.0
        for ln in строки_:
            b = d0.textbbox((0, 0), ln, font=f)
            d.text(((w - (b[2] - b[0])) / 2 - b[0], y - b[1]), ln, font=f,
                   fill=(238, 239, 242, 255))
            y += кегль * 1.08
        return img.resize((w // S, h // S), Image.LANCZOS)
    return _кэш(("узел", str(слово), tuple(acc), px), сделать)


def _блок(img, cam, tex, x, z, h, осадка=0.0, acc=(200, 170, 90)):
    """Блок на полу: передняя грань с подписью, боковая грань, кромка."""
    w = h * tex.size[0] / float(tex.size[1])
    y0 = max(0.0, осадка)
    углы = [(x - w / 2, y0 + h, z), (x + w / 2, y0 + h, z),
            (x + w / 2, y0, z), (x - w / 2, y0, z)]
    d = ImageDraw.Draw(img, "RGBA")
    # боковая грань — объём; сторона зависит от того, слева блок или справа
    sx = 1 if x < cam.x else -1
    бок = [(x + sx * w / 2, y0 + h, z), (x + sx * w / 2, y0 + h, z + 0.45),
           (x + sx * w / 2, y0, z + 0.45), (x + sx * w / 2, y0, z)]
    _полигон(d, cam, бок, (30, 31, 35, 255))
    zc.paste_quad(img, tex, [cam.proj(q) for q in углы])
    a = cam.proj((x - w / 2, y0 + h, z))
    b = cam.proj((x + w / 2, y0 + h, z))
    d.line([(a[0], a[1]), (b[0], b[1])],
           fill=tuple(_светлее(acc, 0.25)) + (225,), width=3)
    return углы


def _стрела(слой, cam, откуда, куда, acc, фаза, толщина=0.17):
    """Стрела усилия между двумя точками пространства.

    Рисуется В ЭКРАННЫХ координатах по спроецированным концам: стрела — это
    указатель, а не предмет в комнате, и перспективной глубины ей не нужно.
    Бегущий по ней светлый сгусток и показывает НАПРАВЛЕНИЕ усилия.
    """
    a = cam.proj(откуда)
    b = cam.proj(куда)
    ax, ay, bx, by = a[0], a[1], b[0], b[1]
    dx, dy = bx - ax, by - ay
    L = math.hypot(dx, dy)
    if L < 24:
        return
    ux, uy = dx / L, dy / L
    nx, ny = -uy, ux
    t_px = max(5.0, толщина * zc.F / max(1.0, (откуда[2] + куда[2]) / 2 - cam.z))
    гол = t_px * 2.6                                  # длина наконечника
    кx, кy = bx - ux * гол, by - uy * гол
    d = ImageDraw.Draw(слой, "RGBA")
    d.polygon([(ax + nx * t_px * 0.42, ay + ny * t_px * 0.42),
               (кx + nx * t_px * 0.52, кy + ny * t_px * 0.52),
               (кx - nx * t_px * 0.52, кy - ny * t_px * 0.52),
               (ax - nx * t_px * 0.42, ay - ny * t_px * 0.42)],
              fill=tuple(_темнее(acc, 0.15)) + (225,))
    d.polygon([(bx, by), (кx + nx * t_px * 1.15, кy + ny * t_px * 1.15),
               (кx - nx * t_px * 1.15, кy - ny * t_px * 1.15)],
              fill=tuple(_светлее(acc, 0.22)) + (248,))
    # сгусток, бегущий от того, кто давит, к тому, на кого давят
    ф = zc.clamp01(фаза)
    сx, сy = ax + dx * ф, ay + dy * ф
    r = t_px * 0.85
    d.ellipse([сx - r, сy - r, сx + r, сy + r],
              fill=tuple(_светлее(acc, 0.55)) + (int(220 * (1.0 - abs(ф - 0.5) * 1.1)),))


def mehanizm(out=None, t=None, text="", pary=(), source="", channel="",
             watermark="", dur=0.0, sfx=None, **_):
    """Блоки и стрелы давления: кто на кого нажимает."""
    tt = 3.2 if t is None else float(t)
    acc, ink, mid = пал(channel)
    # камера чуть смещается вбок — от этого ряд блоков читается объёмом, а
    # не плоской схемой. Без тряски: 0,22 м за полный цикл, ход синусом.
    # снос камеры 0,18 м, а не 0,34 (13.11, по клипу: на 14-й секунде
    # крайние блоки обрезались краем кадра)
    cam = zc.Cam(x=0.18 * math.sin(tt * 0.19), y=1.56, z=0.045 * tt)
    img = зал(cam, acc, ink, mid, шаг=3.0, даль=40.0)
    слой = Image.new("RGBA", (W, H), (0, 0, 0, 0))

    пары, узлы = _пары(pary)
    узлы = узлы[:4]
    n = max(1, len(узлы))
    # ВСЕ БЛОКИ ОБЯЗАНЫ БЫТЬ В КАДРЕ (14.11, его слово по сцене 21 ролика
    # `planeta-2-strashnye-poteri`: «Почему эти квадраты выходят за пределы
    # кадра? Левые и правые, они не видны. Неужели это не видно?»).
    # Шаг был КОНСТАНТОЙ (3,4 мировых единицы при трёх и более узлах), и на
    # четырёх парах крайние блоки уезжали за края — в кадре оставались два
    # средних, а стрелки вели из ниоткуда в никуда. Теперь шаг подбираем:
    # уменьшаем, пока крайние узлы не встанут внутри безопасного поля.
    _поле = int(W * 0.055)              # 5,5% от края — там же, где знак канала
    шаг_x = 3.4 if n > 2 else 2.6
    for _проба in [шаг_x - 0.2 * _i for _i in range(0, 14)]:
        if _проба <= 0.8:
            break
        _кx = ((n - 1) / 2.0) * _проба
        try:
            _лев = cam.proj((-_кx, 0.9, MEH_Z))[0]
            _прав = cam.proj((_кx, 0.9, MEH_Z))[0]
        except Exception:
            break
        # блок рисуется вокруг точки, поэтому держим ещё полблока запаса
        if _лев - W * 0.085 >= _поле and _прав + W * 0.085 <= W - _поле:
            шаг_x = _проба
            break
    else:
        шаг_x = max(0.9, шаг_x - 0.2 * 13)
    # РЯД ЦЕНТРИРУЕМ ПО ФАКТИЧЕСКОЙ ПРОЕКЦИИ, А НЕ ПО МИРОВОМУ НУЛЮ: камера
    # этого приёма смещена вбок, поэтому ряд, симметричный в мире, в кадре
    # уезжает влево (видно на первой же пробе правки 14.11).
    _сдвиг = 0.0
    try:
        _кx = ((n - 1) / 2.0) * шаг_x
        _л = cam.proj((-_кx, 0.9, MEH_Z))[0]
        _п = cam.proj((_кx, 0.9, MEH_Z))[0]
        _центр_кадра = W / 2.0
        _центр_ряда = (_л + _п) / 2.0
        # переводим расхождение в мировые единицы по масштабу ряда
        if abs(_п - _л) > 1:
            _сдвиг = (_центр_кадра - _центр_ряда) * (2 * _кx) / (_п - _л)
    except Exception:
        _сдвиг = 0.0
    места = {}
    for i, у in enumerate(узлы):
        x = (i - (n - 1) / 2.0) * шаг_x + _сдвиг
        места[у] = x

    # кто на кого давит — по этому блок и приседает
    жмут = {}
    for i, (а, б) in enumerate(пары):
        жмут.setdefault(б, []).append(i)

    высоты, tex_узла = {}, {}
    for у, x in места.items():
        tex = узел_тех(у, acc)
        h = вписать(zc.Cam(x=0.0, y=1.56, z=0.0), MEH_Z,
                    tex.size[0] / float(tex.size[1]),
                    min(0.17, 0.60 / n), 0.26)
        высоты[у], tex_узла[у] = h, tex

    for i, у in enumerate(узлы):
        фаза_нажима = ((tt - 0.9 - 0.45 * i) % MEH_ЦИКЛ) / MEH_ЦИКЛ
        осадка = 0.0
        if у in жмут:
            осадка = -0.055 * высоты[у] * math.sin(math.pi * zc.clamp01(
                (фаза_нажима - 0.45) / 0.35))
        пок = плавно(дол(tt, 0.1 + 0.22 * i, 0.55 + 0.22 * i))
        if пок <= 0:
            continue
        h = высоты[у] * пок
        _блок(img, cam, tex_узла[у], места[у], MEH_Z, h, осадка=осадка, acc=acc)
        _ev(sfx, 0.1 + 0.22 * i, "label")

    for i, (а, б) in enumerate(пары):
        if а not in места or б not in места:
            continue
        пок = дол(tt, 0.9 + 0.3 * i, 1.3 + 0.3 * i)
        if пок <= 0:
            continue
        ha, hb = высоты[а], высоты[б]
        wa = ha * tex_узла[а].size[0] / float(tex_узла[а].size[1])
        wb = hb * tex_узла[б].size[0] / float(tex_узла[б].size[1])
        знак_ = 1.0 if места[б] > места[а] else -1.0
        # КОНЦЫ СТРЕЛЫ — ОТ КРАЯ БЛОКА, А НЕ ОТ ЕГО ЦЕНТРА: иначе стрела
        # идёт прямо по надписи (13.11, по первому кадру).
        откуда = (места[а] + знак_ * (wa / 2 + 0.10), ha * 0.52, MEH_Z - 0.4)
        куда = (места[б] - знак_ * (wb / 2 + 0.10), hb * 0.52, MEH_Z - 0.4)
        фаза = ((tt - 0.9 - 0.45 * i) % MEH_ЦИКЛ) / MEH_ЦИКЛ
        _стрела(слой, cam, откуда, куда, acc, фаза * пок)
        _ev(sfx, 0.9 + 0.3 * i, "accent")

    img = свечение(img, слой, радиус=26, сила=0.55)
    # сами стрелы кладём ещё раз поверх свечения — чтобы они были резкими
    img.alpha_composite(слой)

    стр = строки(text, строк=2, знаков=19)
    if стр:
        надпись_сверху(img, текст_тех(стр, fsize=108, color=(238, 239, 242),
                                      acc=acc), плавно(дол(tt, 0.0, 0.8)))
    источник(img, source)
    знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


