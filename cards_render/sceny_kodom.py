def kreslo(out=None, t=None, text="", role="", place="", source="",
           channel="", watermark="", dur=0.0, sfx=None, **_):
    """Кабинет с пустым креслом. Камера медленно подъезжает к столу."""
    tt = 3.0 if t is None else float(t)
    acc, ink, mid = пал(channel)
    # ВЫСОТА КАМЕРЫ И ДАЛЬНОСТЬ ПРЕДМЕТА СВЯЗАНЫ ЖЁСТКО (13.11, посчитано
    # после двух негодных кадров). Наклона камеры в движке нет — горизонт
    # всегда по центру, — поэтому точка пола на расстоянии d проецируется в
    # 540 + cam.y·F/d, и чтобы ОСНОВАНИЕ предмета попало в кадр, нужно
    # d > cam.y·F/540. При камере 2,25 м это 8,2 м: кресло на 5,75 м уходило
    # нижним краем за кадр, сколько его ни двигай. Берём обычную высоту
    # взгляда 1,52 м (тогда порог 5,5 м) и ставим кресло на 6,6 м: оно
    # целиком в кадре и крупное. Стол ушёл ЗА кресло и работает фоном.
    cam = zc.Cam(x=-0.30, y=1.52 + 0.004 * tt, z=0.030 * tt)
    img = зал(cam, acc, ink, mid, шаг=2.8, даль=34.0)
    слой = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ds = ImageDraw.Draw(слой, "RGBA")
    # ОКНО СЛЕВА И ЛУЧ ИЗ НЕГО: единственный источник света в кадре. Пустое
    # кресло в ровном свете читается как мебель в каталоге, а в луче — как
    # место, с которого ушли.
    k = плавно(дол(tt, 0.0, 1.2))
    for i, (zz, hh) in enumerate(((5.6, 2.8), (9.4, 2.8))):
        q = [cam.proj((-WALL + 0.05, hh, zz)), cam.proj((-WALL + 0.05, hh, zz + 2.2)),
             cam.proj((-WALL + 0.05, 0.75, zz + 2.2)), cam.proj((-WALL + 0.05, 0.75, zz))]
        ds.polygon([(p[0], p[1]) for p in q],
                   fill=tuple(_светлее(acc, 0.72)) + (int(185 * k),))
    луч = [cam.proj((-WALL + 0.2, 0.02, 5.2)), cam.proj((-WALL + 0.2, 0.02, 9.2)),
           cam.proj((1.9, 0.02, 7.8)), cam.proj((1.2, 0.02, 5.0))]
