#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ВОЗВРАЩАЕТ «Ё» В ТЕКСТ ПЕРЕД ОЗВУЧКОЙ — только там, где омографа нет.

Повод 15.11: текст темы «2-Против РФ ответ Москвы» лёг на диск с НУЛЁМ «ё»
на 1682 слова, гейт `ozvuchka.py` (07.11) справедливо не пустил его в
сервис — «все» вместо «всё» слышно только в готовом ролике. Руками такую
правку не делают: это 40-60 слов на текст.

ЧТО ПРАВИТ: формы, где «е» на месте «ё» даёт НЕСУЩЕСТВУЮЩЕЕ слово
(«ещё», «её», «идёт», «приём», «чёрный», «пришёл»). Регистр сохраняется.
ЧЕГО НЕ ТРОГАЕТ: «все/всё», «небо/нёбо», «совершенный/совершённый» и прочие
пары, где обе формы существуют, — их решает только человек. Поэтому после
прогона в тексте «ё» появляется, но ручная вычитка «всё» остаётся за автором.

    python3 template/yofikator.py <файл.txt>            # показать, что изменится
    python3 template/yofikator.py <файл.txt> --pisat    # записать (рядом .bak-noyo)
"""
import argparse, io, os, re, sys

# Однозначные основы: «е» здесь не бывает никогда.
ОСНОВЫ = [
    "ещё", "её", "неё", "своё", "твоё", "моё", "всё-таки",
    "идёт", "идём", "идёте", "найдёт", "придёт", "пойдёт", "уйдёт", "зайдёт",
    "ведёт", "приведёт", "берёт", "возьмёт", "несёт", "принесёт", "живёт",
    "даёт", "отдаёт", "передаёт", "создаёт", "растёт", "зовёт", "льёт",
    "шёл", "пришёл", "ушёл", "нашёл", "произошёл", "подошёл", "перешёл",
    "вошёл", "дошёл", "обошёл", "прошёл",
    "приём", "объём", "подъём", "счёт", "учёт", "отчёт", "расчёт", "зачёт",
    "вперёд", "назём",
    "серьёзн", "чёрн", "жёлт", "тёпл", "тёмн", "надёжн", "жёстк", "тяжёл",
    "лёгк", "далёк", "мёртв", "свёрт", "твёрд", "чёткий", "чётко", "чётк",
    "актёр", "режиссёр", "партнёр", "тренер",  # «тренер» — без ё, см. ИСКЛ
    "миллиардёр", "монтёр", "шофёр", "гравёр",
    "трёх", "четырёх", "сёстр", "полёт", "самолёт", "налёт",
    "перелёт", "вылет",  # «вылет» без ё, см. ИСКЛ
    "льготн",  # без ё, см. ИСКЛ
]
# ОМОГРАФЫ, КОТОРЫЕ НЕЛЬЗЯ ТРОГАТЬ МАШИНОЙ (проверено на живом тексте
# 15.11): «чем» (творительный от «что»: «чем больше») → «чём» ломает фразу;
# «сел» (сесть) → «сёл»; «гнет» и «вылет» существуют без ё.
ИСКЛ = {"тренер", "вылет", "льготн", "назём", "чём", "сёл", "гнёт"}
ОСНОВЫ = [о for о in ОСНОВЫ if о not in ИСКЛ]


def _vary(о):
    """Пишем правило как пару (без ё → с ё)."""
    return о.replace("ё", "е"), о


ПРАВИЛА = [_vary(о) for о in ОСНОВЫ]


def _kak_bylo(src, dst):
    """Сохранить регистр первой буквы исходника."""
    if src[:1].isupper():
        return dst[:1].upper() + dst[1:]
    return dst


def yoficirovat(text):
    смен = {}
    for без, сё in ПРАВИЛА:
        # только как часть слова, начинающаяся с границы: «идёт», «пришёл»,
        # «чёрный» — но не внутри чужого корня
        шаблон = re.compile(r"\b(" + без + r")", re.IGNORECASE)

        def зам(m, сё=сё):
            смен[m.group(1)] = _kak_bylo(m.group(1), сё)
            return _kak_bylo(m.group(1), сё)

        text = шаблон.sub(зам, text)
    return text, смен


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("fayl")
    ap.add_argument("--pisat", action="store_true")
    a = ap.parse_args()
    if not os.path.exists(a.fayl):
        print("нет файла: %s" % a.fayl, file=sys.stderr)
        return 2
    было = io.open(a.fayl, encoding="utf-8").read()
    стало, смен = yoficirovat(было)
    yo_до = было.count("ё") + было.count("Ё")
    yo_после = стало.count("ё") + стало.count("Ё")
    print("«ё» было %d, стало %d (знаков %d)" % (yo_до, yo_после, len(стало)))
    if смен:
        print("заменено форм: %d — %s"
              % (len(смен), ", ".join("%s→%s" % кв for кв in list(смен.items())[:14])))
    if yo_после == 0:
        print("ОДНОЗНАЧНЫХ ФОРМ В ТЕКСТЕ НЕТ — «ё» вернуть может только автор "
              "(спорные пары «все/всё» инструмент не трогает).")
        return 1
    if not a.pisat:
        print("\nничего не записано (нужен ключ --pisat)")
        return 0
    bak = a.fayl + ".bak-noyo"
    if not os.path.exists(bak):
        io.open(bak, "w", encoding="utf-8").write(было)
    io.open(a.fayl, "w", encoding="utf-8").write(стало)
    print("записано; исходник сохранён как %s" % os.path.basename(bak))
    print("ВНИМАНИЕ: пары «все/всё» инструмент не трогал — если в тексте есть "
          "«всё», автору стоит пройтись глазами.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
