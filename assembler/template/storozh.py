# -*- coding: utf-8 -*-
"""СТОРОЖ НА ВХОДЕ ИНСТРУМЕНТА — ПРАВИЛО ДЕРЖИТ КОД, А НЕ ТЕКСТ (11.11.2026).

Откуда: разбор чужого конвейера cinecode. У него правила экономии не написаны
в инструкции, а стоят на двери: вкладка пытается сделать — её не пускают.
Его слово 11.11: «если у нас хуёвая, а у него хорошая — давай сделаем хорошую».

ПОЧЕМУ ЭТО ГЛАВНАЯ СТАТЬЯ. Замер 09.11: 99,3% расхода вкладки — перечитывание
собственного контекста. Всё, что попало в переписку ОДИН раз, подаётся заново
в КАЖДОМ следующем запросе — а их у вкладки 400-600. Значит один `Read` на
300 КБ стоит не 300 КБ, а 300 КБ × число оставшихся запросов. Текстовое
правило «читать только грепом» существует с 16.10 и исправно обходится.

ЧТО ДЕРЖИТ (всё остальное пропускается молча):
  1. Большой справочник целиком. `Read` файла `.md` тяжелее 60 КБ без
     `offset`/`limit` — отказ с подсказкой: грепни по симптому.
  2. Полный кадр сцены в переписку. `Read` файла `images/scene_*`,
     `overlays/scene_*`, `clips/*` и любой картинки тяжелее 6 Мп — отказ с
     подсказкой: контактный лист или `zoom.py`. Листы (`*sheet*`) и готовые
     уменьшенные копии (`*_small*`, `*zoom*`, `*thumb*`) проходят: ими и
     положено смотреть.
  3. Картинок больше сорока за вкладку — отказ: брать нового субагента.
     Замер 23.10: один проверяющий прочитал 222 полных кадра, 82% объёма
     всех транскриптов дня — это изображения в субагентах.

ОБХОД — одной переменной, когда он прямо так сказал:
    VIDEORYAD_BEZ_STOROZHA=1

Ставится хуком PreToolUse в ~/.claude/settings.json. Своя ошибка сторожа
никогда не мешает работе: любое исключение = пропустить.
"""
import json
import os
import sys

СЧЁТ = "/tmp/videoryad-storozh"
ПРЕДЕЛ_MD = 60 * 1024
ПРЕДЕЛ_МП = 6.0
ПРЕДЕЛ_КАРТИНОК = 40
КАРТИНКИ = (".jpg", ".jpeg", ".png", ".webp", ".gif", ".bmp")
ПРОПУСК = ("sheet", "_small", "zoom", "thumb", "list", "лист", "превью", "prevyu")


def отказ(причина):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": причина}}, ensure_ascii=False))
    sys.exit(0)


def мегапиксели(путь):
    try:
        from PIL import Image
        with Image.open(путь) as im:
            return im.size[0] * im.size[1] / 1e6
    except Exception:
        return 0.0


def сколько_картинок(сессия):
    try:
        os.makedirs(СЧЁТ, exist_ok=True)
        f = os.path.join(СЧЁТ, (сессия or "нет")[:40])
        n = int(open(f).read().strip()) if os.path.exists(f) else 0
        open(f, "w").write(str(n + 1))
        return n + 1
    except Exception:
        return 0


def main():
    if os.environ.get("VIDEORYAD_BEZ_STOROZHA"):
        return
    данные = json.load(sys.stdin)
    если_не = данные.get("tool_name") or ""
    if если_не != "Read":
        return
    вход = данные.get("tool_input") or {}
    путь = вход.get("file_path") or ""
    if not путь or not os.path.exists(путь):
        return
    имя = os.path.basename(путь).lower()
    низ = путь.lower().replace("\\", "/")

    # 1. СПРАВОЧНИК ЦЕЛИКОМ
    if имя.endswith((".md", ".txt")) and not (вход.get("offset") or вход.get("limit")):
        try:
            вес = os.path.getsize(путь)
        except OSError:
            return
        if вес > ПРЕДЕЛ_MD:
            отказ(
                f"СТОРОЖ: «{os.path.basename(путь)}» весит {вес // 1024} КБ, а читается "
                f"ЦЕЛИКОМ. Один такой разворот подаётся заново в каждом из "
                f"оставшихся запросов вкладки — это и есть 99% нашего расхода.\n"
                f"Как надо: grep -n по симптому, потом Read с offset/limit на "
                f"нужный кусок. Оглавление: grep -n '^#' «{путь}».\n"
                f"Если файл правда нужен целиком — VIDEORYAD_BEZ_STOROZHA=1.")

    # 2. ПОЛНЫЙ КАДР В ПЕРЕПИСКУ
    if имя.endswith(КАРТИНКИ):
        if not any(м in имя for м in ПРОПУСК):
            кадр = ("/images/scene_" in низ or "/overlays/scene_" in низ
                    or "/clips/" in низ or "/cards/" in низ)
            мп = мегапиксели(путь)
            if кадр or мп > ПРЕДЕЛ_МП:
                отказ(
                    f"СТОРОЖ: «{os.path.basename(путь)}» — полный кадр ({мп:.1f} Мп). "
                    f"Картинка остаётся в контексте до конца вкладки и перечитывается "
                    f"на каждом шаге (замер 23.10: 82% объёма субагентов — это кадры).\n"
                    f"Как надо: смотреть контактный лист, а спорную плитку — "
                    f"python3 ~/.claude/skills/news-video/template/zoom.py «{путь}» "
                    f"(ужатая копия или четыре угла 1:1 для клейм).\n"
                    f"Если кадр правда нужен целиком — VIDEORYAD_BEZ_STOROZHA=1.")
        n = сколько_картинок(данные.get("session_id"))
        if n > ПРЕДЕЛ_КАРТИНОК:
            отказ(
                f"СТОРОЖ: это {n}-я картинка в этой вкладке (потолок {ПРЕДЕЛ_КАРТИНОК}). "
                f"Каждая лежит в контексте до конца и перечитывается на каждом шаге.\n"
                f"Как надо: закончить круг, взять НОВОГО субагента под следующий "
                f"осмотр — у него контекст свой и в основной поток не копится.")


if __name__ == "__main__":
    try:
        main()
    except Exception:
        pass   # сторож никогда не мешает работе из-за собственной ошибки
