POL_T = 2.5
POL_HERO = 1.9
POL_RISE = (0.60, 0.167)      # выезд из пола: 167 мс, как на плёнке
# плиты: (глубина, высота, ширина, |x|, когда подскакивает, зерно)
POL_PLITY = ((17.0, 1.3, 0.9, 5.6, 0.00, 1), (13.5, 1.6, 1.0, 5.0, 0.42, 2),
             (10.0, 1.9, 1.1, 4.7, 0.80, 3), (7.0, 2.3, 1.2, 4.6, 1.18, 4),
             (4.4, 2.6, 1.2, 4.5, 1.56, 5), (22.0, 1.6, 1.0, 5.4, 1.94, 6))


def _плита(img, cam, t, x, z, wm, hm, dm, t0):
    """Тёмная стопка плит на полу: подскакивает в кадр, на верхней кромке
    тлеет уголёк. Возвращает точки углей (их рисуем общим проходом)."""
    p = _pop(t0, t, dur=0.10, k0=1.15)
    if p is None:
        return []
    s, op = p
    wm2, hm2, dm2 = wm * s, hm * s, dm * s
    x0, x1 = x - wm2 / 2.0, x + wm2 / 2.0
    z0, z1 = z, z + dm2
    front = [(x0, hm2, z0), (x1, hm2, z0), (x1, 0, z0), (x0, 0, z0)]
    top = [(x0, hm2, z1), (x1, hm2, z1), (x1, hm2, z0), (x0, hm2, z0)]
    if x > 0:
        sidef = [(x0, hm2, z1), (x0, hm2, z0), (x0, 0, z0), (x0, 0, z1)]
    else:
        sidef = [(x1, hm2, z0), (x1, hm2, z1), (x1, 0, z1), (x1, 0, z0)]
    if not _видно(cam, front):
        return []
    ft = _плита_тек(wm, hm)
    st = _плита_тек(dm, hm)
    tt_ = Image.new("RGBA", (64, 64), (52, 48, 46, 255))
    sh = [(x0 + 0.6, 0.01, z0 + 0.9), (x1 + 0.6, 0.01, z1 + 0.9),
          (x1, 0.01, z1), (x0, 0.01, z0)]
    shl = Image.new("RGBA", (64, 64), (40, 38, 36, int(70 * op)))
    zc.paste_quad(img, shl.filter(ImageFilter.GaussianBlur(4)),
                  [cam.proj(q) for q in sh])
    zc.paste_quad(img, tt_, [cam.proj(q) for q in top], op)
    zc.paste_quad(img, st, [cam.proj(q) for q in sidef], op)
    zc.paste_quad(img, ft, [cam.proj(q) for q in front], op)
    ex = x0 + wm2 * (0.25 if x > 0 else 0.75)
    return [(ex, hm2 + 0.10, z0 + 0.10, 0.95)]


_ТЕКСТУРЫ = {}


def _плита_тек(wm, hm, px=360):
    """Тёмная стопка: горизонтальные швы примерно через 0,22 м.

    КЭШИРУЕТСЯ (11.11, замер): в кадре двенадцать плит, у каждой две грани —
    двадцать четыре построения текстуры НА КАЖДЫЙ кадр, и сцена считалась
    втрое дольше вида `zal`. От кадра текстура не зависит вовсе.
    """
    ключ = ("плита", round(wm, 3), round(hm, 3), px)
    if ключ in _ТЕКСТУРЫ:
        return _ТЕКСТУРЫ[ключ]
    w = px
    h = max(8, int(px * hm / max(0.01, wm)))
    img = Image.new("RGBA", (w, h), (34, 31, 30, 255))
    d = ImageDraw.Draw(img)
    step = max(2, int(h * 0.22 / max(0.01, hm)))
    y = h - 1
    k = 0
    while y > 0:
        d.line([(0, y), (w, y)], fill=(58, 54, 52, 255), width=max(2, px // 90))
        d.line([(0, y - 2), (w, y - 2)], fill=(20, 18, 17, 255), width=1)
        y -= step + (k % 3) * 3
        k += 1
    d.rectangle([0, 0, w - 1, h - 1], outline=(24, 22, 21, 255), width=2)
    if len(_ТЕКСТУРЫ) < 64:
        _ТЕКСТУРЫ[ключ] = img
    return img


def zal_pol(out=None, t=None, text="", na_polu="", accent="", words=(),
            sheets=(), channel="", watermark="", dur=0.0, sfx=None, **_):
    """G10. Верхняя строка (`text`) висит на тросах, ударное слово (`na_polu`)
    ВЫЕЗЖАЕТ ИЗ ПОЛА, по бокам подскакивают плиты с тлеющими углями.
    `accent` — слово верхней строки под маркером канала."""
    tt = POL_HERO if t is None else float(t)
    k = _темп(dur)
    bg, fg = цвета(channel)
    cam = zc.Cam(x=0.0, y=1.55, z=0.28 * tt)
    cam_l = zc.Cam(x=0.0, y=1.55, z=0.28 * POL_T)
    img = zc.room(cam)
    _листы(img, cam, sheets)

    z_в, z_н = 14.5, 13.0
    низ_верхней = SAFE * H
    верх = _строки(text, строк=2, знаков=22)
    if верх:
        пл = _плитки(верх, hl=_маркер(верх, accent), color=(30, 27, 26, 255),
                     hl_color=bg, hl_ink=fg)
        tw, th = _ширина_строки(пл)
        h = _вписать(cam_l, z_в, tw / th, 0.72, 0.17)
        s = h / th
        bw, bh = _коробка_мира(cam_l, z_в, tw * s, th * s)
        cx, cy = _в_мир(cam_l, 0.5 * W, SAFE * H + bh / 2.0, z_в)
        низ_верхней = SAFE * H + bh
        _отметить("верхняя строка", (W - bw) / 2, SAFE * H, (W + bw) / 2,
                  низ_верхней)
        старты = [(0.05 + i * 0.10) * k for i in range(len(пл[2]))]
        for st in старты:
            _ev(sfx, st, "label")
        _строка_слов(img, cam, tt, пл, (cx, cy, z_в), 0.0, s, старты,
                     depth=0.12, side=(18, 16, 15), hang=True, k0=1.08)

    # ПЛИТЫ: дальние рисуем до слова, ближние после — слово должно закрывать
    # собой то, что стоит за ним, иначе угли «просвечивают» сквозь буквы
    далёкие, близкие = [], []
    for (zz, hh, ww, xx, t0, sd) in POL_PLITY:
        for sx in (-1, 1):
            e = _плита(img, cam, tt, sx * xx, zz, ww, hh, ww * 0.9, t0 * k)
            (далёкие if zz > z_н + 0.5 else близкие).extend(e)
        _ev(sfx, t0 * k, "impact")
    if далёкие:
        img = zc.embers(img, cam, далёкие, tt, glow=0.8)

    низ = _строки(na_polu or (words[0] if words else ""), строк=1, знаков=18)
    if низ:
        # СЛОВО ИЗ ПОЛА — ЦВЕТОМ КАНАЛА, а не тёмное, как в образце (11.11,
        # замер: в тёмном варианте акцента канала в кадре было РОВНО НОЛЬ, и
        # два канала не различались ничем). Образец одноканальный, у нас
        # ПЛАНЕТА и «5 МИНУТ» обязаны отличаться — его требование 11.11.
        # БОКОВОЙ ЗАПАС ГАРАНТИРОВАН (11.11, его правка по кадру: «М» и «И»
        # стояли вплотную к кромкам). Доля ширины 0,74 плюс учёт объёма даёт
        # не меньше 12% поля с каждой стороны на любом слове.
        пл = _плитки(низ, color=bg, vertical=True, разрядка=0.10)
        tw, th = _ширина_строки(пл)
        h = _на_полу(cam_l, z_н, tw / th, 0.74, 0.44,
                     зазор_сверху=низ_верхней + 0.035 * H, depth_rel=0.19)
        s = h / th
        глуб = h * 0.19
        bw2, bh2 = _коробка_мира(cam_l, z_н, tw * s, th * s, depth=глуб)
        пол = _пол_на_экране(cam_l, z_н)
        _отметить("слово из пола", (W - bw2) / 2, пол - bh2, (W + bw2) / 2, пол)
        подъём = (POL_RISE[0] * k, POL_RISE[1] * k)
        _ev(sfx, подъём[0], "accent")
        _строка_слов(img, cam, tt, пл, (0.0, 0.0, z_н), 0.0, s,
                     [-1.0] * len(пл[2]), depth=глуб,
                     side=tuple(int(c * 0.72) for c in bg[:3]),
                     floor=True, shadow=True, rise=подъём)

    if близкие:
        img = zc.embers(img, cam, близкие, tt, glow=0.8)
    _знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


