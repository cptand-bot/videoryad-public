def _ширина_панели(dist, yaw, xoff):
    cam = zc.Cam(xoff, 1.55, EFIR_Z - dist)
    pts = [cam.proj(p) for p in zc.quad((0.0, 1.55, EFIR_Z), EFIR_W, EFIR_H,
                                        yaw=yaw)]
    xs = [p[0] for p in pts]
    return (max(xs) - min(xs)) / W


def _дальность(want, yaw, xoff):
    """Дальность камеры, при которой панель занимает `want` ширины кадра.
    Считается делением отрезка, а не подбирается числом."""
    lo, hi = 1.5, 14.0
    for _ in range(30):
        mid = (lo + hi) / 2.0
        if _ширина_панели(mid, yaw, xoff) > want:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2.0


