def _сч_число(value, сдвиг):
    """(строка счётчика, бежит ли он). `сдвиг` — на сколько кадров сдвинуть.

    Считаем только то, что СЧИТАЕТСЯ: «7 856» добегает, «4,3 млрд» и
    «каждый третий» показываются как есть (прибавлять единицу к доле —
    бессмыслица, а молча испортить число хуже, чем не считать).
    """
    s = str(value or "").strip()
    # СЧИТАЕМ ТОЛЬКО ЦЕЛОЕ С КОРОТКОЙ МЕРОЙ. Шаблон нарочно не принимает
    # запятую и точку: на «4,3 млрд» вольная разборка давала «4» числом и
    # «,3 млрд» хвостом, и счётчик показывал «9 ,3 млрд» (поймано прогоном
    # 11.11). Доля по единице в кадр не считается — значит, показываем как
    # написано, а дверь об этом предупреждает.
    m = re.match(r"^(\d[\d\s  ]*?)\s*([^\d.,]{0,10})$", s)
    if not m:
        return s, False
    цифры = re.sub(r"\D", "", m.group(1))
    суф = m.group(2).strip()
    if not цифры or len(цифры) > 12:
        return s, False
    n = max(0, int(цифры) + int(сдвиг))
    txt = f"{n:,}".replace(",", " ")          # разряды пробелом, не запятой
    return (txt + (" " + суф if суф else "")), True


