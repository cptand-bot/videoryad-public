def _грани(cam, cx, cy0, cz, w, th, yaw, бок, крышка, фронт, дно):
    """Грани одной плиты в порядке рисования (крышка/дно, бок, фронт)."""
    c, s = math.cos(yaw), math.sin(yaw)

    def P(ux, uz, y):
        return (cx + ux * c - uz * s, y, cz + ux * s + uz * c)

    h = w / 2.0
    y1 = cy0 + th
    g = {"fbl": P(-h, -h, cy0), "fbr": P(h, -h, cy0), "ftl": P(-h, -h, y1),
         "ftr": P(h, -h, y1), "bbl": P(-h, h, cy0), "bbr": P(h, h, cy0),
         "btl": P(-h, h, y1), "btr": P(h, h, y1)}
    pr = {kk: cam.proj(v) for kk, v in g.items()}
    faces = []
    if cam.y > y1:
        faces.append(([pr["btl"], pr["btr"], pr["ftr"], pr["ftl"]], крышка))
    elif cam.y < cy0:
        faces.append(([pr["bbl"], pr["bbr"], pr["fbr"], pr["fbl"]], дно))
    if cam.x > g["fbr"][0]:
        faces.append(([pr["ftr"], pr["btr"], pr["bbr"], pr["fbr"]], бок))
    else:
        faces.append(([pr["btl"], pr["ftl"], pr["fbl"], pr["bbl"]], бок))
    faces.append(([pr["ftl"], pr["ftr"], pr["fbr"], pr["fbl"]], фронт))
    return faces


def _столб(img, cam, x, z, h, полная, bg):
    """Столб плит цвета канала: внизу готовые, наверху одна в полёте."""
    тон = lambda m: (min(255, int(bg[0] * m)), min(255, int(bg[1] * m)),
                     min(255, int(bg[2] * m)), 255)
    shl = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    s = SHKALA_SLAB * 0.75
    sh = [cam.proj(p) for p in ((x - s, 0, z - s), (x + s, 0, z - s),
                                (x + s * 1.3, 0, z + s * 1.6),
                                (x - s * 1.3, 0, z + s * 1.6))]
    ImageDraw.Draw(shl).polygon([(p[0], p[1]) for p in sh],
                                fill=(50, 50, 54, int(90 * zc.clamp01(h / 0.3))))
    img.alpha_composite(shl.filter(ImageFilter.GaussianBlur(16)))
    items = []
    for (y0f, thf, dx, dz, yw) in _ПЛИТЫ:
        y0, th = y0f * полная, thf * полная
        if h < y0 + 0.001:
            break
        пад = 0.55 * (1 - zc.clamp01((h - y0) / max(1e-6, th)))
        items.append((y0 + пад, th, dx, dz, yw))
    items.sort(key=lambda it: -abs((it[0] + it[1] / 2) - cam.y))
    lay = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(lay)
    for (y0, th, dx, dz, yw) in items:
        for pts, col in _грани(cam, x + dx, y0, z + dz, SHKALA_SLAB, th, yw,
                               тон(0.80), тон(1.04), тон(0.93), тон(0.70)):
            d.polygon([(p[0], p[1]) for p in pts], fill=col)
    img.alpha_composite(lay)


def _число(value, доля):
    """Текущее значение счётчика и его подпись. Числом считаем то, что им
    является: «116 175» добегает, «каждый третий» показывается как есть."""
    цифры = re.sub(r"[^\d]", "", str(value or ""))
    if not цифры or len(цифры) > 12:
        return str(value or "").strip(), доля >= 1.0
    n = int(round(int(цифры) * доля))
    хвост = str(value).strip()
    # хвост вида «%», «млрд», «тыс.» сохраняем и дописываем к бегущему числу
    m = re.search(r"[\d\s ]+(.*)$", хвост)
    суф = (m.group(1).strip() if m else "")
    txt = f"{n:,}".replace(",", " ")          # тонкая шпация, не запятая
    return (txt + (" " + суф if суф else ""), доля >= 1.0)


def _плашка(value, доля, sub, bg, w=1040, h=470):
    """Тёмная плашка: мелкая строка сверху, крупное число цветом канала.
    Пока число бежит — у цифр вертикальный шлейф, как у табло."""
    img = Image.new("RGBA", (w, h), (66, 58, 48, 255))
    d = ImageDraw.Draw(img)
    d.rectangle([10, 10, w - 11, h - 11], fill=(26, 23, 20, 255))
    d.rectangle([0, 0, w - 1, h - 1], outline=(92, 82, 68, 255), width=3)
    if sub:
        fs = zc.font("Oswald-Bold.ttf", int(h * 0.23))
        txt = str(sub).strip().upper()
        while d.textlength(txt, font=fs) > w * 0.90 and fs.size > 16:
            fs = zc.font("Oswald-Bold.ttf", fs.size - 2)
        b = d.textbbox((0, 0), txt, font=fs)
        d.text(((w - (b[2] - b[0])) / 2 - b[0], h * 0.10 - b[1]), txt,
               font=fs, fill=(240, 238, 232, 255))
    txt, готово = _число(value, доля)
    fd = zc.font("Oswald-Bold.ttf", int(h * 0.50))
    while d.textlength(txt, font=fd) > w * 0.88 and fd.size > 24:
        fd = zc.font("Oswald-Bold.ttf", fd.size - 4)
    b = d.textbbox((0, 0), txt, font=fd)
    x = (w - (b[2] - b[0])) / 2 - b[0]
    y = h * 0.42 - b[1]
    цвет = (bg[0], bg[1], bg[2])
    if not готово:
        lay = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        ld = ImageDraw.Draw(lay)
        for i in range(-3, 4):
            ld.text((x, y + i * h * 0.035), txt, font=fd, fill=цвет + (70,))
        img.alpha_composite(lay)
        d.text((x, y), txt, font=fd, fill=цвет + (190,))
    else:
        d.text((x, y), txt, font=fd, fill=цвет + (255,))
    return img


def zal_shkala(out=None, t=None, text="", accent="", value="", value_sub="",
               source="", words=(), sheets=(), channel="", watermark="",
               dur=0.0, sfx=None, **_):
    """G15. Фраза (`text`) набирается по словам вверху, из пола растёт столб
    плит цвета канала, рядом едет вверх плашка, на которой добегает `value`.
    `value_sub` — мелкая строка над числом, `source` — откуда счёт."""
    tt = SHKALA_HERO if t is None else float(t)
    k = _темп(dur)
    bg, fg = цвета(channel)
    cam = zc.Cam(x=0.0, y=1.55, z=0.12 * tt)
    cam_l = zc.Cam(x=0.0, y=1.55, z=0.12 * SHKALA_T)
    img = zc.room(cam)
    _листы(img, cam, sheets)

    t0 = 0.25 * k
    длит = 1.95 * k
    доля = zc.clamp01(zc.seg(tt, t0, t0 + длит))
    доля = 1 - (1 - доля) * (1 - доля)              # outQuad, как на плёнке

    # --- фраза вверху: её низ задаёт потолок для столба и плашки ----------
    низ_фразы = SAFE * H
    строки = _строки(text, строк=2, знаков=18)
    if строки:
        hl = _маркер(строки, accent)
        шаг = min(0.16, 1.20 / max(1, len(" ".join(строки).split(" ")) - 1)) * k
        полн, cap_п, _ = _полный(строки, hl=hl, hl_color=bg, hl_ink=fg,
                                 step=шаг)
        cap_m = _вписать_блок(cam_l, полн, cap_п, 8.0, 0.86, 0.20)
        _, bh = _коробка_мира(cam_l, 8.0, полн.size[0] * cap_m / cap_п,
                              полн.size[1] * cap_m / cap_п)
        низ_фразы = SAFE * H + bh
        _bw, _ = _коробка_мира(cam_l, 8.0, полн.size[0] * cap_m / cap_п,
                               полн.size[1] * cap_m / cap_п)
        _отметить("фраза вверху", (W - _bw) / 2, SAFE * H, (W + _bw) / 2,
                  низ_фразы)
        tex, cap, _ = _блок(строки, tt, hl=hl, hl_color=bg, hl_ink=fg,
                            step=шаг, start=0.05 * k)
        if tex is not None:
            _место_блока(img, cam, tex, cap, cap_m, 8.0, 0.5, SAFE * H)
        for i in range(len(" ".join(строки).split(" "))):
            _ev(sfx, 0.05 * k + i * шаг, "label")

    # --- столб: высота считается от места между полом и низом фразы -------
    полная = _на_полу(cam_l, SHKALA_Z, SHKALA_SLAB / 2.4, 0.22, 0.52,
                      зазор_сверху=низ_фразы + 0.045 * H)
    x_столба = _в_мир(cam_l, 0.30 * W, 0.5 * H, SHKALA_Z)[0]
    _сw, _сh = _коробка_мира(cam_l, SHKALA_Z, SHKALA_SLAB, полная)
    _пол_с = _пол_на_экране(cam_l, SHKALA_Z)
    _отметить("столб", 0.30 * W - _сw / 2, _пол_с - _сh, 0.30 * W + _сw / 2,
              _пол_с)
    _ev(sfx, t0, "accent")
    if tt >= t0:
        _столб(img, cam, x_столба, SHKALA_Z, полная * доля, полная, bg)

    # --- плашка: едет вверх вместе с верхом столба ------------------------
    if tt >= t0 and (value or value_sub):
        тек = _плашка(value, доля, value_sub, bg)
        hp = _вписать(cam_l, SHKALA_Z - 0.1,
                      тек.size[0] / float(тек.size[1]), 0.34, 0.20)
        wp = hp * тек.size[0] / float(тек.size[1])
        верх_столба = полная * доля
        низ = max(0.26, верх_столба - hp * 1.25)
        низ += 0.35 * (1 - zc.out_cubic(zc.seg(tt, t0, t0 + 0.10)))
        cx = _в_мир(cam_l, 0.70 * W, 0.5 * H, SHKALA_Z - 0.1)[0]
        cy = низ + hp / 2.0
        # выше низа фразы плашка не поднимается — считаем в мире, а не на глаз
        потолок_мир = _в_мир(cam_l, 0.70 * W, низ_фразы + 0.03 * H,
                             SHKALA_Z - 0.1)[1] - hp / 2.0
        cy = min(cy, потолок_мир)
        _пw, _пh = _коробка_мира(cam_l, SHKALA_Z - 0.1, wp, hp)
        _вy = _zs._короб(cam_l, zc.quad((cx, cy, SHKALA_Z - 0.1), wp, hp))[1]
        _отметить("плашка", 0.70 * W - _пw / 2, _вy, 0.70 * W + _пw / 2,
                  _вy + _пh)
        zc.wire(img, cam, (cx - wp * 0.42, cy + hp / 2.0, SHKALA_Z - 0.1))
        zc.wire(img, cam, (cx + wp * 0.42, cy + hp / 2.0, SHKALA_Z - 0.1))
        zc.extrude(img, cam, zc.quad((cx, cy, SHKALA_Z - 0.1), wp, hp), тек,
                   depth=0.10, steps=4, shade=(40, 36, 30))
