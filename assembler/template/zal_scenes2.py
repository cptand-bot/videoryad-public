KUB_HERO = 2.3


def _постамент(img, cam, x, z, size=2.4, h=0.06):
    """Белая плита на полу под кубом, с мягкой тенью."""
    s = size / 2.0
    sh = [cam.proj(p) for p in ((x - s - .25, 0, z - s - .1),
                                (x + s + .25, 0, z - s - .1),
                                (x + s + .35, 0, z + s + .5),
                                (x - s - .35, 0, z + s + .5))]
    shl = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    ImageDraw.Draw(shl).polygon([(p[0], p[1]) for p in sh], fill=(60, 62, 66, 70))
    img.alpha_composite(shl.filter(ImageFilter.GaussianBlur(18)))
    lay = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(lay)
    top = [cam.proj(p) for p in ((x - s, h, z - s), (x + s, h, z - s),
                                 (x + s, h, z + s), (x - s, h, z + s))]
    front = [cam.proj(p) for p in ((x - s, h, z - s), (x + s, h, z - s),
                                   (x + s, 0, z - s), (x - s, 0, z - s))]
    d.polygon([(p[0], p[1]) for p in front], fill=(214, 216, 219, 255))
    d.polygon([(p[0], p[1]) for p in top], fill=(248, 248, 247, 255))
    img.alpha_composite(lay)


def zal_kub(out=None, t=None, text="", accent="", kick="", words=(), sheets=(),
            channel="", watermark="", dur=0.0, sfx=None, **_):
    """G11. Фраза (`text`) набирается по словам, слово `accent` — под
    маркером канала; фраза уезжает вверх, и с потолка на тросах спускается
    стеклянный куб. `kick` — короткая вторая фраза, приходит вместе с кубом.
    """
    k = _темп(dur)
    bg, fg = цвета(channel)
    строки = _строки(text, строк=3, знаков=15)
    hl = _маркер(строки, accent)
    n = len(" ".join(строки).split(" ")) if строки else 0
    шаг = min(0.18, 1.30 / max(1, n - 1)) * k
    уход = (0.10 * k + шаг * max(0, n - 1) + 0.45 * k)
    куб_в = уход + 0.05
    куб_дл = 0.27 * k
    tt = (куб_в + куб_дл + 0.25) if t is None else float(t)
    cam = zc.Cam(x=0.0, y=1.55, z=-0.06 * tt)
    cam_l = zc.Cam(x=0.0, y=1.55, z=-0.06 * KUB_T)
    img = zc.room(cam)
    _листы(img, cam, sheets)
    z_куб = 7.0
    _постамент(img, cam, 0.0, z_куб, size=2.4)

    if строки:
        tex, cap, _ = _блок(строки, tt, hl=hl, hl_color=bg, hl_ink=fg,
                            step=шаг, start=0.10 * k, align="left")
        if tex is not None and tt < уход + 0.30 * k:
            полн, cap_п, _ = _полный(строки, hl=hl, hl_color=bg,
                                     hl_ink=fg, step=шаг, align="left")
            cap_m = _вписать_блок(cam_l, полн, cap_п, 7.0, 0.74, 0.40)
            _bw, _bh = _коробка_мира(cam_l, 7.0, полн.size[0] * cap_m / cap_п,
                                     полн.size[1] * cap_m / cap_п)
            _отметить("фраза", 0.46 * W - _bw / 2, SAFE * H,
                      0.46 * W + _bw / 2, SAFE * H + _bh)
            u = zc.seg(tt, уход, уход + 0.23 * k)
            _строка_вверх = 4.2 * zc.clamp01(u) ** 2.0
            _место_блока(img, cam, tex, cap, cap_m, 7.0, 0.46, SAFE * H,
                         rise=_строка_вверх, blur_steps=4 if u > 0 else 0)
        for i in range(n):
            _ev(sfx, 0.10 * k + i * шаг, "label")
        _ev(sfx, уход, "whoosh")

    if kick:
        стр2 = _строки(kick, строк=1, знаков=20)
        tex2, cap2, _ = _блок(стр2, tt, step=0.10 * k, start=куб_в,
                              align="center")
        if tex2 is not None:
            полн2, cap2п, _ = _полный(стр2, step=0.10 * k, align="center")
            cap_m2 = _вписать_блок(cam_l, полн2, cap2п, 6.5, 0.66, 0.17)
            _bw, _bh = _коробка_мира(cam_l, 6.5, полн2.size[0] * cap_m2 / cap2п,
                                     полн2.size[1] * cap_m2 / cap2п)
            _отметить("вторая фраза", (W - _bw) / 2, SAFE * H,
                      (W + _bw) / 2, SAFE * H + _bh)
            _место_блока(img, cam, tex2, cap2, cap_m2, 6.5, 0.5, SAFE * H,
                         wires=0)

    img = zc.embers(img, cam, [(-0.26, 0.30, z_куб - 0.25, 0.62),
                               (0.0, 0.42, z_куб - 0.35, 0.55),
                               (0.26, 0.34, z_куб - 0.15, 0.48)], tt, glow=1.0)

    if tt >= куб_в:
        _ev(sfx, куб_в + куб_дл, "impact")
        u = zc.clamp01(zc.seg(tt, куб_в, куб_в + куб_дл)) ** 1.3
        # размер куба считается, а не берётся числом: он обязан сесть на
        # постамент и не упереться в верхнее поле кадра
        size = min(2.1, _вписать(cam_l, z_куб, 1.0, 0.34, 0.46))
        низ = 3.35 - (3.35 - 0.06) * u
        низ -= 0.02 * math.sin(zc.seg(tt, куб_в + куб_дл,
                                      куб_в + куб_дл + 0.1) * math.pi)
        # СТЕКЛО ПОДСВЕЧЕНО ЦВЕТОМ КАНАЛА (11.11, замер по пикселям: в
        # кадре-постере акцента канала было РОВНО НОЛЬ — первая фраза с
        # маркером к этому времени уезжает, и ПЛАНЕТА с «5 МИНУТ»
        # выглядели одинаково, чего он прямо требовал не допускать).
        zc.glass_cube(img, cam, (0.0, низ + size / 2.0, z_куб), size, tt,
                      tint=bg[:3])

    _знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


