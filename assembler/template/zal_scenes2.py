def _сч_плашка_база(label, образец, bg, w=1260):
    """Пустая плашка и мерки шрифтов. КЭШИРУЕТСЯ: от кадра зависит только
    само число, а подпись, кегли и ширина ячейки — нет.

    КЕГЛИ УЖИМАЮТСЯ ШРИФТОМ, А НЕ ПРИКИДЫВАЮТСЯ: русское слово-подпись
    («СОКРАЩЕНО») вчетверо длиннее английского `FRAME` образца, и на
    фиксированном кегле оно наехало бы на число. Поле подписи 7-41%
    ширины, поле числа 48-93% — они не пересекаются по построению.
    """
    ключ = (str(label), образец, tuple(bg[:3]), w)
    if ключ in _СЧ_ПЛАШКА:
        return _СЧ_ПЛАШКА[ключ]
    h = max(8, int(w * SCH_LH / SCH_LW))
    img = Image.new("RGBA", (w, h), (98, 98, 102, 255))
    d = ImageDraw.Draw(img)
    br = int(h * 0.075)
    d.rectangle([br, br, w - br - 1, h - br - 1], fill=(27, 27, 29, 255))
    подпись = str(label or "").strip().upper()
    f = zc.font("Oswald-Bold.ttf", int(h * 0.50))
    while подпись and d.textlength(подпись, font=f) > w * 0.34 and f.size > 14:
        f = zc.font("Oswald-Bold.ttf", f.size - 2)
    if подпись:
        bb = d.textbbox((0, 0), подпись, font=f)
        d.text((w * 0.07 - bb[0], (h - (bb[3] - bb[1])) / 2.0 - bb[1]),
               подпись, font=f, fill=CREAM)

    def мерки(fnt):
        cell = max(d.textlength(c, font=fnt) for c in "0123456789") * 1.16
        gap = cell * 0.55
        шир = 0.0
        for ch in образец:
            if ch.isdigit():
                шир += cell
            elif ch == " ":
                шир += gap
            else:
                шир += d.textlength(ch, font=fnt) * 1.10
        return cell, gap, шир

    fd = zc.font("Oswald-Bold.ttf", int(h * 0.56))   # цифры крупнее подписи
    cell, gap, шир = мерки(fd)
    while шир > w * 0.45 and fd.size > 18:
        fd = zc.font("Oswald-Bold.ttf", fd.size - 2)
        cell, gap, шир = мерки(fd)
    bd = d.textbbox((0, 0), "0123456789", font=fd)
    if len(_СЧ_ПЛАШКА) > 8:
        _СЧ_ПЛАШКА.clear()
    _СЧ_ПЛАШКА[ключ] = (img, fd, bd[1], bd[3] - bd[1], cell, gap)
    return _СЧ_ПЛАШКА[ключ]


def _сч_плашка(label, txt, образец, bg, roll):
    """Плашка с числом. Цифры стоят в ЯЧЕЙКАХ ОДНОЙ ШИРИНЫ — иначе число
    дёргается на каждом кадре, а оно меняется тридцать раз в секунду.
    `roll` ∈ [0,1) — насколько единицы укатились к следующей цифре: у
    катящейся цифры остаётся призрак предыдущей, как в одометре.
    """
    база, fd, ty, th, cell, gap = _сч_плашка_база(label, образец, bg)
    img = база.copy()
    d = ImageDraw.Draw(img)
    pw, ph = img.size
    цвет = tuple(bg[:3])

    def ширина(ch):
        if ch.isdigit():
            return cell
        if ch == " ":
            return gap
        return d.textlength(ch, font=fd) * 1.10

    полная = sum(ширина(ch) for ch in txt)
    x = pw * 0.715 - полная / 2.0
    y = (ph - th) / 2.0 - ty
    катится = max((i for i, c in enumerate(txt) if c.isdigit()), default=-1)
    for k, ch in enumerate(txt):
        wch = ширина(ch)
        if ch == " ":
            x += wch
            continue
        cw = d.textlength(ch, font=fd)
        cx = x + (wch - cw) / 2.0
        if k == катится and roll > 0:
            prev = str((int(ch) - 1) % 10)
            lay = Image.new("RGBA", img.size, (0, 0, 0, 0))
            ld = ImageDraw.Draw(lay)
            ld.text((cx, y + th * 0.10 * roll), ch, font=fd, fill=цвет + (255,))
            gh = Image.new("RGBA", img.size, (0, 0, 0, 0))
            ImageDraw.Draw(gh).text((cx, y - th * 0.12 * roll), prev, font=fd,
                                    fill=цвет + (int(255 * 0.8 * roll),))
            lay.alpha_composite(gh)
            img.alpha_composite(lay.filter(
                ImageFilter.GaussianBlur(max(1.0, th * 0.025))))
        else:
            d.text((cx, y), ch, font=fd, fill=цвет + (255,))
        x += wch
    return img


def _сч_пятно(img, cam, cx, z0, z1, hw, alpha=64):
    """Мягкое пятно тени на полу под висящей панелью."""
    tex = Image.new("RGBA", (300, 160), (0, 0, 0, 0))
    ImageDraw.Draw(tex).rounded_rectangle([30, 20, 270, 140], 50,
                                          fill=(38, 40, 44, alpha))
    tex = tex.filter(ImageFilter.GaussianBlur(22))
    pts = [(cx - hw, 0.01, z1), (cx + hw, 0.01, z1),
           (cx + hw, 0.01, z0), (cx - hw, 0.01, z0)]
    if min(p[2] for p in pts) - cam.z < 0.5:
        return
    zc.paste_quad(img, tex, [cam.proj(p) for p in pts])


def zal_schetchik(out=None, t=None, text="", accent="", value="",
                  value_sub="", sheets=(), channel="", watermark="",
                  dur=0.0, sfx=None, **_):
    """G17. Панель висит на тросах, камера отъезжает от неё в упор назад
    (3,5 → 7,9 м), под панелью на коротких тросах качается плашка, и на
    плашке ЧИСЛО РАСТЁТ НА ЕДИНИЦУ В КАЖДЫЙ КАДР.

    `text` — фраза сцены: первая её часть висит на тросах над панелью,
    вторая СТОИТ НА ПОЛУ цветом канала. `accent` — слово верхней строки под
    маркером канала; оно же идёт подписью на плашке (`value_sub` подпись
    перебивает). `value` — значение счётчика: ровно это число стоит на
    постере, до него счётчик добегает и дальше продолжает считать.
    """
    k = _темп(dur)
    tt = SCH_HERO * k if t is None else float(t)
    bg, fg = цвета(channel)
    cam = zc.Cam(x=0.0, y=1.55, z=SCH_Z - _сч_дальность(tt))
    cam_l = zc.Cam(x=0.0, y=1.55, z=SCH_Z - SCH_D1)
    img = zc.room(cam)
    _листы(img, cam, sheets)

    строки = _строки(text, строк=2, знаков=15)
    верх = строки[:1]
    низ = строки[1:2]
    z_в, z_п = SCH_Z - 0.3, SCH_Z

    # --- верхняя строка: висит на тросах над панелью ----------------------
    низ_верхней = SAFE * H
    if верх:
        пл = _плитки(верх, hl=_маркер(верх, accent), color=INK, hl_color=bg,
                     hl_ink=fg)
        tw, th = _ширина_строки(пл)
        h = _вписать(cam_l, z_в, tw / th, 0.78, 0.13, depth_rel=0.08)
        s = h / th
        bw, bh = _коробка_мира(cam_l, z_в, tw * s, th * s, depth=h * 0.08)
        cx, cy = _в_мир(cam_l, 0.5 * W, SAFE * H + bh / 2.0, z_в)
        низ_верхней = SAFE * H + bh
        _отметить("верхняя строка", (W - bw) / 2, SAFE * H, (W + bw) / 2,
                  низ_верхней)
        старты = [(0.10 + i * STEP) * k for i in range(len(пл[2]))]
        for st in старты:
            _ev(sfx, st, "label")
        _строка_слов(img, cam, tt, пл, (cx, cy, z_в), 0.0, s, старты,
                     depth=h * 0.08, side=INK_SIDE, hang=True)

    # --- строка на полу: её линия пола задаёт нижнюю полосу кадра ---------
    # Глубина ВЫЧИСЛЯЕТСЯ из нужной высоты в кадре (`_глубина_пола`), а не
    # задаётся метрами: иначе строка уехала бы на знак канала или вверх, на
    # плашку. Тот же механизм, что у подписей макетов (разбор 11.11).
    # НИЗ СЦЕНЫ — ВЫШЕ ПОЛОСЫ СУБТИТРОВ (13.11, пункт 0-В): было 982, и
    # подпись плашки «ОТСЧЕТ» садилась на 881-987, прямо под титр.
    пол_низ = min(SUB_Y - 8, (1 - SAFE) * H - 6, H - SCH_НИЗ)
    z_н = _глубина_пола(cam_l, пол_низ)
    # НЕТ НИЖНЕЙ СТРОКИ — ПОЛОСУ ПОД НЕЁ НЕ ДЕРЖИМ (11.11, по кадру: на
    # фразе в одно слово нижняя четверть кадра оставалась пустой, а панель
    # зря ужималась). Дверь о коротком тексте предупреждает, но кадр
    # обязан быть собранным и в этом случае.
    верх_пола = (пол_низ - 0.17 * H) if низ else пол_низ

    # --- панель и плашка: считаем ОДНОЙ группой --------------------------
    # Группа = панель + зазор + плашка. Вписываем её коробку целиком, потом
    # раздаём высоты по пропорциям: панель не может «не заметить» плашку,
    # висящую под ней, а плашка — уехать на строку на полу.
    гw = max(SCH_PW, SCH_LW)
    гh = SCH_PH + SCH_GAP + SCH_LH
    верх_группы = низ_верхней + 0.03 * H
    доля_h = max(0.10, (верх_пола - 0.025 * H - верх_группы) / H)
    Hг = _вписать(cam_l, z_п, гw / гh, 0.52, доля_h)
    пан_h = Hг * SCH_PH / гh
    пан_w = пан_h * SCH_PW / SCH_PH
    пл_h = Hг * SCH_LH / гh
    пл_w = пл_h * SCH_LW / SCH_LH
    зазор = Hг * SCH_GAP / гh
    _гw, _гh = _коробка_мира(cam_l, z_п, гw * Hг / гh, Hг)
    _, гy = _в_мир(cam_l, 0.5 * W, верх_группы + _гh / 2.0, z_п)
    верх_мира = гy + Hг / 2.0                 # мировая высота верха группы

    _пw, _пh = _коробка_мира(cam_l, z_п, пан_w, пан_h)
    _отметить("панель", (W - _пw) / 2, верх_группы, (W + _пw) / 2,
              верх_группы + _пh)
    _лw, _лh = _коробка_мира(cam_l, z_п, пл_w, пл_h)
    _зазор_px = _коробка_мира(cam_l, z_п, пл_w, зазор)[1]
    _отметить("плашка", (W - _лw) / 2, верх_группы + _пh + _зазор_px,
              (W + _лw) / 2, верх_группы + _пh + _зазор_px + _лh)

    # панель вытягивается тросами, пока камера отъезжает (снято по пяти кадрам)
    f = _сч_ход(tt / max(1e-6, k))
    pH = пан_h * (SCH_STRETCH + (1.0 - SCH_STRETCH) * f)
    pY = верх_мира - pH / 2.0
    _сч_пятно(img, cam, 0.3, z_п - 0.4, z_п + 2.6, пан_w * 0.75)
    for xx in (-пан_w * 0.27, пан_w * 0.27):
        zc.wire(img, cam, (xx, pY + pH / 2.0, z_п),
                color=(96, 98, 102, 230), width=3)
    zc.extrude(img, cam, zc.quad((0.0, pY, z_п), пан_w, pH), _сч_панель(bg),
               depth=0.10, steps=4, shade=(70, 70, 74))

    # --- плашка со счётчиком ---------------------------------------------
    # СЧЁТЧИК ДОБЕГАЕТ ДО `value` И ТАМ ОСТАЁТСЯ, А НЕ СЧИТАЕТ БЕСКОНЕЧНО.
    # Шаг приёма сохранён дословно — +1 на КАЖДЫЙ кадр, тридцать в секунду,
    # — но посадка обязательна: покадрово рисуется 2,6 с из девяти, дальше
    # кадр застывает, и бесконечный счёт оставил бы в кадре на шесть секунд
    # ЧУЖОЕ число (116 199 вместо 116 175). На экране должна стоять та
    # цифра, которую написала вкладка, — и на постере, и в хвосте.
    i_кадр = int(round(tt * SCH_FPS))
    i_посадки = int(round(SCH_HERO * k * SCH_FPS))
    сдвиг = min(0, i_кадр - i_посадки)
    образец, _ = _сч_число(value, 0)
    txt, бежит = _сч_число(value, сдвиг)
    roll = 0.42 if (бежит and сдвиг < 0 and i_кадр % 2) else 0.0
    тек = _сч_плашка(value_sub or accent or (верх[0].split()[-1] if верх else ""),
                     txt, образец, bg, roll)
    зп = SCH_GAP0 + (SCH_GAP - SCH_GAP0) * f
    пл_y = pY - pH / 2.0 - зп * (пл_h / SCH_LH) - пл_h / 2.0
    for xx in (-пл_w * 0.34, пл_w * 0.34):
        a_ = cam.proj((xx, pY - pH / 2.0, z_п))
        b_ = cam.proj((xx, пл_y + пл_h / 2.0, z_п))
        ImageDraw.Draw(img, "RGBA").line([(a_[0], a_[1]), (b_[0], b_[1])],
                                         fill=(90, 92, 96, 230), width=2)
    zc.extrude(img, cam, zc.quad((0.0, пл_y, z_п), пл_w, пл_h), тек,
               depth=0.12, steps=4, shade=(72, 72, 76))
    _ev(sfx, 0.0, "whoosh")
    if бежит:
        _ev(sfx, 0.70 * k, "accent")

    if низ:
        пл2 = _плитки(низ, color=bg, vertical=True, разрядка=0.08)
        tw2, th2 = _ширина_строки(пл2)
        h2 = _на_полу(cam_l, z_н, tw2 / th2, 0.78, 0.17,
                      зазор_сверху=верх_группы + _гh + 0.025 * H,
                      depth_rel=0.17)
        s2 = h2 / th2
        глуб = h2 * 0.17
        bw2, bh2 = _коробка_мира(cam_l, z_н, tw2 * s2, th2 * s2, depth=глуб)
        _отметить("строка на полу", (W - bw2) / 2, пол_низ - bh2,
                  (W + bw2) / 2, пол_низ)
        старты = [(0.85 + i * 0.22) * k for i in range(len(пл2[2]))]
        for st in старты:
            _ev(sfx, st, "accent")
        _строка_слов(img, cam, tt, пл2, (0.0, 0.0, z_н), 0.0, s2, старты,
                     depth=глуб, side=tuple(int(c * 0.76) for c in bg[:3]),
                     floor=True, shadow=True)

    _знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


