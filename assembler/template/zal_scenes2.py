def zal_slova(out=None, t=None, text="", na_polu="", accent="", words=(),
              sheets=(), channel="", watermark="", dur=0.0, sfx=None, **_):
    """G02. Верхняя строка (`text`) висит на тросах тёмным объёмом, нижняя
    (`na_polu`) стоит НА ПОЛУ цветом канала. Слова встают по одному.
    `accent` — слово верхней строки под маркером канала.

    Возвращает RGB-кадр 1920×1080 (этого ждёт `style_cards.render_anim`).
    """
    tt = SLOVA_HERO if t is None else float(t)
    k = _темп(dur)
    bg, fg = цвета(channel)
    cam = zc.Cam(x=0.0, y=1.52, z=0.30 * tt)
    cam_l = zc.Cam(x=0.0, y=1.52, z=0.30 * SLOVA_T)
    img = zc.room(cam)
    _листы(img, cam, sheets)

    верх = _строки(text, строк=2, знаков=16)
    низ = _строки(na_polu or (words[0] if words else ""), строк=1, знаков=14)
    z_в, z_н = 10.4, 9.0
    yaw_в, yaw_н = math.radians(6.0), math.radians(-12.0)

    низ_верхней = SAFE * H
    if верх:
        пл = _плитки(верх, hl=_маркер(верх, accent), color=INK, hl_color=bg,
                     hl_ink=fg)
        tw, th = _ширина_строки(пл)
        h = _вписать(cam_l, z_в, tw / th, 0.80, 0.26, yaw=yaw_в)
        s = h / th
        bw, bh = _коробка_мира(cam_l, z_в, tw * s, th * s, yaw=yaw_в)
        cx, cy = _в_мир(cam_l, 0.5 * W, SAFE * H + bh / 2.0, z_в)
        низ_верхней = SAFE * H + bh
        _отметить("верхняя строка", (W - bw) / 2, SAFE * H, (W + bw) / 2,
                  низ_верхней)
        старты = [i * STEP * k for i in range(len(пл[2]))]
        for st in старты:
            _ev(sfx, st, "label")
        _строка_слов(img, cam, tt, пл, (cx, cy, z_в), yaw_в, s, старты,
                     depth=0.16, side=INK_SIDE, hang=True)

    if низ:
        # ГЛУБИНА ОБЪЁМА — ДОЛЯ ВЫСОТЫ БУКВ, А НЕ ЧИСЛО В МЕТРАХ (11.11, по
        # кадру): полметра на букве высотой 0,9 м давало слитную синюю массу
        # вместо слов. 0,17 высоты читается как объём и не склеивает соседей.
        пл = _плитки(низ, color=bg, vertical=True, разрядка=0.07)
        tw, th = _ширина_строки(пл)
        h = _на_полу(cam_l, z_н, tw / th, 0.80, 0.34, yaw=yaw_н,
                     зазор_сверху=низ_верхней + 0.035 * H, depth_rel=0.17)
        s = h / th
        глуб = h * 0.17
        bw2, bh2 = _коробка_мира(cam_l, z_н, tw * s, th * s, yaw=yaw_н,
                                 depth=глуб)
        пол = _пол_на_экране(cam_l, z_н)
        _отметить("нижняя на полу", (W - bw2) / 2, пол - bh2, (W + bw2) / 2, пол)
        t0 = 0.55 * k
        старты = [t0 + i * 0.22 * k for i in range(len(пл[2]))]
        for st in старты:
            _ev(sfx, st, "accent")
        _строка_слов(img, cam, tt, пл, (0.0, 0.0, z_н), yaw_н, s, старты,
                     depth=глуб, side=tuple(int(c * 0.76) for c in bg[:3]),
                     floor=True, shadow=True)

    # УГЛЕЙ В ЭТОЙ СЦЕНЕ НЕТ (11.11, его правка по кадру: горсть ложилась на
    # последнюю букву нижней строки и съедала её). Отодвинуть их некуда:
    # строка на полу идёт почти во всю ширину кадра, а угли живут на полу
    # же. В образце угли и есть только у приёма с плитами (G10 → zal_pol),
    # у G02 их не было — возвращаемся к образцу.
    _знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


