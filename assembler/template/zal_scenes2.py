def _темп(dur, полное=2.4):
    """Коэффициент сжатия времён сцены под её ДЛИТЕЛЬНОСТЬ.

    Покадрово рисуется min(2,6 с, длительность сцены), дальше кадр не
    перерисовывается. На сцене короче окна движение обязано уложиться в
    него целиком — иначе куб не сядет, макет не упадёт, число не добежит,
    а прогон отчитается успехом (класс «успех значит ничего не сделано»).
    """
    окно = min(полное, float(dur)) if dur else полное
    return max(0.35, окно / полное)


