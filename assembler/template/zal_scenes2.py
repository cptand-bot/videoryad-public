def _сч_ход(t):
    """Ход отъезда 0→1: `1−exp(−8,8·t^1,7)` — снято с плёнки по пяти кадрам
    (ширина панели 87% → 76% → 59% → 47% → 40% → 39% и стоп)."""
    if t <= 0:
        return 0.0
    return 1.0 - math.exp(-8.8 * (t ** 1.7))


def _сч_дальность(t):
    """Дальность камеры до панели: быстрый отъезд с остановкой к 0,7 с и
    еле заметный дрейф дальше (на плёнке он есть)."""
    return (SCH_D0 + (SCH_D1 - SCH_D0) * _сч_ход(t)
            + 0.02 * max(0.0, t - 0.8))


