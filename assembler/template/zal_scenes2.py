def _падение(t0, t, dur=0.10, hfrom=3.6):
    """Падение с потолка: три кадра разгона, посадка с коротким приседом.
    Возвращает (высота над полом, смаз, присед) или None."""
    if t < t0 - 1e-6:
        return None
    u = zc.seg(t, t0, t0 + dur)
    dy = hfrom * (1 - u * u)
    smear = (1 - u) * 0.9 if u < 1 else 0.0
    sq = 0.0
    if u >= 1:
        b = zc.seg(t, t0 + dur, t0 + dur + 0.10)
        sq = 0.06 * math.sin(b * math.pi)
    return dy, smear, sq


def _макет_тек(kind):
    """Готовый макет с подложкой — КЭШИРОВАННЫЙ: от кадра он не зависит,
    а размытие альфы стоит дороже всей остальной отрисовки макета."""
    ключ = ("макет", kind)
    if ключ in _ТЕКСТУРЫ:
        return _ТЕКСТУРЫ[ключ]
    tex = zc.maket_tex(kind, 480)
    if kind == "power":
        r_, g_, b_, a_ = tex.split()
        tex = Image.merge("RGBA", (r_.point(lambda v: v * 0.45),
                                   g_.point(lambda v: v * 0.45),
                                   b_.point(lambda v: v * 0.45), a_))
    else:
        # белый объём на белом фоне без подложки сливается со стеной
        under = Image.new("RGBA", tex.size, (0, 0, 0, 0))
        a_ = tex.split()[3].filter(ImageFilter.GaussianBlur(3))
        sh = Image.new("RGBA", tex.size, (150, 154, 160, 255))
        sh.putalpha(a_)
        under.alpha_composite(sh, (4, 5))
        under.alpha_composite(tex)
        tex = under
    _ТЕКСТУРЫ[ключ] = tex
    return tex


def _макет(img, cam, t, kind, x, z, size, t0):
    r = _падение(t0, t)
    if r is None:
        return
    dy, smear, sq = r
    tex = _макет_тек(kind)
    h = size * (1 - sq)
    w = size * (1 + sq * 0.6)
    c = zc.quad((x, dy + h / 2.0, z), w, h)
    if not _видно(cam, c):
        return
    if dy < 0.02:
        a_ = tex.split()[3].point(lambda v: int(v * 0.22))
        dark = Image.new("RGBA", tex.size, (40, 40, 42, 255))
        dark.putalpha(a_)
        sh = [(x - w / 2 + 0.5, 0.01, z + 0.6), (x + w / 2 + 0.5, 0.01, z + 0.6),
              (x + w / 2, 0.01, z), (x - w / 2, 0.01, z)]
        zc.paste_quad(img, dark.filter(ImageFilter.GaussianBlur(12)),
                      [cam.proj(p) for p in sh])
    if smear > 0:
        for kk in (0.35, 0.7):
            cc = zc.quad((x, dy + h / 2.0 + smear * kk * 1.2, z), w, h)
            zc.paste_quad(img, tex, [cam.proj(p) for p in cc], 0.30)
    if kind == "power":
        zc.paste_quad(img, tex, [cam.proj(p) for p in c])
    else:
        _объём(img, cam, c, tex, 0.30, (0.0, 0.0, 1.0), steps=5,
               side=(170, 174, 180))


def zal_makety(out=None, t=None, text="", accent="", makety=(), words=(),
               sheets=(), channel="", watermark="", dur=0.0, sfx=None, **_):
    """G12. Заголовок (`text`) висит на тросах, слово `accent` — под маркером
    канала; с потолка падают белые макеты и под каждым встаёт его подпись.

    `makety` — список «вид=ПОДПИСЬ» (вид: банк, больница, лэп), 1-3 штуки.
    """
    tt = MAKETY_HERO if t is None else float(t)
    k = _темп(dur)
    bg, fg = цвета(channel)
    cam = zc.Cam(x=0.0, y=1.55, z=0.18 * tt)
    cam_l = zc.Cam(x=0.0, y=1.55, z=0.18 * MAKETY_T)
    img = zc.room(cam)
    _листы(img, cam, sheets)

    # --- разбор задания: «вид=подпись» ------------------------------------
    пары = []
    for i, s in enumerate([str(x).strip() for x in (makety or ()) if str(x).strip()][:3]):
        if "=" in s:
            вид, подпись = s.split("=", 1)
        elif ":" in s:
            вид, подпись = s.split(":", 1)
        else:
            вид, подпись = "", s
        kind = ВИДЫ_МАКЕТОВ.get(вид.strip().lower(),
                                ("bank", "hospital", "power")[i % 3])
        пары.append((kind, подпись.strip().upper()))
    n = max(1, len(пары))

    # --- заголовок --------------------------------------------------------
    низ_заголовка = SAFE * H
    строки = _строки(text, строк=2, знаков=18)
    if строки:
        hl = _маркер(строки, accent)
        пл = _плитки(строки, hl=hl, color=(30, 27, 26, 255), hl_color=bg,
                     hl_ink=fg)
        tw, th = _ширина_строки(пл)
        z_в = 11.0
        h = _вписать(cam_l, z_в, tw / th, 0.82, 0.24)
        s = h / th
        bw, bh = _коробка_мира(cam_l, z_в, tw * s, th * s)
        cx, cy = _в_мир(cam_l, 0.5 * W, SAFE * H + bh / 2.0, z_в)
        низ_заголовка = SAFE * H + bh
        _отметить("заголовок", (W - bw) / 2, SAFE * H, (W + bw) / 2,
                  низ_заголовка)
        старты = [i * 0.09 * k for i in range(len(пл[2]))]
        for st in старты:
            _ev(sfx, st, "label")
        _строка_слов(img, cam, tt, пл, (cx, cy, z_в), 0.0, s, старты,
                     depth=0.14, side=(18, 16, 15), hang=True, k0=1.10)

    # --- макеты: размер и места СЧИТАЮТСЯ от числа макетов -----------------
    # ПОДПИСЬ СТОИТ НИЖЕ ЗДАНИЯ, А НЕ ПОВЕРХ НЕГО (11.11, его правка по
    # кадру: «БАНКИ» перекрывало колонны, «ЭНЕРГОСЕТИ» — опоры ЛЭП).
    # Раньше подпись ставилась на 0,7 м ближе макета — на экране это те же
    # 17 пикселей ниже его основания, то есть буквы ложились на цоколь.
    # Теперь глубина подписи ВЫЧИСЛЯЕТСЯ: её линия пола должна прийтись на
    # низ кадра, а верх букв — ниже основания здания с зазором. Не хватает
    # места по высоте — ужимаем МАКЕТ, а не наезжаем подписью.
    доля = (0.86 / n) * 0.90
    есть_подписи = any(п for _k, п in пары)
    размер = _на_полу(cam_l, MAKETY_Z, 1.0, доля, 0.44,
                      зазор_сверху=низ_заголовка + 0.03 * H)
    # ПОДПИСЬ НЕ СЯДЕТ НА ЗНАК КАНАЛА (он рисуется по y = H-62): низ строки
    # поднят над ним, иначе «БАНКИ» и «ПЛАНЕТА» стояли бы вплотную.
    # ПОДПИСЬ МАКЕТА НЕ ЛЕЗЕТ В ПОЛОСУ СУБТИТРОВ (13.11, пункт 0-В):
    # было 982, замер по кадру — ДЕНЬГИ/ЭНЕРГОСЕТИ/ЗИМА на 863-984.
    низ_подписи = min(SUB_Y - 8, (1 - SAFE) * H - 6, H - 92)
    z_подписи = _глубина_пола(cam_l, низ_подписи)
    пол_подписи = низ_подписи
    ЗАЗОР = 0.022 * H
    ПОЛОСА = 0.085 * H                       # сколько нужно подписи по высоте
    for _ in range(4):
        пол_макета = _пол_на_экране(cam_l, MAKETY_Z)
        верх_макета = пол_макета - _коробка_мира(cam_l, MAKETY_Z,
                                                 размер, размер)[1]
        место = низ_подписи - (пол_макета + ЗАЗОР)
        if not есть_подписи or место >= ПОЛОСА or размер < 0.4:
            break
        размер *= max(0.55, 1.0 - (ПОЛОСА - место) / max(1.0, пол_макета))
    верх_макета = _пол_на_экране(cam_l, MAKETY_Z) - \
        _коробка_мира(cam_l, MAKETY_Z, размер, размер)[1]
    верх_подписи = _пол_на_экране(cam_l, MAKETY_Z) + ЗАЗОР
    for i, (kind, подпись) in enumerate(пары):
        x_доля = МЕСТА[n][i]
        x = _в_мир(cam_l, x_доля * W, 0.5 * H, MAKETY_Z)[0]
        _mw, _mh = _коробка_мира(cam_l, MAKETY_Z, размер, размер)
        _пол_м = _пол_на_экране(cam_l, MAKETY_Z)
        _отметить("макет %d" % (i + 1), x_доля * W - _mw / 2, _пол_м - _mh,
                  x_доля * W + _mw / 2, _пол_м)
        t0 = (0.13 + i * 0.40) * k
        _ev(sfx, t0 + 0.10, "impact")
        _макет(img, cam, tt, kind, x, MAKETY_Z, размер, t0)
        if not подпись:
            continue
        пл = _плитки([подпись], color=(34, 31, 30, 255), vertical=True)
        tw, th = _ширина_строки(пл)
        # ширина — своя доля кадра, высота — РОВНО полоса между основанием
        # здания (плюс зазор) и нижним полем кадра
        hp = _на_полу(cam_l, z_подписи, tw / th, доля * 0.92,
                      max(0.03, (пол_подписи - верх_подписи) / H),
                      depth_rel=0.16)
        sp = hp / th
        xp = _в_мир(cam_l, x_доля * W, 0.5 * H, z_подписи)[0]
        _pw, _ph = _коробка_мира(cam_l, z_подписи, tw * sp, th * sp,
                                 depth=hp * 0.16)
        _отметить("подпись %d" % (i + 1), x_доля * W - _pw / 2,
                  пол_подписи - _ph, x_доля * W + _pw / 2, пол_подписи)
        старты = [t0 + (0.14 + j * 0.10) * k for j in range(len(пл[2]))]
        _строка_слов(img, cam, tt, пл, (xp, 0.0, z_подписи), 0.0, sp, старты,
                     depth=hp * 0.16, side=(20, 18, 17), floor=True,
                     shadow=True)

    _знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


