def _екр_слова(say, tt, шаг):
    """Какие слова реплики уже видны к моменту `tt` (от заполнения кадра)."""
    слова = [w for w in str(say or "").split() if w]
    return [w for i, w in enumerate(слова) if tt >= 0.27 + i * шаг]


def _екр_оформление(tt, text, say, author, role, source, bg, шаг, карта=None):
    """Оформление эфира поверх картинки. `tt` — время от заполнения кадра
    (до него отрицательное: субтитра нет, плашка ещё не въехала).

    Поля НЕ ДУБЛИРУЮТСЯ: шапка слева — `source` (где и когда), логотип
    справа — рубрика «ПРЯМОЙ ЭФИР», низ — имя и должность, субтитр — сама
    реплика. Фраза сцены (`text`) живёт в ЗАЛЕ и сюда не попадает: в
    возврате зал и панель видны одновременно, и один текст стоял бы дважды.
    """
    w, h = W, H
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    x0 = w * EKR_КРАЙ
    прав = w * (1 - EKR_КРАЙ)

    def тень(xy, txt, f, fill, r=2):
        x, y = xy
        for dx, dy in ((r, r), (-r, r), (r, -r), (-r, -r), (0, r + 1)):
            d.text((x + dx, y + dy), txt, font=f, fill=(0, 0, 0, 160))
        d.text((x, y), txt, font=f, fill=fill)

    # --- шапка слева: вертикаль гаммы канала и источник ------------------
    ист = str(source or "").strip()
    if ист:
        d.rectangle([x0, h * 0.072, x0 + 9, h * 0.150],
                    fill=tuple(bg[:3]) + (255,))
        fs = zc.font("Oswald-Bold.ttf", 52)
        while d.textlength(ист, font=fs) > w * 0.40 and fs.size > 18:
            fs = zc.font("Oswald-Bold.ttf", fs.size - 2)
        b = d.textbbox((0, 0), ист, font=fs)
        тень((x0 + 26, h * 0.085 - b[1]), ист, fs, (255, 255, 255, 255))
    if карта is not None:
        карта.append(("шапка эфира", x0, h * 0.072, x0 + 26 + w * 0.40,
                      h * 0.150))

    # --- логотип справа: рубрика двумя словами ---------------------------
    fb = zc.font("Oswald-Bold.ttf", 78)
    _лево = прав
    for i, слово in enumerate(("ПРЯМОЙ", "ЭФИР")):
        tw = d.textlength(слово, font=fb)
        _лево = min(_лево, прав - tw)
        тень((прав - tw, h * 0.070 + i * h * 0.078), слово, fb,
             (255, 255, 255, 255) if i == 0 else tuple(bg[:3]) + (255,), r=3)
    if карта is not None:
        карта.append(("логотип эфира", _лево, h * 0.070, прав, h * 0.070
                      + h * 0.078 + 78))

    # --- нижняя плашка: имя и должность, шторкой слева -------------------
    kk = zc.clamp01(zc.seg(tt, EKR_ШТОРКА[0], EKR_ШТОРКА[1]))
    if kk > 0:
        лэй = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        ld = ImageDraw.Draw(лэй)
        # ПЛАШКА ПОДНЯТА ДО 0,776 (11.11, по кадру): на 0,800 её нижняя
        # полоса ложилась ровно на знак канала в левом нижнем углу.
        # И ЕЩЁ ВЫШЕ — ИЗ-ПОД СУБТИТРОВ (13.11, пункт 0-В): имя и должность
        # сидели на 899, то есть в полосе субтитров (ниже 886).
        y0 = h * 0.670
        ld.rectangle([0, y0, w * 0.215, y0 + h * 0.062],
                     fill=tuple(bg[:3]) + (255,))
        _ч = (26, 26, 30, 255) if sum(bg[:3]) > 420 else (255, 255, 255, 255)
        fr = zc.font("Oswald-Bold.ttf", 38)
        ld.text((x0, y0 + h * 0.008), "ИНТЕРВЬЮ", font=fr, fill=_ч)
        ld.rectangle([0, y0 + h * 0.062, w * 0.86, y0 + h * 0.128],
                     fill=(246, 247, 250, 255))
        ld.rectangle([0, y0 + h * 0.128, w * 0.86, y0 + h * 0.146],
                     fill=tuple(bg[:3]) + (255,))
        имя = str(author or "").strip().upper()
        fn = zc.font("ArialBlack.ttf", 44)
        while имя and ld.textlength(имя, font=fn) > w * 0.30 and fn.size > 16:
            fn = zc.font("ArialBlack.ttf", fn.size - 2)
        ld.text((x0, y0 + h * 0.072), имя, font=fn, fill=(26, 26, 30, 255))
        xч = x0 + max(w * 0.20, ld.textlength(имя, font=fn)) + w * 0.014
        долж = str(role or "").strip()
        if долж:                      # без должности черта делила бы пустоту
            ld.line([(xч, y0 + h * 0.068), (xч, y0 + h * 0.124)],
                    fill=(120, 122, 130, 255), width=3)
        fo = zc.font("Oswald-Bold.ttf", 46)
        while долж and ld.textlength(долж, font=fo) > (w * 0.86 - xч - w * 0.02) \
                and fo.size > 16:
            fo = zc.font("Oswald-Bold.ttf", fo.size - 2)
        ld.text((xч + w * 0.016, y0 + h * 0.072), долж, font=fo,
                fill=(26, 26, 30, 255))
        срез = int(w * 0.86 * zc.out_cubic(kk))
        маска = Image.new("L", (w, h), 0)
        ImageDraw.Draw(маска).rectangle([0, 0, срез, h], fill=255)
        лэй.putalpha(Image.fromarray(np.minimum(
            np.asarray(лэй.split()[3]), np.asarray(маска))))
        img.alpha_composite(лэй)
        if карта is not None:
            # МЕРИМ ТЕКСТ, А НЕ ПОЛОСУ. Полоса плашки нарочно уходит в левый
            # край (так она и устроена в эфире), и её обрез не виден; текст
            # обрезать нельзя, поэтому в замер идут буквы, а не подложка.
            _пр = xч + w * 0.016 + (ld.textlength(долж, font=fo) if долж else 0)
            карта.append(("плашка имени", x0, y0 + h * 0.062,
                          max(_пр, x0 + w * 0.20), y0 + h * 0.128))

    # --- субтитр: слова по одному, перенос ПО МЕРКЕ ШРИФТА ---------------
    видны = _екр_слова(say, tt, шаг)
    if видны:
        f = zc.font("Arimo-Bold.ttf", 44)
        поле = прав - x0
        строки, тек = [], ""
        for wd in видны:
            проба = (тек + " " + wd).strip()
            if d.textlength(проба, font=f) > поле and тек:
                строки.append(тек)
                тек = wd
            else:
                тек = проба
        строки.append(тек)
        строки = строки[-4:]            # ниже четвёртой начинается плашка
        b = d.textbbox((0, 0), "Ру", font=f)
        # СТРОКИ РАСТУТ ВВЕРХ ОТ ПЛАШКИ, А НЕ ВНИЗ ОТ СЕРЕДИНЫ: субтитр
        # стоит там же, где в эфире, и короткая реплика не висит посреди
        # кадра. Якорь — низ последней строки, он же потолок плашки.
        верх = h * 0.700 - (len(строки) - 1) * h * 0.058
        y = верх - b[1]
        for ln in строки:
            тень((x0, y), ln, f, (255, 255, 255, 255))
            y += h * 0.058
        if карта is not None:
            карта.append(("субтитр", x0, верх, прав, h * 0.700 + h * 0.048))
    return img


def _екр_эфир(tt, text, say, author, role, source, bg, шаг, карта=None):
    """Кадр эфира целиком: студия, дыхание силуэта и оформление."""
    задник, силуэт = _екр_студия(bg)
    img = задник.copy()
    # ДЫХАНИЕ СИЛУЭТА ЗАМЕТНО НА СОСЕДНИХ КАДРАХ (11.11, замер): на прежних
    # 4 px и 1,3 рад/с смещение менялось меньше чем на полпикселя в кадр,
    # округлялось в то же целое, и первые кадры полного экрана выходили
    # ПОБАЙТНО одинаковыми — экран стоял мёртвым, пока не пришло первое
    # слово субтитра.
    dx = int(round(6 * math.sin(tt * 2.6)))
    dy = int(round(3 * math.sin(tt * 1.7 + 1.0)))
    img.alpha_composite(силуэт, (dx, dy))
    img.alpha_composite(_екр_оформление(tt, text, say, author, role, source,
                                        bg, шаг, карта=карта))
    return img


def _екр_времена(k):
    """(старт разворота, конец разворота, старт возврата, конец возврата)."""
    t0 = EKR_T0 * k
    t1 = t0 + EKR_IN * k
    t2 = t1 + EKR_HOLD * k
    return t0, t1, t2, t2 + EKR_OUT * k


def _екр_камера(t, k):
    """(камера, наклон панели, доля ширины кадра) по времени клипа.

    Ширина панели снята с плёнки: 0,44 → 0,57 → 0,85 → 1,02 за 0,73 с.
    Дальность под нужную ширину считает `_дальность` делением отрезка —
    та же, что у `zal_efir`: панель у обоих 3,2 × 1,8 м.
    """
    t0, t1, t2, t3 = _екр_времена(k)
    if t < t0:
        want = 0.42 + 0.02 * zc.clamp01(t / max(1e-6, t0))
        yaw, xoff = EKR_YAW0, EKR_XOFF
    elif t < t1:
        u = zc.seg(t, t0, t1)
        want = float(np.interp(u, [0.0, 0.41, 0.82, 1.0],
                               [0.44, 0.57, 0.85, 1.02]))
        e = 1 - (1 - u) ** 2                  # выпрямление с торможением
        yaw, xoff = EKR_YAW0 * (1 - e), EKR_XOFF * (1 - e)
    elif t < t2:
        want, yaw, xoff = 1.02, 0.0, 0.0
    elif t < t3:
        # ХОД ВОЗВРАТА — outCubic, НО С МЯГКИМ ВХОДОМ В НЕГО (11.11, замер
        # соседних кадров). Чистый outCubic на первом же кадре отводит
        # камеру на 6% масштаба: панель мгновенно открывает по краям
        # светлый зал, и стык читается СКЛЕЙКОЙ, а не отъездом — разница
        # соседних кадров прыгала с нуля до 35 уровней. Разгон по
        # smoothstep этого не допускает (3 уровня на первом кадре),
        # длительность и характер хода («быстро отходим, долго садимся»)
        # остаются те же: концы кривой не сдвинулись.
        _u = zc.seg(t, t2, t3)
        u = zc.out_cubic(_u * _u * (3.0 - 2.0 * _u))
        want = 1.02 + (0.40 - 1.02) * u
        yaw, xoff = EKR_YAW1 * u, 0.7 * u
    else:
        want = 0.40 - 0.015 * zc.seg(t, t3, t3 + 0.6 * k)
        yaw, xoff = EKR_YAW1, 0.7
    d = _дальность(want, yaw, xoff)
    return zc.Cam(xoff, 1.55, EFIR_Z - d), yaw, want


def zal_ekran(out=None, t=None, text="", say="", author="", role="",
              source="", sheets=(), channel="", watermark="", dur=0.0,
              sfx=None, **_):
    """G25. Панель эфира разворачивается в полный экран, держит его и
    УЕЗЖАЕТ НАЗАД В ЗАЛ, доворачиваясь до 22°.

    `text` — фраза сцены: объёмная надпись в зале над панелью (после
    возврата она и остаётся в кадре). `say` — реплика, которая набирается
    словами субтитра; `author` и `role` — кто говорит, `source` — где и
    когда сказано.
    """
    k = _темп(dur, полное=EKR_ПОЛНОЕ)
    tt = EKR_HERO * k if t is None else float(t)
    bg, fg = цвета(channel)
    t0, t1, t2, t3 = _екр_времена(k)
    cam, yaw, want = _екр_камера(tt, k)
    эфир_t = tt - t1

    # ШАГ СЛОВ УЖИМАЕТСЯ ПОД ДЛИНУ РЕПЛИКИ, А НЕ БЕРЁТСЯ ЧИСЛОМ. 0,165 с —
    # шаг плёнки, но полный экран держится 1,5 с: на длинной реплике
    # последние слова пришли бы, когда панель уже уехала, и на постере
    # стояла бы половина фразы.
    n_сл = max(1, len([w for w in str(say or "").split() if w]))
    шаг = min(EKR_СЛОВО, max(0.045, (EKR_HOLD * 0.86 - 0.27) / n_сл)) * k

    # --- надпись в зале: мерим по камере ВХОДА (там она крупнее всего) ---
    cam_в, yaw_в, _ = _екр_камера(0.0, k)
    стр = _строки(text, строк=2, знаков=18)
    над = None
    if стр:
        тек, cap, _ = _полный(стр, step=0.0, align="center")
        cap_m = _вписать_блок(cam_в, тек, cap, EFIR_Z, 0.56, 0.17, yaw=yaw_в)
        над = (тек, cap, cap_m)

    карта = [] if os.environ.get("ZAL_LAYOUT") else None
    эфир = _екр_эфир(эфир_t, text, say, author, role, source, bg, шаг,
                     карта=карта)
    углы = zc.quad((0.0, 1.55, EFIR_Z), EFIR_W, EFIR_H, yaw=yaw)

    if want >= EKR_ПОЛНЫЙ:
        # ЗАЛА ЗА ПАНЕЛЬЮ УЖЕ НЕ ВИДНО — и мы его не считаем. Картинку
        # кладём ТЕМ ЖЕ `paste_quad`, что и в зале, поэтому на стыке нет
        # скачка: меняется только то, что всё равно закрыто панелью.
        img = Image.new("RGBA", (W, H), (10, 11, 16, 255))
        zc.paste_quad(img, эфир, [cam.proj(p) for p in углы])
        if карта is not None:
            _кор = _короб(cam, углы)
            for (имя, x0, y0, x1, y1) in карта:
                _отметить(имя,
                          _кор[0] + x0 / W * (_кор[2] - _кор[0]),
                          _кор[1] + y0 / H * (_кор[3] - _кор[1]),
                          _кор[0] + x1 / W * (_кор[2] - _кор[0]),
                          _кор[1] + y1 / H * (_кор[3] - _кор[1]))
    else:
        img = zc.room(cam)
        _листы(img, cam, sheets)
        for fx in (0.08, 0.92):
            px = (fx - 0.5) * EFIR_W
            zc.wire(img, cam, (px * math.cos(yaw), 1.55 + EFIR_H / 2.0,
                               EFIR_Z + px * math.sin(yaw)), width=2)
        if над is not None:
            тек, cap, cap_m = над
            _bw, _bh = _коробка_мира(cam, EFIR_Z, тек.size[0] * cap_m / cap,
                                     тек.size[1] * cap_m / cap, yaw=yaw)
            # НАДПИСЬ СТОИТ НАД ПАНЕЛЬЮ, А НЕ ПО ЦЕНТРУ КАДРА (11.11, по
            # кадру): камера смещена вбок, панель висит слева, и надпись
            # по центру экрана читалась оторванной от неё. Долю берём у
            # самой панели и прижимаем, чтобы надпись не вышла за поле.
            _пк = _короб(cam, углы)
            _доля = (_пк[0] + _пк[2]) / 2.0 / W
            _доля = min(max(_доля, (SAFE * W + _bw / 2) / W),
                        ((1 - SAFE) * W - _bw / 2) / W)
            if карта is not None:
                _отметить("надпись в зале", _доля * W - _bw / 2, SAFE * H,
                          _доля * W + _bw / 2, SAFE * H + _bh)
            # НАДПИСЬ ГАСНЕТ, ПОКА ПАНЕЛЬ ДО НЕЁ НЕ ДОШЛА (11.11, осмотр
            # кадров клипа). Панель растёт снизу вверх и на середине
            # разворота накрывала надпись своей верхней кромкой: в кадре
            # оставались верхушки букв — рваная чёрная полоса вдоль края
            # экрана. Теперь считаем зазор до кромки и на последних 3%
            # высоты кадра уводим надпись в ноль — она уходит до касания и
            # так же возвращается на отъезде.
            _зазор = _короб(cam, углы)[1] - (SAFE * H + _bh)
            _видимость = zc.clamp01(_зазор / (0.03 * H))
            if _видимость > 0.02:
                _т = тек
                if _видимость < 1.0:
                    _т = тек.copy()
                    _т.putalpha(тек.split()[3].point(
                        lambda v: int(v * _видимость)))
                _место_блока(img, cam, _т, cap, cap_m, EFIR_Z, _доля,
                             SAFE * H, yaw=yaw, wires=0)
        zc.floor_shadow(img, cam, углы, эфир)
        zc.reflection(img, cam, углы, эфир, strength=0.22)
        корпус = Image.new("RGBA", (16, 9), (24, 24, 28, 255))
        zc.paste_quad(img, корпус, [cam.proj(p) for p in
                                    zc.quad((0.0, 1.55, EFIR_Z + 0.03),
                                            EFIR_W * 1.03, EFIR_H * 1.05,
                                            yaw=yaw)])
        zc.paste_quad(img, эфир, [cam.proj(p) for p in углы])
    _ev(sfx, t0, "whoosh")
    _ev(sfx, t1, "impact")
    _ev(sfx, t1 + EKR_ШТОРКА[0] * k, "label")
    _ev(sfx, t2, "whoosh")
    _знак(img, watermark)
    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


