def used_phrases(days=10):
    """Фразы, уже ушедшие в дело за последние дни. Рейтинга у фраз нет и
    быть не может — CTR и показов нет НИ В ОДНОМ документе библиотеки, —
    поэтому единственная честная защита от приедания это НЕ ПОВТОРЯТЬСЯ."""
    if not os.path.isfile(ZHURNAL):
        return []
    try:
        rows = json.load(open(ZHURNAL, encoding="utf-8"))
    except (OSError, ValueError):
        return []
    import datetime as dt
    edge = (dt.date.today() - dt.timedelta(days=days)).isoformat()
    out = []
    for r in rows:
        if str(r.get("дата", "")) >= edge:
            out += r.get("заголовки", []) + r.get("надписи", [])
    return out[-200:]


