def _только_итог(события):
    """ЧЕРНОВИКИ НАБОРА — НЕ ПРИМЕРЫ ЕГО ВКУСА (11.11, его вопрос «это
    делается? проверить»).

    Поле заголовка сохраняется САМО, пока он печатает (`svoyWatch`: blur и
    пауза 1,2 с). Поэтому в журнал ложится каждая промежуточная версия одной
    и той же фразы: «В СВОЁМ УМЕ?» → «В СВОЁМ УМЕ? РАЗ ТАКОЙ СМЕЛЫЙ СЛУШАЙ
    СЮДА» → … → готовый заголовок. Замер 11.11: из четырнадцати примеров,
    уходивших агенту, ДЕСЯТЬ были черновиками ДВУХ заголовков — остальные
    примеры вытеснялись, и «обучение на примерах» училось на обрезках.

    Журнал остаётся полной историей (он пишется только дополнением), а здесь
    внутри каждой пары (канал+тема, вид события) выбрасываем запись, чей
    текст — НАЧАЛО любой более поздней записи той же пары. Сравнение без
    знаков и регистра: он дописывает запятую или тире посреди набора, и
    буквальное сравнение оставляло два черновика одной фразы.
    """
    def _н(x):
        return " ".join("".join(c if (c.isalnum() or c.isspace()) else " "
                                for c in str(x).lower()).split())

    группы, порядок = {}, []
    for e in события:
        if not isinstance(e, dict):
            continue
        ключ = (str(e.get("канал") or ""), str(e.get("тема") or ""),
                str(e.get("событие") or ""))
        if ключ not in группы:
            группы[ключ] = []
            порядок.append(ключ)
        группы[ключ].append(e)

    итог = []
    for ключ in порядок:
        группа = группы[ключ]
        if ключ[2] == "превью":
            итог.append(группа[-1])          # превью: последний выбор и есть итог
            continue
        тексты = [_н(e.get("выбрано") or "") for e in группа]
        for i, e in enumerate(группа):
            т = тексты[i]
            if not т:
                continue
            # ЧЕРНОВИК — НЕ ТОЛЬКО РОВНОЕ НАЧАЛО. Он правит фразу посреди
            # набора: «…неприятный подарочек М» → «…подарочек канцлеру».
            # Строгий префикс такую брошенную ветку не ловит, поэтому считаем
            # ОБЩЕЕ НАЧАЛО: совпало ≥80% короткой строки и позже есть длиннее
            # — значит это та же фраза в работе, а не отдельный заголовок.
            def _черновик_для(поздний):
                if not поздний or поздний == т:
                    return поздний == т
                общее = 0
                for x, y in zip(т, поздний):
                    if x != y:
                        break
                    общее += 1
                короткая = min(len(т), len(поздний))
                return (len(поздний) > len(т)
                        and общее >= 0.8 * короткая)

            if not any(_черновик_для(тексты[j])
                       for j in range(i + 1, len(группа))):
                итог.append(e)
    return итог


