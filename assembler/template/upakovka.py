    ap.add_argument("folder")
    ap.add_argument("--all", action="store_true", help="все темы внутри папки")
    a = ap.parse_args()
    root = os.path.abspath(a.folder)
    if a.all:
        targets = [os.path.join(root, d) for d in sorted(os.listdir(root))
                   if os.path.isdir(os.path.join(root, d))]
        targets = [t for t in targets if find_text(t)]
    else:
        targets = [root]
    print("УПАКОВКА: %d тем" % len(targets))
    ok = sum(1 for t in targets if do_one(t))
    print("готово: %d из %d" % (ok, len(targets)))
    return 0 if ok == len(targets) else 1


