def parse(ans):
    out = {"описание": "", "заголовки": [], "надписи": [], "превью": "",
           "паттерн": ""}
    blocks = re.split(r"===\s*(ОПИСАНИЕ|ЗАГОЛОВКИ|НАДПИСИ|ПАТТЕРН|ПРЕВЬЮ)\s*===",
                      ans)
    for i in range(1, len(blocks) - 1, 2):
        name, body = blocks[i].strip(), blocks[i + 1].strip()
        if name == "ОПИСАНИЕ":
            out["описание"] = body
        elif name == "ПРЕВЬЮ":
            out["превью"] = body
        elif name == "ПАТТЕРН":
            out["паттерн"] = body.splitlines()[0].strip() if body else ""
        else:
            items = [re.sub(r"^\s*\d+[.)]\s*", "", l).strip()
                     for l in body.splitlines() if l.strip()]
            out["заголовки" if name == "ЗАГОЛОВКИ" else "надписи"] = \
                [x for x in items if x]
    return out


def do_one(folder):
    src = find_text(folder)
    if not src:
        print("  ✗ нет текста статьи: %s" % folder)
        return False
