    if not src:
        print("  ✗ нет текста статьи: %s" % folder)
        return False
    ch = channel_of(folder)
    title = os.path.basename(folder)
    text = read_text(src)
    _used = used_phrases()
    task = PROMPT.format(
        channel=ch or "НОВОСТИ", title=title, text=text,
        patterns=" · ".join(PATTERNS), families=FAMILIES,
        used=("· " + "\n· ".join(_used[-24:])) if _used
             else "(пока пусто, это первый ролик)",
        samples=lib_text("arhiv-geo2.txt", 2600) + "\n" +
                lib_text("arhiv-5min.txt", 3200),
        vybor=выбор_его(канал=ch or ""),
        bank=lib_text("bank.txt"))

    tmp = os.path.join(folder, "ЗАДАНИЕ-УПАКОВКА.txt")
    open(tmp, "w", encoding="utf-8").write(task)
    print("  %s / %s — спрашиваю агента (%d знаков)…" % (ch, title, len(text)))
    r = subprocess.run(["bash", os.path.join(HERE, "codex_ask.sh"), tmp],
                       capture_output=True, text=True, timeout=1800)
    ans_path = tmp[:-4] + ".ОТВЕТ.txt"
    if not os.path.exists(ans_path):
        print("  ✗ агент не ответил: %s" % (r.stderr or "")[:160])
        return False
    data = parse(read_text(ans_path))
    if not data["описание"]:
        print("  ✗ в ответе нет блока ОПИСАНИЕ — формат не соблюдён")
        return False
    data["канал"], data["тема"], data["папка"] = ch, title, folder

    json.dump(data, open(os.path.join(folder, "УПАКОВКА.json"), "w",
                         encoding="utf-8"), ensure_ascii=False, indent=1)
    L = ["КАНАЛ: %s" % ch, "ТЕМА: %s" % title, "", "ОПИСАНИЕ", "-" * 60,
         data["описание"], "", "ЗАГОЛОВКИ", "-" * 60]
    L += ["%2d. %s" % (i + 1, t) for i, t in enumerate(data["заголовки"])]
    L += ["", "НАДПИСИ НА ПРЕВЬЮ", "-" * 60]
    L += ["%2d. %s" % (i + 1, t) for i, t in enumerate(data["надписи"])]
    if data.get("паттерн"):
        L += ["", "ПАТТЕРН: " + data["паттерн"]]
    # Промпт на превью здесь больше НЕ НУЖЕН (07.11, его слово: «не нужно
    # делать ему отдельные промпты, и мне тоже его не нужно делать — ты
