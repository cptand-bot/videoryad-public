def read_text(path):
    raw = open(path, "rb").read()
    for enc in ("utf-8-sig", "utf-8", "cp1251", "koi8-r"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("cp1251", "replace")


def find_text(folder):
    c = [os.path.join(folder, n) for n in os.listdir(folder)
         if n.lower().endswith(".txt")
         and not any(s in n.upper() for s in SKIP_TXT)]
    return max(c, key=os.path.getsize) if c else ""


def channel_of(path):
    parts = [p.strip().upper() for p in os.path.abspath(path).split(os.sep)]
    for name in ("ПЛАНЕТА", "5 МИНУТ", "ОЛЬКА НОВОСТИ", "ОЛЬКА",
                 "ДИПЛОМАТИЯ СИЛЫ", "ПЕРЕВОД С ДИПЛОМАТИЧЕСКОГО"):
        if name in parts:
            return name
    return ""


