#!/usr/bin/env python3
# СВЕРКА ПРОПУСКОВ — ПРОВЕРЯЕТ ПРИЧИНУ, А НЕ ВЕРИТ ЕЙ (25.11.2026, его
# прямое требование: «не в бриф, не в текст — на уровне кода»).
#
# Повод: два ролика подряд (usuario-a4 45 из 77, usuario-c0 ~26 из 73)
# массово писали в propuski.json «нет чисел/материала» для видов типа
# bubbles/map_dist/line/network/globus_map — а в тексте сцен РЕАЛЬНО был
# материал (страна, город, имя), просто не в точно той форме, что названа
# в карточке. Текстовое правило про это уже в БРИФ-КОРОТКО.md («ЧИСЛА»,
# 24.11 и 25.11) — не держит, вкладка может его не перечитать, а гейт
# `obyazatelno.py` принимает любую причину ≥10 знаков не проверяя её.
#
# ЭТОТ СКРИПТ — ДОПОЛНИТЕЛЬНАЯ, НЕЗАВИСИМАЯ ПРОВЕРКА САМОГО ТЕКСТА
# СЦЕН. Он не трогает obyazatelno.py и не встроен в faza.sh (это отдельный
# шаг раскатки, п.174 НА-РАСКАТКУ.md — живые гейты, которыми в момент
# написания пользуются другие вкладки, в бою не редактируются).
#
# ЛОГИКА: для propuski.json-записи, чья причина похожа на «нет
# чисел/данных/материала», и чей вид входит в «списочные» (им по правилу
# 24.11 достаточно ЛЮБОГО перечня из 2-3 однородных вещей — город, страна,
# человек, организация, а не точных величин) — сканируем ВЕСЬ scenes.json
# на кандидатов: цифры, известные страны/столицы (готовый список уже есть
# в kartochki_srazu.py — переиспользуем, не плодим новый), заглавные слова
# подряд (грубый, но дешёвый признак имени/организации). Нашли — причина
# не принимается, скрипт падает и называет, что и где нашлось.
import json
import os
import re
import sys

T = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, T)
try:
    from kartochki_srazu import СТРАНЫ, СТОЛИЦЫ  # готовый список, не дублируем
except ImportError:
    СТРАНЫ, СТОЛИЦЫ = [], {}

# «СПИСОЧНЫЕ» ВИДЫ — им достаточно перечня 2-3 вещей, не точных цифр
# (БРИФ-КОРОТКО.md, «ЧИСЛА», его слово 24.11): страна/город/имя/организация
# годится сам по себе. Имена видов — как в obyazatelno.py --list.
ИМЕННЫЕ_ВИДЫ = {
    "bubbles", "map_dist", "network", "globus_map", "device", "dossier",
    "lenta_foto", "perematka",
}
# ЧИСЛОВЫЕ ВИДЫ — по смыслу самого вида (доля, ряд, разбивка, было→стало)
# именного перечня НЕ ЗАМЕНЯЕТ число: тут нужна цифра/процент/ряд точек,
# иначе кандидат ложный (живой случай 25.11: «Тут», «Володя» сошли за
# имена на waterfall, а водопаду нужна числовая разбивка, не персона).
ЧИСЛОВЫЕ_ВИДЫ = {"pie", "slope", "waterfall", "line"}
СПИСОЧНЫЕ_ВИДЫ = ИМЕННЫЕ_ВИДЫ | ЧИСЛОВЫЕ_ВИДЫ

# ПРИЗНАК «ОТГОВОРКИ ПРО ОТСУТСТВИЕ МАТЕРИАЛА», не любой причины вообще —
# причина может быть структурной и честной («нужны ровно 4 клипа» и т.п.),
# её не трогаем. Ловим именно формулировки класса «нет чисел/данных».
_ОТГОВОРКА = re.compile(
    r"нет\s+(числ|данн|материал|информаци|стат|перечн|цифр)", re.IGNORECASE)

_ТЕКСТ_ПОЛЯ = ("text", "текст", "line", "reply", "srt_text")


def _текст_сцены(scene):
    for k in _ТЕКСТ_ПОЛЯ:
        v = scene.get(k)
        if isinstance(v, str) and v.strip():
            return v.strip()
    return ""


# ЗАГЛАВНЫЕ СЛОВА ПОДРЯД — ГРУБЫЙ ПРИЗНАК ИМЕНИ/ОРГАНИЗАЦИИ. Не идеально
# (ловит и начало предложения), поэтому это только КАНДИДАТ для человека
# посмотреть, не окончательный вердикт — скрипт печатает находку, решение
# всё равно за вкладкой/координатором.
_ЗАГЛАВНОЕ = re.compile(r"\b[А-ЯЁ][а-яёА-ЯЁ-]{2,}(?:\s+[А-ЯЁ][а-яёА-ЯЁ-]{2,}){0,2}\b")
_СТОП_ЗАГЛАВНЫЕ = {"Однако", "Также", "После", "Сейчас", "Поэтому", "Тогда"}


_ЧИСЛО = re.compile(r"\d{2,}|\d+\s*%")  # одна голая цифра — слабый кандидат
# (живой случай 25.11: «Брата 2» дал ложную «цифру», как и в озвучке того
# же дня, см. feedback_dig_for_real_substitute_before_propuski — там же
# урок, что цифра в названии не считается).


def найти_кандидатов(text):
    """Вернуть список найденных кандидатов (строки) в тексте сцены."""
    found = []
    if _ЧИСЛО.search(text):
        found.append("число")
    for страна in СТРАНЫ:
        if re.search(r"\b%s\b" % re.escape(страна), text):
            found.append(страна)
    for столица in СТОЛИЦЫ:
        if re.search(r"\b%s\b" % re.escape(столица), text):
            found.append(столица + " (" + СТОЛИЦЫ[столица] + ")")
    for m in _ЗАГЛАВНОЕ.finditer(text):
        слово = m.group(0)
        if слово.split()[0] not in _СТОП_ЗАГЛАВНЫЕ:
            found.append(слово)
    # убрать дубли, сохранить порядок
    seen = set()
    out = []
    for f in found:
        if f not in seen:
            seen.add(f)
            out.append(f)
    return out


def main():
    if len(sys.argv) < 3:
        print("propuski_sverka.py <scenes.json> <propuski.json>", file=sys.stderr)
        return 2
    scenes_path, propuski_path = sys.argv[1], sys.argv[2]
    try:
        _raw = json.load(open(scenes_path, encoding="utf-8"))
    except (OSError, ValueError) as e:
        print("не открыть %s: %s" % (scenes_path, e), file=sys.stderr)
        return 2
    # ДВА ФОРМАТА В ОБОРОТЕ: голый список сцен ИЛИ {"channel":.., "scenes":[..]}
    # (живой случай 25.11 — на этом же упал первый прогон теста).
    scenes = _raw.get("scenes", []) if isinstance(_raw, dict) else _raw
    if not isinstance(scenes, list):
        print("%s: не нашёл список сцен (ни голый список, ни ключ scenes)"
              % scenes_path, file=sys.stderr)
        return 2
    # НЕТ propuski.json — НЕЧЕГО СВЕРЯТЬ, ЭТО НЕ ОТКАЗ. Большинство ролика
    # вообще не доходит до пропусков; вызов со стороны `faza.sh` должен
    # пройти молча, а не падать на отсутствующем файле.
    if not os.path.isfile(propuski_path):
        print("сверка пропусков: propuski.json нет — нечего сверять")
        return 0
    try:
        propuski = json.load(open(propuski_path, encoding="utf-8"))
    except (OSError, ValueError) as e:
        print("не открыть %s: %s" % (propuski_path, e), file=sys.stderr)
        return 2
    if not isinstance(propuski, dict):
        print("propuski.json — не объект {вид: причина}", file=sys.stderr)
        return 2

    отказ = False
    for вид, причина in propuski.items():
        if вид not in СПИСОЧНЫЕ_ВИДЫ:
            continue
        if not _ОТГОВОРКА.search(str(причина)):
            continue
        for scene in scenes:
            text = _текст_сцены(scene)
            if not text:
                continue
            кандидаты = найти_кандидатов(text)
            # ЧИСЛОВОМУ ВИДУ ИМЁН/СТРАН НЕДОСТАТОЧНО — нужна хотя бы одна
            # настоящая цифра в кандидатах, иначе «Тут»/«Володя» и подобные
            # заглавные слова ложно сходят за повод для водопада/доли/ряда.
            if вид in ЧИСЛОВЫЕ_ВИДЫ:
                кандидаты = [k for k in кандидаты if k == "число"]
            if кандидаты:
                отказ = True
                print(
                    "!! ПРОПУСК «%s» ОТКЛОНЁН: сцена %s — в тексте есть %s, "
                    "а причина «%s» говорит «нет материала». Поставь этот "
                    "вид с этим материалом вместо пропуска."
                    % (вид, scene.get("id"), ", ".join(кандидаты[:5]), причина),
                )
                break  # одной находки достаточно, дальше сцены не смотрим

    if отказ:
        print("сверка пропусков: ОТКАЗ — есть материал, который причина не учла",
              file=sys.stderr)
        return 1
    print("сверка пропусков: чисто — ни одна отговорка не противоречит тексту сцен")
    return 0


if __name__ == "__main__":
    sys.exit(main())
