def _srt_до(путь, секунд=30.0, слов_крючка=0):
    """Слова субтитров до отметки и момент, когда дочитан крючок.

    ДЛИНУ КРЮЧКА СЧИТАЕМ ПО ЧИСЛУ СЛОВ, А НЕ ПО ПЕРВОЙ ТОЧКЕ (правка 11.11).
    Субтитры нарезаны по ФРАЗАМ, и многие строки кончаются без знака: поиск
    «первой строки с точкой» давал 45,8 с там, где крючок звучит двенадцать —
    то есть признак врал почти вчетверо.
    """
    try:
        t = io.open(путь, encoding="utf-8-sig").read().replace("\r\n", "\n")
    except Exception:
        return 0, None
    блоки = re.split(r"\n\s*\n", t.strip())
    слов, конец_первой, всего_слов = 0, None, 0
    for b in блоки:
        ls = [x for x in b.split("\n") if x.strip()]
        if len(ls) < 3 or "-->" not in ls[1]:
            continue
        m = re.match(r"(\d+):(\d+):(\d+)[,.](\d+)\s*-->\s*(\d+):(\d+):(\d+)[,.](\d+)", ls[1])
        if not m:
            continue
        g = [int(x) for x in m.groups()]
        нач = g[0] * 3600 + g[1] * 60 + g[2] + g[3] / 1000.0
        кон = g[4] * 3600 + g[5] * 60 + g[6] + g[7] / 1000.0
        текст = " ".join(ls[2:])
        всего_слов += len(текст.split())
        if конец_первой is None and слов_крючка and всего_слов >= слов_крючка:
            конец_первой = round(кон, 1)
        if нач < секунд:
            слов += len(текст.split())
    return слов, конец_первой


def признаки_контента(папка_темы, карта):
    """КОНТЕНТНЫЙ СЛОЙ ВОРОНКИ (11.11, его слово: «сначала работает превью,
    потом заголовок уточняет — это 70% успеха. Но дальше начинает работать
    контент, дальше текст. Крючок и эти первые 30 секунд очень важны: если
    уходят, то всё, капец. И какое удержание дальше на этой теме»).

    Поэтому к превью и заголовку пристёгиваем то, что встречает зрителя
    ВНУТРИ ролика: сам крючок, его длина, и чем заняты первые 30 секунд —
    сколько сцен, видео это или фото, стоит ли карточка, всплывашка, надпись.
    Всё считается с диска, ничего не спрашивается у человека.
    """
    out = {п: "" for п in ПРИЗНАКИ_КОНТЕНТА}
    import glob as _g
    # ОТБОР ТЕКСТА — ОБЩЕЙ ФУНКЦИЕЙ, А НЕ СВОЕЙ (правка 11.11, его слово:
    # «что-то какой-то путь у тебя через задницу получился»). Сначала здесь
    # стоял свой список исключений плюс обнюхивание первых строк на `http` —
    # то есть ТРЕТЬЯ копия логики «какой из .txt в папке и есть статья».
    # Правильно оказалось одно: дырку закрыли в ОБЩЕМ `ozvuchka.SKIP_TXT`
    # (туда добавлены «ССЫЛКИ» и «ГЕОРАДАР»), и теперь её видят все, включая
    # сторож озвучки, который мог отправить список ссылок в озвучку.
    try:
        import ozvuchka
    except Exception:
        sys.path.insert(0, HERE)
        import ozvuchka
    тексты = ozvuchka.find_text(папка_темы)
    if тексты:
        try:
            b = open(тексты[0], "rb").read()
            for enc in ("utf-8-sig", "utf-8", "cp1251"):
                try:
                    t = b.decode(enc)
                    break
                except Exception:
                    t = b.decode("cp1251", "replace")
            фразы = [x.strip() for x in re.split(r"(?<=[.!?])\s+", re.sub(r"\s+", " ", t)) if x.strip()]
            крючок = " ".join(фразы[:2])[:220]
            out["крючок"] = крючок
            out["крючок_слов"] = len(крючок.split())
            out["крючок_вопрос"] = int("?" in крючок)
            # субъект = есть имя собственное или страна в первых двух фразах
            out["крючок_субъект"] = int(bool(re.search(
                r"\b[А-ЯЁ][а-яё]{3,}", крючок[1:])))
        except Exception:
            pass
    srt = _g.glob(os.path.join(папка_темы, "*.srt"))
    if srt:
        слов, первая = _srt_до(srt[0], 30.0, out.get("крючок_слов") or 0)
        out["слов_в_30с"] = слов
        out["крючок_секунд"] = первая if первая else ""
    проект = карта.get(папка_темы) or карта.get(папка_темы.rstrip("/"))
    if проект:
        sj = sorted(_g.glob(os.path.join(проект, "*.scenes.json")))
        if sj:
            try:
                d = json.load(io.open(sj[0], encoding="utf-8"))
                сц = d["scenes"] if isinstance(d, dict) else d
                out["сцен_всего"] = len(сц)
                посл = сц[-1]
                out["минут"] = round(((посл.get("start_sec") or 0) +
                                      (посл.get("duration_sec") or 0)) / 60.0, 1)
                в30 = [x for x in сц if (x.get("start_sec") or 0) < 30]
                out["сцен_в_30с"] = len(в30)
                out["видео_в_30с"] = sum(
                    1 for x in в30 if "video" in str(x.get("source") or "")
                    or str(x.get("source") or "").endswith("_video"))
                out["карточка_в_30с"] = sum(
                    1 for x in в30 if str(x.get("source") or "").startswith("card:"))
            except Exception:
                pass
        ov = os.path.join(проект, "overlays.json")
        if os.path.exists(ov):
            try:
                o = json.load(io.open(ov, encoding="utf-8"))
                нач = [k for k in o if str(k).isdigit() and int(k) <= 4]
                out["всплывашка_в_30с"] = sum(
                    1 for k in нач if (o[k] or {}).get("photo"))
                out["надпись_в_30с"] = sum(
                    1 for k in нач if (o[k] or {}).get("text"))
            except Exception:
                pass
    return out


def файл_превью(папка, вариант):
    """Готовое превью темы: сначала то, что лёг рядом с роликом, иначе вариант."""
    import glob as _g
    гот = [f for f in _g.glob(os.path.join(папка, "*ПРЕВЬЮ*.png"))
           if "КВАДРАТ" not in os.path.basename(f)]
    if гот:
        return sorted(гот)[0]
    if вариант:
        p = os.path.join(папка, "превью-варианты", "ПРЕВЬЮ-%s.png" % вариант)
        if os.path.exists(p):
            return p
    return ""


def собрать():
    заг, надп, превью = _журнал()
    _карта = _проекты_по_темам()
    строки = []
    for mp4 in glob.glob(os.path.join(НОВОСТИ, "*", "*", "[0-3][0-9]-[01][0-9]", "*", "*.mp4")):
        if os.path.getsize(mp4) < 100 * 1024 * 1024:
            continue                       # пробы и образцы, не готовый ролик
        части = os.path.relpath(mp4, НОВОСТИ).split(os.sep)
        if len(части) < 4:
            continue
        канал, _месяц, день, тема = части[0], части[1], части[2], части[3]
        ключ = (канал, тема)
        строки.append({
            "канал": канал,
            "день": день,
            "тема": тема,
            "файл": os.path.basename(mp4),
            "мб": round(os.path.getsize(mp4) / 1048576),
            "секунд": _длительность(mp4),
            "его_заголовок": заг.get(ключ, ""),
            "надпись_верх": (надп.get(ключ) or ["", ""])[0],
            "надпись_низ": (надп.get(ключ) or ["", ""])[1],
            "вариант_превью": превью.get(ключ),
            **{п: "" for п in ПОЛЯ_СТАТИСТИКИ},
        })
        _пап = os.path.dirname(mp4)
        _пре = файл_превью(_пап, превью.get(ключ))
        строки[-1]["превью_файл"] = os.path.basename(_пре) if _пре else ""
        строки[-1].update(признаки_превью(_пре) if _пре else
                          {п: "" for п in ПРИЗНАКИ_ПРЕВЬЮ})
        строки[-1].update(признаки_контента(_пап, _карта))
    строки.sort(key=lambda r: (r["день"], r["канал"], r["тема"]))
    return строки


def слить(новые):
    """Старые заполненные цифры НЕ затирать — таблица копится."""
    старые = {}
    if os.path.exists(ТАБЛИЦА):
        try:
            for r in json.load(io.open(ТАБЛИЦА, encoding="utf-8")):
                старые[(r.get("канал"), r.get("день"), r.get("тема"))] = r
        except Exception:
            pass
    for r in новые:
        was = старые.get((r["канал"], r["день"], r["тема"])) or {}
        for п in ПОЛЯ_СТАТИСТИКИ:
            if was.get(п):
                r[п] = was[п]
    os.makedirs(os.path.dirname(ТАБЛИЦА), exist_ok=True)
    json.dump(новые, io.open(ТАБЛИЦА, "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    return новые


