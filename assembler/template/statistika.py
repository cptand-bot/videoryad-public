def _длительность(p):
    try:
        r = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                            "format=duration", "-of", "csv=p=0", p],
                           capture_output=True, text=True, timeout=30)
        return round(float(r.stdout.strip()), 1)
    except Exception:
        return None


def _журнал():
    """Последний его выбор на каждую пару (канал, тема)."""
    заг, надп, превью = {}, {}, {}
    if not os.path.exists(ЖУРНАЛ):
        return заг, надп, превью
    for line in io.open(ЖУРНАЛ, encoding="utf-8"):
        try:
            e = json.loads(line)
        except ValueError:
            continue
        ключ = (str(e.get("канал") or ""), str(e.get("тема") or ""))
        с = e.get("событие")
        if с == "свой_заголовки" and e.get("выбрано"):
            # позже = итог: поле сохраняется само, пока он печатает
            заг[ключ] = e["выбрано"]
        elif с == "превью":
            надп[ключ] = [e.get("надпись_сверху") or "", e.get("надпись_снизу") or ""]
            превью[ключ] = e.get("выбран_вариант")
    return заг, надп, превью


