def признаки_превью(path):
    """ЗАСЕЧКИ ПО САМОЙ КАРТИНКЕ (11.11, его слово: «делать засечки — что было
    в этот момент на превью, на самом, что на картинке… какие моменты мы,
    может быть, не учитывали, и тогда добавлять дополнительные параметры,
    чтобы генерировать превью, которые удачные по статистике»).

    Картинку рисует внешняя модель, наш код кладёт только текстовые плашки —
    значит параметров генерации у нас нет, и признаки надо ИЗМЕРЯТЬ с файла.
    Меряем то, что устойчиво и не зависит от содержания сюжета: свет, контраст,
    насыщенность, доля тёмного, доля красного и жёлтого (цвета тревоги,
    которыми живёт кликбейт), «крупность» — насколько кадр про один большой
    объект, а не про мелкую россыпь деталей, и три доминирующих цвета.

    Лиц НЕ детектируем: cv2 на машине нет, а врать прокси-признаком хуже, чем
    не мерить. Когда появится статистика и лица понадобятся — ставить cv2.
    """
    try:
        from PIL import Image
        import numpy as np
    except Exception:
        return {}
    try:
        im = Image.open(path).convert("RGB")
    except Exception:
        return {}
    im.thumbnail((256, 256))
    a = np.asarray(im).astype("float32")
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    ярк = (0.299 * r + 0.587 * g + 0.114 * b)
    mx, mn = a.max(axis=2), a.min(axis=2)
    нас = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1), 0)
    # ДЕТАЛИЗАЦИЯ — средний перепад яркости между соседними пикселями.
    # Низкая = кадр про ОДИН крупный объект, высокая = мелкая россыпь деталей.
    # Пишем ЧИСЛО КАК ЕСТЬ, без выдуманной шкалы: первая версия переводила его
    # в «крупность» по формуле 100-(г*4) и давала РОВНО НОЛЬ на всех 33 строках
    # — шкала насыщалась, признак был мёртвым. Пусть связь с CTR найдёт
    # корреляция, а не наша догадка о том, какой масштаб правильный.
    гx = np.abs(np.diff(ярк, axis=1)).mean()
    гy = np.abs(np.diff(ярк, axis=0)).mean()
    детализация = round(float((гx + гy) / 2), 2)
    красн = float(((r > 110) & (r > g * 1.45) & (r > b * 1.45)).mean())
    жёлт = float(((r > 130) & (g > 110) & (b < g * 0.72)).mean())
    кв = im.quantize(colors=3, method=Image.Quantize.FASTOCTREE)
    пал = кв.getpalette()[:9]
    цвета = ["#%02x%02x%02x" % tuple(пал[i:i + 3]) for i in range(0, 9, 3)]
    return {
        "яркость": round(float(ярк.mean()), 1),
        "контраст": round(float(ярк.std()), 1),
        "насыщенность": round(float(нас.mean()), 3),
        "доля_тёмного": round(float((ярк < 60).mean()), 3),
        "доля_красного": round(красн, 3),
        "доля_жёлтого": round(жёлт, 3),
        "детализация": детализация,
        "цвета": " ".join(цвета),
    }


