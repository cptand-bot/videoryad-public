"""СОКРАЩЕНИЕ ВТОРОЙ СТАТЬИ: РЕШАЕМ МЫ, А НЕ АГЕНТ (08.11.2026).

Его слово, когда я пересказал, как сокращал текст: «ты ему не давай запрос
„просил убрать 1100 знаков“. Так не делается. Ты ему конкретно говори, что
убрать. Ты же сам решил, что нужно убрать — так и пиши: убрать то-то, то-то,
то-то. Всё».

ПОЧЕМУ ЭТО ВЕРНО, ЗАМЕР ДНЯ: задание «убери столько-то знаков» возвращалось
почти нетронутым три раза подряд — из 1100 знаков агент убрал 225, из 3895
убрал 471. Арифметику он не выполняет; закрытую команду выполняет. Это тот же
принцип, что у аудита: «точные и конкретные инструкции, в жёстких рамках, не
давать свободы действий».

ПОРЯДОК РАБОТЫ:
    1) python3 rewrite_cut.py <текст.txt> --спиcок
       печатает абзацы с номерами, длиной и первой строкой — по ним видно
       повторы и подводки;
    2) глазами выбираем, ЧТО выбросить;
    3) python3 rewrite_cut.py <текст.txt> --убрать 8,19,24 --out <готово.txt>
       режет ровно названные абзацы и показывает, сколько стало.

Инструмент НИЧЕГО не решает сам: он не угадывает «лишнее» и не ужимает фразы.
Решение — наше, его дело выполнить и посчитать. Неприкосновенное (авторские
мысли, шутки, числа, утверждённый крючок, два призыва подписаться) он
проверяет после реза и предупреждает, если призывов стало меньше двух или
крючок уехал.
"""

import argparse
import io
import os
import re
import sys


# ПРИЗЫВ СЧИТАЕТСЯ ПО ФОРМАМ ВТОРОГО ЛИЦА, А НЕ ПО КОРНЮ «подпиш» (09.11,
# живой случай на тексте ПЛАНЕТЫ про поражение Запада). В тексте стояло ровно
# два настоящих призыва, а третьим засчиталось «в кабинете, где ПОДПИШУТ
# конкретный документ» — и `rewrite_fix` напечатал «ВНИМАНИЕ: призывов
# подписаться 3, лишние сними руками» на ЧИСТОМ файле. На отказ линта это не
# влияло (там только строка замера), зато гнало вкладку снимать несуществующий
# CTA или ломать живую фразу. Корень «подпиш» несёт целую ветку обычных слов:
# подпишут, подпишет, подпишем, подпишу — все про подписание документа.
# Призыв же бывает только в повелительном втором лице: подпишись,
# подпишитесь, подписывайся, подписывайтесь.
# ДЕТЕКТОР У ПРАВИЛА ОДИН НА ТРИ ФАЙЛА (`rewrite_fix`, `rewrite_lint`,
# `rewrite_cut`): два разных сита на одно правило — это не «строже», это
# другой ответ. Правишь здесь — правь во всех трёх, иначе `rewrite_fix`
# вставит третий призыв там, где линт видит два (на этом уже обжигались).
CTA_RE = re.compile(r"подпиш(?:ись|итесь)|подписывай(?:ся|тесь)", re.I)


def читать(path):
    raw = open(path, "rb").read()
    for enc in ("utf-8-sig", "utf-8", "cp1251"):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            continue
    return raw.decode("cp1251", "replace")




def мысли_из_задания(path):
    """Авторские мысли из задания рерайта, если оно лежит рядом с текстом.

    Ищем НЕ по заголовку блока, а по самим меткам строк `[мысль]` — заголовок
    «АВТОРСКИЕ МЫСЛИ» встречается в задании трижды (в правилах, в заголовке
    блока и внутри самого текста оригинала), и деление по нему давало пустой
    список: последнее вхождение приходилось на середину статьи. Проверено на
    живом задании 08.11: по заголовку — 0 мыслей, по меткам — все.

    Строки `[УКАЗАНИЕ — ВЫПОЛНИТЬ МОЛЧА]` не берём: это распоряжение по
    работе, а не материал текста (запрет 16).
    """
    if not path or not os.path.isfile(path):
        return []
    out = []
    for ln in читать(path).splitlines():
        ln = ln.strip()
        if "[УКАЗАНИЕ" in ln:
            continue
        if "[мысль]" in ln or "[note]" in ln:
            out.append(ln.split("]", 1)[-1].strip())
    return [x for x in out if len(x) > 25]


def кандидаты(абзацы, нужно, мысли=()):
    """ЧТО РЕЗАТЬ — ПОДСКАЗКА, А НЕ РЕШЕНИЕ (08.11).

    Замер по четырём темам подряд: текст приходит на 20-25% длиннее
    заказанного, и каждый раз вкладка ищет лишнее глазами. Режут при этом
    всегда одно и то же — ВОДУ: абзац без единого имени, числа и живой
    интонации, пересказывающий своими словами уже сказанное.

    Сначала пробовал искать повторы по общим редким словам — не сработало
    ни на одном живом тексте (максимум пересечения 0,23 при любом пороге):
    повтор вывода пишется ДРУГИМИ словами, совпадают только служебные.
    Поэтому метрика другая и проверяемая: считаем ЯКОРЯ — имена
    собственные, числа, кавычки, вопрос. Нет якорей совсем — абзац
    держится на одной интонации, и именно он уходит под нож первым.

    Решение всегда за вкладкой: печатаем список с объяснением, режем только
    по названным номерам.
    """
    ЧИСЛО = re.compile(r"\d|\b(дв[ае]|тр[ие]|четыр|пят|шест|сем|восем|девят|"
                       r"десят|сорок|сто|тысяч|миллион|миллиард|процент)", re.I)
    ИМЯ = re.compile(r"(?<![.!?]\s)(?<!^)\b[А-ЯЁ][а-яё]{2,}")
    ЖИВОЕ = re.compile(r"[«»\"?!]|подпиш", re.I)

    # АВТОРСКАЯ МЫСЛЬ — ВТОРОЙ ЯКОРЬ (08.11, просьба вкладки `usuario-47`).
    # Её замер на живом тексте: из десяти подсказок две были ценными абзацами
    # без чисел и имён — парадокс Прибалтики и финальный разворот про
    # Америку-кассу. Значит абзац, несущий мысль ИЗ ЗАДАНИЯ, в кандидаты не
    # ставим вовсе: авторская мысль не вода, даже если в ней нет цифр.
    def _слова(x):
        return {w for w in re.findall(r"[А-Яа-яЁёA-Za-z]{5,}", (x or "").lower())}

    _мысли = [_слова(m) for m in мысли if len(m or "") > 25]

    def _несёт_мысль(p_):
        sp = _слова(p_)
        if not sp:
            return False
        # СМОТРИМ ОБА НАПРАВЛЕНИЯ. Мысль автора длинная, абзац короткий:
        # доля от мысли почти всегда мала, а доля от абзаца показательна.
        # Порог 0.18 замерен на живом тексте 08.11: финальный разворот про
        # «Америку-кассу» даёт 0.20 и защищается, случайные соседи — 0.00.
        for m in _мысли:
            if not m:
                continue
            общ = len(sp & m)
            if общ and max(общ / float(len(sp)), общ / float(len(m))) >= 0.18:
                return True
        return False

    out = []
    for i, p_ in enumerate(абзацы):
        if len(p_) < 110:
            continue                      # короткая строка — это ритм, не вода
        if _несёт_мысль(p_):
            continue                      # авторская мысль не режется никогда
        якоря = 0
        if ЧИСЛО.search(p_):
            якоря += 2
        якоря += min(2, len(ИМЯ.findall(p_)))
        if ЖИВОЕ.search(p_):
            якоря += 1
        if якоря == 0:
            out.append((len(p_), i, якоря))
    out.sort(reverse=True)                # длинная вода — в первую очередь
    итог, набрано = [], 0
    for длина, i, _я in out:
        итог.append((i, длина))
        набрано += длина
        if нужно and набрано >= нужно:
            break
    return итог, набрано


def main():
    ap = argparse.ArgumentParser(description="сократить вторую статью названными абзацами")
    ap.add_argument("text")
    ap.add_argument("--спиcок", "--list", action="store_true", dest="show",
                    help="напечатать абзацы с номерами и длиной")
    ap.add_argument("--убрать", "--drop", default="", dest="drop",
                    help="номера абзацев через запятую")
    ap.add_argument("--out", default="")
    ap.add_argument("--задание", default="", dest="brief",
                    help="ЗАДАНИЕ-РЕРАЙТ.txt — из него берутся авторские мысли, "
                         "их абзацы в кандидаты на рез не попадают")
    ap.add_argument("--цель", "--target", type=int, default=0, dest="target",
                    help="сколько знаков должно остаться (для подсказки)")
    a = ap.parse_args()

    if not os.path.isfile(a.text):
        sys.exit("нет файла: %s" % a.text)
    t = читать(a.text)
    абзацы = [p for p in t.split("\n") if p.strip()]

    if a.show or not a.drop:
        print("абзацев: %d, знаков: %d" % (len(абзацы), len(t)))
        if a.target:
            print("цель: %d знаков — резать %d" % (a.target, max(0, len(t) - a.target)))
        for i, p in enumerate(абзацы):
            print("%3d [%4d] %s" % (i, len(p), p[:100]))
        if a.target and len(t) > a.target:
            нужно = len(t) - a.target
            _бриф = a.brief
            if not _бриф:
                _ряд = os.path.join(os.path.dirname(os.path.abspath(a.text)),
                                    "ЗАДАНИЕ-РЕРАЙТ.txt")
                _бриф = _ряд if os.path.isfile(_ряд) else ""
            _мысли = мысли_из_задания(_бриф)
            if _мысли:
                print("авторских мыслей из задания учтено: %d (их абзацы "
                      "в кандидаты не идут)" % len(_мысли))
            сп, набрано = кандидаты(абзацы, нужно, _мысли)
            if сп:
                print("")
                print("КАНДИДАТЫ НА РЕЗ — абзацы без единого якоря:")
                print("ни имени, ни числа, ни прямой речи, ни вопроса.")
                print("(решаешь ты, инструмент только показывает)")
                print("ВНИМАНИЕ: шутка и ирония тоже живут без чисел и имён —")
                print("если в абзаце есть острота, он остаётся, режем воду.")
                print("Абзацы, пересказывающие авторскую мысль ДРУГИМИ словами,")
                print("инструмент не распознаёт — такие проверяй глазами.")
                for i, длина in сп:
                    print("  %3d [%4d] %s" % (i, длина, абзацы[i][:85]))
                print("  итого в них %d знаков при нужных %d" % (набрано, нужно))
                print("  команда: --убрать %s --out <готово.txt>"
                      % ",".join(str(i) for i, _ in сп))
        if not a.drop:
            print("\nдальше: --убрать 8,19,24 --out <готово.txt>")
        return 0

    номера = set()
    for кусок in a.drop.replace(" ", "").split(","):
        if not кусок:
            continue
        if "-" in кусок:
            a1, a2 = кусок.split("-", 1)
            номера.update(range(int(a1), int(a2) + 1))
        else:
            номера.add(int(кусок))

    плохие = [n for n in номера if n < 0 or n >= len(абзацы)]
    if плохие:
        sys.exit("таких абзацев нет: %s (всего %d)" % (плохие, len(абзацы)))

    оставить = [p for i, p in enumerate(абзацы) if i not in номера]
    новый = "\n".join(оставить).strip() + "\n"

    print("убрано абзацев: %d" % len(номера))
    for n in sorted(номера):
        print("  %3d [%4d] %s" % (n, len(абзацы[n]), абзацы[n][:80]))
    print("было %d знаков → стало %d (минус %d)" % (len(t), len(новый), len(t) - len(новый)))
    if a.target:
        print("цель %d — %s" % (a.target, "уложились" if len(новый) <= a.target
                                else "НЕ уложились, резать ещё %d" % (len(новый) - a.target)))

    cta = len(CTA_RE.findall(новый))
    if cta < 2:
        print("  !! призывов подписаться осталось %d, по правилу их ДВА" % cta)
    if абзацы and абзацы[0] not in оставить:
        print("  !! УБРАН ПЕРВЫЙ АБЗАЦ — проверь, не был ли это утверждённый крючок")
    if новый.count("—"):
        print("  !! в тексте появились тире (%d) — их быть не должно" % новый.count("—"))

    if not a.out:
        print("\n--out не задан, файл не записан")
        return 0
    io.open(a.out, "w", encoding="utf-8").write(новый)
    print("готово: %s" % a.out)
    print("дальше: rewrite_lint.py <оригинал> %s --brief ЗАДАНИЕ-РЕРАЙТ.txt" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
