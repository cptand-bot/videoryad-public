#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ПРЕВЬЮ ДЛЯ КЛОНИРОВАННОГО КАНАЛА — БЕЗ ЕДИНОЙ НОВОЙ ГЕНЕРАЦИИ (08.11.2026).

Его слово: «на клонированные каналы могут уходить и оригиналы, те, которые я
утвердил… просто её отзеркаливаем. И пишем, может быть, даже те же надписи. Но
генерировать, перегенерировать точно не будем. Генерация может быть только на
„Планете“ и на „5 минутах“».

И раньше, про пять вариантов: «из трёх нечего будет выбрать. Я почему пять
оставил — что наверняка хоть одно мне подойдёт». То есть пять вариантов на
оригинале ОСТАЮТСЯ, а клоны живут тем, что уже нарисовано.

ОТКУДА БЕРЁМ КАРТИНКУ, по порядку:
  1. НЕИСПОЛЬЗОВАННЫЙ вариант донора — он их видел и не взял, значит они
     свободны (`превью-варианты/ПРЕВЬЮ-N.png`, кроме того, что он утвердил);
  2. если свободных нет — УТВЕРЖДЁННОЕ превью донора; оно зеркалится, чтобы
     в ленте не читалось как та же картинка.

ЧТО ДЕЛАЕМ С НЕЙ: зеркалим (по его слову), кладём надписи в гамме НОВОГО
канала и делаем квадрат 1:1 — ровно как на оригинале. Надписи можно взять
донорские (`--надписи донор`) или свои (`--верх`/`--низ`).

    python3 prevyu_klon.py "<папка донора>" "<папка клона>" \\
            [--верх "ДОИГРАЛИСЬ"] [--низ "ПРИШЛА РАСПЛАТА"] [--без-зеркала]

Ни одного обращения к внешнему агенту этот инструмент не делает.
"""

import argparse
import io
import glob
import os
import re
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ЗДЕСЬ)
import prevyu_text as _pt                                    # noqa: E402

try:
    from PIL import Image, ImageOps
except ImportError:
    sys.exit("нужен Pillow")


def варианты(folder):
    d = os.path.join(folder, "превью-варианты")
    if not os.path.isdir(d):
        return []
    out = []
    for n in sorted(os.listdir(d)):
        m = re.match(r"ПРЕВЬЮ-(\d+)\.png$", n)
        if m:
            out.append((int(m.group(1)), os.path.join(d, n)))
    return out


def _sibling_papki(folder):
    """Та же тема/день на «5 МИНУТ» и ПЛАНЕТЕ (п.241, 18.11): при ТРЁХ
    каналах на одну тему (5 МИНУТ + ПЛАНЕТА + третий клон) вариант,
    свободный у ОДНОГО донора, может быть уже занят ВТОРЫМ — `prevyu_klon`
    сверялся только с переданным в аргументах, отдал клону вариант,
    который уже стоял на сестринском канале."""
    ч = os.path.abspath(folder).replace("\\", "/").split("/")
    try:
        i = [x.upper() for x in ч].index("НОВОСТИ")
    except ValueError:
        return []
    номер = re.match(r"\s*(\d+)\s*-", ч[-1])
    найдено = []
    for канал in ("5 МИНУТ", "ПЛАНЕТА"):
        день = "/".join(ч[:i + 1] + [канал] + ч[i + 2:-1])
        if not os.path.isdir(день):
            continue
        for d in sorted(os.listdir(день)):
            путь = os.path.join(день, d)
            if not os.path.isdir(путь):
                continue
            свой = номер and re.match(r"\s*%s\s*-" % номер.group(1), d)
            if свой and os.path.abspath(путь) != os.path.abspath(folder):
                найдено.append(путь)
    return найдено


def утверждённые(folder):
    """Номера вариантов, которые уже взяты в работу — на переданном
    канале-доноре И на любом сестринском канале той же темы/дня."""
    взято = set()
    for папка in [folder] + _sibling_papki(folder):
        for n in os.listdir(папка):
            m = re.search(r"ПРЕВЬЮ-(\d+)(?:-КВАДРАТ)?\.png$", n)
            if m:
                взято.add(int(m.group(1)))
    return взято


def main():
    ap = argparse.ArgumentParser(description="превью клона из готовых вариантов донора")
    ap.add_argument("донор")
    ap.add_argument("клон")
    ap.add_argument("--верх", default="", dest="top")
    ap.add_argument("--низ", default="", dest="bottom")
    ap.add_argument("--надписи", default="свои", choices=("свои", "донор"),
                    help="«донор» — взять надписи с утверждённого превью донора")
    ap.add_argument("--без-зеркала", action="store_true", dest="no_mirror")
    # ЧИСТЫЕ ВАРИАНТЫ — ЕГО ПРЯМОЕ СЛОВО 15.11: «просто пустые варианты, без
    # никаких надписей, картинки должны приходить туда сейчас. Я ещё ничего
    # не правил». Надписи он ставит САМ на дашборде, выбрав кадр; до этого
    # момента на клон-канал должны лечь все пять отзеркаленных вариантов
    # БЕЗ единой буквы. Отказ «превью без надписей не делается» (14.11)
    # остаётся для ГОТОВОГО превью, а не для вариантов.
    ap.add_argument("--чисто", action="store_true", dest="chisto",
                    help="положить ВСЕ варианты донора отзеркаленными и БЕЗ "
                         "надписей в превью-варианты/ клона")
    ap.add_argument("--номер", type=int, default=0,
                    help="взять конкретный вариант донора")
    a = ap.parse_args()

    for p in (a.донор, a.клон):
        if not os.path.isdir(p):
            sys.exit("нет папки: %s" % p)

    все = варианты(a.донор)
    if not все:
        sys.exit("у донора нет вариантов превью (%s/превью-варианты/)" % a.донор)
    занятые = утверждённые(a.донор)

    if a.номер:
        выбор = [(n, p) for n, p in все if n == a.номер]
        if not выбор:
            sys.exit("варианта %d у донора нет" % a.номер)
        n, src = выбор[0]
        откуда = "вариант %d (назван ключом)" % n
    else:
        свободные = [(n, p) for n, p in все if n not in занятые]
        if свободные:
            n, src = свободные[0]
            откуда = "НЕиспользованный вариант %d донора" % n
        else:
            n, src = все[0]
            откуда = "утверждённое превью донора (свободных не осталось)"

    канал = _pt.channel_of(a.клон) if hasattr(_pt, "channel_of") else ""
    gamma = _pt.GAMMA.get((канал or "").upper(), _pt.DEFAULT)
    имя = _pt.theme_name(a.клон)

    # ЗЕРКАЛО — ЕГО ПРЯМОЕ СЛОВО: одна и та же картинка на двух каналах не
    # должна читаться как одна и та же картинка.
    tmp = os.path.join(a.клон, ".prevyu_klon_tmp.png")
    im = Image.open(src).convert("RGB")
    if not a.no_mirror:
        im = ImageOps.mirror(im)
    im.save(tmp)

    if a.chisto:
        # все варианты донора — зеркалом и без надписей
        _папка = os.path.join(a.клон, "превью-варианты")
        os.makedirs(_папка, exist_ok=True)
        _истч = sorted(glob.glob(os.path.join(a.донор, "превью-варианты",
                                              "ПРЕВЬЮ-*.png")))
        if not _истч:
            sys.exit("у донора нет вариантов в превью-варианты/")
        _сделано = 0
        for _ф in _истч:
            _им = Image.open(_ф).convert("RGB")
            if not a.no_mirror:
                _им = ImageOps.mirror(_им)
            _им.save(os.path.join(_папка, os.path.basename(_ф)))
            _сделано += 1
        os.remove(tmp)
        print("положено чистых вариантов: %d → %s" % (_сделано, _папка))
        print("надписи НЕ ставились — их выбирает он на дашборде")
        print("генерация НЕ запускалась: кадры взяты у донора зеркалом")
        return 0

    top, bottom = a.top.upper(), a.bottom.upper()
    # ПРЕВЬЮ БЕЗ НАДПИСЕЙ — ЭТО НЕ ПРЕВЬЮ (14.11, улов `usuario-3a`).
    # Без `--верх`/`--низ` инструмент молча клал ГОЛЫЙ кадр и печатал
    # «готово»: ровно тот класс «успех значит ничего не сделано», на
    # котором за день до этого сгорел целый прогон карточек. Сначала
    # пробуем взять надписи у самого клона — их пишет упаковка, — и только
    # если взять неоткуда, отказываем вслух.
    if not (top or bottom):
        for _имя_ф in ("УПАКОВКА.txt", "ЗАДАНИЕ-УПАКОВКА.ОТВЕТ.txt"):
            _пф = os.path.join(a.клон, _имя_ф)
            if not os.path.isfile(_пф):
                continue
            try:
                _т = open(_пф, encoding="utf-8", errors="replace").read()
            except OSError:
                continue
            # Надписи превью в упаковке стоят строками «ВЕРХ: …» / «НИЗ: …»
            _в = re.search(r"(?mi)^\s*(?:верх|верхняя\s+надпись)\s*[:—-]\s*(.+)$", _т)
            _н = re.search(r"(?mi)^\s*(?:низ|нижняя\s+надпись)\s*[:—-]\s*(.+)$", _т)
            if _в or _н:
                top = top or (_в.group(1).strip().upper() if _в else "")
                bottom = bottom or (_н.group(1).strip().upper() if _н else "")
                print("надписи взяты из упаковки клона (%s)" % _имя_ф)
                break
    if not (top or bottom):
        sys.exit("ОШИБКА: превью без надписей не делается — это голый кадр, "
                 "а не превью.\n"
                 "  Надписи донора в файле не хранятся, в упаковке клона их "
                 "тоже нет.\n"
                 "  Задай их прямо: --верх «…» --низ «…» — возьми с "
                 "УТВЕРЖДЁННОГО превью донора или из его упаковки.")

    dst = os.path.join(a.клон, "%s ПРЕВЬЮ-%d.png" % (имя, n))
    _pt.put(tmp, dst, top, bottom, gamma)
    _pt.put(tmp, os.path.join(a.клон, "%s ПРЕВЬЮ-%d-КВАДРАТ.png" % (имя, n)),
            top, bottom, gamma, square=True)
    os.remove(tmp)

    print("взято: %s" % откуда)
    print("канал клона: %s%s" % (канал or "не определён",
                                 "" if a.no_mirror else ", кадр отзеркалён"))
    print("готово: %s" % dst)
    print("        + квадрат рядом")
    print("генерация НЕ запускалась: превью рисуются только на «5 МИНУТ» и ПЛАНЕТЕ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
