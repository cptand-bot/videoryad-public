ЛИМИТ_ФРАЗЫ = 120


def _fraza(текст, лимит=ЛИМИТ_ФРАЗЫ):
    """Фраза для карточки — ЦЕЛЫМИ предложениями, слово не рвём.

    13.11, его прямое слово по сцене 20 ролика ПЛАНЕТЫ: «важна сама формула
    „Москва предлагает об“ — прерывается слово». Резалось грубо: `т[:120]`,
    ровно по 120-му символу, посреди слова «обвести». В кадр уезжал обрывок,
    и это видно только глазами на дашборде.

    Теперь: набираем предложения, пока влезают; если даже первое длиннее
    лимита — режем по границе СЛОВА и ставим многоточие.
    """
    т = " ".join(str(текст or "").split())
    if len(т) <= лимит:
        return т
    куски, тек = [], ""
    for кусок in re.split(r"(?<=[.!?])\s+", т):
        if not кусок:
            continue
        проба = (тек + " " + кусок).strip()
        if len(проба) <= лимит:
            тек = проба
        elif тек:
            break
        else:
            # первое же предложение не влезает — режем по словам
            слова, стр = кусок.split(), ""
            for w in слова:
                if len((стр + " " + w).strip()) > лимит - 1:
                    break
                стр = (стр + " " + w).strip()
            return _bez_ogryzka(стр) if стр else _bez_ogryzka(кусок[:лимит - 1])
    return _bez_ogryzka(тек) if тек else _bez_ogryzka(т[:лимит - 1])


# СЛУЖЕБНЫЕ СЛОВА, НА КОТОРЫХ ФРАЗУ ОБРЫВАТЬ НЕЛЬЗЯ (14.11, его слово по
# сцене 22 ролика `planeta-2-strashnye-poteri`: «Опять оборвана фраза на.
# Население и кадров. На. И дальше что? На. Это зачем обрывать?»).
# В кадр уехало «будущий дефицит населения и кадров. На исчезновение» — то
# есть сначала целое предложение, а за ним огрызок следующего, который в
# кадре разбился и кончился предлогом «На». Правило простое: карточка
# держит ЦЕЛЫЕ предложения; если после последней точки остался хвост — он
# отбрасывается, а не доносится до кадра.
_СЛУЖЕБНЫЕ = {
    "и", "а", "но", "да", "или", "либо", "то", "же", "ли", "бы", "не", "ни",
    "в", "во", "на", "над", "под", "за", "из", "от", "до", "по", "при", "про",
    "для", "без", "через", "о", "об", "обо", "с", "со", "к", "ко", "у", "их",
    "его", "её", "что", "как", "чем", "тем", "так", "это", "эта", "этот",
    "который", "которая", "которые", "когда", "если", "чтобы", "потому",
}


def _bez_ogryzka(стр):
    """Фраза кончается ЦЕЛОЙ мыслью, а не предлогом и не половиной фразы."""
    т = " ".join(str(стр or "").split()).strip()
    if not т:
        return ""
    # 1. есть граница предложения — держим ровно до неё, хвост отбрасываем
    m = list(re.finditer(r"[.!?…]", т))
    if m:
        конец = m[-1].end()
        целое = т[:конец].strip()
        хвост = т[конец:].strip()
        # хвост оставляем, только если он сам ЦЕЛОЕ предложение (кончается
        # знаком) — иначе это огрызок, ровно тот, что он поймал
        if хвост and not re.search(r"[.!?…]$", хвост):
            т = целое
    # 2. последним словом не должно стоять служебное
    слова = т.rstrip(" ,;:—-").split()
    while слова and слова[-1].strip(" ,;:—-…").lower() in _СЛУЖЕБНЫЕ:
        слова.pop()
    т = " ".join(слова).rstrip(" ,;:—-")
    return т


def _сцены(path):
    d = json.load(open(path, encoding="utf-8"))
    if isinstance(d, dict):
        for k in ("scenes", "сцены"):
            if isinstance(d.get(k), list):
                return d, d[k]
        raise SystemExit("в %s нет списка сцен" % path)
    return None, d


def _текст(s):
    for k in ("text", "текст", "line", "reply", "srt_text"):
        v = s.get(k)
        if isinstance(v, str) and v.strip():
            return v.strip()
    return ""


def _источник(s):
    return str(s.get("source") or s.get("источник") or "")


def _занята(s):
    и = _источник(s)
    return и.startswith("card:") or и.startswith("fx:") or bool(s.get("fx"))


def _номер(s, i):
    for k in ("sid", "id", "scene", "номер"):
        v = s.get(k)
        if isinstance(v, int):
            return v
        if isinstance(v, str) and v.isdigit():
            return int(v)
    return i


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scenes")
    ap.add_argument("--stavit", action="store_true",
                    help="поставить то, что выводится из текста сцены")
    ap.add_argument("--otpravit", action="store_true",
                    help="после постановки отправить рендер в облако")
    ap.add_argument("--naznachennye", action="store_true",
                    help="НАПОЛНИТЬ карточки, которые УЖЕ назначил агент "
                         "(source `card:<вид>` без задания в cards/queue): "
                         "ключи выводятся из текста той же сцены. Это главный "
                         "режим при комплекте 56 — иначе 56 вызовов руками")
    ap.add_argument("--limit", type=int, default=0,
                    help="поставить не больше N карточек (0 — сколько получится)")
    a = ap.parse_args()

    if not os.path.isfile(a.scenes):
        raise SystemExit("нет файла сцен: %s" % a.scenes)
    _, сцены = _сцены(a.scenes)
    всего = len(сцены)
    свободные = []
    for i, s in enumerate(сцены, 1):
        if i == 1 or _занята(s):
            continue
        т = _текст(s)
        if len(т) < 40:
            continue
        свободные.append((_номер(s, i), т))

    # ── РЕЖИМ «НАПОЛНИТЬ НАЗНАЧЕННЫЕ» (14.11, дыра `usuario-70`) ──
    # Инструмент умел только ПРЕДЛАГАТЬ новые карточки на свободные сцены. А
    # с комплектом 56 расклад обратный: виды уже назначены агентом в
    # раскадровке (`source: card:<вид>`), наполнять их нужно материалом из
    # текста той же сцены — и это 56 вызовов `card_put` руками с разными
    # ключами у каждого вида. У вкладки это съедало и время, и контекст:
    # «свободных под карточку: 4» при 56 назначенных.
    # Логика вывода ключей из текста уже есть (`_klyuchi`, П-0154) — здесь
    # она просто применяется к НАЗНАЧЕННОМУ виду, а не к выбранному нами.
    # Наполнена карточка или нет, видно по заданию в `cards/queue`: его
    # пишет `card_put`, и дальше по нему рисует облако.
    if a.naznachennye:
        _dir = os.path.dirname(os.path.abspath(a.scenes)) or "."
        _queue = os.path.join(_dir, "cards", "queue")
        назначенные, готовые, нечем = [], 0, []
        for i, s_ in enumerate(сцены, 1):
            ист = _источник(s_)
            if not ист.startswith("card:"):
                continue
            вид = ист[len("card:"):].strip()
            ном = _номер(s_, i)
            if os.path.isfile(os.path.join(_queue, "scene_%03d.json" % ном)):
                готовые += 1
                continue
            т = _текст(s_)
            дверь = _dver_vida(вид)
            if дверь and дверь != CARD_PUT:
                # ВИД ДРУГОЙ ДВЕРИ: ключи у него свои и почти все требуют
                # КАДРА (`--photo`, `--shot`) или готовых рядов, из текста их
                # не вывести. Честно называем вид и дверь, а не отбиваем его
                # «invalid choice» от `card_put`.
                нечем.append((ном, вид, os.path.basename(дверь)))
                continue
            фраза = _fraza_pod_vid(вид, т) or _fraza(т)
            кл = _klyuchi(вид, фраза, т)
            if кл is None:
                нечем.append((ном, вид, "материал"))
                continue
            назначенные.append((ном, вид, т, кл))
        print("НАЗНАЧЕНО АГЕНТОМ: карточек %d · уже с заданием %d · "
              "наполняю %d" % (готовые + len(назначенные) + len(нечем),
                               готовые, len(назначенные)))
        if нечем:
            print("материал из текста не выводится (%d) — поставь руками, "
                  "числа и фамилии выдумывать запрещено:" % len(нечем))
            for ном, вид, чем in нечем[:16]:
                if чем == "element_put.py":
                    print("  сцена %-3d %-16s дверь element_put.py "
                          "(нужен кадр или ряды)" % (ном, вид))
                elif чем == "style_card.py":
                    print("  сцена %-3d %-16s дверь style_card.py" % (ном, вид))
                else:
                    print("  сцена %-3d %-16s материал из текста не выводится"
                          % (ном, вид))
        if not a.stavit:
            print("ничего не поставлено (нужен ключ --stavit)")
            return 0
        поставлено, отказы = 0, []
        for ном, вид, т, кл in назначенные:
            r = subprocess.run([sys.executable, CARD_PUT, a.scenes, str(ном), вид] + кл,
                               capture_output=True, text=True)
            if r.returncode == 0:
                поставлено += 1
                print("  [ОК]    сцена %d → %s" % (ном, вид))
            else:
                хвост = (r.stderr or r.stdout or "").strip().splitlines()
                отказы.append("сцена %d (%s): %s"
                              % (ном, вид, хвост[-1] if хвост else "код %d" % r.returncode))
        print("\nнаполнено карточек: %d из %d" % (поставлено, len(назначенные)))
        for о in отказы:
            print("  [ОТКАЗ] %s" % о)
        if a.otpravit and поставлено:
            print("\nотправляю рисовку в облако:")
            subprocess.run([sys.executable, CARDS_CLOUD], cwd=_dir)
        return 0 if not отказы else 1

    print("сцен в ролике: %d · свободных под карточку: %d" % (всего, len(свободные)))
    print("кадр НЕ нужен 28 видам из 36 — фетча и аудита они не ждут")

    # ── 1. РАСПРЕДЕЛЕНИЕ ПО ПРИЗНАКАМ ТЕКСТА ──
    план = []          # (сцена, вид, текст, ключи card_put)
    занято = set()
    for вид, рг in ПРИЗНАКИ:
        if вид not in САМИ:
            continue
        for ном, т in свободные:
            if ном in занято:
                continue
            if not рг.search(т):
                continue
            кл = _klyuchi(вид, _fraza_pod_vid(вид, т), т)
            if not кл:
                continue
            план.append((ном, вид, т, кл))
            занято.add(ном)
            break

    # ── 2. ДЕВЯТЬ ПРИЁМОВ ЗАЛА — ОБЯЗАТЕЛЬНЫ, РАЗНОСИМ ПО РОЛИКУ ──
    # ВИД ИДЁТ ТУДА, ГДЕ В ТЕКСТЕ ЕСТЬ НУЖНОЕ (13.11, пункт 55). Раньше вид
    # вставал на сцену ПО ПОРЯДКУ, без оглядки на то, выводятся ли его ключи:
    # шкала попадала на сцену без единого числа, панель эфира — на сцену без
    # реплики и имени, и `card_put` отбивал одиннадцать карточек из двенадцати.
    # Теперь каждый приём ищет СВОЮ сцену: идём от позиции с шагом, но берём
    # первую сцену, где ключи выводятся честно; не нашлось — вид пропускается
    # и называется вслух, а не отбивается молча на чужой сцене.
    залы = [в for в in САМИ if в.startswith("zal")]
    шаг = max(1, len(свободные) // max(1, len(залы)))
    поз, без_материала = 0, []
    for вид in залы:
        порядок = list(range(поз, len(свободные))) + list(range(0, поз))
        взял = None
        for i in порядок:
            ном, т = свободные[i]
            if ном in занято:
                continue
            кл = _klyuchi(вид, _fraza_pod_vid(вид, т), т)
            if not кл:
                continue
            взял = (i, ном, т, кл)
            break
        if not взял:
            без_материала.append(вид)
            continue
        i, ном, т, кл = взял
        план.append((ном, вид, т, кл))
        занято.add(ном)
        поз = min(len(свободные), i + шаг)

    план.sort()
    if a.limit:
        план = план[:a.limit]

    print("\nПЛАН (ставится по тексту, кадр не нужен):")
    for ном, вид, т, кл in план:
        _видно = " ".join(
            ("%s %s" % (к, v)) for к, v in zip(кл[::2], кл[1::2])
            if к in ("--na-polu", "--kick", "--value", "--say", "--author",
                     "--maket", "--accent"))
        print("  сцена %-3d %-14s %s" % (ном, вид, САМИ[вид]))
        print("            «%s»" % т[:90])
        if _видно:
            print("            ключи: %s" % _видно[:150])
    if без_материала:
        print("\nВ ТЕКСТЕ НЕТ МАТЕРИАЛА ПОД ЭТИ ПРИЁМЫ (%d) — выдумывать "
              "числа и фамилии запрещено:" % len(без_материала))
        for в in без_материала:
            чего = {"value": "величины в тексте", "makety": "двух названных "
                    "предметов", "say": "реплики в кавычках и имени говорящего",
                    "author": "имени говорящего", "na_polu": "ударного слова",
                    "kick": "ударного слова"}
            нужно = sorted({чего.get(k, k) for k in ТРЕБУЕТ.get(в, ())})
            print("  %-14s нет %s" % (в, ", ".join(нужно)))
        print("  поставь их сам там, где материал есть: python3 %s <сцена> "
              "<вид> --text «…» …" % CARD_PUT)

    # ── 3. ЧТО ТРЕБУЕТ ЕГО РЕШЕНИЯ: ЦИФРЫ И ОБЛАСТИ ──
    счётные = [(н, т) for н, т in свободные if н not in занято and ЧИСЛО.search(т)]
    if счётные:
        print("\nСЦЕНЫ С ЧИСЛАМИ — под диаграмму или карту (ряды задаёшь ты,")
        print("выдумывать цифры запрещено; нет цифр — показываем соотношение):")
        for н, т in счётные[:8]:
            print("  сцена %-3d «%s»" % (н, т[:80]))
        print("  чем ставить: python3 %s %s <сцена> bubbles|pie|map_regions|slope|waterfall …"
              % (CARD_PUT, a.scenes))

    if not a.stavit:
        print("\nничего не поставлено (нужен ключ --stavit)")
        return 0

    # ── 4. ПОСТАНОВКА ──
    поставлено, отказы = 0, []
    for ном, вид, т, кл in план:
        кмд = [sys.executable, CARD_PUT, a.scenes, str(ном), вид] + кл
        r = subprocess.run(кмд, capture_output=True, text=True)
        if r.returncode == 0:
            поставлено += 1
            print("  [ОК]    сцена %d → %s" % (ном, вид))
        else:
            хвост = (r.stderr or r.stdout or "").strip().splitlines()
            отказы.append("сцена %d (%s): %s" % (ном, вид, хвост[-1] if хвост else "код %d" % r.returncode))

    print("\nпоставлено карточек: %d из %d" % (поставлено, len(план)))
    for о in отказы:
        print("  [ОТКАЗ] %s" % о)

    # ── 5. РЕНДЕР В ОБЛАКЕ, ПОКА ИДЁТ ФЕТЧ ──
    if a.otpravit and поставлено:
        print("\nотправляю рисовку в облако (идёт параллельно фетчу):")
        r = subprocess.run([sys.executable, CARDS_CLOUD],
                           cwd=os.path.dirname(os.path.abspath(a.scenes)) or ".")
        if r.returncode != 0:
            print("  рендер не отправился — позови cards_cloud.py вручную", file=sys.stderr)
            return 1
    elif a.otpravit:
        print("\nотправлять нечего: ни одна карточка не поставлена")
    return 0 if поставлено or not a.stavit else 1


if __name__ == "__main__":
    sys.exit(main())
