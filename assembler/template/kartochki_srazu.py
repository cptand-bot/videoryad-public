#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""КАРТОЧКИ, КОТОРЫМ НЕ НУЖЕН НАЙДЕННЫЙ КАДР — СТАВИМ СРАЗУ ПОСЛЕ РАСКАДРОВКИ.

Его слово 13.11.2026: «у нас есть карточки, которые не требуют картинок,
аудита, перепроверок на всякого рода логотипы, водяные знаки, детей и тому
подобное. Там какая-то цитата, да, вот этих карточек. То их, в принципе, при
получении раскадровки можно делать сразу, чтобы они уже лежали готовыми. Это
особенно касается вторых вариантов статей на канал Планета».

ЗАЧЕМ. Из 36 видов двери `card:<вид>` кадр нужен только восьми (`photo`,
`film`, `dossier`, `vyrezka`, `split`, `torn`, `device`, `film_frame`).
Остальные 28 рисуются ПО ТЕКСТУ: цитата, лоскуты, лента, карты, диаграммы,
девять приёмов белого зала. Им не нужен ни фетч, ни аудит на клейма, ни
проверка на детей — значит ждать фетча незачем, они могут лежать готовыми к
моменту, когда приедут кадры.

    python3 kartochki_srazu.py <ролик>.scenes.json                 # план: что ставить и чем
    python3 kartochki_srazu.py <ролик>.scenes.json --stavit        # поставить то, что выводится из текста
    python3 kartochki_srazu.py <ролик>.scenes.json --stavit --otpravit   # и сразу отрисовать в облаке

ЧТО СТАВИТ САМ. Только там, где все параметры берутся из ТЕКСТА сцены:
девять приёмов зала, цитата, лоскуты, лента, врез, маркер. Диаграммам и
картам нужны ряды и области — на них печатается готовая команда с
подсказкой, решает вкладка: цифр в тексте может не быть вовсе, а выдумывать
их запрещено (его слово 28.10).

ЧЕГО НЕ ДЕЛАЕТ. Не трогает сцены, где уже стоит наш кадр или эффект, не
занимает первую сцену (крючок) и не ставит две карточки подряд там, где
зазор ещё можно соблюсти: порядок выбора — сначала сцены с запасом, и лишь
когда свободных мест не остаётся, идут соседние (с 13.11 это норма, а не
брак, см. SKILL.md «КУДА ИДЁТ ВИДЕОРЯД»).
"""
import argparse
import json
import os
import re
import subprocess
import sys

SKILL = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CARD_PUT = os.path.join(SKILL, "fullcycle", "card_put.py")
CARDS_CLOUD = os.path.join(SKILL, "fullcycle", "cards_cloud.py")

# Виды, у которых ВСЕ параметры выводятся из текста сцены: их ставим сами.
# Остальные самодостаточные (карты, диаграммы) требуют рядов и областей —
# по ним печатаем команду, а не угадываем числа.
САМИ = {
    "zal":            "панорама зала: фраза сцены и наклейки со словами",
    "zal_slova":      "фраза в зале, нижняя строка объёмными буквами на полу",
    "zal_pol":        "слово выезжает из пола",
    "zal_kub":        "фраза по словам, с потолка стеклянный куб",
    "zal_shkala":     "вертикальная шкала наливается светом",
    "zal_schetchik":  "перекидное табло со счётчиком",
    "zal_makety":     "макеты в зале (банк, больница, ЛЭП)",
    "zal_efir":       "панель эфира во весь кадр",
    "zal_ekran":      "экран в зале с расшифровкой справа",
    "quote":          "лоскут бумаги с маркером: прямая речь",
    "tape":           "лента: сухая официальная формулировка",
    "paper_hand":     "лоскут от руки, синие чернила",
    "paper_typed":    "лоскут-машинопись, ёлочки",
    "pull":           "врез: вынесенная фраза крупно",
    "marker_serif":   "мазок маркером под словом",
    "doc":            "документ: заголовок и строки",
}

# Что в тексте сцены выдаёт подходящий вид. Порядок важен: первый
# совпавший забирает сцену.
ПРИЗНАКИ = [
    ("quote",     re.compile(r"[«\"].{12,}?[»\"]")),
    ("tape",      re.compile(r"\b(заявил|сообщил|подчеркнул|отметил|по словам|как сказал)\b", re.I)),
    ("pull",      re.compile(r"\b(главное|именно поэтому|вот и вся|итог|вывод)\b", re.I)),
    ("doc",       re.compile(r"\b(соглашени|документ|протокол|меморандум|договор|проект решения)\w*", re.I)),
    ("strike",    re.compile(r"\b(обещал|обещан|говорил ранее|теперь говорит|передумал)\w*", re.I)),
]

ЧИСЛО = re.compile(r"\d|\b(процент|миллион|миллиард|тысяч|триллион)\w*", re.I)


ЛИМИТ_ФРАЗЫ = 120


def _fraza(текст, лимит=ЛИМИТ_ФРАЗЫ):
    """Фраза для карточки — ЦЕЛЫМИ предложениями, слово не рвём.

    13.11, его прямое слово по сцене 20 ролика ПЛАНЕТЫ: «важна сама формула
    „Москва предлагает об“ — прерывается слово». Резалось грубо: `т[:120]`,
    ровно по 120-му символу, посреди слова «обвести». В кадр уезжал обрывок,
    и это видно только глазами на дашборде.

    Теперь: набираем предложения, пока влезают; если даже первое длиннее
    лимита — режем по границе СЛОВА и ставим многоточие.
    """
    т = " ".join(str(текст or "").split())
    if len(т) <= лимит:
        return т
    куски, тек = [], ""
    for кусок in re.split(r"(?<=[.!?])\s+", т):
        if not кусок:
            continue
        проба = (тек + " " + кусок).strip()
        if len(проба) <= лимит:
            тек = проба
        elif тек:
            break
        else:
            # первое же предложение не влезает — режем по словам
            слова, стр = кусок.split(), ""
            for w in слова:
                if len((стр + " " + w).strip()) > лимит - 1:
                    break
                стр = (стр + " " + w).strip()
            return (стр.rstrip(",;:—-") + "…") if стр else кусок[:лимит - 1] + "…"
    return тек or т[:лимит - 1] + "…"


def _сцены(path):
    d = json.load(open(path, encoding="utf-8"))
    if isinstance(d, dict):
        for k in ("scenes", "сцены"):
            if isinstance(d.get(k), list):
                return d, d[k]
        raise SystemExit("в %s нет списка сцен" % path)
    return None, d


def _текст(s):
    for k in ("text", "текст", "line", "reply", "srt_text"):
        v = s.get(k)
        if isinstance(v, str) and v.strip():
            return v.strip()
    return ""


def _источник(s):
    return str(s.get("source") or s.get("источник") or "")


def _занята(s):
    и = _источник(s)
    return и.startswith("card:") or и.startswith("fx:") or bool(s.get("fx"))


def _номер(s, i):
    for k in ("sid", "id", "scene", "номер"):
        v = s.get(k)
        if isinstance(v, int):
            return v
        if isinstance(v, str) and v.isdigit():
            return int(v)
    return i


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("scenes")
    ap.add_argument("--stavit", action="store_true",
                    help="поставить то, что выводится из текста сцены")
    ap.add_argument("--otpravit", action="store_true",
                    help="после постановки отправить рендер в облако")
    ap.add_argument("--limit", type=int, default=0,
                    help="поставить не больше N карточек (0 — сколько получится)")
    a = ap.parse_args()

    if not os.path.isfile(a.scenes):
        raise SystemExit("нет файла сцен: %s" % a.scenes)
    _, сцены = _сцены(a.scenes)
    всего = len(сцены)
    свободные = []
    for i, s in enumerate(сцены, 1):
        if i == 1 or _занята(s):
            continue
        т = _текст(s)
        if len(т) < 40:
            continue
        свободные.append((_номер(s, i), т))

    print("сцен в ролике: %d · свободных под карточку: %d" % (всего, len(свободные)))
    print("кадр НЕ нужен 28 видам из 36 — фетча и аудита они не ждут")

    # ── 1. РАСПРЕДЕЛЕНИЕ ПО ПРИЗНАКАМ ТЕКСТА ──
    план = []          # (сцена, вид, текст)
    занято = set()
    for вид, рг in ПРИЗНАКИ:
        if вид not in САМИ:
            continue
        for ном, т in свободные:
            if ном in занято:
                continue
            if рг.search(т):
                план.append((ном, вид, т))
                занято.add(ном)
                break

    # ── 2. ДЕВЯТЬ ПРИЁМОВ ЗАЛА — ОБЯЗАТЕЛЬНЫ, РАЗНОСИМ ПО РОЛИКУ ──
    залы = [в for в in САМИ if в.startswith("zal")]
    шаг = max(1, len(свободные) // max(1, len(залы)))
    поз = 0
    for вид in залы:
        while поз < len(свободные) and свободные[поз][0] in занято:
            поз += 1
        if поз >= len(свободные):
            break
        ном, т = свободные[поз]
        план.append((ном, вид, т))
        занято.add(ном)
        поз += шаг

    план.sort()
    if a.limit:
        план = план[:a.limit]

    print("\nПЛАН (ставится по тексту, кадр не нужен):")
    for ном, вид, т in план:
        print("  сцена %-3d %-14s %s" % (ном, вид, САМИ[вид]))
        print("            «%s»" % т[:90])

    # ── 3. ЧТО ТРЕБУЕТ ЕГО РЕШЕНИЯ: ЦИФРЫ И ОБЛАСТИ ──
    счётные = [(н, т) for н, т in свободные if н not in занято and ЧИСЛО.search(т)]
    if счётные:
        print("\nСЦЕНЫ С ЧИСЛАМИ — под диаграмму или карту (ряды задаёшь ты,")
        print("выдумывать цифры запрещено; нет цифр — показываем соотношение):")
        for н, т in счётные[:8]:
            print("  сцена %-3d «%s»" % (н, т[:80]))
        print("  чем ставить: python3 %s %s <сцена> bubbles|pie|map_regions|slope|waterfall …"
              % (CARD_PUT, a.scenes))

    if not a.stavit:
        print("\nничего не поставлено (нужен ключ --stavit)")
        return 0

    # ── 4. ПОСТАНОВКА ──
    поставлено, отказы = 0, []
    for ном, вид, т in план:
        фраза = _fraza(т)
        слова = [w.strip(",.!?;:«»\"()").upper()
                 for w in фраза.split() if len(w.strip(",.!?;:«»\"()")) >= 5][:4]
        кмд = [sys.executable, CARD_PUT, a.scenes, str(ном), вид, "--text", фраза]
        if вид.startswith("zal"):
            for w in слова[:2]:
                кмд += ["--word", w]
            for _ in range(2):
                кмд += ["--sheet", фраза[:60]]
        elif слова:
            кмд += ["--accent", слова[0]]
        r = subprocess.run(кмд, capture_output=True, text=True)
        if r.returncode == 0:
            поставлено += 1
            print("  [ОК]    сцена %d → %s" % (ном, вид))
        else:
            хвост = (r.stderr or r.stdout or "").strip().splitlines()
            отказы.append("сцена %d (%s): %s" % (ном, вид, хвост[-1] if хвост else "код %d" % r.returncode))

    print("\nпоставлено карточек: %d из %d" % (поставлено, len(план)))
    for о in отказы:
        print("  [ОТКАЗ] %s" % о)

    # ── 5. РЕНДЕР В ОБЛАКЕ, ПОКА ИДЁТ ФЕТЧ ──
    if a.otpravit and поставлено:
        print("\nотправляю рисовку в облако (идёт параллельно фетчу):")
        r = subprocess.run([sys.executable, CARDS_CLOUD],
                           cwd=os.path.dirname(os.path.abspath(a.scenes)) or ".")
        if r.returncode != 0:
            print("  рендер не отправился — позови cards_cloud.py вручную", file=sys.stderr)
            return 1
    elif a.otpravit:
        print("\nотправлять нечего: ни одна карточка не поставлена")
    return 0 if поставлено or not a.stavit else 1


if __name__ == "__main__":
    sys.exit(main())
