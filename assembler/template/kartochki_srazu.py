def _udarnoe(фраза, сколько=1):
    """Ударные слова фразы ЗАГЛАВНЫМИ — то, что встаёт на полу и в кубе."""
    слова = []
    for w in str(фраза or "").split():
        ч = w.strip(",.!?;:«»\"()—-–").strip()
        if len(ч) < 5 or ч.lower() in СЛУЖЕБНЫЕ or ч.isdigit():
            continue
        # ГЛАГОЛ НА ПОЛУ ЧИТАЕТСЯ КАК ОШИБКА ВЁРСТКИ (13.11, первый же прогон
        # поставил «ПОЯВЛЯЮТСЯ» и «ВЫРАЖАТЬ»). Объёмной строкой встаёт ПРЕДМЕТ
        # разговора, поэтому отбрасываем формы глагола по окончанию.
        if ГЛАГОЛ.search(ч.lower()):
            continue
        if ч.upper() in слова:
            continue
        слова.append(ч.upper())
    # ИМЯ СОБСТВЕННОЕ СИЛЬНЕЕ ДЛИННОГО СЛОВА: «ШВЕЙЦАРИЯ» на полу читается
    # как предмет разговора, «ПОРУЧИЛ» — как опечатка. Первым словом фразы
    # предложение начинается всегда, поэтому его за имя собственное не
    # считаем.
    свои = []
    for w in str(фраза or "").split()[1:]:
        ч = w.strip(",.!?;:«»\"()—-–").strip()
        if (len(ч) >= 5 and ч[:1].isupper() and ч.upper() in слова
                and ч.upper() not in свои):
            свои.append(ч.upper())
    слова.sort(key=len, reverse=True)
    итог = свои + [w for w in слова if w not in свои]
    return итог[:сколько]


