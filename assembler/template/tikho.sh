#!/usr/bin/env bash
# ТИХО — запустить инструмент, не затаскивая его простыню в переписку (09.11).
#
#   bash template/tikho.sh <команда…>
#   bash template/tikho.sh --log /путь/мой.log python3 template/selfcheck.py s.json images
#
# Зачем: расход токенов = число шагов × размер переписки. Замер 09.11: за день
# инструменты вылили в переписку 13,3 МБ вывода, 56 ответов крупнее 20 КБ —
# и каждый такой ответ потом перечитывается на КАЖДОМ следующем шаге вкладки.
#
# Что делает: весь вывод кладёт в лог (по умолчанию `.tikho.log` рядом с cwd),
# в переписку печатает ТОЛЬКО: код возврата, число строк, значимые строки
# (находки, отказы, итоги) и последние три строки. Код возврата сохраняется,
# поэтому `&&`/`||` в вызывающем месте работают как раньше.
set -uo pipefail
LOG=".tikho.log"
if [ "${1:-}" = "--log" ]; then LOG="$2"; shift 2; fi
[ $# -gt 0 ] || { echo "ОШИБКА: tikho.sh [--log файл] <команда…>"; exit 1; }
MARK='ОШИБКА|ОТКАЗ|ЗАПРЕТ|!!|НЕ ВЫТЯНУТА|ФАНТОМ|ПОСМОТРЕТЬ ГЛАЗАМИ|подозрит|ИСЧЕРПАНА|не совпал|битый|НЕ НАЙДЕН|ИТОГ|ГОТОВО'
OUT="$(mktemp)"
"$@" > "$OUT" 2>&1; RC=$?
cat "$OUT" >> "$LOG"
N=$(wc -l < "$OUT")
echo "—— $* · код $RC · строк $N · полностью: $LOG"
grep -nE "$MARK" "$OUT" | grep -vE "(нет|чисто|ровное|не найдено)\s*$|ых нет" | head -8 | cut -c1-200
echo "·· хвост:"; tail -3 "$OUT" | cut -c1-200
rm -f "$OUT"
exit $RC
