"""СЧЁТ ПРИЗЫВОВ ПОДПИСАТЬСЯ — ОДИН ДЕТЕКТОР НА ТРИ ИНСТРУМЕНТА (15.11.2026).

Улов `usuario-1a`: `rewrite_fix` ВСТАВИЛ ТРЕТИЙ призыв в текст, где их уже
было два. Детектор считал только повелительные формы
(«подпишись/подпишитесь/подписывайся») и не видел инфинитив в безличном
обороте — «Не забудьте ПОДПИСАТЬСЯ». Инструмент насчитал один призыв,
добавил свой, и в разложенном файле стало три. `rewrite_lint` молчал,
потому что считал ТЕМ ЖЕ узким выражением — три инструмента держали одну
и ту же половинчатую проверку.

НЕ СЧИТАЕМ подписание документов: «подпишут соглашение», «подпишет указ»,
«подписание договора» — это про бумаги, а не про канал.

    from prizyv import ПРИЗЫВ_RE, сколько
"""
import re

# повелительные + инфинитив в обороте призыва + «подписка на канал»
ПРИЗЫВ_RE = re.compile(
    r"подпиш(?:ись|итесь)"
    r"|подписывай(?:ся|тесь)"
    r"|(?:не\s+забудь(?:те)?|стоит|можно|советую|рекомендую|прошу|успей(?:те)?)"
    r"[^.!?]{0,40}подписаться"
    r"|подписаться\s+на\s+(?:канал|нас)"
    r"|подписк[ауе]\s+на\s+(?:канал|нас)",
    re.I)


def сколько(текст):
    """Сколько призывов подписаться в тексте."""
    return len(ПРИЗЫВ_RE.findall(str(текст or "")))


def места(текст):
    """Фрагменты с призывами — чтобы показать, какие именно нашлись."""
    return [m.group(0).strip() for m in ПРИЗЫВ_RE.finditer(str(текст or ""))]
