#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""smena_pora.py — ПОРА ЛИ ПЕРЕДАВАТЬ СМЕНУ (09.11.2026).

    python3 smena_pora.py            # про текущую (самую свежую) вкладку
    python3 smena_pora.py --vse      # по всем живым вкладкам дня

Его вопрос 09.11: «осталось решить, когда тебе передавать смену другой новой
управляющей вкладке. На каком этапе?» — ответ должен быть ЧИСЛОМ, а не
ощущением, поэтому порог считается по транскрипту.

ПОЧЕМУ ВООБЩЕ НАДО МЕНЯТЬ. Каждый запрос заново подаёт весь накопленный
контекст, значит цена запроса растёт вместе с ним. Замер 16.10 по четвертям
сессии: 233 К → 433 К → 591 К → 670 К, то есть к концу вкладки запрос дороже
начала в 2,9 раза. Пересчёт 12 длинных сессий: 6558 М против 2882 М, если бы
те же запросы шли отрезками по 250 в свежих вкладках.

ПОРОГИ ПОНИЖЕНЫ 11.11.2026 ПО РАЗБОРУ ЧУЖОГО КОНВЕЙЕРА (cinecode). Его слово:
«если у нас есть хуёвая, а у него есть хорошая, то давай сделаем хорошую».
Что у него лучше и что отсюда взято:
  1. ПОРОГИ РАНЬШЕ. У него первое предупреждение на 160 К, второе на 260 К —
     у нас было 400 К. Наш же замер 16.10 (233 К → 433 К → 591 К → 670 К по
     четвертям) говорит, что цена растёт С САМОГО НАЧАЛА: к 400 К половина
     переплаты уже сделана. Ждать 400 К — значит ловить момент, когда поздно.
  2. СРАБАТЫВАЕТ НА ВХОДЕ В ХОД, А НЕ НА ВЫХОДЕ. У него напоминание приходит
     вместе с сообщением пользователя, то есть вкладка может закруглиться
     ПРЯМО СЕЙЧАС. У нас висело на Stop — вкладка узнавала, когда ход уже
     закончен, и всё равно начинала следующий.
  3. ОДИН РАЗ НА ПОРОГ. У него напоминание не повторяется. У нас после 400 К
     красная простыня печаталась КАЖДЫЙ ход — а то, что мелькает каждый раз,
     перестают замечать.
Своё, чего нет у него, оставлено: красная плашка большими буквами для него
лично (его прямое слово 09.11) и счёт по числу запросов.

  контекст ≥ 260 К   — ТИХО агенту: закругляйся, сдашь шаг — /clear;
  контекст ≥ 400 К   — ПОРА, красная плашка ему;
  контекст ≥ 550 К   — СРОЧНО, каждый шаг стоит как три утренних;
  запросов ≥ 600     — ПОРА, независимо от контекста.

ПОРОГИ ПОДНЯТЫ 12.11 ЕГО ПРЯМЫМ СЛОВОМ: «до 250 — это капец, мы же будем
менять управляющие вкладки как перчатки. Мы на 400 договаривались, что
начинается это „пора“, ну не 250». Счёт по запросам сбивал смену на 259-м
запросе при контексте 231 К — то есть вдвое раньше договорённости; теперь он
страхует только разогнавшуюся вкладку, а решает контекст.

ЧТО ПЕРЕДАВАТЬ: ничего. Состояние пишется само (`sostoyanie.sh` в cron
каждые 20 минут), план — `ПЛАН-ЭКОНОМИИ.md`, решения — `CHANGELOG.md`, память
— в `~/.claude/projects/-home-andrey/memory`. Новая вкладка говорит «смена».
"""
import glob
import json
import os
import sys
import time

ROOT = os.path.expanduser("~/.claude/projects")
ПОРОГ_ТИХО = 260_000      # первое, тихое — только агенту
ПОРОГ_КОНТЕКСТ = 400_000  # ПОРА (его слово 12.11: «мы на 400 договаривались»)
ПОРОГ_СРОЧНО = 550_000    # СРОЧНО
ПОРОГ_ЗАПРОСОВ = 600      # страховка от разогнавшейся вкладки, не повод смены
ОТМЕТКИ = "/tmp/videoryad-smena"   # что уже сказали этой вкладке


def разбор(путь):
    ctx = 0
    запросов = 0
    начало = ""
    последний = ""
    for line in open(путь, encoding="utf-8", errors="replace"):
        if '"type":"assistant"' not in line and '"type": "assistant"' not in line:
            continue
        try:
            d = json.loads(line)
        except Exception:
            continue
        u = (d.get("message") or {}).get("usage") or {}
        if not u:
            continue
        запросов += 1
        c = u.get("cache_read_input_tokens", 0) + u.get("input_tokens", 0) + \
            u.get("cache_creation_input_tokens", 0)
        if c > ctx:
            ctx = c
        ts = d.get("timestamp", "")[:16].replace("T", " ")
        начало = начало or ts
        последний = ts or последний
    return ctx, запросов, начало, последний


def сказано_раньше(файл, уровень):
    """Один порог — одно напоминание на вкладку. Повтор каждый ход превращает
    предупреждение в фон, который перестают читать (это и было нашей бедой)."""
    try:
        os.makedirs(ОТМЕТКИ, exist_ok=True)
        метка = os.path.join(ОТМЕТКИ,
                             os.path.basename(файл)[:40] + "." + уровень)
        if os.path.exists(метка):
            return True
        open(метка, "w").close()
    except Exception:
        return False
    return False


def вердикт(ctx, запросов):
    if ctx >= ПОРОГ_СРОЧНО:
        return "СРОЧНО", ("контекст %d К — каждый шаг стоит как три утренних" % (ctx // 1000))
    if ctx >= ПОРОГ_КОНТЕКСТ:
        return "ПОРА", ("контекст %d К (порог %d К)" % (ctx // 1000, ПОРОГ_КОНТЕКСТ // 1000))
    if запросов >= ПОРОГ_ЗАПРОСОВ:
        return "ПОРА", ("запросов %d (порог %d)" % (запросов, ПОРОГ_ЗАПРОСОВ))
    if ctx >= ПОРОГ_ТИХО:
        return "закругляйся", ("контекст %d К — дальше каждый запрос дороже; "
                               "доведи текущий шаг и /clear" % (ctx // 1000))
    остаток = min(ПОРОГ_ТИХО - ctx, 10 ** 9)
    return "рано", ("контекст %d К, запросов %d — до порога ещё ~%d К" % (
        ctx // 1000, запросов, остаток // 1000))


def не_пора_молчим(пора):
    """Тихий режим: молчим, пока не пора. Хук на каждом ответе не должен
    мелькать строкой «рано» — иначе его перестают замечать."""
    return not пора


def main():
    все = "--vse" in sys.argv
    тихо = "--tiho" in sys.argv   # молчит, пока не пора: для хука на каждом ответе
    вход = "--hook-vhod" in sys.argv  # хук НА ВХОДЕ в ход: агент успевает закруглиться
    файлы = sorted(glob.glob(os.path.join(ROOT, "*", "*.jsonl")),
                   key=os.path.getmtime, reverse=True)
    свежие = time.time() - 6 * 3600
    файлы = [f for f in файлы if os.path.getmtime(f) > свежие] or файлы[:1]
    if not все:
        файлы = файлы[:1]
    пора = False
    уровень, причина, текущий = "рано", "", ""
    строки = []
    for f in файлы:
        ctx, запросов, нач, посл = разбор(f)
        if not запросов:
            continue
        в, почему = вердикт(ctx, запросов)
        пора = пора or (в in ("ПОРА", "СРОЧНО"))
        if not текущий:
            уровень, причина, текущий = в, почему, f
        строки.append("%-10s %-7s %s  (с %s по %s)" % (os.path.basename(f)[:8], в, почему, нач, посл))
    # ХУК НА ВХОДЕ В ХОД (взято у cinecode): вкладка узнаёт о пороге, пока ход
    # только начинается, и может довести шаг и закрыться сама. Печатается
    # ровно один раз на порог — иначе напоминание становится фоном.
    if вход:
        if уровень == "рано" or not текущий:
            return 0
        if сказано_раньше(текущий, уровень):
            return 0
        if уровень == "закругляйся":
            print("КОНТЕКСТ РАСТЁТ: %s. Новых больших дел не начинай, доведи "
                  "текущий шаг, запиши состояние файлом и предложи /clear." % причина)
        elif уровень == "ПОРА":
            # ПОРА = «НА БЛИЖАЙШЕМ ШВЕ», А НЕ «БРОСАЙ» (12.11, его слово:
            # «278, ну как-то маловат контекст… мы только раздали задание, и
            # что она будет делать? Это мы только будем заниматься сменами
            # вкладок?»). Пересменка в середине дела дороже дорогого
            # запроса: новая вкладка перечитывает состояние и доделывает
            # чужое. Поэтому порог 260 К держим, но меняемся на ШВЕ —
            # тема роздана, ролик сдан, правки раскатаны. Жёсткий рубеж —
            # СРОЧНО (400 К), там шов уже не ждут.
            print("ПОРА МЕНЯТЬ ВКЛАДКУ НА БЛИЖАЙШЕМ ШВЕ: %s. Шов — тема "
                  "роздана / ролик сдан / правки раскатаны. Дошёл до шва: "
                  "`peredacha.py --zapisat` и новая вкладка словом «СМЕНА» "
                  "(рабочая — /clear). Посреди дела НЕ менять." % причина)
        else:
            print("%s МЕНЯТЬ ВКЛАДКУ: %s. Доводи до конца только текущий шаг, "
                  "дальше `peredacha.py --zapisat` и новая вкладка словом "
                  "«СМЕНА», рабочая — /clear." % (уровень, причина))
        return 0

    if тихо:
        if не_пора_молчим(пора):
            return 0
        if текущий and сказано_раньше(текущий, "плашка-" + уровень):
            return 0
        # КРАСНЫМ И БОЛЬШИМИ (его прямое слово 09.11: «большими буквами, чтобы
        # я понимал. Можно ещё красным»). Цвет гасим, если вывод не в терминал
        # (`| tee`, лог) — иначе в файле остаётся мусор из escape-последовательностей.
        цвет = sys.stdout.isatty() and os.environ.get("NO_COLOR", "") == ""
        R = "\033[1;97;41m" if цвет else ""   # белым по красному
        Y = "\033[1;31m" if цвет else ""      # красным
        O = "\033[0m" if цвет else ""
        ширина = 66
        print()
        print(R + " " * ширина + O)
        # ТЕКСТ ГОДЕН ДЛЯ ЛЮБОЙ ВКЛАДКИ: хук стоит в глобальных настройках и
        # сработает и в рабочей вкладке тоже (09.11). Поэтому не «управляющую»,
        # а «эту», и отдельная строка для рабочей — ей сначала сдать тему.
        print(R + "  ПОРА ЗАКРЫТЬ ЭТУ ВКЛАДКУ И ОТКРЫТЬ НОВУЮ".ljust(ширина) + O)
        print(R + " " * ширина + O)
        print(Y + "  УПРАВЛЯЮЩАЯ: открой новую, скажи в ней «СМЕНА», эту закрывай." + O)
        print(Y + "  РАБОЧАЯ: сдай тему, запиши состояние файлом, потом /clear." + O)
        print(Y + "  ПЕРЕДАВАТЬ НЕЧЕГО — СОСТОЯНИЕ ПИШЕТСЯ САМО." + O)
        print("  (%s)" % строки[0].split("(")[0].strip())
        print()
        return 0
    for ln in строки:
        print(ln)
    if пора:
        print()
        print("ЧТО СКАЗАТЬ ЕМУ ОДНОЙ СТРОКОЙ:")
        print("  «Открой новую управляющую вкладку и скажи в ней „смена“ — эту закрывай,")
        print("   передавать ничего не надо, состояние пишется само.»")
        print("ПЕРЕД ЗАКРЫТИЕМ: дописать итог в CHANGELOG.md и статусы в ПЛАН-ЭКОНОМИИ.md,")
        print("незаконченную правку кода либо довести, либо описать строкой в BUGS-LIVE.md.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
