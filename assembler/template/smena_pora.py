"""smena_pora.py — ПОРА ЛИ ПЕРЕДАВАТЬ СМЕНУ (09.11.2026).

    python3 smena_pora.py            # про текущую (самую свежую) вкладку
    python3 smena_pora.py --vse      # по всем живым вкладкам дня

Его вопрос 09.11: «осталось решить, когда тебе передавать смену другой новой
управляющей вкладке. На каком этапе?» — ответ должен быть ЧИСЛОМ, а не
ощущением, поэтому порог считается по транскрипту.

ПОЧЕМУ ВООБЩЕ НАДО МЕНЯТЬ. Каждый запрос заново подаёт весь накопленный
контекст, значит цена запроса растёт вместе с ним. Замер 16.10 по четвертям
сессии: 233 К → 433 К → 591 К → 670 К, то есть к концу вкладки запрос дороже
начала в 2,9 раза. Пересчёт 12 длинных сессий: 6558 М против 2882 М, если бы
те же запросы шли отрезками по 250 в свежих вкладках.

ПОРОГИ (для УПРАВЛЯЮЩЕЙ вкладки, она живёт весь день):
  контекст ≥ 400 К   — пора, цена запроса уже вдвое выше начальной;
  запросов ≥ 250     — пора, независимо от контекста;
  контекст ≥ 550 К   — СРОЧНО, каждый следующий шаг стоит как три утренних.
Рабочая вкладка живёт короче и меняется сама по правилу «сдала тему — /clear».

ЧТО ПЕРЕДАВАТЬ: ничего. Состояние пишется само (`sostoyanie.sh` в cron
каждые 20 минут), план — `ПЛАН-ЭКОНОМИИ.md`, решения — `CHANGELOG.md`, память
— в `~/.claude/projects/-home-andrey/memory`. Новая вкладка говорит «смена».
"""
import glob
import json
import os
import sys
import time

ROOT = os.path.expanduser("~/.claude/projects")
ПОРОГ_КОНТЕКСТ = 400_000
ПОРОГ_СРОЧНО = 550_000
ПОРОГ_ЗАПРОСОВ = 250


def разбор(путь):
    ctx = 0
    запросов = 0
    начало = ""
    последний = ""
    for line in open(путь, encoding="utf-8", errors="replace"):
        if '"type":"assistant"' not in line and '"type": "assistant"' not in line:
            continue
        try:
            d = json.loads(line)
        except Exception:
            continue
        u = (d.get("message") or {}).get("usage") or {}
        if not u:
            continue
        запросов += 1
        c = u.get("cache_read_input_tokens", 0) + u.get("input_tokens", 0) + \
            u.get("cache_creation_input_tokens", 0)
        if c > ctx:
            ctx = c
        ts = d.get("timestamp", "")[:16].replace("T", " ")
        начало = начало or ts
        последний = ts or последний
    return ctx, запросов, начало, последний


def вердикт(ctx, запросов):
    if ctx >= ПОРОГ_СРОЧНО:
        return "СРОЧНО", ("контекст %d К — каждый шаг стоит как три утренних" % (ctx // 1000))
    if ctx >= ПОРОГ_КОНТЕКСТ:
        return "ПОРА", ("контекст %d К (порог %d К)" % (ctx // 1000, ПОРОГ_КОНТЕКСТ // 1000))
    if запросов >= ПОРОГ_ЗАПРОСОВ:
        return "ПОРА", ("запросов %d (порог %d)" % (запросов, ПОРОГ_ЗАПРОСОВ))
    остаток = min(ПОРОГ_КОНТЕКСТ - ctx, 10 ** 9)
    return "рано", ("контекст %d К, запросов %d — до порога ещё ~%d К" % (
        ctx // 1000, запросов, остаток // 1000))


def main():
    все = "--vse" in sys.argv
    файлы = sorted(glob.glob(os.path.join(ROOT, "*", "*.jsonl")),
                   key=os.path.getmtime, reverse=True)
    свежие = time.time() - 6 * 3600
    файлы = [f for f in файлы if os.path.getmtime(f) > свежие] or файлы[:1]
    if not все:
        файлы = файлы[:1]
    пора = False
    for f in файлы:
        ctx, запросов, нач, посл = разбор(f)
        if not запросов:
            continue
        в, почему = вердикт(ctx, запросов)
        пора = пора or (в != "рано")
        print("%-10s %-7s %s  (с %s по %s)" % (os.path.basename(f)[:8], в, почему, нач, посл))
    if пора:
        print()
        print("ЧТО СКАЗАТЬ ЕМУ ОДНОЙ СТРОКОЙ:")
        print("  «Открой новую управляющую вкладку и скажи в ней „смена“ — эту закрывай,")
        print("   передавать ничего не надо, состояние пишется само.»")
        print("ПЕРЕД ЗАКРЫТИЕМ: дописать итог в CHANGELOG.md и статусы в ПЛАН-ЭКОНОМИИ.md,")
        print("незаконченную правку кода либо довести, либо описать строкой в BUGS-LIVE.md.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
