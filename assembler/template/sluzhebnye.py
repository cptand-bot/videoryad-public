"""СЛУЖЕБНОЕ ИМЯ ФАЙЛА — ОДНА ПРОВЕРКА НА ВЕСЬ СБОРЩИК (15.11.2026).

Повод: слово «ответ» в НАЗВАНИИ темы («2-Против РФ ответ Москвы») съедало
её единственный текст. Четыре инструмента независимо искали служебное слово
ПОДСТРОКОЙ в `.upper()` — `ozvuchka.find_text`, `rewrite_brief.find_text`,
`razlozhit_rerayt.СЛУЖЕБНЫЕ`, `tema_start`. Последствия были молчаливыми:
сторож 12 минут «не видел текста», `rewrite_brief` печатал «в папке нет
текста темы», автозаказ второй статьи не срабатывал вовсе и никто не узнал
бы причину. Так же встала бы любая тема со словом «статья», «список»,
«ссылки», «итог», «аудит» в заголовке.

ПРАВИЛО: служебным считается слово, отделённое началом имени, точкой,
дефисом или подчёркиванием — то есть НАША разметка (`ЗАДАНИЕ-РЕРАЙТ.txt`,
`…РЕРАЙТ.ОТВЕТ.txt`, `ВИЗУАЛ.txt`), а не слово внутри живой фразы
(«Против РФ ответ Москвы 5 минут.txt»).
"""
РАЗДЕЛИТЕЛИ = ".-_"

# Полный список служебных слов сборщика: объединение четырёх прежних.
SLUZHEBNYE = (
    "ЗАДАНИЕ", "БРИФ", "ОТВЕТ", "ПРОМПТ", "NOTES", "README",
    "ССЫЛКИ", "ГЕОРАДАР", "ПРЕДЛОЖЕНИЯ", "ВИЗУАЛ", "ЗАМЕТКИ",
    "СОСТОЯНИЕ", "ИТОГ", "РЕРАЙТ", "ЧИСТО", "ПОДРЕЗАН", "АУДИТ",
    "ЧЕРНОВИК", "УПАКОВКА", "ПАТТЕРН", "ДОСЬЕ", "СТАТЬЯ", "СПИСОК",
    "ДЛЯ-ВКЛАДКИ",
)


def sluzhebnoe(imya, slova=None):
    """True, если имя файла — наша служебная разметка, а не текст темы."""
    up = (imya or "").upper()
    for s in (slova or SLUZHEBNYE):
        i = up.find(s)
        while i >= 0:
            слева = up[i - 1] if i > 0 else ""
            j = i + len(s)
            справа = up[j] if j < len(up) else ""
            if (слева == "" or слева in РАЗДЕЛИТЕЛИ) and \
               (справа == "" or справа in РАЗДЕЛИТЕЛИ):
                return True
            i = up.find(s, i + 1)
    return False
