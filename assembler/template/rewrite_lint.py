    _фразы = [x.strip() for x in re.split(r"(?<=[.!?])\s+", new) if x.strip()]

    # ПРИЗЫВЫ ПОДПИСАТЬСЯ ИЗ ЭТИХ ПРОВЕРОК ВЫНУТЫ: их по правилу ДВА и они
    # обязаны быть похожими — иначе пункт 5 требует второй призыв, а этот
    # пункт его же бракует как повтор.
    def _не_призыв(ф):
        return not re.search(r"(подпиш|подписк|колокольчик|лайк)", ф, re.I)

    # Числа прописью из счёта повторов выброшены: «две тысячи двадцать
    # первый» и «двадцать тысяч» неизбежно повторяют одни и те же слова.
    _ЧИСЛО_СЛОВОМ = re.compile(
        r"^(ноль|один|одна|одно|два|две|три|четыре|пять|шесть|семь|восемь|"
        r"девять|десять|одиннадцать|двенадцать|тринадцать|четырнадцать|"
        r"пятнадцать|шестнадцать|семнадцать|восемнадцать|девятнадцать|"
        r"двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|"
        r"восемьдесят|девяносто|сто|двести|триста|четыреста|пятьсот|"
        r"шестьсот|семьсот|восемьсот|девятьсот|тысяч|миллион|миллиард|"
        r"процент)")

