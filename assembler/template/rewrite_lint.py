    # (б) ТАВТОЛОГИЧЕСКАЯ ПАРАЛЛЕЛЬ. Его слово: «Закончились деньги —
    #     попросим деньги. Закончились ракеты, попросим ракеты. Да ну нафиг,
    #     это что? Это ты считаешь, нормально написано?»
    #     Признак узкий и потому точный: одно и то же слово стоит ПОСЛЕДНИМ
    #     сразу в двух частях короткой фразы. Именно это даёт ощущение
    #     приёма при нулевой информации: вторая половина повторяет первую.
    #     Простой повтор слова внутри фразы сюда НЕ попадает — он идёт
    #     замечанием по пункту 7, иначе под нож уходят живые противопоставления
    #     («голосование меняет фамилии, но не меняет курс») и числа прописью
    #     («две тысячи двадцать первом… тысячи рождений»).
    #
    # (в) ТРИ ПОДРЯД ОДИНАКОВЫХ ЗАЧИНА — отказ. Два подряд бывают приёмом,
    #     три — это уже заклинание.
    #
    # Лечение во всех случаях одно: сказать КОНКРЕТНОЕ — кто, сколько, чем
    # кончилось. «Закончились деньги, попросим деньги» → «Киев просит ещё
    # сорок миллиардов, пятый транш за год, и каждый следующий дают на
    # условиях хуже прежних». Нечего добавить — строка выбрасывается целиком.
