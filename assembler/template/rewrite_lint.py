        m = re.search(r"\b(а потом|а тут|а затем|а после|и вот|и тут|"
                      r"а в итоге|а дальше)\b", ф, re.I)
        if not m:
            continue
        голова = ф[:m.start()]
        if голова.count(",") < 3:
            continue
        if re.search(r"\d", голова):
            continue
        if re.search(r"(?<!^)\b[А-ЯЁ][а-яё]{2,}", голова):
            continue
        _пустое.append("очевидности через запятую: «%s»" % ф[:110])

