def _тон_бумаги(bg):
    """Цвет пятна на бумаге — ИЗ гаммы канала, а не жёлтый из образца."""
    return tuple(int(c * 0.62) for c in bg[:3]) + (255,)


def _тон_буквы(bg, fg):
    """Боковая грань буквы: темнее бумаги и в сторону чернил.

    Зажата сверху 78% от бумаги: иначе на тёмном акценте со светлым словом
    «толщина» вышла бы СВЕТЛЕЕ самой наклейки и читалась бы как подсветка.
    """
    out = []
    for i in range(3):
        v = int(0.62 * (0.45 * fg[i] + 0.55 * bg[i]))
        out.append(max(0, min(v, int(bg[i] * 0.78))))
    return tuple(out) + (255,)


# ТЕКСТУРЫ СЧИТАЕМ ОДИН РАЗ НА КЛИП, А НЕ НА КАДР. Кусок и его тень — чистые
# функции слова и гаммы, а внутри два гауссиана; без кэша они пересчитывались
# бы 4 × 78 раз за клип и съедали минуты машинного счёта на ровном месте
# (его слово 23.10: лишнего на счёте не жжём).
_ТЕКСТУРЫ = {}


def _кэш(ключ, как):
    if ключ not in _ТЕКСТУРЫ:
        _ТЕКСТУРЫ[ключ] = как()
    return _ТЕКСТУРЫ[ключ]


def наклейка_тек(word, bg, fg, fsize=200):
    """Кусок бумаги с РВАНЫМ КРАЕМ и словом с толщиной (вторая реализация).

    Зерно — `zlib.crc32`, а не `hash()`: у `hash()` в Python 3 своя соль на
    процесс, и рваный край разъехался бы между кадрами одного клипа —
    кадры считаются в несколько процессов (мина движка зала).
    """
    return _кэш(("н", word, tuple(bg), tuple(fg), fsize),
                lambda: _наклейка_тек(word, bg, fg, fsize))


def _наклейка_тек(word, bg, fg, fsize):
    f = zc.font("ArialBlack.ttf", fsize)
    d0 = ImageDraw.Draw(Image.new("RGBA", (8, 8)))
    b = d0.textbbox((0, 0), word, font=f)
    tw, th = max(1, b[2] - b[0]), max(1, b[3] - b[1])
    pw, ph = int(tw + fsize * 0.44), int(th + fsize * 0.42)
    img = Image.new("RGBA", (pw, ph), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    rng = np.random.default_rng(zlib.crc32(word.encode("utf-8")))
    pts, n = [], 14
    for i in range(n + 1):                       # верхний край
        pts.append((pw * i / n, ph * 0.045 + rng.uniform(-1, 1) * ph * 0.022))
    for i in range(1, 5):                        # правый
        pts.append((pw - pw * 0.012 + rng.uniform(-1, 1) * pw * 0.008,
                    ph * (0.045 + 0.91 * i / 5)))
    for i in range(n, -1, -1):                   # нижний
        pts.append((pw * i / n, ph * 0.955 + rng.uniform(-1, 1) * ph * 0.022))
    for i in range(4, 0, -1):                    # левый
        pts.append((pw * 0.012 + rng.uniform(-1, 1) * pw * 0.008,
                    ph * (0.045 + 0.91 * i / 5)))
    d.polygon(pts, fill=tuple(bg))
    # неровность тона бумаги: несколько размытых пятен, срезанных по куску
    shade = Image.new("L", (pw, ph), 0)
    sd = ImageDraw.Draw(shade)
    for _ in range(6):
        x0, y0 = rng.uniform(-pw * 0.2, pw), rng.uniform(-ph * 0.3, ph)
        sd.ellipse([x0, y0, x0 + pw * 0.5, y0 + ph * 0.7],
                   fill=int(rng.uniform(14, 30)))
    shade = shade.filter(ImageFilter.GaussianBlur(fsize * 0.25))
    dark = Image.new("RGBA", (pw, ph), _тон_бумаги(bg))
    dark.putalpha(Image.fromarray(np.minimum(
        np.asarray(shade), np.asarray(img.split()[3])).astype(np.uint8)))
    img.alpha_composite(dark)
    d = ImageDraw.Draw(img)
    x, y = (pw - tw) / 2 - b[0], (ph - th) / 2 - b[1]
    k = max(2, int(fsize * 0.028))
    d.text((x + k, y + k * 1.4), word, font=f, fill=_тон_буквы(bg, fg))
    d.text((x, y), word, font=f, fill=tuple(fg))
    return img


def _тень_тек(tex, ключ):
    """Мягкая тень куска — ложится на листы позади, как в образце."""
    return _кэш(("т",) + ключ, lambda: _тень_тек_счёт(tex))


def _тень_тек_счёт(tex):
    pad = 24
    a = Image.new("L", (tex.size[0] + 2 * pad, tex.size[1] + 2 * pad), 0)
    a.paste(tex.split()[3].point(lambda v: int(v * 0.42)), (pad, pad))
    dark = Image.new("RGBA", a.size, (30, 28, 24, 255))
    dark.putalpha(a)
    return dark.filter(ImageFilter.GaussianBlur(10))


