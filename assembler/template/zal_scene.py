def _времена(dur, n):
    """Когда прилетают куски. На КОРОТКОЙ сцене окно поджимается.

    Повод (11.11): покадрово рисуется `anim` = min(2,6 с, длительность
    сцены), дальше кадр не перерисовывается — на короткой сцене четвёртый
    кусок не появился бы ВООБЩЕ, а прогон отчитался бы успехом (класс
    «успех значит ничего не сделано»). Шаг плёнки 0,55 с держим, пока он
    влезает вместе с осадкой; не влезает — ужимаем шаг, а не теряем кусок.
    """
    if n <= 0:
        return ()
    окно = min(LAYOUT_T, float(dur)) if dur else LAYOUT_T
    место = max(0.12, окно - STICK_SETTLE)       # последний должен ещё сесть
    if STICK_FIRST + STICK_STEP * (n - 1) <= место:
        старт, шаг = STICK_FIRST, STICK_STEP     # шаг плёнки влезает целиком
    else:
        старт = min(STICK_FIRST, место * 0.25)
        шаг = (место - старт) / (n - 1) if n > 1 else 0.0
    return tuple(round(старт + шаг * i, 3) for i in range(n))


