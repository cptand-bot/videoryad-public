def _короб(cam, corners):
    """Экранная коробка четырёхугольника: (x0, y0, x1, y1)."""
    pts = [cam.proj(p) for p in corners]
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def _в_мир(cam, x_scr, y_scr, z):
    """Экранная точка на глубине z → мировые x, y (центр объекта)."""
    dz = max(0.3, z - cam.z)
    return (cam.x + (x_scr - W / 2.0) * dz / zc.F,
            cam.y - (y_scr - H / 2.0) * dz / zc.F)


def _вписать_надпись(cam, tex, строк, доля_h=PHRASE_MAX_H):
    """Размер блока надписи, при котором он целиком в кадре и в своей доле."""
    h = 0.30 * строк + 0.12
    w = h * tex.size[0] / float(tex.size[1])
    for _ in range(4):
        c = zc.quad((-0.15, PHRASE_Y, PHRASE_Z), w, h)
        x0, y0, x1, y1 = _короб(cam, c)
        yc = (y0 + y1) / 2.0
        можно_h = min(доля_h * H, 2.0 * (yc - SAFE * H))
        k = min(1.0, (1 - 2 * SAFE) * W / max(1.0, x1 - x0),
                можно_h / max(1.0, y1 - y0))
        if k > 0.995:
            break
        w *= k
        h *= k
    return w, h


def _ячейки(n, верх):
    """Экранные коробки под куски: (x0, y0, x1, y1) в пикселях.

    Полоса под надписью режется на ряды и колонки. Ячейки не пересекаются,
    поэтому проверять наложение наклеек потом не нужно — его не бывает.
    """
    таблица = ЯЧЕЙКИ.get(n) or ЯЧЕЙКИ[STICK_MAX][:n]
    рядов = max(r for (_c, r, _p) in таблица) + 1
    низ = STICK_FLOOR * H
    верх = min(верх, низ - 0.12 * H)             # ряд не схлопывается в нить
    зазор = STICK_ROW_GAP * H if рядов > 1 else 0.0
    вр = (низ - верх - зазор * (рядов - 1)) / рядов
    out = []
    for (cx, ряд, полу) in таблица:
        x0 = max(SAFE * W, (cx - полу) * W)
        x1 = min((1 - SAFE) * W, (cx + полу) * W)
        y0 = верх + ряд * (вр + зазор)
        out.append((x0, y0, x1, y0 + вр))
    return out


def _вписать_наклейку(cam, tex, кор, z, roll, yaw):
    """(мировые x, y, высота) куска: своя ячейка, с креном и перелётом.

    Мерится СИЛУЭТ повёрнутого куска в самый крупный его момент — на входе
    крен на 2° больше и размер на STICK_OVER больше. Именно этот кадр не
    должен ни вылезать за ячейку, ни трогать соседа.
    """
    x0, y0, x1, y1 = кор
    можно_w = max(40.0, (x1 - x0)) / (1.0 + STICK_OVER)
    можно_h = max(30.0, (y1 - y0)) / (1.0 + STICK_OVER)
    доля = tex.size[0] / float(tex.size[1])
    кр = math.radians(roll + STICK_KREN * (1 if roll >= 0 else -1))
    yw = math.radians(yaw)
    h = 1.0
    for _ in range(6):
        c = zc.quad((cam.x, cam.y, z), h * доля, h, yaw=yw, roll=кр)
        bx0, by0, bx1, by1 = _короб(cam, c)
        k = min(можно_w / max(1.0, bx1 - bx0), можно_h / max(1.0, by1 - by0))
        if 0.995 < k < 1.005:
            break
        h *= k
    c = zc.quad((cam.x, cam.y, z), h * доля, h, yaw=yw, roll=кр)
    bx0, by0, bx1, by1 = _короб(cam, c)
    bw, bh = (bx1 - bx0) * (1.0 + STICK_OVER), (by1 - by0) * (1.0 + STICK_OVER)
    return bw, bh, max(0.02, h)


