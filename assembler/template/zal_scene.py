# -*- coding: utf-8 -*-
"""СЦЕНА «БЕЛЫЙ ЗАЛ» — РИСОВАННЫЙ КАДР РОЛИКА (вид `zal`, заведён 11.11).

ПОЧЕМУ ЦЕЛИКОМ СЦЕНА, А НЕ НАКЛЕЙКА. 11.11 приём G13 сперва внедрили
переходом `fx: sticker` — две наклейки поверх обычного кадра новости. Его
слово дословно: «Нет, это не то, что ты взял в бой. Там целая панорама, там
внутри комната, там именно вот так, как оно и есть, а не вот эти вот две
всплывашки, надписи. Полностью с объёмом, сцены». Поэтому в бой идёт ВЕСЬ
кадр: белый павильон с полом-глянцем, окнами, световыми полосами и тросами,
листы с текстом в глубине, крупная объёмная надпись, угли, отражения — и
наклейки как часть этой сцены.

Ставится обычной дверью карточек (фетч за такой сценой не идёт):

    python3 fullcycle/card_put.py <scenes.json> <сцена> zal \
        --text "фраза сцены" --word ХАЙП --word ФЕЙК \
        --sheet "короткая строка" --sheet "ещё строка"

ГАММА ПРИХОДИТ ПО КАНАЛУ, а не задаётся здесь (его требование 11.11:
ПЛАНЕТА и «5 МИНУТ» должны отличаться). Акцент берётся из
`template/palitra.py` — единственного источника цветов канала: ПЛАНЕТА —
сталь (74,144,226), «5 МИНУТ» — золото (224,179,58). Жёлтый образца
остаётся только там, где канала в палитре нет. Контраст слова к фону
наклейки считается числом (Rec.601) и при нехватке слово уводится в
чёрный или белый предел.

РАСКЛАДКА СЧИТАЕТСЯ, А НЕ ПОДБИРАЕТСЯ НА ГЛАЗ (11.11, четыре дефекта на
первой же пробе боевым текстом: наклейка уехала за край кадра — «ЕГАВАТТЫ»;
наклейки налезли друг на друга; наклейка накрыла крупную надпись; длинное
слово раздуло наклейку на полкадра). Поэтому и надпись, и обе наклейки
размещаются по ЭКРАННЫМ коробкам: считается проекция углов, и размер
ужимается, пока коробка не влезет в свою долю кадра. Доли разнесены по
половинам кадра с просветом посередине — пересечься они не могут.

Рисует на раннере `fullcycle/render_cards.py` (вид `zal` → `zal_scene.zal`),
на машине пользователя не считается ничего.
"""
import math
import os
import sys

from PIL import ImageDraw

import zal_core as zc

W, H = zc.W, zc.H

# ---- времена сцены (секунды от начала клипа) -------------------------------
LINE_AT = (0.00, 0.30, 0.60)       # строки крупной надписи встают по одной
STICK_AT = (1.35, 1.95)            # наклейки прилетают
STICK_SETTLE = 0.14                # перелёт и посадка
STICK_OVER = 0.13                  # насколько наклейка проскакивает размер
HERO_T = 3.0                       # кадр-постер: всё уже на местах
CAM_SPEED = 0.42                   # медленный наезд камеры, ед./с
# РАСКЛАДКУ СЧИТАЕМ ПО САМОМУ ТЕСНОМУ КАДРУ. Камера едет вперёд, и к концу
# покадровой отрисовки всё на экране КРУПНЕЕ; мировые координаты при этом
# стоят. Поэтому коробки меряем на последнем рисуемом кадре — раньше будет
# только просторнее. 2,6 с — `anim` по умолчанию у карточек, дальше идёт
# хвост-наезд, он кадр не перерисовывает.
LAYOUT_T = 2.6

# ---- цвета ------------------------------------------------------------------
BG_БАЗА = (255, 212, 0)            # жёлтый образца — только без палитры
INK = (12, 12, 14)
PAPER = (250, 250, 248)
MIN_CONTRAST = 90.0                # Rec.601, ниже — слово не читается

# ---- доли кадра (от края и под каждый элемент) ------------------------------
# Поле от края БОЛЬШЕ требуемых 3%: в хвосте сцены идёт наезд `tail_zoom`
# (до 4,5%), он подрезает кадр по краям — при поле ровно в 3% срезало бы
# букву уже после отрисовки.
SAFE = 0.06
PHRASE_MAX_H = 0.46                # надпись живёт в верхней половине кадра
STICK_MAX_W = 0.40                 # ≈45% с запасом; половинки не пересекутся
STICK_MAX_H = 0.24
STICK_CX = (0.28, 0.72)            # центры половинок, просвет 4% посередине
STICK_GAP_Y = 0.035                # просвет между надписью и наклейками
STICK_LOW = 0.07                   # левая наклейка ниже правой, как в образце
STICK_FLOOR = 0.90                 # ниже наклейка уходит в пол

# ---- раскладка зала ---------------------------------------------------------
SHEETS = [(-2.9, 2.35, 9.0, 18), (2.6, 2.7, 11.5, -14), (-1.5, 1.75, 14.0, 9),
          (3.1, 1.95, 16.5, -8), (-3.3, 2.9, 19.5, 12), (1.9, 2.45, 22.0, -10)]
STICK_Z = (9.0, 10.0)
STICK_ROT = (-4.5, 3.5)
PHRASE_Z = 9.2
PHRASE_Y = 2.78                    # центр блока надписи в мире


def _lum(c):
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def цвета(channel):
    """(фон наклейки, цвет слова, контраст) — гамма КАНАЛА, не своя."""
    bg = BG_БАЗА
    try:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import palitra
        bg = tuple(palitra.accent(channel, inache=BG_БАЗА))
    except Exception as e:
        print("  белый зал: палитра недоступна (%s) — гамма образца" % e,
              file=sys.stderr)
    fg = INK if abs(_lum(bg) - _lum(INK)) >= abs(_lum(bg) - _lum(PAPER)) else PAPER
    d = abs(_lum(bg) - _lum(fg))
    if d < MIN_CONTRAST:
        fg = (0, 0, 0) if _lum(bg) > 128 else (255, 255, 255)
        d = abs(_lum(bg) - _lum(fg))
        print("  белый зал: слово уведено в предел — контраст к фону был мал",
              file=sys.stderr)
    return tuple(bg) + (255,), tuple(fg) + (255,), d


def разбить(text, строк=3, знаков=17):
    """Фраза сцены → 2-3 строки заглавными. Рвём по словам, а не по буквам."""
    слова = [w for w in str(text or "").upper().split() if w]
    if not слова:
        return []
    ширина = max(знаков, int(math.ceil(len(" ".join(слова)) / float(строк))))
    строки, тек = [], ""
    for w in слова:
        проба = (тек + " " + w).strip()
        if тек and len(проба) > ширина:
            строки.append(тек)
            тек = w
        else:
            тек = проба
    if тек:
        строки.append(тек)
    if len(строки) > строк:                      # хвост дописываем в последнюю
        строки = строки[:строк - 1] + [" ".join(строки[строк - 1:])]
    return строки


def _листы(sheets):
    """Короткие строки-подписи → по 1-3 строки на каждый висящий лист."""
    src = [str(s).strip() for s in (sheets or ()) if str(s).strip()]
    out = []
    for s in src[:len(SHEETS)]:
        слова, строки, тек = s.split(), [], ""
        for w in слова:
            проба = (тек + " " + w).strip()
            if тек and len(проба) > 24:
                строки.append(тек)
                тек = w
            else:
                тек = проба
        if тек:
            строки.append(тек)
        out.append(строки[:3])
    return out


def _времена(dur):
    """Когда прилетают наклейки. На КОРОТКОЙ сцене окно поджимается.

    Повод (11.11, разбор на бумаге, а не после сдачи): покадрово рисуется
    `anim` = min(2,6 с, длительность сцены), дальше кадр не перерисовывается
    — на сцене короче 2,3 с наклейки не появились бы ВООБЩЕ, и прогон
    отчитался бы успехом (класс «успех значит ничего не сделано»).
    """
    окно = min(LAYOUT_T, float(dur)) if dur else LAYOUT_T
    if окно >= STICK_AT[1] + 0.35:
        return STICK_AT
    at1 = max(0.55, окно - 0.3)
    at0 = max(0.10, at1 - 0.45)
    return (at0, at1)


def _ev(sfx, at, role):
    if sfx is not None:
        sfx.append({"at": round(at, 2), "role": role})


# --------------------------------------------------------------------------
# ГЕОМЕТРИЯ РАСКЛАДКИ: мир ↔ экран
# --------------------------------------------------------------------------
def _короб(cam, corners):
    """Экранная коробка четырёхугольника: (x0, y0, x1, y1)."""
    pts = [cam.proj(p) for p in corners]
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def _в_мир(cam, x_scr, y_scr, z):
    """Экранная точка на глубине z → мировые x, y (центр объекта)."""
    dz = max(0.3, z - cam.z)
    return (cam.x + (x_scr - W / 2.0) * dz / zc.F,
            cam.y - (y_scr - H / 2.0) * dz / zc.F)


def _вписать_надпись(cam, tex, строк):
    """Размер блока надписи, при котором он целиком в кадре и в своей доле."""
    h = 0.30 * строк + 0.12
    w = h * tex.size[0] / float(tex.size[1])
    for _ in range(3):
        c = zc.quad((-0.15, PHRASE_Y, PHRASE_Z), w, h)
        x0, y0, x1, y1 = _короб(cam, c)
        yc = (y0 + y1) / 2.0
        можно_h = min(PHRASE_MAX_H * H, 2.0 * (yc - SAFE * H))
        k = min(1.0, (1 - 2 * SAFE) * W / max(1.0, x1 - x0),
                можно_h / max(1.0, y1 - y0))
        if k > 0.995:
            break
        w *= k
        h *= k
    return w, h


def _вписать_наклейку(cam, tex, i, верх_полосы):
    """(мировые x, y, z, высота) наклейки: своя половина кадра, без краёв.

    Размер ужимается, пока экранная коробка не влезет в долю; доли левая и
    правая не пересекаются по построению, поэтому наклейки не налезут друг
    на друга ни при каких словах.
    """
    z, rot = STICK_Z[i], STICK_ROT[i]
    доля = tex.size[0] / float(tex.size[1])
    # коробку меряем с учётом ПЕРЕЛЁТА: в момент посадки наклейка крупнее
    # установившейся на STICK_OVER, и именно этот кадр не должен вылезать
    можно_w = STICK_MAX_W * W / (1.0 + STICK_OVER)
    можно_h = min(STICK_MAX_H * H, (STICK_FLOOR * H - верх_полосы)) / (1.0 + STICK_OVER)
    h = 1.05
    bw = bh = 1.0
    for _ in range(3):
        c = zc.quad((0.0, 1.8, z), h * доля, h, roll=math.radians(rot))
        x0, y0, x1, y1 = _короб(cam, c)
        bw, bh = max(1.0, x1 - x0), max(1.0, y1 - y0)
        k = min(можно_w / bw, можно_h / bh)
        if 0.995 < k < 1.005:
            break
        h *= k
        bw *= k
        bh *= k
    x_scr = STICK_CX[i] * W
    y_scr = верх_полосы + bh * (1.0 + STICK_OVER) / 2.0 + (STICK_LOW * H if i == 0 else 0.0)
    y_scr = min(y_scr, STICK_FLOOR * H - bh * (1.0 + STICK_OVER) / 2.0)
    x, y = _в_мир(cam, x_scr, y_scr, z)
    return x, y, z, h


def zal(out=None, t=None, text="", words=(), sheets=(), channel="",
        watermark="", dur=0.0, sfx=None, **_):
    """Кадр сцены «белый зал». t — секунды от начала клипа, None — постер.

    Возвращает RGB-кадр 1920×1080 (этого ждёт `style_cards.render_anim`).
    """
    tt = HERO_T if t is None else float(t)
    bg, fg, _d = цвета(channel)
    cam = zc.Cam(x=0.0, y=1.52, z=CAM_SPEED * tt)
    # ОТДЕЛЬНАЯ КАМЕРА ПОД РАСКЛАДКУ: раскладка обязана быть одна и та же на
    # всех кадрах клипа, иначе наклейка «ползла» бы по кадру сама по себе.
    cam_l = zc.Cam(x=0.0, y=1.52, z=CAM_SPEED * LAYOUT_T)

    img = zc.room(cam)

    # ЛИСТЫ В ГЛУБИНЕ — короткие строки-подписи из задания
    for (x, y, z, rot), lines in zip(SHEETS, _листы(sheets)):
        if z - cam.z < 0.6:
            continue
        tex = zc.sheet_tex(lines)
        c = zc.quad((x, y, z), 1.55, 1.0, yaw=math.radians(rot))
        zc.wire(img, cam, (x - 0.6, y + 0.5, z))
        zc.wire(img, cam, (x + 0.6, y + 0.5, z))
        zc.paste_quad(img, tex, [cam.proj(p) for p in c])

    # КРУПНАЯ НАДПИСЬ: фраза сцены встаёт по строкам, последнее слово — под
    # маркером канальной гаммы (в образце он жёлтый, у нас — акцент канала)
    строки = разбить(text)
    for i, _ln in enumerate(строки):
        _ev(sfx, LINE_AT[min(i, len(LINE_AT) - 1)], "label")
    показаны = [ln for i, ln in enumerate(строки)
                if tt >= LINE_AT[min(i, len(LINE_AT) - 1)]]
    низ_надписи = SAFE * H
    if строки:
        # размер считаем по ПОЛНОЙ надписи и на кадре раскладки: пока строки
        # появляются по одной, блок не должен прыгать и менять кегль
        tex_all = zc.text_tex(строки, fsize=200)
        w_all, h_all = _вписать_надпись(cam_l, tex_all, len(строки))
        кегль = max(60, int(200 * (h_all / (0.30 * len(строки) + 0.12))))
        низ_надписи = _короб(cam_l, zc.quad((-0.15, PHRASE_Y, PHRASE_Z),
                                            w_all, h_all))[3]
    if показаны:
        hl = None
        if len(показаны) == len(строки):
            hl = {len(" ".join(показаны).split(" ")) - 1}
        tex = zc.text_tex(показаны, fsize=кегль, hl=hl, hl_color=bg, hl_ink=fg)
        # строка той же высоты, что в полном блоке: верх блока стоит на месте
        h = h_all * len(показаны) / float(len(строки))
        w = h * tex.size[0] / float(tex.size[1])
        yc = PHRASE_Y + (h_all - h) / 2.0
        c = zc.quad((-0.15, yc, PHRASE_Z), w, h)
        zc.floor_shadow(img, cam, c, tex)
        zc.reflection(img, cam, c, tex, strength=0.09)
        zc.extrude(img, cam, c, tex, depth=0.055, steps=5)

    # УГЛИ И ИХ ОТРАЖЕНИЯ В ПОЛУ
    img = zc.embers(img, cam,
                    zc.cluster(2.3, 0.30, 7.6, 0.62, 4, 1)
                    + zc.cluster(-2.8, 0.24, 10.5, 0.52, 3, 2)
                    + zc.cluster(3.4, 0.20, 14.0, 0.44, 3, 3), tt)

    # НАКЛЕЙКИ — часть сцены, а не слой поверх чужого кадра. Полоса под них
    # начинается НИЖЕ надписи: трогать её они не должны (его правка 11.11).
    верх = max(низ_надписи + STICK_GAP_Y * H, 0.30 * H)
    ws = [str(x).strip().upper() for x in (words or ()) if str(x).strip()][:2]
    времена = _времена(dur)
    for i, word in enumerate(ws):
        t0 = времена[i % len(времена)]
        _ev(sfx, t0, "accent")
        if tt < t0:
            continue
        tex = zc.sticker_tex(word, bg=bg, fg=fg)
        x, y, z, h0 = _вписать_наклейку(cam_l, tex, i, верх)
        k = 1.0 + STICK_OVER * (1.0 - zc.out_expo((tt - t0) / STICK_SETTLE))
        h = h0 * k
        w = h * tex.size[0] / float(tex.size[1])
        c = zc.quad((x, y, z), w, h, roll=math.radians(STICK_ROT[i]))
        zc.floor_shadow(img, cam, c, tex)
        zc.paste_quad(img, tex, [cam.proj(p) for p in c])

    if watermark:
        d = ImageDraw.Draw(img, "RGBA")
        d.text((54, H - 62), str(watermark), font=zc.font("Arimo-Bold.ttf", 25),
               fill=(96, 98, 102, 255))

    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


if __name__ == "__main__":
    путь = sys.argv[1] if len(sys.argv) > 1 else "/tmp/zal.png"
    кан = sys.argv[2] if len(sys.argv) > 2 else "ПЛАНЕТА"
    zal(out=путь, text="ЕВРОПА ПЛАТИТ ЗА ЧУЖУЮ ВОЙНУ", words=("ЦЕНА", "ИТОГ"),
        sheets=("Бюджет на оборону", "Поставки отложены", "Счёт за газ",
                "Заводы стоят"), channel=кан, watermark=кан)
    print(путь)
