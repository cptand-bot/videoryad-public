def _lum(c):
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def цвета(channel):
    """(фон наклейки, цвет слова, контраст) — гамма КАНАЛА, не своя."""
    bg = BG_БАЗА
    try:
        sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
        import palitra
        bg = tuple(palitra.accent(channel, inache=BG_БАЗА))
    except Exception as e:
        print("  белый зал: палитра недоступна (%s) — гамма образца" % e,
              file=sys.stderr)
    fg = INK if abs(_lum(bg) - _lum(INK)) >= abs(_lum(bg) - _lum(PAPER)) else PAPER
    d = abs(_lum(bg) - _lum(fg))
    if d < MIN_CONTRAST:
        fg = (0, 0, 0) if _lum(bg) > 128 else (255, 255, 255)
        d = abs(_lum(bg) - _lum(fg))
        print("  белый зал: слово уведено в предел — контраст к фону был мал",
              file=sys.stderr)
    return tuple(bg) + (255,), tuple(fg) + (255,), d


def разбить(text, строк=3, знаков=17):
    """Фраза сцены → 2-3 строки заглавными. Рвём по словам, а не по буквам."""
    слова = [w for w in str(text or "").upper().split() if w]
    if not слова:
        return []
    ширина = max(знаков, int(math.ceil(len(" ".join(слова)) / float(строк))))
    строки, тек = [], ""
    for w in слова:
        проба = (тек + " " + w).strip()
        if тек and len(проба) > ширина:
            строки.append(тек)
            тек = w
        else:
            тек = проба
    if тек:
        строки.append(тек)
    if len(строки) > строк:                      # хвост дописываем в последнюю
        строки = строки[:строк - 1] + [" ".join(строки[строк - 1:])]
    return строки


def _листы(sheets):
    """Короткие строки-подписи → по 1-3 строки на каждый висящий лист."""
    src = [str(s).strip() for s in (sheets or ()) if str(s).strip()]
    out = []
    for s in src[:len(SHEETS)]:
        слова, строки, тек = s.split(), [], ""
        for w in слова:
            проба = (тек + " " + w).strip()
            if тек and len(проба) > 24:
                строки.append(тек)
                тек = w
            else:
                тек = проба
        if тек:
            строки.append(тек)
        out.append(строки[:3])
    return out


