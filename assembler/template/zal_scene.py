def _лист(img, cam, место, lines):
    """Лист с репликой на тросах. Ближние — вне глубины резкости.

    Размываем ТЕКСТУРУ, а не кадр: лист плоский, вид тот же, а полный
    гауссиан на 1920×1080 стоил бы десятки миллисекунд на каждом кадре
    клипа (его слово 23.10: ресурсы считаем, лишнего не жжём).
    """
    x, y, z, rot = место
    dz = z - cam.z
    if dz < 0.6:
        return
    кл = tuple(lines)
    tex = _кэш(("л", кл), lambda: zc.sheet_tex(lines))
    c = zc.quad((x, y, z), 1.55, 1.0, yaw=math.radians(rot))
    if dz < ЛИСТ_БЛИЗКО:
        к = _короб(cam, c)
        шир = max(1.0, к[2] - к[0])
        # радиус округляем ДО ЧЕТВЕРТИ ПИКСЕЛЯ: камера почти стоит, разница
        # меньше четверти не видна, а без округления кэш давал бы новую
        # размытую копию на каждый кадр — то есть не давал бы ничего
        r = (ЛИСТ_БЛИЗКО - dz) * 1.5 + 0.6
        rt = round(r * tex.size[0] / шир * 4.0) / 4.0
        чёткий = tex
        tex = _кэш(("лр", кл, rt),
                   lambda: чёткий.filter(ImageFilter.GaussianBlur(rt)))
    zc.wire(img, cam, (x - 0.6, y + 0.5, z))
    zc.wire(img, cam, (x + 0.6, y + 0.5, z))
    zc.paste_quad(img, tex, [cam.proj(p) for p in c])


def zal(out=None, t=None, text="", words=(), sheets=(), channel="",
        watermark="", dur=0.0, sfx=None, **_):
    """Кадр сцены «белый зал». t — секунды от начала клипа, None — постер.

    Возвращает RGB-кадр 1920×1080 (этого ждёт `style_cards.render_anim`).
    """
    tt = HERO_T if t is None else float(t)
    bg, fg, _d = цвета(channel)
    cam = zc.Cam(x=0.0, y=1.52, z=CAM_SPEED * tt)
    # ОТДЕЛЬНАЯ КАМЕРА ПОД РАСКЛАДКУ: раскладка обязана быть одна и та же на
    # всех кадрах клипа, иначе наклейка «ползла» бы по кадру сама по себе.
    cam_l = zc.Cam(x=0.0, y=1.52, z=CAM_SPEED * LAYOUT_T)

    img = zc.room(cam)

    # ЛИСТЫ С РЕПЛИКАМИ В ГЛУБИНЕ — от дальних к ближним
    листы = _листы(sheets)
    for место, lines in sorted(zip(SHEETS, листы), key=lambda q: -q[0][2]):
        _лист(img, cam, место, lines)

    ws = _слова(words)

    # КРУПНАЯ НАДПИСЬ: фраза сцены встаёт по строкам, последнее слово — под
    # маркером канальной гаммы (в образце он жёлтый, у нас — акцент канала).
    # Когда кусков больше двух, им нужен ВТОРОЙ РЯД — надпись жмётся, а не
    # отдаёт полосу: иначе кусок лёг бы на неё (его правка 11.11).
    доля_надписи = PHRASE_MAX_H if len(ws) <= 2 else PHRASE_MAX_H2
    строки = разбить(text)
    for i, _ln in enumerate(строки):
        _ev(sfx, LINE_AT[min(i, len(LINE_AT) - 1)], "label")
    показаны = [ln for i, ln in enumerate(строки)
                if tt >= LINE_AT[min(i, len(LINE_AT) - 1)]]
    низ_надписи = SAFE * H
    if строки:
        # размер считаем по ПОЛНОЙ надписи и на кадре раскладки: пока строки
        # появляются по одной, блок не должен прыгать и менять кегль
        tex_all = zc.text_tex(строки, fsize=200)
        w_all, h_all = _вписать_надпись(cam_l, tex_all, len(строки), доля_надписи)
        кегль = max(60, int(200 * (h_all / (0.30 * len(строки) + 0.12))))
        кор = _короб(cam_l, zc.quad((-0.15, PHRASE_Y, PHRASE_Z), w_all, h_all))
        низ_надписи = кор[3]
        _отметить("надпись", *кор)
    if показаны:
        hl = None
        if len(показаны) == len(строки):
            hl = {len(" ".join(показаны).split(" ")) - 1}
        tex = zc.text_tex(показаны, fsize=кегль, hl=hl, hl_color=bg, hl_ink=fg)
        # строка той же высоты, что в полном блоке: верх блока стоит на месте
        h = h_all * len(показаны) / float(len(строки))
        w = h * tex.size[0] / float(tex.size[1])
        yc = PHRASE_Y + (h_all - h) / 2.0
        c = zc.quad((-0.15, yc, PHRASE_Z), w, h)
        zc.floor_shadow(img, cam, c, tex)
        zc.reflection(img, cam, c, tex, strength=0.09)
        zc.extrude(img, cam, c, tex, depth=0.055, steps=5)

    # УГЛИ И ИХ ОТРАЖЕНИЯ В ПОЛУ
    img = zc.embers(img, cam,
                    zc.cluster(2.3, 0.30, 7.6, 0.62, 4, 1)
                    + zc.cluster(-2.8, 0.24, 10.5, 0.52, 3, 2)
                    + zc.cluster(3.4, 0.20, 14.0, 0.44, 3, 3), tt)

    # НАКЛЕЙКИ — часть сцены, а не слой поверх чужого кадра. Полоса под них
    # начинается НИЖЕ надписи: трогать её они не должны (его правка 11.11).
    верх = max(низ_надписи + STICK_GAP_Y * H, STICK_TOP * H)
    ячейки = _ячейки(len(ws), верх) if ws else []
    времена = _времена(dur, len(ws))
    for i, word in enumerate(ws):
        z, roll, yaw = STICK_Z[i], STICK_ROT[i], STICK_YAW[i]
        ключ = (word, tuple(bg), tuple(fg), 200)
        tex = наклейка_тек(word, bg, fg)
        bw, bh, h0 = _вписать_наклейку(cam_l, tex, ячейки[i], z, roll, yaw)
        x0, y0, x1, y1 = ячейки[i]
        слак = max(0.0, (y1 - y0) - bh)
        x_scr = (x0 + x1) / 2.0
        y_scr = y0 + bh / 2.0 + слак * СДВИГ[i]
        x, y = _в_мир(cam_l, x_scr, y_scr, z)
        _отметить("наклейка %d (%s)" % (i + 1, word),
                  x_scr - bw / 2.0, y_scr - bh / 2.0,
                  x_scr + bw / 2.0, y_scr + bh / 2.0)
        t0 = времена[i]
        _ev(sfx, t0, "accent")
        if tt < t0:
            continue
        # ВХОД БЕЗ ФЕЙДА: кусок появляется сразу целиком, с перелётом по
        # размеру и лишним креном, и садится ходом outExpo (~170 мс).
        k = 1.0 - zc.out_expo((tt - t0) / STICK_SETTLE)
        s = 1.0 + STICK_OVER * k
        r = math.radians(roll + STICK_KREN * k * (1 if roll >= 0 else -1))
        yw = math.radians(yaw)
        hh = h0 * s
        ww = hh * tex.size[0] / float(tex.size[1])
        # тень на листах позади: вниз-вправо и чуть дальше
        тень = _тень_тек(tex, ключ)
        csh = zc.quad((x + 0.05 * s, y - 0.07 * s, z + 0.12), ww, hh,
                      yaw=yw, roll=r)
        zc.paste_quad(img, тень, [cam.proj(p) for p in csh],
                      opacity=0.55 + 0.25 * k)
        # первые два кадра — смаз по масштабу (копии от крупной к точной)
        if tt - t0 < STICK_SMAZ:
            for ss, op in ((1.12, 0.22), (1.06, 0.30)):
                c = zc.quad((x, y, z), ww * ss, hh * ss, yaw=yw, roll=r)
                zc.paste_quad(img, tex, [cam.proj(p) for p in c], opacity=op)
        c = zc.quad((x, y, z), ww, hh, yaw=yw, roll=r)
        zc.paste_quad(img, tex, [cam.proj(p) for p in c])

    if watermark:
        d = ImageDraw.Draw(img, "RGBA")
        d.text((54, H - 62), str(watermark), font=zc.font("Arimo-Bold.ttf", 25),
               fill=(96, 98, 102, 255))

    im = img.convert("RGB")
    if out:
        im.save(out, quality=92)
        return out
    return im


