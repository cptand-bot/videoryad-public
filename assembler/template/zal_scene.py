ПРОБА = ("ЦЕНА", "ИТОГ", "ФЕЙК", "РАЗВОД")
ПРОБА_ДЛИННАЯ = ("ЭНЕРГОСЕТИ", "ПЕРЕРАСПРЕДЕЛЕНО", "ГОСКОРПОРАЦИИ",
                 "МЕЖПРАВИТЕЛЬСТВЕННЫЕ")
ТЕКСТ = "ЕВРОПА ПЛАТИТ ЗА ЧУЖУЮ ВОЙНУ"
ТЕКСТ_ДЛИННЫЙ = ("МЕЖПРАВИТЕЛЬСТВЕННЫЕ КОНСУЛЬТАЦИИ ПРИОСТАНОВЛЕНЫ "
                 "БЕССРОЧНО")
ЛИСТЫ = ("Бюджет на оборону", "Поставки отложены", "Счёт за газ",
         "Заводы стоят", "Контракт заморожен", "Цех остановлен")


def проверка(каналы=("ПЛАНЕТА", "5 МИНУТ", "ДИПЛОМАТИЯ СИЛЫ"),
             сроки=(1.5, 2.6, 13.0)):
    """ЗАМЕР РАСКЛАДКИ ЗАПУСКОМ: ни надпись, ни куски не вышли за поле кадра
    и ни один не налез на другой. Печатает число дефектов; 0 — чисто.

    Зовётся так:  python3 zal_scene.py --проверка
    Глаз она НЕ заменяет (четыре дефекта 11.11 нашёл человек по кадру, см.
    шапку файла) — это защита от того, чтобы они вернулись молча.
    """
    os.environ["ZAL_LAYOUT"] = "1"
    беда = кадров = 0
    for набор, слова, наз in ((ТЕКСТ, ПРОБА, "обычный текст"),
                              (ТЕКСТ_ДЛИННЫЙ, ПРОБА_ДЛИННАЯ, "длинные слова")):
        for кан in каналы:
            for d in сроки:
                for n in range(1, STICK_MAX + 1):
                    РАСКЛАДКА.clear()
                    кадров += 1
                    zal(text=набор, words=слова[:n], sheets=ЛИСТЫ,
                        channel=кан, watermark=кан, dur=d)
                    б = РАСКЛАДКА[:]
                    где = "%s/%s/%.1fс/%d накл." % (наз, кан, d, n)
                    for (имя, x0, y0, x1, y1) in б:
                        п = []
                        if x0 < SAFE * W - 1:
                            п.append("слева %d" % x0)
                        if x1 > (1 - SAFE) * W + 1:
                            п.append("справа %d" % x1)
                        if y0 < SAFE * H - 1:
                            п.append("сверху %d" % y0)
                        if y1 > (1 - SAFE) * H + 1:
                            п.append("снизу %d" % y1)
                        if п:
                            print("!! %s/%s: ЗА ПОЛЕ %s"
                                  % (где, имя, ", ".join(п)))
                            беда += 1
                    for i in range(len(б)):
                        for j in range(i + 1, len(б)):
                            a_, b_ = б[i], б[j]
                            ox = min(a_[3], b_[3]) - max(a_[1], b_[1])
                            oy = min(a_[4], b_[4]) - max(a_[2], b_[2])
                            if ox > 1 and oy > 1:
                                print("!! %s: НАЛЕЗАЮТ %s × %s (%d×%d px)"
                                      % (где, a_[0], b_[0], ox, oy))
                                беда += 1
                    # ЧЕТВЁРТЫЙ КУСОК ОБЯЗАН УСПЕТЬ ПРИЛЕТЕТЬ (класс «успех
                    # значит ничего не сделано»): на короткой сцене кадр
                    # перестают перерисовывать, и опоздавший не появится.
                    вр = _времена(d, n)
                    окно = min(LAYOUT_T, d)
                    if вр and вр[-1] + STICK_SETTLE > окно + 1e-6:
                        print("!! %s: последний кусок не успевает (%.2f с "
                              "при окне %.2f с)" % (где, вр[-1], окно))
                        беда += 1
    print("кадров проверено %d, дефектов раскладки %d" % (кадров, беда))
    return беда


