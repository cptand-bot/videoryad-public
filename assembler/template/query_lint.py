def _has_word(text, words):
    """Матч по границам слов: «road» не должен находиться в «broadcast»."""
    for w in words:
        if re.search(r"(?<![a-z])" + re.escape(w) + r"(?![a-z])", text):
            return True
    return False


def scan_pexels(q):
    """Вернуть (hard, soft) для англоязычного стокового запроса."""
    low = q.lower()
    # «no people»/«empty … no people» снимает претензию по минам-людям,
    # но НИКОГДА по детям и пленным (её исправленный запрос
    # «fuel nozzles row empty gas station no people» прошёл чисто).
    no_people = "no people" in low or "without people" in low
    hard = [(w, fix) for w, fix, lifts in PEXELS_MINES
            if w in low and not (lifts and no_people)]
    soft = []
    has_geo = any(g in low for g in GEO_WORDS)

    # «flag» на стоке ненадёжен ВСЕГДА: «european union flag twelve stars
    # brussels» (страна названа прямым текстом!) вернул французский триколор.
    # Без названия страны — мина, с названием — всё равно предупреждение.
    if "flag" in low:
        if has_geo:
            soft.append("«flag» на стоке промахивается даже когда страна "
                        "названа — бери флаг через press_photo или замени "
                        "объектом (здание института, герб на фасаде)")
        else:
            hard.append(("flag без страны",
                         "случайный флаг чужой страны → назови объект, "
                         "а лучше не бери флаг со стока вовсе"))
    # транспортно-дорожный класс = случайная страна в кадре.
    # Матч ПО ГРАНИЦАМ СЛОВ: подстрочный поиск ловил «broadcast» и «two
    # roads fork» через «road» (cross-session, 2026-10-12).
    if _has_word(low, TRANSPORT_EN) and not has_geo:
        if any(t in low for t in TIGHT) or no_people:
            pass  # крупный план: вывесок и номеров в кадре нет
        else:
            hard.append(("дорожно-транспортная сцена без страны",
                         "английский сток отдаёт случайную страну (вывеска/"
                         "знак/номер всегда в кадре) → уходи на крупный план "
                         "детали: «brake lights red glow closeup», «truck "
                         "tyres rolling highway closeup», «traffic cone "
                         "closeup asphalt»"))
    # ВАЛЮТА НА СТОКЕ — ЧУЖАЯ СТРАНА, А НЕ «ДРУГОЙ НОМИНАЛ» (поднято до мины
    # 2026-10-17): «euro banknote macro» вернул британский FIVE POUNDS с
    # надписью ENGLAND прямо в кадре, и это уже второй ролик подряд. Мягкого
    # «проверь номинал» мало — переписывать запрос.
    if any(w in low for w in ("banknote", "bank note", "currency", "cash")):
        hard.append(("валюта на стоке",
                     "«euro banknote macro» → британский FIVE POUNDS с "
                     "надписью ENGLAND → бери купюры через press_photo "
                     "по-русски и с местом: «купюры евро на столе крупным "
                     "планом»"))
    # ДВА ПРЕДМЕТА В ОДНОМ ЗАПРОСЕ = КОЛЛАЖ (2026-10-17): «electric plug
    # into wall socket closeup» вернул склейку двух фото с видимой границей,
    # на плитке читается как один кадр.
    if low.count(" into ") or (" and " in low and any(
            t in low for t in TIGHT)):
        soft.append("запрос на ПАРУ предметов сток часто отдаёт коллажем из "
                    "двух фото (видна граница) — проси один предмет")
    # радар/антенна/тарелка → гражданский радиотелескоп
    if any(w in low for w in ("radar", "antenna", "dish", "satellite")):
        soft.append("«radar/antenna/dish/satellite» тянет гражданский "
                    "радиотелескоп (Двингело приходил дважды на разные "
                    "запросы) — назови военную установку конкретно")
    # turbine/engine без авиаконтекста = деталь автомобиля
    if ("turbine" in low or "engine" in low) and \
            not any(a in low for a in AVIATION):
        soft.append("«turbine/engine» без aircraft/aviation — приходила "
                    "головка блока цилиндров")
    # capitol/parliament без страны = парламент штата/чужой страны
    if ("capitol" in low or "parliament" in low) and not has_geo:
        soft.append("«capitol/parliament» без страны — приходил Капитолий "
                    "штата вместо федерального")
    # короткий запрос из существительных без привязки
    if len(low.split()) <= 3 and not has_geo:
        soft.append("слишком общий запрос без страны/института — добавь "
                    "конкретный материальный объект и обстановку")
    return hard, soft


# --- КОРЕНЬ МИНЫ СВЕРЯЕТСЯ ПО ГРАНИЦЕ СЛОВА, А НЕ ПОДСТРОКОЙ (2026-10-18) ---
# Повод: «Майкл Флинн бывший советник по национальной безопаСНОСти США» ловился
# как мина «снос». Все 48 корней — морфологические НАЧАЛА слов («купюр»,
# «агитац», «предвыборн»), поэтому \b перед корнем ничего не теряет, а целый
# класс ложных мин внутри длинных слов отсекает.
_MINE_RE = {w: re.compile(r"\b" + re.escape(w)) for w, _ in MINES}

# --- ОГОВОРКА СНИМАЕТ МИНУ, ЕСЛИ ОНА УЖЕ ВЫПОЛНЕНА (2026-10-18) ---
# Повод: «купюры евро НА СТОЛЕ крупным планом реальное фото» получал мину
# «купюр… добавь место: купюры евро НА СТОЛЕ крупным планом» — линтер предлагал
# ровно то, что в запросе уже написано. Для англоязычных транспортных мин такое
# снятие (`closeup`/`no people`) было с самого начала, для русских — нет.
# Сюда попадают только мины, чей совет буквально называет обстановку.
