def scan_query(q, source):
    """Вернуть (mines, charts) — списки найденных проблем."""
    low = q.lower()
    mines = [(w, fix) for w, fix in MINES
             if _MINE_RE[w].search(low)
             and not any(lift in low for lift in MINE_LIFTS.get(w, ()))]
    # «дет» ловит «детали»/«определ» — отсечём ложные срабатывания
    mines = [(w, f) for w, f in mines
             if not (w == "дет" and not re.search(r"\bдет(и|ей|ям|ск)", low))]
    mines = [(w, f) for w, f in mines
             if not (w == "семь" and not re.search(r"\bсем(ья|ьи|ей|ьями)", low))]
    charts = [w for w in CHART_BAIT if re.search(r"\b" + re.escape(w), low)]
    has_object = any(w in low for w in OBJECT_WORDS)
    is_real = "реальное фото" in low or "реальн" in low
    return mines, charts, has_object, is_real


def lint(paths, strict=False):
    problems = 0
    soft = 0
    for p in paths:
        try:
            data = json.load(open(p, encoding="utf-8"))
        except Exception as e:
            print("!! не прочитать %s: %s" % (p, e))
            problems += 1
            continue
        print("\n=== %s ===" % p)
        for s in data.get("scenes", []):
            src = s.get("source", "")
            q = s.get("source_query", "")
            if src == "local_library":
                continue  # путь к файлу, не поисковый запрос
            if src in PEXELS:
                hard, soft_hits = scan_pexels(q)
                for w, fix in hard:
                    print("  [%3s] МИНА (сток): «%s» → %s" % (s.get("id"), w, fix))
                    print("        запрос: %s" % q)
                    problems += 1
                for msg in soft_hits:
                    print("  [%3s] сток, мягко: %s" % (s.get("id"), msg))
                    print("        запрос: %s" % q)
                    soft += 1
                continue

            mines, charts, has_object, is_real = scan_query(q, src)
            sid = s.get("id")
            for w, fix in mines:
                print("  [%3s] МИНА: «%s» в запросе → %s" % (sid, w, fix))
                print("        запрос: %s" % q)
                problems += 1
            for w, fix in RU_WRONG_COUNTRY:
                # по границе слова: «поезд» сидел внутри «поездки» (2026-10-18)
                if re.search(r"\b" + re.escape(w), q.lower()) and not (
                        w == "поезд" and "поездк" in q.lower()):
                    print("  [%3s] чужая страна: «%s» → %s" % (sid, w, fix))
                    soft += 1
            if charts and not is_real:
                print("  [%3s] риск инфографики: %s → добавь «реальное фото» "
                      "или запроси объект" % (sid, ", ".join(charts)))
                soft += 1
            # ГОД В ЗАПРОСЕ — такой же якорь, как «реальное фото» (2026-10-17):
            # рабочая формула «род войск + страна + ГОД» даёт современный кадр
            # и уводит от ч/б архива WWII; пилить её мягким замечанием незачем.
            _has_year = bool(re.search(r"\b20[2-9]\d\b", q))
            if not mines and not has_object and not is_real and not _has_year:
                print("  [%3s] мягко: запрос не называет объект и не просит "
                      "«реальное фото» — %s" % (sid, q))
                soft += 1

    print("\n" + "=" * 60)
    print("МИН: %d   мягких замечаний: %d" % (problems, soft))
    if problems:
        print("Переписать мины ДО фетча — от объекта (здание/техника/"
              "помещение/улица), а не от человека и действия.")
        return 1
    if soft and strict:
        return 1
    print("Чисто — можно фетчить.")
    return 0


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        print(__doc__)
        sys.exit(2)
    sys.exit(lint(args, strict="--strict" in sys.argv))
