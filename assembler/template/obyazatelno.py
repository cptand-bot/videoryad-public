# ── РОЛИК-КЛОН СЧИТАЕТСЯ ПО-ДРУГОМУ (08.11, улов вкладки `usuario-cd`) ──
# У рерайта на второй канал часть кадров донора ПО УСТРОЙСТВУ уезжает внутрь
# элементов: донор закрывает не больше 80% сцен, остальное — свой кадр или
# свой элемент. На 90 сценах это дало 21 элемент от уникализации плюс 15
# карточек раскадровки — 36 рисованных кадров при норме 14, и вкладка
# ставила КАЖДЫЙ через `--force`, то есть глушила заодно и проверку зазора,
# которая держит качество. Считать это перебором неправильно: столько
# элементов там ровно потому, что мы не копируем чужой ролик целиком.
# Поэтому `unikalizaciya.py` пишет в scenes.json число `clone_wrapped`, а
# норма и зазор прибавляют его к обязательным.
def клонов_в(scenes):
    """Сколько кадров в этом ролике рождено уникализацией донора."""
    try:
        if isinstance(scenes, str):
            scenes = json.load(open(scenes, encoding="utf-8"))
        if isinstance(scenes, dict):
            return int(scenes.get("clone_wrapped") or 0)
    except Exception:
        pass
    return 0


def норма(n_scenes, клонов=0):
    """НОРМА РИСОВАННЫХ КАДРОВ С ПОЛОМ ПО ОБЯЗАТЕЛЬНЫМ (06.11).

    Прежняя норма — одна карточка на 15 сцен (при 70 сценах пять). После
    того как он назвал одиннадцать обязательных элементов, старая норма и
    обязательный список стали противоречить друг другу: инструмент требовал
    поставить одиннадцать и тут же ругался, что их больше нормы. Пол по
    обязательным снимает противоречие и не задирает норму там, где
    обязательных мало.
    """
    return (max(1, round(n_scenes / PER_SCENES), обязательных_карточек())
            + max(0, int(клонов or 0)))


# СКОЛЬКО ВИДОВ РОЛИК ОБЯЗАН ПОКАЗАТЬ СВЕРХ ОБЯЗАТЕЛЬНОГО СПИСКА (его слово
# 07.11: «ну как это лежат без дела?»). Проверка стоит в `check()` ниже; счёт
# места под карточки обязан знать это же число, иначе арифметика расходится.
СВОИХ_СВЕРХ = 3
# НИЖЕ ДВУХ СЦЕН ЗАЗОР НЕ УЖИМАЕТСЯ: соседние рисованные кадры читаются как
# слайды презентации. Два — это предел, а не норма.
ЗАЗОР_ПОЛ = 2
_сказано_про_зазор = set()


def место_под_карточки(n_scenes, клонов=0):
    """Сколько карточек ролик ОБЯЗАН вместить, сколько влезает и какой зазор.

    Отдаёт `(нужно, влезает, зазор, невозможно)`.

    АРИФМЕТИКА НЕ СХОДИЛАСЬ, И ОБ ЭТОМ НИКТО НЕ ГОВОРИЛ (09.11, улов
    `usuario-e6`). Обязательных карточек четырнадцать, плюс требование
    «не меньше трёх своих видов» — семнадцать. При зазоре 5 это ролик в 85
    сцен, а приходят 66-67. Вкладка узнавала о невозможности только из
    гейтов, уже потратив круг: `card_put` ставил карточки и МОЛЧАЛ.
    Считаем честно — вместе со тремя «своими» видами, иначе место считается
    под четырнадцать, а ставится семнадцать.
    """
    # СПИСОК СИЛЬНЕЕ ЗАЗОРА (12.11, решение координатора по улову
    # `usuario-0d`). Список обязательного вырос до 23 кадров — девять приёмов
    # зала по его прямому слову плюс двенадцать прежних, — и на 65 сценах при
    # поле зазора 2 влезал только 21. Зазор — наша внутренняя норма
    # «не кучей», список — его прямое слово; значит уступает зазор, а не
    # список. Поле опускается до 1 ТОЛЬКО когда иначе набор не влезает:
    # на деле 23 кадра на 65 сцен это шаг 2,8 — редко, минимум лишь
    # разрешает соседство там, где иначе ролик встал бы.
    # И «три своих вида сверх» с таким списком больше не требуем: список и
    # есть минимум, а сверх него ролику уже некуда.
    _sverh_vidov = 0 if обязательных_карточек() >= 20 else СВОИХ_СВЕРХ
    свои = обязательных_карточек() + _sverh_vidov
    need = свои + max(0, int(клонов or 0))
    if need <= 1:
        return need, n_scenes, MIN_GAP_БАЗА, False
    _пол = ЗАЗОР_ПОЛ
    if int(n_scenes / (ЗАЗОР_ПОЛ + 1)) < свои:
        _пол = 1
    сырой = int(n_scenes / need) - 1
    зазор_ = max(_пол, min(MIN_GAP_БАЗА, сырой))
    влезает = int(n_scenes / (_пол + 1))
    # «НЕВОЗМОЖНО» СЧИТАЕМ БЕЗ КЛОНОВ, И ЭТО НЕ ПРИДИРКА. Кадры от
    # уникализации донора (`clone_wrapped`) УЖЕ стоят в ролике — их не надо
    # куда-то вмещать, они только ужимают зазор. На 90 сценах с 21 клоном
    # отказ был бы ложным и встал бы поперёк каждого ролика-клона. Отказ
    # означает одно: ролик короче САМОГО ОБЯЗАТЕЛЬНОГО НАБОРА.
    return need, влезает, зазор_, (int(n_scenes / свои) - 1) < _пол


def зазор(n_scenes, клонов=0):
    """ЗАЗОР МЕЖДУ РИСОВАННЫМИ КАДРАМИ — ПО МЕСТУ, А НЕ КОНСТАНТОЙ 8.

    Одиннадцать обязательных кадров при зазоре 8 требуют ролика в 88 сцен —
    а приходят 56-78. Поэтому зазор считается от того, сколько кадров ролик
    ОБЯЗАН вместить: на 100 сценах это 4 сцены, на 67 ужимается до 2, ниже
    не опускается — соседние карточки читаются как слайды. Там, где
    обязательных мало, зазор остаётся прежним.

    И ГОВОРИТ ОБ УЖАТИИ ВСЛУХ (09.11): молчаливое ужатие вкладка принимала
    за баг проверки и ставила карточки через `--force`, глуша заодно и всё
    остальное. Строка печатается ОДИН раз на процесс — функцию зовут на
    каждую карточку.
    """
    need, влезает_, зазор_, невозможно = место_под_карточки(n_scenes, клонов)
    ключ = (int(n_scenes), int(клонов or 0))
    if зазор_ < ЗАЗОР_МЕЖДУ and ключ not in _сказано_про_зазор:
        _сказано_про_зазор.add(ключ)
        print("зазор: сцен %d, карточек %d (%d обязательных + %d своих вида%s) "
              "— ужат с %d до %d"
              % (n_scenes, need, обязательных_карточек(), СВОИХ_СВЕРХ,
                 " + %d от уникализации" % int(клонов) if клонов else "",
                 ЗАЗОР_МЕЖДУ, зазор_))
        if невозможно:
            print("   НЕ ВЛЕЗАЕТ: при зазоре %d на %d сценах помещается "
                  "максимум %d карточек, а обязательный набор требует %d. "
                  "Либо сцен больше, либо часть элементов снимает координатор."
                  % (ЗАЗОР_ПОЛ, n_scenes, влезает_,
                     обязательных_карточек() + СВОИХ_СВЕРХ))
    return зазор_


def зазор_или_отказ(n_scenes, клонов=0, назвать=""):
    """То же, но при физически невозможном зазоре — ОТКАЗ с числом.

    Зовётся инструментами РАССТАНОВКИ (`card_put`, `element_put`): им есть
    что сказать вкладке до работы. Гейты и приёмка зовут обычный `зазор()` —
    они обязаны досчитать ролик до конца и назвать все недостачи сразу.
    """
    need, влезает_, зазор_, невозможно = место_под_карточки(n_scenes, клонов)
    зазор(n_scenes, клонов)       # печатает строку про ужатие (один раз)
    if невозможно:
        sys.exit("КАРТОЧКИ В ЭТОТ РОЛИК НЕ ВЛЕЗАЮТ%s: сцен %d, обязательный "
                 "набор требует %d карточек, а при минимальном зазоре %d "
                 "помещается %d.\n"
                 "  Это не ошибка расстановки: ролик короче, чем набор. "
                 "Несите координатору — он решает, что снять."
                 % ((" (%s)" % назвать) if назвать else "", n_scenes,
                    обязательных_карточек() + СВОИХ_СВЕРХ, ЗАЗОР_ПОЛ, влезает_))
    return зазор_


# СЕМЬИ ВИДОВ (06.11, улов `usuario-a3`). Зазор между карточками зависит от
# того, что видит зритель: две ЦИТАТЫ рядом читаются как слайды, а карта и
