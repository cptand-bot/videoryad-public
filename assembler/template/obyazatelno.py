def свои_сверх(scenes, список=None):
    """(виды в ролике, свои сверх списка, незанятые виды).

    `список` — замороженный состав этого ролика (`список_ролика`).
    """
    _сп = ОБЯЗАТЕЛЬНЫЕ if список is None else список
    обяз = {el.get("view") for el in _сп if el.get("view")}
    есть = set()
    for s in (scenes or []):
        src = str(s.get("source", ""))
        if src.startswith("card:"):
            есть.add(src.split(":", 1)[1].strip())
    return есть, sorted(есть - обяз), [v for v in ВСЕ_ВИДЫ if v not in есть]


def свободные_сцены(scenes, сколько):
    """Куда реально встанут новые карточки: `(список id, зазор)`.

    Зазор берётся тот же, что у расстановки (`место_под_карточки`), карточки
    уже стоящие в ролике — занятые места. Без этого «предложение» было бы
    советом поставить кадр туда, где его тут же забракует гейт плотности.

    ЕСЛИ ПРИ ЭТОМ ЗАЗОРЕ МЕСТ НЕ ХВАТАЕТ — УЖИМАЕМ ДО ПОЛА (11.11). Замер на
    сданном ролике: 92 сцены, 14 карточек, расчётный зазор 4 — свободной
    осталась ОДНА сцена из 92, и «предложи три» выродилось бы в «поставь
    одну». Пол 2 — предел, ниже соседние карточки читаются как слайды.
    """
    ids, занято = [], []
    for i, s in enumerate(scenes or []):
        ids.append(s.get("id", i + 1))
        _src = str(s.get("source", ""))
        # ЗАНЯТО — не только карточка (11.11): первая сцена держит видео-лид
        # (`check_lead`), а `direct_url` несёт вложение досье, которое гейт
        # `dossier_use` требует употребить. Предложить их — отправить вкладку
        # чинить один гейт, ломая два других.
        if _src.startswith("card:") or _src == "direct_url" or i == 0:
            занято.append(i)
    if not ids:
        return [], ЗАЗОР_ПОЛ
    g0 = место_под_карточки(len(ids))[2]
    # ПОЛ ОПУСКАЕТСЯ ДО НУЛЯ — И ЦИКЛ ОБЯЗАН ЭТО ПЕРЕЖИТЬ (12.11, блокер
    # `usuario-0d`). При `g0 = 0` прежний `range(0, ЗАЗОР_ПОЛ - 1, -1)` пуст,
    # `свободные` не создавалась вовсе, и функция падала UnboundLocalError —
    # РОВНО ТОГДА, когда набор закрыт целиком и сказать было нечего. Класс
    # «проверка валит инструмент своим молчанием».
    свободные = []
    for g in range(max(0, int(g0)), -1, -1):
        for i in range(len(ids)):
            if any(abs(i - j) <= g for j in занято + свободные):
                continue
            свободные.append(i)
        if len(свободные) >= сколько:
            # РАСТАСКИВАЕМ ПО РОЛИКУ, а не три подряд в начале: карточки
            # одного прогона не должны сбиться в кучу.
            шаг = len(свободные) / float(сколько)
            взяты = sorted({свободные[min(len(свободные) - 1, int(k * шаг))]
                            for k in range(сколько)})
            return [ids[i] for i in взяты], g
    return [ids[i] for i in свободные], max(0, int(g0))


# ── ЧИСЛОВЫЕ ВИДЫ НА ТЕКСТЕ БЕЗ ЧИСЕЛ НЕ ТРЕБУЮТСЯ (13.11, улов `usuario-03`) ──
# Два его правила столкнулись лбами. 13.11: «весь комплект, пропусков нет».
# 28.10: «если нет цифр, не ставим цифры… не надо какие-то точности».
# Двенадцать видов физически требуют ЧИСЕЛ на входе (network отбивает «вес не
# число: приветы», line — «Пиши метка=12»), и закрыть ими гейт можно только
# ВЫДУМАВ веса и значения. На аналитическом канале выдуманная диаграмма хуже
# отсутствующей: она читается как факт. Поэтому решает КОД, а не отговорка
# агента (пропуски так и остаются отменёнными): если во всём тексте ролика
# меньше трёх числовых фактов, числовые виды из нормы выпадают, а остальные
# тридцать остаются обязательными.
# `network`, `map`, `map_regions`, `bubbles`, `map_dist` ИЗ СПИСКА УБРАНЫ
# (13.11, проверено по `card_put.VIEWS` и разбору строк): граф принимает
# связь без веса («Варшава>Берлин» = 1.0), карты — список названий без
# значений. Они работают на событиях и именах, а значит обязательны всегда.
# Шкала зала (G15) и табло (G17) требуют `value` — пока в этом списке, до
# ключа `--sobytiya` (очередь, пункт 0-А).
# 14.11, ЕГО ПРЯМОЕ СЛОВО ПО СЧЁТУ ВИДОВ: «все эти 56 видов карточек, плюс 13
# эффектов, должны присутствовать в видеоряде». Поэтому самоотвод остался
# только у видов, которым НЕЧЕМ рисовать без величины: `slider` (диапазон
# «от и до» — без чисел это не оценка, а пустая шкала), `zal_shkala` G15 и
# `zal_schetchik` G17 (на плашке ДОБЕГАЕТ число, ключ `--value` обязателен).
# ШЕСТЬ ВИДОВ ИЗ САМООТВОДА УБРАНЫ: `line`, `slope`, `pie`, `radar`,
# `waterfall` имеют второй путь `--sobytiya` (перечень без цифр, величины
# равные, ось и подписи значений гасятся — П-0097, раскатано 13.11), `bars`
# рисует СООТНОШЕНИЕ по его слову 28.10 («если нет цифр, не ставим цифры»,
# «не надо какие-то точности, нам наглядно надо показать»). То есть
# выдумывать данные для них не нужно, а значит и снимать их нельзя: щель
# была ровно в том, что самоотвод 13.11 написан в обход уже готового
# бесчислового пути и тремя видами в день гасил комплект.
# РАДАР ВЕРНУЛСЯ В САМООТВОД (14.11, блокер `usuario-1f`, тот же день, что и
# П-0160). Снимая самоотвод, я записал `radar` к видам с бесчисловым путём —
# и ошибся: `card_put.py` отказывает радару ЖЁСТКО и СОЗНАТЕЛЬНО («без
# величин все оси равны, профиль вырождается в правильный многоугольник,
# 85% кадра чёрное»), перечень он не берёт ни `--sobytiya`, ни `--row`.
# Водопад на событиях там же РАЗРЕШЁН — значит дело не в недосмотре, а в
# природе вида: радар показывает РАЗНИЦУ по осям, и без разницы показывать
# нечего. Два гейта стояли друг против друга: `obyazatelno` требовал радар
# на каждом ролике, `card_put` его на безцифровом тексте не давал.
# Радар остаётся обязательным там, где в тексте есть ряд величин на 3-8 осей.
ЧИСЛОВЫЕ_ВИДЫ = ("slider", "radar", "zal_shkala", "zal_schetchik")
# МЕРА — ЭТО ВЕЛИЧИНА, А НЕ РИТОРИКА (13.11, улов `usuario-65`). Первый
# вариант считал мерой «год», «раз», «час» и «сутки» — и порог в три факта
# добирался оборотами речи: «в две тысячи девятнадцатом году» (это дата),
# «большинство в двух палатах Конгресса» (устройство парламента), «поставить
# рядом два кадра» (оборот). Настоящих данных в тексте ноль, а гейт снова
# требовал семь числовых видов, то есть толкал выдумывать цифры.
_МЕРА = re.compile(
    r"(процент|%|миллион|миллиард|триллион|тысяч|рубл|доллар|евро|гривен|"
    r"километр|метр|тонн|вдвое|втрое|кратн|градус|человек|солдат|"
    r"единиц|штук|баррел|киловатт|мегаватт|гектар)", re.I)
# Обороты, в которых число ничего не измеряет: считать их фактом нельзя.
_НЕ_МЕРА = re.compile(
    r"(палат\w*|кадр\w*|сторон\w*|раунд\w*|част(?:ь|и)|год(?:а|у|ов)?|"
    r"раз(?:а|ов)?|сут(?:ки|ок)|час(?:ов|а)?)", re.I)
_ЦИФРА = re.compile(r"\d")
_ЧИСЛО_СЛОВОМ = re.compile(
    r"\b(дв(?:а|е|ух|умя)|тр(?:и|ёх|ех)|четыр(?:е|ёх|ех)|пят(?:ь|и)|"
    r"шест(?:ь|и)|сем(?:ь|и)|восем(?:ь|и)|девят(?:ь|и)|десят(?:ь|и)|"
    r"сорок|пятьдесят|сто|двести|триста|тысяч(?:а|и))\b", re.I)


def числовых_фактов(scenes):
    """Сколько в тексте ролика чисел, стоящих рядом с мерой."""
    n = 0
    for s in (scenes or []):
        if not isinstance(s, dict):
            continue
        т = ""
        for k in ("text", "текст", "line", "reply", "srt_text"):
            v = s.get(k)
            if isinstance(v, str) and v.strip():
                т = v
                break
        if not т:
            continue
        for кусок in re.split(r"[.!?;]", т):
            # Обороты вычёркиваем ИЗ КУСКА, а не отбрасываем кусок целиком:
            # во фразе «просит сорок миллиардов долларов, пятый транш за год»
            # есть и риторика, и настоящая величина — факт тут ЕСТЬ.
            чистый = _НЕ_МЕРА.sub(" ", кусок)
            if not _МЕРА.search(чистый):
                continue
            if _ЦИФРА.search(чистый) or _ЧИСЛО_СЛОВОМ.search(чистый):
                n += 1
    return n


def ряд_в_одной_сцене(scenes):
    """Максимум числовых величин В ОДНОЙ сцене — для видов, которым нужен РЯД.

    14.11, блокер `usuario-1f` (вторая попытка по радару за день). Порог
    `ЧИСЛОВОЙ_ПОРОГ` считает числовые факты ПО ВСЕМУ РОЛИКУ и не отличает
    ряд по одной мере от разрозненных чисел: «десять лет до ЕС», «пять лет
    на восстановление», «больше половины мощностей», «миллионы связей» — это
    четыре РАЗНЫЕ меры из разных кусков текста, рисовать по ним профиль по
    осям нечем. А порог они перебивают, и радар требовался бы на любом
    новостном тексте всегда.
    Радару (и любому виду, который рисует ПРОФИЛЬ или РЯД) нужна одна сцена,
    где величин три и больше — тогда это настоящий ряд.
    """
    лучший = 0
    for s in (scenes or []):
        if not isinstance(s, dict):
            continue
        т = ""
        for k in ("text", "текст", "line", "reply", "srt_text"):
            v = s.get(k)
            if isinstance(v, str) and v.strip():
                т = v
                break
        if not т:
            continue
        n = 0
        for кусок in re.split(r"[.!?;]", т):
            чистый = _НЕ_МЕРА.sub(" ", кусок)
            if not _МЕРА.search(чистый):
                continue
            if _ЦИФРА.search(чистый) or _ЧИСЛО_СЛОВОМ.search(чистый):
                n += 1
        лучший = max(лучший, n)
    return лучший


# ВИДЫ, КОТОРЫМ НУЖЕН РЯД В ОДНОЙ СЦЕНЕ, А НЕ ЧИСЛА ПО РОЛИКУ (14.11).
# Радар рисует профиль по 3-8 осям одной меры — разрозненные величины из
# разных кусков текста ему не годятся, и `card_put` отказывает жёстко.
ВИДЫ_РЯДА = ("radar",)
ЧИСЛОВОЙ_ПОРОГ = 3

# КАРТА ОБЛАСТЕЙ НА ТЕКСТЕ БЕЗ ОБЛАСТЕЙ НЕ ТРЕБУЕТСЯ (13.11, улов
# `usuario-65`, тот же класс, что числовые виды выше). `map_regions` рисует
# КОНТУРЫ административных единиц и требует `--places` с их именами. В
# ролике, где не названо ни одной области, республики, края или штата,
# закрыть этот вид можно только подсветив единицы, которых в закадровке
# нет, — то есть проиллюстрировав НЕ СКАЗАННОЕ. Это прямо против его
# правила «иллюстрируем названное» и равно выдуманным цифрам.
# Страны (`map`, `bubbles`) под это не подпадают: страна в новостном тексте
# названа всегда, и там вид остаётся обязательным.
# ЕДИНИЦА СЧИТАЕТСЯ ТОЛЬКО С ИМЕНЕМ (13.11, две пробы подряд). Родового
# слова мало: «вывести из привычной области», «все вокруг», «Соединённых
# Штатов» дали шесть мнимых единиц на тексте, где не названо ни одной, и
# гейт продолжал требовать карту контуров. Контур рисуется по ИМЕНИ, поэтому
# засчитываем только пару «имя + родовое слово» в любом порядке:
# «Ростовская область», «Краснодарский край», «Республика Крым», «штат
# Техас», «Люблинское воеводство».
# ГРАНИЦА СЛОВА ПЕРЕД РОДОВЫМ СЛОВОМ (13.11, точный разбор `usuario-c9`):
# без неё второе плечо матчило «округ Украины» ВНУТРИ оборота «вокруг
# Украины» — на ПЛАНЕТЕ-3 этого хватило, чтобы вид не ушёл в «не требуется».
# Первая проба не поймала дефект, потому что в ней за «вокруг» не стояло
# слово с заглавной буквы.
_РОД = (r"(?<![А-Яа-яЁё])(?:[Оо]бласт(?:ь|и|ью|ей|ям|ями|ях)|"
        r"[Кк]ра(?:й|я|ю|ем)|[Рр]еспублик\w+|[Гг]уберни\w+|[Пп]ровинци\w+|"
        # «штат» только в ЕДИНСТВЕННОМ числе: «Штаты» и «Штатов» — это США,
        # на них первая проба 13.11 и попалась («Соединённых Штатов» читалось
        # как «имя + родовое слово»).
        r"[Вв]оеводств\w+|[Кк]антон\w*|[Шш]тат(?:а|е|ом)?(?![А-Яа-яЁё])|"
        r"[Оо]круг(?:а|е|ом|ов|и)?(?![А-Яа-яЁё]))")
_АДМ_ЕДИНИЦА = re.compile(
    r"(?:(?!Его|Её|Эта|Это|Эти|Эту|Этой|Наша|Нашей|Своя|Своей|Та|Той|Вся|"
    r"Всей|Одна|Одной|Соединённых|Соединенных)[А-ЯЁ][а-яё]{2,}"
    r"(?:ская|ский|ское|ской|скую|ского|ском|ья|ая|ий)?\s+"
    # между именем и родовым словом может стоять прилагательное:
    # «Ямало-Ненецкий АВТОНОМНЫЙ округ», «Еврейская АВТОНОМНАЯ область»
    r"(?:[а-яё]+\s+)?"
    + _РОД + r"|" + _РОД + r"\s+[А-ЯЁ][а-яё]{2,})")
ВИДЫ_АДМ = ("map_regions",)


def адм_единиц(scenes):
    """Сколько раз в тексте ролика названа административная единица."""
    n = 0
    for s in (scenes or []):
        if not isinstance(s, dict):
            continue
        for k in ("text", "текст", "line", "reply", "srt_text"):
            v = s.get(k)
            if isinstance(v, str) and v.strip():
                n += len(_АДМ_ЕДИНИЦА.findall(v))
                break
    return n


def check(scenes, channel="", gate="dashboard", scenes_path=""):
    """Чего не хватает. Возвращает список строк отказа (пустой — всё стоит)."""
    n_scenes = len(scenes or [])
    # НОРМА НАЛОЖЕНИЙ СЧИТАЕТСЯ ТОЛЬКО ПО ОБЫЧНЫМ СЦЕНАМ (09.11, его правило:
    # «на наших элементах не должны быть ни надписей, ни всплывашек»). На
    # рисованный кадр надпись запрещена и её снимает гейт, поэтому карточки в
    # знаменателе нормы — это требование слоя, который тут же забракуют:
    # вкладка попадает в вилку и теряет круг правок. У роликов 09-10.11
    # карточек 15-17 из 67-71 сцены, то есть ЧЕТВЕРТЬ — норма выходила на
    # две надписи больше, чем ролик физически может нести.
    # Элементы-КАДРЫ (`view`) этим не затронуты: у них нормы без `на_сцен`.
    обычных = len([s for s in (scenes or [])
                   if not str(s.get("source", "")).startswith("card:")])
    have, have_fx = {}, {}
    # СОСТАВ — ТОТ, С КОТОРЫМ РОЛИК НАЧИНАЛСЯ (13.11, пункт 59 очереди):
    # список растёт каждый день, ролик живёт полдня.
    _список, _записка = список_ролика(scenes_path)
    if _записка:
        print(_записка)
    _чисел = числовых_фактов(scenes if isinstance(scenes, list) else [])
    _ряд = ряд_в_одной_сцене(scenes if isinstance(scenes, list) else [])
    _адм = адм_единиц(scenes if isinstance(scenes, list) else [])
    have_ov = (_overlay_styles(scenes_path)
               if any(e.get("overlay_style") for e in _список) else {})
    for s in scenes:
        src = str(s.get("source", ""))
        if src.startswith("card:"):
            have[src[5:].strip()] = have.get(src[5:].strip(), 0) + 1
        f = str(s.get("fx", "")).strip().lower()
        if f:
            have_fx[f] = have_fx.get(f, 0) + 1
    bad = []
    _не_занято = []
    for el in _список:
        if gate == "dashboard" and el["gate"] == "video":
            continue                      # этот спрашиваем только перед сборкой
        if el["каналы"] and channel and channel.upper() not in [
                c.upper() for c in el["каналы"]]:
            continue
        if el.get("overlay_style"):
            n = have_ov.get(el["overlay_style"], 0)
        elif el.get("fx"):
            n = have_fx.get(el["fx"], 0)
        else:
            n = have.get(el["view"], 0)
        _норма = el["min"]
        if el.get("на_сцен"):
            # наложение (надпись) — от ОБЫЧНЫХ сцен; кадр — от всех
            _база = обычных if el.get("overlay_style") else n_scenes
            if _база:
                _норма = max(el["min"],
                             int(round(_база / float(el["на_сцен"]))))
        if n >= _норма:
            continue
        _вид_ = str(el.get("view") or el.get("fx") or "").split(":")[-1]
        if _вид_ in ВИДЫ_АДМ and not _адм:
            _не_занято.append("%s — не требуется: в тексте не названо ни "
                              "одной области, республики, края или штата, "
                              "а вид рисует их контуры; подсвечивать "
                              "не сказанное запрещено" % _вид_)
            continue
        # ЭФФЕКТОВ ТРЕБУЕМ НЕ БОЛЬШЕ, ЧЕМ ЕСТЬ МЕСТ (14.11, блокер
        # `usuario-70`, та же арифметика, что с надписями в П-0175). Эффект
        # ложится ПО ОДНОМУ на сцену, на рисованный кадр слой запрещён его
        # правилом — значит мест ровно столько, сколько НЕКАРТОЧНЫХ сцен
        # минус занятые кнопкой «ПОДПИШИСЬ». На живом ролике: 67 сцен, 56
        # карточек, 11 некарточных, два места под кнопку → максимум 9 видов
        # против требуемых 13, и гейт гонял вкладку по кругу: закрыла один
        # вид — попросил следующий, закрыла его — вылетел первый.
        # Поэтому: пока эффектов СТОЛЬКО ЖЕ, сколько мест, остальные виды
        # уходят в «не занято» с причиной, а не в отказ. Комплект при этом не
        # ослаблен: мест под эффекты становится больше ровно тогда, когда
        # сцен в ролике больше, чем карточек.
        if el.get("fx"):
            _mest_fx = max(0, обычных - 2)
            _vsego_fx = sum(1 for e in _список if e.get("fx"))
            _stoit_fx = sum(1 for e in _список
                            if e.get("fx") and have_fx.get(e["fx"], 0) > 0)
            if _vsego_fx > _mest_fx and _stoit_fx >= _mest_fx:
                _не_занято.append(
                    "fx:%s — не требуется: мест под эффекты %d (некарточных "
                    "сцен %d минус две под кнопку «ПОДПИШИСЬ»), и они уже "
                    "заняты другими видами; эффект ложится по одному на "
                    "сцену, а на рисованный кадр слой запрещён"
                    % (el["fx"], _mest_fx, обычных))
                continue
        if _вид_ in ВИДЫ_РЯДА and _ряд < ЧИСЛОВОЙ_ПОРОГ:
            _не_занято.append("%s — не требуется: ряда величин одной меры в "
                              "тексте нет (лучшая сцена даёт %d из %d), а вид "
                              "рисует профиль по осям; разрозненные числа из "
                              "разных кусков ему не годятся, выдумывать "
                              "данные запрещено" % (_вид_, _ряд, ЧИСЛОВОЙ_ПОРОГ))
            continue
        if _вид_ in ЧИСЛОВЫЕ_ВИДЫ and _чисел < ЧИСЛОВОЙ_ПОРОГ:
            _не_занято.append("%s — не требуется: числовых фактов в тексте %d "
                              "(порог %d), выдумывать данные запрещено"
                              % (_вид_, _чисел, ЧИСЛОВОЙ_ПОРОГ))
            continue
        _пч = _причина_пропуска(scenes_path, el.get("view") or el.get("fx"))
        if _пч:
            _не_занято.append("%s — пропущен: %s" % (el.get("view") or el.get("fx"), _пч))
            continue
        bad.append(
            "ОБЯЗАТЕЛЬНЫЙ ЭЛЕМЕНТ %s («%s») стоит %d раз при норме %d.\n"
            "    когда уместен: %s\n"
            "    чем ставится: %s"
            % (el["код"], el["имя"], n, _норма, el["когда"], el["чем"]))

    # СПИСОК — ЭТО МИНИМУМ (07.11, его слово: «ну как это лежат без дела?
    # Зачем мы их разрабатываем, если используешь только девять?»).
    # Держит ГЕЙТ ДАШБОРДА: пока ролик не утверждён, карточку ещё можно
    # поставить и отрисовать облаком тем же прогоном. Перед полной сборкой
    # (`video`) требование только называется — после «утверждаю» ролик
    # заморожен, и валить его там значило бы гнать вкладку в обход гейта.
    _есть, _свои, _свободны = свои_сверх(scenes, _список)
    if _не_занято:
        print("НЕ ЗАНЯТО НИ РАЗУ (%d из наших видов) — поставь те, что ложатся "
              "по смыслу, остальные пропусти:" % len(_не_занято))
        for _s in _не_занято[:40]:
            print("   · %s" % _s)
    _надо_сверх = 0 if обязательных_карточек(_список) >= 20 else СВОИХ_СВЕРХ
    if gate == "dashboard" and _надо_сверх and len(_свои) < _надо_сверх:
        _надо = _надо_сверх - len(_свои)
        _куда, _g = свободные_сцены(scenes, _надо)
        _виды = _свободны[:_надо]
        _строки = ["    python3 ~/.claude/skills/news-video/fullcycle/card_put.py "
                   "<scenes.json> %s %s %s"
                   % (sid, v, ЧЕМ_КОРМИТЬ.get(v, '--text "…"'))
                   for sid, v in zip(_куда, _виды)]
        if len(_куда) < _надо:
            # Ролик физически не вмещает — требовать невыполнимое нельзя.
            # Это единственный случай, когда гейт молчит, и он назван вслух
            # в `main()`: «мест нет», а не «можно и так».
            pass
        else:
            bad.append(
                "СВОИХ ВИДОВ СВЕРХ ОБЯЗАТЕЛЬНОГО СПИСКА %d, НАДО %d.\n"
                "    обязательный список — это МИНИМУМ, а не потолок: видов "
                "принято %d, в ролике занято %d.\n"
                "    не заняты: %s\n"
                "    свободные сцены (зазор %d): %s\n%s"
                % (len(_свои), СВОИХ_СВЕРХ, len(ВСЕ_ВИДЫ), len(_есть),
                   ", ".join(_свободны[:14]) or "нет", _g,
                   ", ".join(str(x) for x in _куда),
                   "\n".join(_строки)))
    return bad


def main():
    ap = argparse.ArgumentParser(description="обязательные элементы ролика")
    ap.add_argument("scenes", nargs="?", default="")
    ap.add_argument("--gate", choices=["dashboard", "video"], default="dashboard")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--list", action="store_true")
    # ЗАМОРОЗКА СОСТАВА (13.11, пункт 59). Обычно её делает приёмка
    # раскадровки сама; ключ нужен для ролика, начатого до этой правки.
    ap.add_argument("--zamorozit", action="store_true",
                    help="заморозить состав списка рядом со сценами")
    ap.add_argument("--perezamorozit", action="store_true",
                    help="перезаписать снимок состава (только по его слову)")
    a = ap.parse_args()

    if a.list or not a.scenes:
        print("ОБЯЗАТЕЛЬНЫЕ ЭЛЕМЕНТЫ (гейт → код → вид → сколько):")
        for el in ОБЯЗАТЕЛЬНЫЕ:
            метка = ("надпись:" + el["overlay_style"] if el.get("overlay_style")
                     else "fx:" + el["fx"] if el.get("fx")
                     else "card:" + el["view"])
            # СКОЛЬКО ИХ НАДО — ПЕЧАТАЕМ ПО ПРАВИЛУ, А НЕ ПОЛЕ `min` (09.11).
            # У `N-текст` норма считается от длины ролика (`на_сцен: 8.5`), а
            # список показывал голое «x1» — и документы вслед за ним держали
            # «норма 1, потолок 4», пока вкладка ставила восемь ПО КОДУ и
            # шла их снимать по документу. Проверка не менялась, только вывод.
            _скл = ("x%d на ролик" % el["min"] if not el.get("на_сцен")
                    else "x1 на %g обычн.сцен" % float(el["на_сцен"])
                    if el.get("overlay_style")
                    else "x1 на %g сцен" % float(el["на_сцен"]))
            print("  %-9s %-4s %-17s %-13s %s"
                  % (el["gate"], el["код"], метка, _скл, el["имя"]))
        return 0

    if not os.path.isfile(a.scenes):
        print("нет файла сцен: %s" % a.scenes, file=sys.stderr)
        return 2
    scenes, meta = _scenes(a.scenes)
    if a.zamorozit or a.perezamorozit:
        _p, _n, _nov = заморозить(a.scenes, _channel(meta, a.scenes),
                                  a.perezamorozit)
        if _nov:
            print("состав обязательных заморожен (%d элементов) → %s" % (_n, _p))
        else:
            print("состав уже заморожен (%d элементов) → %s\n"
                  "   перезаписать (только по его слову): --perezamorozit"
                  % (_n, _p))
        return 0
    bad = check(scenes, _channel(meta, a.scenes), a.gate, a.scenes)
    if a.json:
        print(json.dumps({"gate": a.gate, "ok": not bad, "нет": bad},
                         ensure_ascii=False, indent=1))
        return 1 if bad else 0
    if bad:
        print("❌ ОБЯЗАТЕЛЬНЫХ ЭЛЕМЕНТОВ НЕТ В РОЛИКЕ (%d):" % len(bad))
        for b in bad:
            print("  - " + b)
        return 1
    print("✅ обязательные элементы на месте (%s)" % a.gate)

    # СВОИ ВИДЫ СВЕРХ СПИСКА. Сам ОТКАЗ живёт в `check()` (гейт дашборда),
    # сюда он уже приехал через `bad` — здесь только картина по ролику.
    # 11.11: раньше тут печаталось «нужно не меньше 3» и возвращался НОЛЬ.
    _есть, _свои, _свободны = свои_сверх(scenes, список_ролика(a.scenes)[0])
    print("видов в ролике: %d (обязательных %d + своих %d)"
          % (len(_есть), len(_есть) - len(_свои), len(_свои)))
    if _свои:
        print("   сверх обязательных: %s" % ", ".join(_свои))
    if len(_свои) < СВОИХ_СВЕРХ:
        # сюда доходим, только если `check()` не отказал: гейт `video`
        # (ролик утверждён и заморожен) либо в ролике нет места
        _куда, _g = свободные_сцены(scenes, СВОИХ_СВЕРХ - len(_свои))
        if len(_куда) < СВОИХ_СВЕРХ - len(_свои):
            print("   своих видов %d из %d, но СВОБОДНЫХ СЦЕН НЕТ даже при "
                  "зазоре %d — ролик короче набора, требование снято."
                  % (len(_свои), СВОИХ_СВЕРХ, ЗАЗОР_ПОЛ))
        else:
            print("   своих видов %d из %d; добавить можно: %s"
                  % (len(_свои), СВОИХ_СВЕРХ, ", ".join(_свободны[:10])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
