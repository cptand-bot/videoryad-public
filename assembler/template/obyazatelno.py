def _причина_пропуска(scenes_path, вид):
    if not ПРОПУСКИ_РАЗРЕШЕНЫ:
        return ""
    if not scenes_path or not вид:
        return ""
    п = os.path.join(os.path.dirname(os.path.abspath(scenes_path)),
                     ПРОПУСКИ_ФАЙЛ)
    try:
        with open(п, encoding="utf-8") as f:
            д = json.load(f)
    except (OSError, ValueError):
        return ""
    причина = str((д or {}).get(вид, "")).strip()
    # Пустая строка причиной НЕ является: пропуск без объяснения — это
    # тихий обход гейта, ровно то, от чего он и поставлен.
    return причина if len(причина) >= 10 else ""


def _overlay_styles(scenes_path):
    """Сколько каких НАДПИСЕЙ стоит в `overlays.json` рядом со сценами.

    Наложение живёт не в `scenes.json`, а в `overlays.json`, поэтому для
    таких элементов смотрим туда. Файла нет — считаем, что надписей ноль:
    это честный отказ, а не поломка гейта.
    """
    out = {}
    if not scenes_path:
        return out
    ov = os.path.join(os.path.dirname(os.path.abspath(scenes_path)),
                      "overlays.json")
    try:
        d = json.load(open(ov, encoding="utf-8"))
    except (OSError, ValueError):
        return out
    for k, spec in (d or {}).items():
        if not isinstance(spec, dict):
            continue
        ts = spec.get("text")
        if not isinstance(ts, dict):
            continue
        st = str(ts.get("style", "")).strip().lower()
        if st:
            out[st] = out.get(st, 0) + 1
    return out


