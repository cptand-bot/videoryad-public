#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ЖУРНАЛ ЕГО ВЫБОРА → ТАБЛИЦА (локально и на Google Диск), 08.11.2026.

Его слово: «давай не копим локально, давай сделаем свою таблицу на Google
диске, чтобы это всё накапливалось там. Пусть будет и локально, и там… чтобы
я мог дать задание чату GPT туда залезть, посмотреть, как это делается».

ЧТО КОПИМ. Дашборд упаковки (`upakovka_dash.py`) пишет каждое его действие в
`upakovka_lib/vybor.jsonl`: какой заголовок скопировал (и какие девять при
этом не взял), какую надпись выбрал, какое превью, что вписал руками, когда
нажал «ещё 10 вариантов» (это отказ от всей пачки).

ЧТО ДЕЛАЕТ ЭТОТ ИНСТРУМЕНТ. Разворачивает журнал в плоскую таблицу CSV —
её и кладём на Диск отдельным файлом (НЕ в георадар: туда писать запрещено
его же словом, это наша собственная таблица).

    python3 vybor_svod.py                 # показать сводку
    python3 vybor_svod.py --csv <файл>    # выгрузить таблицу

Колонки: когда · событие · канал · тема · выбрано · вписал_сам ·
номер_превью · отвергнуто · предложено.

ПОЧЕМУ ТАБЛИЦА НА ДИСКЕ ОБНОВЛЯЕТСЯ ЦЕЛИКОМ: коннектор Drive умеет создавать
файл и править его свойства, но не дописывать содержимое. Поэтому выгрузка
всегда полная — таблица на Диске заменяется новой, история не теряется,
потому что живёт в локальном журнале.
"""

import argparse
import csv
import io
import json
import os
import sys

ЖУРНАЛ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "upakovka_lib", "vybor.jsonl")
КОЛОНКИ = ("когда", "событие", "канал", "тема", "выбрано", "вписал_сам",
           "номер_превью", "отвергнуто", "предложено")


def строки():
    if not os.path.exists(ЖУРНАЛ):
        return []
    out = []
    for line in io.open(ЖУРНАЛ, encoding="utf-8"):
        try:
            e = json.loads(line)
        except ValueError:
            continue
        выбрано = e.get("выбрано") or ""
        if e.get("событие") == "превью":
            выбрано = " / ".join(x for x in (e.get("надпись_сверху"),
                                             e.get("надпись_снизу")) if x)
        out.append({
            "когда": e.get("когда", ""),
            "событие": e.get("событие", ""),
            "канал": e.get("канал", ""),
            "тема": e.get("тема", ""),
            "выбрано": выбрано,
            "вписал_сам": "да" if e.get("вписал_сам") else "",
            "номер_превью": e.get("выбран_вариант", ""),
            "отвергнуто": " | ".join(str(x) for x in (e.get("отвергнуто") or [])),
            "предложено": " | ".join(str(x) for x in (e.get("предложено")
                                                      or e.get("предложенные_надписи") or [])),
        })
    return out


def main():
    ap = argparse.ArgumentParser(description="журнал выбора → таблица")
    ap.add_argument("--csv", default="", help="куда выгрузить CSV")
    a = ap.parse_args()

    rows = строки()
    if not rows:
        print("журнал пуст: он ещё ничего не выбирал на дашборде упаковки")
    else:
        счёт = {}
        for r in rows:
            счёт[r["событие"]] = счёт.get(r["событие"], 0) + 1
        print("записей: %d" % len(rows))
        for к, v in sorted(счёт.items(), key=lambda x: -x[1]):
            print("  %-12s %d" % (к, v))
        print("последняя: %s" % rows[-1]["когда"])

    if a.csv:
        with io.open(a.csv, "w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=КОЛОНКИ)
            w.writeheader()
            for r in rows:
                w.writerow(r)
        print("выгружено: %s (%d строк)" % (a.csv, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
