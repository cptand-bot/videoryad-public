#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""СУБЪЕКТ ПО-ЛАТИНСКИ — ЧТОБЫ АРХИВЫ ВООБЩЕ НАС ПОНИМАЛИ (11.11.2026).

ЧТО ВСКРЫЛОСЬ. Разведка наличия (`nalichie.py`) на живом ролике дала ноль по
архивам у ВСЕХ пятнадцати поисковых сцен. Проверка руками показала причину:
архивы подписаны латиницей, а мы спрашиваем по-русски.

    «Роберт Фицо»            → Викисклад 0
    «Robert Fico»            → Викисклад 702
    «Фридрих Мерц»           → Викисклад 0 (по полному запросу)
    «Friedrich Merz»         → Викисклад 1382

То есть водопад источников (Openverse → Flickr → Архив → Викисклад) у нас
молча пустовал на западных субъектах и всегда скатывался в картиночный поиск
— в ту самую рулетку, которая и даёт мимо-тему, чужие клейма и круги правок.
Это не «архивов мало», это мы спрашивали на языке, которого они не знают.

КАК РАБОТАЕТ. Русская Википедия знает субъект и знает его английское имя:
    запрос → поиск статьи в ru.wikipedia → межъязыковая ссылка на en → имя
Имя подставляется в архивные источники, русский запрос при этом НЕ отменяется:
советский и российский архив как раз подписан по-русски, и его мы потеряем,
если переключимся целиком (правило из SKILL.md).

ЗАЩИТА ОТ НЕ ТОГО СУБЪЕКТА. Википедия на нечёткий запрос охотно отдаёт
соседнюю статью: «Берлин федеральная канцелярия» → «Федеральный президент
Германии». Такой ответ ОТБРАСЫВАЕТСЯ: каждое значимое слово найденной статьи
обязано отозваться в исходном запросе. Пропускаются только совпадения, где
статья действительно про то, что спросили.

    python3 latinka.py "Роберт Фицо"        # разово, посмотреть глазами
"""
import json
import re
import sys
import urllib.parse
import urllib.request

# Викимедиа просит честно представляться. С браузерным User-Agent их API на
# пачке запросов отвечает 429 (поймано 11.11 на разведке из 15 сцен).
UA = {"User-Agent": "videoryad-nalichie/1.0 (cptand@gmail.com) python-urllib"}
_КЭШ = {}


def _j(url, timeout=12):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def _значимые(s):
    """Слова от четырёх букв, без года и знаков."""
    return [w for w in re.sub(r"[^\w\s-]", " ", s, flags=re.U).split()
            if len(w) >= 4 and not re.fullmatch(r"(19|20)\d{2}", w)]


def _отзывается(заголовок, запрос):
    """Все значимые слова статьи должны найтись в запросе по пятибуквенному
    началу. Иначе Википедия подсунула соседнюю тему."""
    зап = запрос.lower()
    слова = _значимые(заголовок)
    if not слова:
        return False
    return all(w.lower()[:5] in зап for w in слова)


def латиница(запрос, timeout=12):
    """Возвращает английское имя субъекта или None.

    None значит одно из трёх: статьи нет, у статьи нет английской версии,
    либо найденная статья не про то, что спросили."""
    if запрос in _КЭШ:
        return _КЭШ[запрос]
    итог = None
    try:
        u = "https://ru.wikipedia.org/w/api.php?" + urllib.parse.urlencode(
            {"action": "query", "format": "json", "list": "search",
             "srsearch": запрос, "srlimit": "1"})
        найдено = _j(u, timeout).get("query", {}).get("search", [])
        if найдено:
            заголовок = найдено[0]["title"]
            if _отзывается(заголовок, запрос):
                u2 = "https://ru.wikipedia.org/w/api.php?" + urllib.parse.urlencode(
                    {"action": "query", "format": "json", "prop": "langlinks",
                     "titles": заголовок, "lllang": "en"})
                стр = list(_j(u2, timeout).get("query", {}).get("pages", {}).values())
                ll = стр[0].get("langlinks") if стр else None
                if ll:
                    итог = ll[0]["*"]
    except Exception:
        итог = None
    _КЭШ[запрос] = итог
    return итог


def обогатить(запрос, timeout=12):
    """Запрос для архивов: ОДНО имя субъекта латиницей, без хвоста.

    Хвост пробовали приклеивать («Robert Fico Братислава») — выдача от этого
    только сужалась, а русские слова в хвосте архив всё равно не понимает.
    Архив индексирует ИМЯ; обрезать выдачу по месту и событию незачем, этим
    занимаются прежние сита качества. Поэтому здесь ровно имя."""
    return латиница(запрос, timeout)


if __name__ == "__main__":
    q = " ".join(sys.argv[1:])
    print(f"запрос:    {q}")
    print(f"субъект:   {латиница(q)}")
    print(f"для архива: {обогатить(q)}")
