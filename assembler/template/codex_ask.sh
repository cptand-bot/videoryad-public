#
# ЧЕСТНО О ТОЧНОСТИ: сервис не отдаёт остаток лимита числом, поэтому считаем
# ЗАХОДЫ за текущее пятичасовое окно по нашему же журналу `codex_zahody.tsv`
# (там теперь пишется аккаунт). Бюджет окна — переменная `CODEX_BUDGET`,
# по умолчанию 40 заходов: это ОЦЕНКА, уточняется замером; как только
# поймаем живой упор в лимит, число заменим на измеренное.
# Правило: дошли до 80% бюджета на ЕГО аккаунте — следующие заходы идут на
