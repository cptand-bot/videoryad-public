    _edge="$(date -d '5 hours ago' +%Y-%m-%dT%H:%M:%S 2>/dev/null || echo 0)"
    _used="$(awk -F'\t' -v e="$_edge" '$1 >= e && ($4 == "основной" || $4 == "") {n++} END {print n+0}' "$_jr")"
    _limit=$(( _budget * 80 / 100 ))
    if [ "$_used" -ge "$_limit" ]; then
      export CODEX_ACCOUNT=eva
      echo "агент: окно основного аккаунта израсходовано на $_used из $_budget" >&2
      echo "       (порог 80% = $_limit) — беру РЕЗЕРВНЫЙ аккаунт, чтобы" >&2
      echo "       остаток окна остался тебе на свою работу в чате." >&2
