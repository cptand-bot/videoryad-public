# ЧИСТКА ОДНА НА ВСЁ (замок + копии вложений): два отдельных `trap ... EXIT`
# не складываются — второй МОЛЧА затирает первый, и тогда либо имя держателя
# остаётся лежать мёртвым, либо копии вложений не убираются из его папки.
_mine=()
_cleanup() {
  for f in ${_mine[@]+"${_mine[@]}"}; do rm -f "$f"; done
  # Имя держателя убираем ТОЛЬКО если замок наш: иначе ждущий вызов снёс бы
  # подпись того, кого он ждёт, и в логе осталось бы «жду неизвестно кого».
  if [ "$_lock_mine" = 1 ]; then rm -f "$_lock_who"; fi
  return 0
}
trap _cleanup EXIT
# Сам замок — дескриптор: его ядро отпускает при ЛЮБОЙ смерти процесса,
# включая `kill -9`, где никакой `trap` не сработает. Поэтому мёртвого замка
# не бывает в принципе; подпись держателя страхуем перехватом сигналов —
# `exit` из обработчика запускает `trap ... EXIT` выше.
trap 'exit 130' INT HUP
trap 'exit 143' TERM

_lock_fail() {
  echo "!! внешний агент занят больше $(( _lock_wait_max / 60 )) минут — не дождался, задание НЕ отправлено." >&2
  echo "   Лимит агента не потрачен, заново писать задание не надо." >&2
  echo "   Посмотри, что идёт:   pgrep -af codex" >&2
  echo "   Держатель замка:      cat $_lock_who" >&2
  echo "   Живого вызова нет — замок уже свободен, просто повтори команду." >&2
  echo "   Вызов висит — дождись его конца (или сними) и повтори." >&2
  exit 3
}

_waited=0
exec 7>"$_lock" || { echo "codex_ask.sh: не открыть замок $_lock" >&2; exit 6; }
if ! flock -n 7; then
  _hold="$(cat "$_lock_who" 2>/dev/null || true)"
  echo "внешний агент занят другим вызовом, стою в очереди (потолок $(( _lock_wait_max / 60 )) мин)." >&2
  [ -n "$_hold" ] && echo "   занял: $_hold" >&2
  # ПРИЗНАК ЖИЗНИ РАЗ В 30 СЕКУНД, не чаще: ждать можно полчаса, и лог
  # вкладки не должен от этого распухнуть. Шаг даёт сам `flock -w 30`.
  while [ "$_waited" -lt "$_lock_wait_max" ]; do
    if flock -w 30 7; then break; fi
    _waited=$(( _waited + 30 ))
    _hold="$(cat "$_lock_who" 2>/dev/null || true)"
    echo "   жду ${_waited} с из ${_lock_wait_max}${_hold:+ · занял: $_hold}" >&2
  done
  if [ "$_waited" -ge "$_lock_wait_max" ]; then _lock_fail; fi
fi
