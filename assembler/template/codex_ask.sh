# ЧУЖОЙ ЖИВОЙ `codex exec` — ТОЖЕ ЗАНЯТОСТЬ, ЗАМКА ЗДЕСЬ НЕ ХВАТАЕТ (09.11,
# найдено проверкой на `kill -9`). Замок привязан к ОБЁРТКЕ, и это сделано
# нарочно (см. `7>&-` у пайплайна ниже): иначе осиротевший `tee` или сам
# агент продолжают держать дескриптор, и мёртвый замок останавливает всю
# смену. Обратная сторона — обёртку убили, а `codex exec` жив сиротой: замок
# свободен, память занята, и новый вызов опять уводит машину в OOM. Поэтому
# ВТОРОЕ условие старта: на машине не должно идти ни одного `codex exec`.
# Сегодня это не теория — две таких раскадровки идут прямо сейчас, запущенные
# ещё версией без замка.
# ИЩЕМ ПО ИМЕНИ ПРОЦЕССА, А НЕ ПО КОМАНДНОЙ СТРОКЕ (09.11, поймано своей же
# проверкой). `pgrep -f 'codex exec'` ловит ЛЮБУЮ строку, где встретились эти
# два слова: собственную оболочку вкладки, которая пишет `pgrep -af "codex
# exec"`, наш же тестовый прогон, любой `grep`. Ложное срабатывание здесь
# стоит 30 минут простоя на ровном месте — именно это и случилось при
# проверке. Поэтому `pgrep -x codex`: точное `comm` самого бинаря агента
# (`codex-code-mode-host` под него не попадает, у него `comm` другой), плюс
# сверка по `/proc/<pid>/cmdline`, что это действительно `exec`.
# `|| true` ОБЯЗАТЕЛЕН: под `pipefail` пустой `pgrep` отдаёт 1, и присваивание
# `_live="$(_codex_live)"` роняло весь вызов под `set -e` — поймано прогоном
# с `-x` 09.11: «ничего не идёт» читалось как ошибка и скрипт молча выходил.
_codex_live() {
  local p out=""
  for p in $(pgrep -x codex 2>/dev/null || true); do
    case " $(tr '\0' ' ' < "/proc/$p/cmdline" 2>/dev/null || true) " in
      *" exec "*) out="$out$p " ;;
    esac
  done
  printf '%s' "$out"
}
# ЧУЖОЙ АККАУНТ БОЛЬШЕ НЕ СЧИТАЕТСЯ ЗАНЯТОСТЬЮ (13.11). Проверка «на машине
# не должно идти НИ ОДНОГО codex exec» сводила на нет замок-на-аккаунт от
# 12.11: вторая раскадровка всё равно ждала первую до 30 минут, хотя аккаунты
# разные. Теперь сирот ищем ТОЛЬКО по своему `CODEX_HOME`, а от OOM (ради
# которого стояла глухая проверка) защищает порог свободной памяти: два
# `codex exec` разом живут, если памяти хватает обоим.
_codex_live_moy() {
  local p out="" home="${CODEX_HOME:-$HOME/.codex}"
  for p in $(pgrep -x codex 2>/dev/null || true); do
    case " $(tr '\0' ' ' < "/proc/$p/cmdline" 2>/dev/null || true) " in
      *" exec "*) ;;
      *) continue ;;
    esac
    local _h
    _h="$(tr '\0' '\n' < "/proc/$p/environ" 2>/dev/null | sed -n 's/^CODEX_HOME=//p' | head -1)"
    [ -n "$_h" ] || _h="$HOME/.codex"
    [ "$_h" = "$home" ] && out="$out$p "
  done
  printf '%s' "$out"
}
_mem_free_mb() { awk '/MemAvailable/ {print int($2/1024)}' /proc/meminfo 2>/dev/null || echo 99999; }
_MEM_MIN="${CODEX_MEM_MIN_MB:-2200}"
if command -v pgrep >/dev/null 2>&1; then
  _live="$(_codex_live_moy)"
  _mf="$(_mem_free_mb)"
  if [ -z "$_live" ] && [ -n "$(_codex_live)" ] && [ "$_mf" -lt "$_MEM_MIN" ]; then
    echo "агент: чужой аккаунт считает, свободно ${_mf} МБ (<${_MEM_MIN}) — жду, чтобы не уронить машину" >&2
    _live="$(_codex_live)"
  fi
  if [ -n "$_live" ]; then
    echo "уже идёт codex exec СВОЕГО аккаунта (pid $_live) — жду его конца." >&2
  fi
  # ОПРАШИВАЕМ ЧАСТО, ПЕЧАТАЕМ РЕДКО: шаг 30 с добавлял до полуминуты
  # простоя после смерти сироты, а признак жизни чаще раза в 30 с распухает
  # в логе вкладки. Поэтому опрос каждые 5 с, строка — раз в 30 с.
  while [ -n "$_live" ] && [ "$_waited" -lt "$_lock_wait_max" ]; do
    sleep 5
    _waited=$(( _waited + 5 ))
    _live="$(_codex_live_moy)"
    if [ -n "$_live" ] && [ $(( _waited % 30 )) -eq 0 ]; then
      echo "   жду ${_waited} с из ${_lock_wait_max} · живой codex exec: $_live" >&2
    fi
  done
  if [ -n "$_live" ]; then _lock_fail; fi
fi
