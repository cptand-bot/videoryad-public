#!/usr/bin/env bash
# СПРОСИТЬ ВНЕШНЕГО АГЕНТА (Codex) НАПРЯМУЮ, БЕЗ ПОЛЬЗОВАТЕЛЯ.
#
# До 24.10 текст между нами носил пользователь руками: мы клали бриф файлом, он
# прикладывал его в чат Codex, ответ копировал обратно. Его слово 24.10:
# «я заебусь туда-сюда файлы гонять, придумай систему, чтобы ты работал через
# него… API». Система нашлась на самой машине: Codex CLI стоит в WSL
# (`~/.local/bin/codex`, своя `auth.json`), умеет неинтерактивный `exec` и
# принимает КАРТИНКИ ключом `-i`. Значит листы можно отдавать ему прямо отсюда.
#
#     codex_ask.sh <бриф.txt> <картинка> [картинка ...]
#
# Печатает его ответ и кладёт рядом с брифом файл <бриф>.ОТВЕТ.txt.
#
# ДВЕ МИНЫ, обе проверены живьём 24.10:
#  1. `-i` ВАРИАТИВНЫЙ — он съедает следующий позиционный аргумент как ещё одну
#     картинку. Поэтому промпт передаём ТОЛЬКО через stdin с аргументом `-`,
#     иначе «No prompt provided via stdin» и пустой прогон.
#  2. Без `--skip-git-repo-check` он отказывается работать вне git-репозитория.
#
# Картинки в НАШ контекст при этом не попадают вообще — в этом весь смысл:
# смотрит он, мы читаем строчки. Потолок на вызов — 8 листов, дальше он сам
# начинает экономить внимание.
set -euo pipefail

# ИСПОЛНЯЕМСЯ ИЗ КОПИИ — ПРАВКА ФАЙЛА НЕ УБИВАЕТ ИДУЩИЙ ПРОГОН (24.10).
# Живой случай: диспетчер правил этот скрипт в 17:10, пока шёл вызов с 17:08.
# Bash читает файл ИНКРЕМЕНТАЛЬНО, по смещению: новая длина строк сдвинула
# позицию, и интерпретатор прочитал середину комментария как команду
# («line 95: берём: command not found»). Под `set -e` вызов умер на месте —
# после четырнадцати минут работы агента, — а снаружи это выглядело как
# `exited with code 0`. Копия в /tmp от правок не меняется.
if [ -z "${CODEX_ASK_INNER:-}" ]; then
  _self="$(mktemp /tmp/codex_ask.XXXXXX.sh)" || exit 1
  cp "$0" "$_self" || exit 1
  CODEX_ASK_INNER=1 bash "$_self" "$@"
  _rc=$?
  rm -f "$_self"
  exit $_rc
fi

# КЛЮЧИ В ЛЮБОМ ПОРЯДКЕ (24.10, улов `usuario-91`). Сначала это были два
# отдельных блока — `--json` только первым, `--attach` только вторым, — и
# вызов, написанный в обратном порядке, падал с usage: `brief` становился
# строкой «--json». Падал явно, не молча, но попытку вкладка теряла. Входных
# файлов со временем станет больше (srt, досье, прошлый scenes.json), поэтому
# разбор один цикл и порядок свободный.
#   --json <путь>   вырезать JSON из ответа, проверить разбором и положить файлом;
#                   агент в песочнице только на чтение и сам записать не может.
#   --attach <файл> положить входной файл РЯДОМ С ЗАДАНИЕМ (через CLI агент живёт
#                   в WSL и путей `D:\...` не видит вообще); не-UTF-8 перекодируем.
json_out=""
attach=()
while : ; do
  case "${1:-}" in
    --json)
      json_out="${2:-}"; shift 2 || true ;;
    --attach)
      src="${2:-}"; shift 2 || true
      [ -f "$src" ] || { echo "нет файла: $src" >&2; exit 2; }
      attach+=("$src") ;;
    *)
      break ;;
  esac
done

brief="${1:-}"
shift || true
if [ -z "$brief" ] || [ ! -f "$brief" ]; then
  echo "codex_ask.sh <задание.txt> [картинка ...]   # картинки необязательны" >&2
  exit 2
fi

imgs=()
for f in "$@"; do
  [ -f "$f" ] || { echo "нет файла: $f" >&2; exit 2; }
  imgs+=(-i "$f")
done
if [ "${#imgs[@]}" -gt 16 ]; then
  echo "codex_ask.sh: больше восьми листов за раз не даём — разбей на два вызова" >&2
  exit 2
fi

workdir="$(cd "$(dirname "$brief")" && pwd)"
for src in ${attach[@]+"${attach[@]}"}; do
  base="$(basename "$src")"
  # ФАЙЛ МОЖЕТ УЖЕ ЛЕЖАТЬ РЯДОМ С ЗАДАНИЕМ (24.10, улов `usuario-91`):
  # `cp` на самого себя ругается «are the same file», под `set -e` вызов
  # умирал с пустым результатом и кодом 0 — опять «успех при нулевой работе».
  if [ "$(readlink -f "$src")" = "$(readlink -f "$workdir/$base")" ]; then
    echo "  уже на месте: $base"
    continue
  fi
  if iconv -f UTF-8 -t UTF-8 "$src" >/dev/null 2>&1; then
    cp -f "$src" "$workdir/$base"
  else
    iconv -f CP1251 -t UTF-8 "$src" > "$workdir/$base" 2>/dev/null \
      || cp -f "$src" "$workdir/$base"
    echo "перекодировал в UTF-8: $base"
  fi
  echo "  приложен: $base"
done

out="${brief%.txt}.ОТВЕТ.txt"
{
  cat "$brief"
  echo
  # ВНИМАНИЕ: не `[ ... ] && echo` последней строкой блока — при пустом списке
  # картинок оно возвращает 1, и под `set -e` весь скрипт падал с кодом 1
  # (поймано 24.10 на текстовом задании без листов).
  if [ "${#imgs[@]}" -gt 0 ]; then
    echo "Листы приложены картинками к этому сообщению — смотри их, в папку ходить не надо."
  fi
  echo
  echo "ВАЖНО ПРО СРЕДУ: ты запущен в Linux (WSL), а не в приложении на Windows."
  echo "Путей вида D:\\... здесь НЕ СУЩЕСТВУЕТ. Все нужные файлы лежат в ТЕКУЩЕЙ"
  echo "папке, обращайся к ним по именам без пути. Ничего никуда не записывай:"
  echo "результат верни текстом в ответе."
} | (cd "$workdir" && timeout "${CODEX_TIMEOUT:-900}" codex exec --skip-git-repo-check ${imgs[@]+"${imgs[@]}"} - ) \
  2>&1 | tee "${out}.raw" >/dev/null

# из полного лога берём только последний блок — сам ответ
# после строки «tokens used» идёт САМО ЧИСЛО, и только потом ответ — его тоже
# пропускаем, иначе первой строкой ответа приезжает «3,012» (поймано 24.10).
awk '/^tokens used/{flag=1;next} flag&&!skipped{skipped=1;next} flag' "${out}.raw" \
  | sed '/^[[:space:]]*$/d' > "$out"
[ -s "$out" ] || cp "${out}.raw" "$out"
# СЫРОЙ ОТВЕТ — СТРАХОВКА ОТ ПОТЕРИ ЛИМИТА АГЕНТА (24.10): именно из `.raw`
# сегодня вытащили раскадровку, когда разбор упал после четырнадцати минут
# его работы. Удаляем только когда ответ действительно разобран.
if [ -s "$out" ]; then
  rm -f "${out}.raw"
else
  echo "ответ не разобран — сырой оставлен: ${out}.raw" >&2
fi
if [ -n "$json_out" ]; then
  python3 - "$out" "$json_out" <<'PYJ' || true
import json, re, sys
raw = open(sys.argv[1], encoding="utf-8", errors="replace").read()
m = re.search(r"```(?:json)?\s*(.+?)```", raw, re.S) or re.search(r"(\{.*\})", raw, re.S)
if not m:
    sys.exit("в ответе нет JSON — класть нечего, смотри текст ответа")
try:
    data = json.loads(m.group(1))
except ValueError as e:
    sys.exit("JSON в ответе битый: %s" % e)
sc = data.get("scenes") if isinstance(data, dict) else data
if not sc:
    sys.exit("в JSON нет сцен")
json.dump(data, open(sys.argv[2], "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("JSON принят и записан: %d сцен -> %s" % (len(sc), sys.argv[2]))
PYJ
  # НЕ РОНЯТЬ ВЕСЬ ВЫЗОВ, ЕСЛИ JSON НЕ НАШЁЛСЯ (24.10): ответ агента уже
  # получен и стоит его лимита — его надо показать и сохранить, даже когда
  # он вернул таблицу вместо JSON. Иначе вкладка видит только «JSON нет».
  true
fi
echo "— ответ Codex ($(wc -l < "$out") строк), сохранён: $out"
echo "────────────────────────────────────────────"
cat "$out"
