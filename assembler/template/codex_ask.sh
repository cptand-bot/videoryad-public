# ПУТИ КАРТИНОК — ТОЛЬКО АБСОЛЮТНЫЕ (25.10, диспетчер `andrey-b9`).
# Ниже идёт `cd "$workdir"` (папка задания), поэтому ОТНОСИТЕЛЬНЫЙ путь к листу,
# переданный из папки ролика, после cd не разрешается. Проверка `[ -f ]` при
# этом проходит (она до cd), агент получает `-i` на несуществующий файл и
# отвечает «файлы не прикрепились, приложите повторно» — вызов потрачен, а
# выглядит как каприз агента. Живой случай: `thumbs/sheet_1.jpg` из
# `5min-otvetka-2610-cloud` при задании в scratchpad.
imgs=()
for f in "$@"; do
  [ -f "$f" ] || { echo "нет файла: $f" >&2; exit 2; }
  imgs+=(-i "$(readlink -f "$f")")
done
if [ "${#imgs[@]}" -gt 16 ]; then
  echo "codex_ask.sh: больше восьми листов за раз не даём — разбей на два вызова" >&2
  exit 2
fi

# РЕЗЕРВНЫЙ АККАУНТ ВКЛЮЧАЕТСЯ САМ НА 80% ОКНА (08.11, его слово: «мне
# нужны будут лимиты, чтобы писать статьи, писать рерайт. Если я подхожу к
