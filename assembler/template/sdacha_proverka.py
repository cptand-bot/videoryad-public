# -*- coding: utf-8 -*-
"""ПРОВЕРКА ПЕРЕД СДАЧЕЙ СМЕНЫ — «ВСЁ ДО НИТОЧКИ» (13.11.2026).

Его слово 13.11, злое и по делу: «Так это надо делать постоянно, а не один
раз. Если ты сдаёшь смену, ты должен всё перепроверить. Всё до ниточки, всё
до словечка, до копеечки должен сдать».

ПОВОД. Координатор объявил смену сданной и сказал «перепроверил, сошлось
всё». На его требование проверить ещё раз нашлись ЧЕТЫРЕ дыры: итог дня не
дописан в `CHANGELOG.md`, шапка `BUGS-LIVE.md` и реестр вкладок остались от
прошлой смены, и третий шаг его прямого приказа по новым видам (полка
библиотеки) не был сделан вовсе. То есть «перепроверил» означало «сверил то,
что сам написал», а не «сверил с тем, что обязан сдать».

ПОЭТОМУ ПРОВЕРКА — КОД, А НЕ ПАМЯТЬ. Она гоняется САМА на каждом
`peredacha.py --zapisat` и НЕ ДАЁТ объявить смену сданной, пока дыры есть.
Правило 11.11 ровно об этом: правило, записанное только в памяти, обходят;
держит гейт.

ЧТО СВЕРЯЕТСЯ (каждый пункт — дыра, которая уже случалась):
 1. итог дня дописан в `CHANGELOG.md` — раздел сегодняшнего числа;
 2. шапка `BUGS-LIVE.md` называет СЕГОДНЯШНЮЮ смену;
 3. реестр вкладок `ВКЛАДКИ-<ДД-ММ>.md` тронут сегодня;
 4. файл передачи `ПЕРЕДАЧА-*<ДД-ММ>*.md` тронут сегодня;
 5. КАЖДЫЙ файл кода, изменённый сегодня, есть в журнале правок за сегодня —
    это и есть «до ниточки»: правка без записи = потерянная правка;
 6. в журнале за сегодня нет строки «раскатка без записи» (пустое описание);
 7. очередь `НА-РАСКАТКУ.md` тронута сегодня, если сегодня были правки кода;
 8. имя координатора в `CLAUDE.md` совпадает с тем, кто сдаёт.

    python3 sdacha_proverka.py                 # отчёт, код 1 при дырах
    python3 sdacha_proverka.py --kto usuario-03
"""
import datetime
import io
import os
import re
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
СКИЛЛ = os.path.dirname(ЗДЕСЬ)
ЖУРНАЛ = os.path.join(СКИЛЛ, "base", "pravki.tsv")
CLAUDE_MD = os.path.expanduser("~/.claude/CLAUDE.md")

# Папки, правки в которых обязаны быть в журнале. `fullcycle/` входит: его
# код в облако не раскатывается, но уезжает посылкой — потеряется так же.
КОД = ("template", "cloud", "fullcycle", "base")
НЕ_КОД = (".pyc", ".tsv", ".log", ".json.tmp", "__pycache__", ".bak")


def _ч(p):
    try:
        return io.open(p, encoding="utf-8", errors="replace").read()
    except OSError:
        return ""


def _сегодня():
    return datetime.date.today()


def _тронут_сегодня(p):
    try:
        return datetime.date.fromtimestamp(os.path.getmtime(p)) == _сегодня()
    except OSError:
        return False


def правки_сегодня():
    """Файлы кода, изменённые сегодня."""
    из_файлов = set()
    for под in КОД:
        d = os.path.join(СКИЛЛ, под)
        if not os.path.isdir(d):
            continue
        for корень, папки, файлы in os.walk(d):
            папки[:] = [x for x in папки if x != "__pycache__"]
            for f in файлы:
                if f.endswith(НЕ_КОД) or not f.endswith((".py", ".sh")):
                    continue
                p = os.path.join(корень, f)
                if _тронут_сегодня(p):
                    из_файлов.add(os.path.relpath(p, СКИЛЛ))
    return из_файлов


def журнал_сегодня():
    """(упомянутые файлы, есть ли строка без описания)."""
    текст = _ч(ЖУРНАЛ)
    д = _сегодня().strftime("%d.%m.%Y")
    файлы = set()
    описаны = set()      # файлы, у которых ЕСТЬ живая запись за сегодня
    пустышки = []        # наборы файлов из строк «описание не задано»
    for строка in текст.splitlines():
        if д not in строка:
            continue
        свои = set()
        for кусок in re.split(r"[\t;,]", строка):
            кусок = кусок.strip()
            if _кусок_файл(кусок):
                свои.add(кусок)
        файлы |= свои
        if "раскатка без записи" in строка or "описание не задано" in строка:
            пустышки.append(свои)
        else:
            описаны |= свои
    # ПУСТЫШКА, ФАЙЛЫ КОТОРОЙ УЖЕ ОПИСАНЫ ЖИВОЙ СТРОКОЙ ТОГО ЖЕ ДНЯ, — НЕ
    # ДЫРА (13.11). Раскатка везёт всё, что изменилось, и её набор почти
    # никогда не совпадает с набором одной описанной правки; сведения в
    # журнале при этом есть, просто строкой выше. Дыра — только та пустышка,
    # у которой НИ ОДИН файл нигде не описан: вот о ней никто не знает.
    пустые = sum(1 for н in пустышки if н and not (н & описаны))
    return файлы, пустые


def _кусок_файл(s):
    return bool(re.fullmatch(r"[\w\-./]+\.(py|sh)", s or ""))


def проверить(кто=""):
    дыры, сошлось = [], []
    д = _сегодня()
    дм = д.strftime("%d-%m")
    дт = д.strftime("%d.%m.%Y")

    # 1 CHANGELOG
    ch = _ч(os.path.join(СКИЛЛ, "CHANGELOG.md"))
    if (дт in ch) or (d2(д) in ch):
        сошлось.append("итог дня в CHANGELOG.md")
    else:
        дыры.append("CHANGELOG.md · НЕТ раздела за %s. Итог смены не дописан — "
                    "завтра его никто не восстановит." % дт)

    # 2 BUGS-LIVE
    bl = _ч(os.path.join(СКИЛЛ, "BUGS-LIVE.md"))
    шапка = bl.split("\n##", 2)[1] if bl.count("\n##") >= 1 else ""
    if d2(д) in шапка or дт in шапка:
        сошлось.append("шапка BUGS-LIVE.md за сегодня")
    else:
        дыры.append("BUGS-LIVE.md · шапка не называет сегодняшнюю смену — "
                    "улов ляжет под чужой датой.")

    # 3 реестр вкладок
    р = os.path.join(СКИЛЛ, "ВКЛАДКИ-%s.md" % дм)
    if _тронут_сегодня(р):
        сошлось.append("реестр вкладок ВКЛАДКИ-%s.md" % дм)
    else:
        дыры.append("ВКЛАДКИ-%s.md · не тронут сегодня. Новая вкладка не "
                    "узнает, кто что ведёт и какие трубы заняты." % дм)

    # 4 файл передачи
    пер = [f for f in os.listdir(СКИЛЛ)
           if f.startswith("ПЕРЕДАЧА") and дм in f and f.endswith(".md")
           and _тронут_сегодня(os.path.join(СКИЛЛ, f))]
    if пер:
        сошлось.append("передача: " + ", ".join(sorted(пер)))
    else:
        дыры.append("ПЕРЕДАЧА-*%s*.md · нет файла передачи за сегодня." % дм)

    # 5 каждая правка в журнале
    кода = правки_сегодня()
    вжурнале, пустые = журнал_сегодня()
    потеряны = sorted(f for f in кода
                      if not any(f.endswith(x) or x.endswith(f) or
                                 os.path.basename(f) == os.path.basename(x)
                                 for x in вжурнале))
    if кода and потеряны:
        дыры.append("ЖУРНАЛ ПРАВОК · сегодня изменено файлов кода: %d, из них "
                    "НЕ записано %d:\n       %s\n       Запиши: pravki.py dobav "
                    "--fayly «…» --chto «…» --povod «…» --provereno «…»"
                    % (len(кода), len(потеряны), "\n       ".join(потеряны)))
    elif кода:
        сошлось.append("все %d правок кода за сегодня есть в журнале" % len(кода))
    else:
        сошлось.append("правок кода сегодня не было")

    # 6 раскатка без описания
    if пустые:
        дыры.append("ЖУРНАЛ ПРАВОК · %d строк раскатки БЕЗ описания. Такая "
                    "строка не говорит, что уехало и зачем." % пустые)
    else:
        сошлось.append("строк раскатки без описания нет")

    # 7 очередь
    нр = os.path.join(СКИЛЛ, "НА-РАСКАТКУ.md")
    if не_нужна_очередь(кода) or _тронут_сегодня(нр):
        сошлось.append("очередь НА-РАСКАТКУ.md")
    else:
        дыры.append("НА-РАСКАТКУ.md · не тронут сегодня, хотя код правился. "
                    "Закрытые пункты не помечены, новый улов не записан.")

    # 8 имя координатора
    cm = _ч(CLAUDE_MD)
    if not кто:
        сошлось.append("имя координатора в CLAUDE.md не проверялось (--kto)")
    elif кто in cm:
        сошлось.append("имя координатора «%s» стоит в CLAUDE.md" % кто)
    else:
        дыры.append("CLAUDE.md · имя координатора «%s» там не стоит. Рабочие "
                    "вкладки шлют улов по этой строке — он уйдёт в пустоту."
                    % кто)
    return дыры, сошлось


def d2(д):
    return д.strftime("%d.%m")


def не_нужна_очередь(кода):
    return not кода


def main():
    кто = ""
    for i, a in enumerate(sys.argv):
        if a == "--kto" and i + 1 < len(sys.argv):
            кто = sys.argv[i + 1]
    кто = кто or os.environ.get("VIDEORYAD_KTO", "")
    дыры, сошлось = проверить(кто)
    print("=" * 66)
    print("ПРОВЕРКА ПЕРЕД СДАЧЕЙ СМЕНЫ — всё до ниточки")
    print("=" * 66)
    for s in сошлось:
        print("  ✓ %s" % s)
    if not дыры:
        print("\nДЫР НЕТ. Смену можно сдавать.")
        return 0
    print("\n!! ДЫР: %d — СМЕНА НЕ СДАНА, пока они не закрыты:" % len(дыры))
    for s in дыры:
        print("  ✗ %s" % s)
    print("\nЕго слово 13.11: «всё до ниточки, всё до словечка, до копеечки "
          "должен сдать». Закрой дыры и прогони снова.")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
