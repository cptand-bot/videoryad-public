#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""МЕХАНИЧЕСКИЕ ПРАВКИ РЕРАЙТА — У СЕБЯ, А НЕ У ВНЕШНЕГО АГЕНТА (08.11.2026).

ЗАЧЕМ. Замер дня 08.11: на одну тему ушло ШЕСТЬ заходов к внешнему агенту —
раскадровка, текст и ЧЕТЫРЕ круга правок. Два круга из четырёх вернули текст
без единого изменения (агент дважды проигнорировал «вставь второй призыв»),
а последний призыв в итоге вставила вкладка сама. То есть перерасход лимита
идёт не от объёма работы, а от холостых кругов на ПРОСТЫХ правках.

Его слово 08.11: «он жрёт очень много… надо будет часть брать всё-таки на
себя», и отдельно: «главное не нарушить и не сломать ни хрена».

ПОЭТОМУ ЭТОТ ИНСТРУМЕНТ ДЕЛАЕТ РОВНО ТО, ЧТО МОЖНО СДЕЛАТЬ БЕЗ РИСКА ДЛЯ
СМЫСЛА, и НЕ ТРОГАЕТ ничего спорного:
  · снимает служебные строки, которые агент приписывает к ответу
    («ЗНАКОВ: 15793», «Вот исправленная версия:», ограду ```);
  · убирает ТИРЕ — они запрещены правилом TTS, замена механическая;
  · вставляет ВТОРОЙ призыв подписаться, если он один: место считается
    (другая треть текста), формулировка берётся из набора, смысл не меняется;
  · про ЦИФРЫ только ДОКЛАДЫВАЕТ. Перевод в пропись со склонением — это
    не механика, и выдумывать падежи инструмент не станет.

ЧЕГО ОН НЕ ДЕЛАЕТ НИКОГДА: не сокращает текст (длина — это смысл, режет
автор), не переставляет абзацы, не правит фактуру, не трогает авторские
мысли и шутки.

ПОРЯДОК:
    python3 rewrite_fix.py <рерайт.txt> --out <готово.txt> [--channel "ПЛАНЕТА"]
    python3 rewrite_fix.py <рерайт.txt> --dry-run      # только показать

Дальше как обычно: `rewrite_lint.py` и аудит. Если после этого остаются
отказы (длина, ход мысли, цифры) — ВОТ ТОГДА заход к агенту, и он будет
ровно один, с конкретным списком.
"""

import argparse
import io
import os
import re
import sys

# Призывы в интонации канала. Содержания не несут, поэтому их вставка — это
# механика, а не авторство: правило «два призыва» пришло из георадара
# (EditorialRules, «Фильтр TTS и CTA»), а не от писателя.
ПРИЗЫВЫ = {
    "ПЛАНЕТА": "Подпишись, если хочешь видеть разбор целиком, а не в пересказе пресс-службы.",
    "5 МИНУТ": "Подписывайся, если хочешь разбираться в этом раньше остальных.",
    "": "Подпишись, если такие разборы тебе нужны.",
}

СЛУЖЕБНЫЕ = (
    r"^\s*ЗНАКОВ\s*:\s*\d+\s*$",
    r"^\s*```.*$",
    r"^\s*(вот|ниже)\s+(исправленн|готов|итогов|финальн)\w*[^\n]{0,60}:\s*$",
    r"^\s*(исправленный|готовый|итоговый)\s+текст\s*:?\s*$",
    r"^\s*(правки внесены|готово)\s*[.:]?\s*$",
)


def читать(path):
    raw = open(path, "rb").read()
    for enc in ("utf-8-sig", "utf-8", "cp1251"):
        try:
            return raw.decode(enc), enc
        except UnicodeDecodeError:
            continue
    return raw.decode("cp1251", "replace"), "cp1251"


def снять_служебное(text):
    было = text.split("\n")
    стало, снято = [], []
    for l in было:
        if any(re.match(p, l, re.I) for p in СЛУЖЕБНЫЕ):
            снято.append(l.strip())
            continue
        стало.append(l)
    return "\n".join(стало).strip() + "\n", снято


def убрать_тире(text):
    """Тире запрещены (голос читает их паузой и ломает фразу).

    Замена по месту: тире между частями предложения становится запятой,
    тире в начале строки снимается вместе с пробелом. Дефис внутри слова
    («из-за», «кто-то») — ДРУГОЙ знак, его не трогаем.
    """
    n = text.count("—") + text.count("–")
    if not n:
        return text, 0
    t = re.sub(r"^\s*[—–]\s*", "", text, flags=re.M)      # тире в начале строки
    t = re.sub(r"\s+[—–]\s+", ", ", t)                     # между частями фразы
    t = t.replace("—", "").replace("–", "")                # всё остальное
    t = re.sub(r",\s*,", ",", t)
    t = re.sub(r"\s+([.,!?])", r"\1", t)
    return t, n


# СЧИТАТЬ РОВНО ТАК ЖЕ, КАК СЧИТАЕТ ГЕЙТ (08.11, поймано на первой же пробе).
# Первая версия искала «подпишись|подписывайтесь», а `rewrite_lint` ищет
# короткое «подпиш» — и на тексте, где призывов УЖЕ два, инструмент их не
# увидел и вставил третий. Два разных сита на одно правило — это не «строже»,
# это другой ответ; детектор у правила должен быть ОДИН.
def призывов(text):
    return len(re.findall(r"подпиш", text, re.I))


def добавить_призыв(text, channel):
    """Второй призыв — в ДРУГУЮ треть текста, чем первый."""
    если_есть = призывов(text)
    if если_есть >= 2:
        return text, None
    строки = text.split("\n")
    непустые = [i for i, l in enumerate(строки) if l.strip()]
    if not непустые:
        return text, None
    место_первого = None
    for k, i in enumerate(непустые):
        if re.search(r"подпиш[ио]сь|подписывай(?:тесь|ся)", строки[i], re.I):
            место_первого = k / max(1, len(непустые))
            break
    # первый в начале — второй ближе к финалу, и наоборот
    доля = 0.78 if (место_первого is None or место_первого < 0.5) else 0.22
    поз = непустые[int(len(непустые) * доля)]
    фраза = ПРИЗЫВЫ.get((channel or "").upper(), ПРИЗЫВЫ[""])
    строки.insert(поз + 1, фраза)
    return "\n".join(строки), фраза


def цифры(text):
    """Только доклад: где стоят цифры и что вокруг них."""
    найдено = []
    for m in re.finditer(r"[^.!?\n]*\d[^.!?\n]*[.!?]?", text):
        s = " ".join(m.group(0).split())
        if s and any(ch.isdigit() for ch in s):
            найдено.append(s[:120])
    return найдено


def main():
    ap = argparse.ArgumentParser(
        description="механические правки рерайта: служебные строки, тире, второй призыв")
    ap.add_argument("text")
    ap.add_argument("--out", help="куда положить готовый текст (по умолчанию рядом, …-ЧИСТО.txt)")
    ap.add_argument("--channel", default="", help="канал: от него зависит формулировка призыва")
    ap.add_argument("--dry-run", action="store_true", help="показать, что изменится, и ничего не писать")
    ap.add_argument("--encoding", default="utf-8", choices=("utf-8", "cp1251"),
                    help="кодировка готового файла (тексты на D: лежат в cp1251)")
    a = ap.parse_args()

    if not os.path.isfile(a.text):
        sys.exit("нет файла: %s" % a.text)

    текст, откуда = читать(a.text)
    было_знаков = len(текст)
    отчёт = []

    текст, снято = снять_служебное(текст)
    if снято:
        отчёт.append("снято служебных строк: %d (%s)" % (len(снято), "; ".join(снято)[:120]))

    текст, n_тире = убрать_тире(текст)
    if n_тире:
        отчёт.append("убрано тире: %d" % n_тире)

    текст, фраза = добавить_призыв(текст, a.channel)
    if фраза:
        отчёт.append("вставлен второй призыв подписаться: «%s»" % фраза)
    if призывов(текст) > 2:
        отчёт.append("ВНИМАНИЕ: призывов подписаться %d, по правилу их ДВА — "
                     "лишние сними руками" % призывов(текст))

    числа = цифры(текст)

    print("прочитано: %s (%s), знаков %d" % (os.path.basename(a.text), откуда, было_знаков))
    for r in отчёт:
        print("  · %s" % r)
    if not отчёт:
        print("  · править нечего — текст и так чист")
    print("стало знаков: %d, призывов подписаться: %d" % (len(текст), призывов(текст)))

    if числа:
        print("  !! ЦИФРЫ В ТЕКСТЕ (%d) — их инструмент НЕ переводит, падежи "
              "выдумывать нельзя. Отдай эти строки агенту одним списком:" % len(числа))
        for s in числа[:10]:
            print("     %s" % s)

    if a.dry_run:
        print("--dry-run: файл не записан")
        return 0

    out = a.out or (os.path.splitext(a.text)[0] + "-ЧИСТО.txt")
    io.open(out, "w", encoding=a.encoding, errors="replace").write(текст)
    print("готово: %s" % out)
    print("дальше: rewrite_lint.py <оригинал> %s --brief ЗАДАНИЕ-РЕРАЙТ.txt" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
