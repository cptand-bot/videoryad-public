def win(path):
    """/mnt/d/YouTube/... -> D:\\YouTube\\..."""
    m = re.match(r"^/mnt/([a-z])/(.*)$", path)
    if not m:
        return path
    return m.group(1).upper() + ":\\" + m.group(2).replace("/", "\\")


