def imena_i_mesta(текст):
    """Заглавные слова, похожие на имя, город или название объекта.

    Первое слово КАЖДОЙ фразы отбрасывается: там заглавная буква стоит по
    правилу письма, а не потому, что слово — имя собственное.
    """
    найдено = []
    for фраза in _ФРАЗЫ.split(str(текст or "")):
        ф = фраза.strip()
        if not ф:
            continue
        for м in _СЛОВО.finditer(ф):
            if м.start() == 0:
                continue
            сл = м.group(0)
            if _stop(сл):
                continue
            # СЛОВО ИЗ НАШИХ ЖЕ СЛОВАРЕЙ МЕСТОМ НЕ СЧИТАЕТСЯ. На живом
            # прогоне «Удары» с заглавной (начало фразы внутри склейки
            # реплик) читалось как топоним и давало «объект «мост» в месте
            # «Удары»».
            _н = _низ(сл)
            if _н in ЛИЧНЫЕ_ИМЕНА:
                continue
            if any(_низ(к) in _н for к in ОБЪЕКТЫ + ТЕХНИКА + ДЕЙСТВИЯ):
                continue
            if сл not in найдено:
                найдено.append(сл)
    return найдено


def konkretnaya(текст):
    """(да/нет, причина) — обязана ли сцена закрываться НАЙДЕННЫМ кадром.

    Да — только при СИЛЬНОЙ конкретике, то есть когда в реплике есть СВЯЗКА:
    предмет и событие, предмет и место, событие и место. Одиночное слово
    связкой не считается, и это проверено на живых роликах: «придумали
    способ решить проблему с мостами» и «подходящей техники в Европе
    немного» — рассуждение, снимать там нечего, такая сцена остаётся
    карточкой. А «удары по железнодорожным станциям в Запорожской области»
    и «перекрыли движение по мосту имени Преображенского» — предмет и
    событие названы, кадр обязан быть про них.

    Замер на сданных роликах 16.11 (те самые, где он увидел непопадание):
    по одиночному слову выходило 49-43 сцены из 82-86 — больше половины
    ролика, обязательный комплект туда не встанет вовсе. По связке — 20-30
    сцен, то есть ровно те места, где звучит конкретика события.
    """
    т = str(текст or "")
    if len(т.strip()) < 25:
        return False, ""

    объект = _есть(т, ОБЪЕКТЫ)
    техника = _есть(т, ТЕХНИКА)
    действие = _есть(т, ДЕЙСТВИЯ)
    места = imena_i_mesta(т)
    место = места[0] if места else ""

    # Образец техники — предмет сам по себе, но кадр нужен, когда с ним
    # что-то происходит или он где-то находится.
    if техника and (действие or место):
        return True, ("названа техника «%s» и %s"
                      % (техника,
                         "событие «%s»" % действие if действие
                         else "место «%s»" % место))
    if объект and действие:
        return True, "событие «%s» на объекте «%s»" % (действие, объект)
    if объект and место:
        return True, "объект «%s» в названном месте «%s»" % (объект, место)
    if действие and место:
        return True, "событие «%s» в названном месте «%s»" % (действие, место)
    return False, ""


def podskazka(текст):
    """СЛОВА-ПОДСКАЗКИ ДЛЯ ОТКАЗА — ЧТО ИМЕННО ДОЛЖНО БЫТЬ В КАДРЕ.

    Это НЕ готовый запрос: слова стоят в падежах реплики («мосту»,
    «Запорожской», «авиаудара»), а поиску нужен именительный и субъект.
    Пробовал собирать запрос автоматом — выходило «мосту Запорожье
    авиаудара», такое `query_lint` справедливо отбивает. Поэтому запрос
    пишет агент (заходы к нему по времени пользователя бесплатны, замер
    24.10), а приёмка лишь называет предмет, место и событие, чтобы не
    пересказывать реплику целиком.
    """
    т = str(текст or "")
    да, _ = konkretnaya(т)
    if не_строка(т) or not да:
        return ""
    части = []
    предмет = _есть(т, ТЕХНИКА) or _есть(т, ОБЪЕКТЫ)
    if предмет:
        # берём слово ЦЕЛИКОМ, как оно стоит в реплике, а не корень словаря
        м = re.search(r"[А-Яа-яЁё\-]*%s[А-Яа-яЁё\-]*" % re.escape(предмет),
                      т, re.IGNORECASE)
        части.append((м.group(0) if м else предмет).strip("-"))
    места = imena_i_mesta(т)
    if места:
        части.append(места[0])
    действие = _есть(т, ДЕЙСТВИЯ)
    if действие:
        м = re.search(r"[А-Яа-яЁё\-]*%s[А-Яа-яЁё\-]*" % re.escape(действие),
                      т, re.IGNORECASE)
        части.append((м.group(0) if м else действие).strip("-"))
    # дубли и пустое — вон; порядок «предмет · место · событие» не меняем
    итог, видели = [], set()
    for ч in части:
        н = _низ(ч)
        if н and н not in видели:
            видели.add(н)
            итог.append(ч)
    return " ".join(итог)


def не_строка(т):
    return not isinstance(т, str) or not т.strip()


def scenes_konkretiki(path_or_scenes):
    """Номера сцен конкретики: {номер: причина}. Принимает путь или список."""
    данные = path_or_scenes
    if isinstance(данные, str):
        with open(данные, encoding="utf-8") as f:
            данные = json.load(f)
    if isinstance(данные, dict):
        данные = данные.get("scenes") or данные.get("сцены") or []
    итог = {}
    for i, s in enumerate(данные or [], 1):
        if not isinstance(s, dict):
            continue
        ном = s.get("sid") or s.get("id") or s.get("номер") or i
        try:
            ном = int(ном)
        except Exception:
            ном = i
        текст = s.get("text") or s.get("текст") or s.get("replika") or ""
        да, почему = konkretnaya(текст)
        if да:
            итог[ном] = почему
    return итог


# Источники, которые СЧИТАЮТСЯ найденным кадром под фразу.
ПОИСКОВЫЕ = ("web_search", "press_photo", "direct_url", "pexels", "stock",
             "pexels_video", "wiki", "archive")


def poiskovyy(источник):
    и = _низ(источник)
    if not и:
        return False
    if и.startswith("card:") or и.startswith("fx:"):
        return False
    if и.startswith("local_library") or и.startswith("baza"):
        return False
    return any(и.startswith(p) for p in ПОИСКОВЫЕ) or "search" in и or "photo" in и


def main():
    ap = argparse.ArgumentParser(
        description="сцены, которые обязан закрыть НАЙДЕННЫЙ кадр")
    ap.add_argument("scenes", nargs="?", help="<ролик>.scenes.json")
    ap.add_argument("--text", help="проверить одну реплику")
    a = ap.parse_args()

    if a.text:
        да, почему = konkretnaya(a.text)
        print("КОНКРЕТИКА: %s" % почему if да else "не конкретика — карточка")
        return 0

    if not a.scenes or not os.path.isfile(a.scenes):
        ap.error("нужен файл сцен или --text")

    with open(a.scenes, encoding="utf-8") as f:
        данные = json.load(f)
    сцены = данные.get("scenes") or данные.get("сцены") or данные
    итог = scenes_konkretiki(сцены)
    всего = len(сцены or [])
    нарушения = []
    for i, s in enumerate(сцены or [], 1):
        ном = i
        for k in ("sid", "id", "номер"):
            v = s.get(k)
            if isinstance(v, int):
                ном = v
                break
        if ном in итог and not poiskovyy(s.get("source") or s.get("источник")):
            нарушения.append((ном, str(s.get("source") or "?"), итог[ном]))

    print("сцен всего: %d · конкретики: %d (%.0f%%)"
          % (всего, len(итог), 100.0 * len(итог) / max(1, всего)))
    for ном, почему in sorted(итог.items()):
        print("  %3d  %s" % (ном, почему))
    if нарушения:
        print("\nНЕ ЗАКРЫТЫ НАЙДЕННЫМ КАДРОМ — %d:" % len(нарушения))
        for ном, ист, почему in нарушения:
            print("  %3d  источник %-18s %s" % (ном, ист, почему))
    return 0


