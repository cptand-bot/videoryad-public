# Заглавное слово длиной меньше этого считаем аббревиатурой обихода.
МИН_ЗАГЛАВНОГО = 4

_СЛОВО = re.compile(r"[А-ЯЁ][а-яё\-]{%d,}" % (МИН_ЗАГЛАВНОГО - 1))
_ФРАЗЫ = re.compile(r"[.!?…]+")


def _низ(с):
    return str(с or "").strip().lower().replace("ё", "е")


_СЛОВА_В_ТЕКСТЕ = re.compile(r"[а-яёa-z0-9]+")

# Насколько длиннее слово стема допускается считать той же формой слова
# (падежные окончания: «-ом», «-ами», «-ах» и т.п.). Нужен, чтобы «док»
# не ловил «документах», а «удар» — «государственным» (19.11, живой
# прогон: 8 из 9 срабатываний гейта оказались такими ложными совпадениями
# внутри случайного слова — «хОТЕЛ», «раСКЛАД», «гоСУДАРственным»,
# «завиСИМОСТЬ», «необходиМОСТИ», «поряДОК»).
_МАКС_ОКОНЧАНИЕ = 4


def _есть(текст, словарь):
    """Какое слово словаря встретилось — слово должно НАЧИНАТЬСЯ со стема,
    а не просто содержать его где-то внутри (иначе «отел» ловит «хотел»,
    «склад» — «расклад», «удар» — «государственным»). Сравнение без «ё» —
    тексты рознятся. Многословные и латинские записи (техника) по-прежнему
    ищем простой подстрокой — там коллизий с обычными русскими словами нет.
    """
    т = _низ(текст)
    слова = _СЛОВА_В_ТЕКСТЕ.findall(т)
    for сл in словарь:
        стем = _низ(сл)
        if " " in стем or "-" in стем or re.search(r"[a-z]", стем):
            if стем in т:
                return сл
            continue
        for слово in слова:
            if слово.startswith(стем) and len(слово) - len(стем) <= _МАКС_ОКОНЧАНИЕ:
                return сл
    return ""


def _stop(сл):
    н = _низ(сл)
    if н in НЕ_КОНКРЕТИКА:
        return True
    # месяц и должность ловим корнем: «Ноябре», «Министра»
    return any(н.startswith(к) for к in НЕ_КОНКРЕТИКА if len(к) >= 5)


