"""«О ЧЁМ ЭТОТ РОЛИК?» — ПРОВЕРКА СВЕЖИМ ГЛАЗОМ (11.11.2026).

Откуда: разбор чужого конвейера cinecode. Самая дешёвая проверка у них и
самая обидная для нас: свежему помощнику дают ТОЛЬКО контактный лист готового
ролика и один вопрос — о чём это? Его ответ кладут рядом с темой. Не угадал —
значит видеоряд рассказывает не то, о чём текст, и чинить надо это, а не
отдельные кадры.

ЗАЧЕМ НАМ. Все наши сита смотрят ПОСЦЕННО: этот кадр с клеймом, тот не по
запросу, здесь повтор. Ни одно не отвечает на вопрос «а ролик-то про что
получился». Через эту дыру проезжал целый ролик: «мне приехал Лондон телефон
НАТО против РФ» — по сценам всё чисто, а вместе не читается. Стоит проверка
один лист и один ответ, это 5-10 тысяч токенов.

КАК ПОЛЬЗОВАТЬСЯ (два шага):

  1. python3 o_chem.py --zadanie <готовый.mp4> [--srt <файл.srt>]
     Печатает задание. Лист уже лежит (его делает final_sheet.py).
     Задание отдать СВЕЖЕМУ субагенту вместе с листом — своему, который вёл
     ролик, нельзя: он знает тему и угадает по памяти, а не по картинке.

  2. python3 o_chem.py --sverka "<его ответ одним предложением>" --srt <файл.srt>
     Сверяет ответ с темой и печатает вердикт.

ВЕРДИКТ:
  СОВПАЛО  — видеоряд читается, можно сдавать
  БЛИЗКО   — узнал тему, но не главное действующее лицо или не событие
  МИМО     — видеоряд не про то; чинить СНАЧАЛА это, а не отдельные кадры
"""
import argparse
import os
import re
import sys
from collections import Counter

# Служебные слова: в теме ролика они ничего не значат.
ШУМ = set("""этот этого эта эти тот том там так как что чтобы который которая
которые если когда уже ещё его её их наш ваш для над под при без про между
после перед из-за потому поэтому чтоб либо тоже также очень просто только
может быть будет были было есть нет все всё весь вся свои свой своя себя
один одна одно два три год года году лет день дня сегодня вчера сейчас
теперь почти более менее самый самая самое очень именно даже либо либо""".split())


def слова(текст):
    return [w for w in re.findall(r"[А-Яа-яЁёA-Za-z-]{4,}", текст)]


def тема_из(путь):
    """Главные слова темы: кто и что. Имена собственные весят втрое —
    именно их обязан узнать свежий глаз."""
    текст = open(путь, encoding="utf-8", errors="replace").read()
    текст = re.sub(r"^\d+\s*$|^[\d:,>\s-]+$", " ", текст, flags=re.M)  # тайминги SRT
    счёт = Counter()
    for w in слова(текст):
        если_имя = w[0].isupper()
        н = w.lower()
        if н in ШУМ:
            continue
        счёт[н] += 3 if если_имя else 1
    return [w for w, _ in счёт.most_common(12)]


def совпало(ответ, ключи):
    низ = ответ.lower()
    попало = [k for k in ключи if k[:5] in низ]
    return попало


def main():
    ap = argparse.ArgumentParser(description="Проверка «о чём ролик» свежим глазом")
    ap.add_argument("--zadanie", help="готовый .mp4 — напечатать задание субагенту")
    ap.add_argument("--sverka", help="ответ субагента одним предложением")
    ap.add_argument("--srt", help="файл .srt или .txt сценария (тема берётся отсюда)")
    a = ap.parse_args()

    if a.zadanie:
        папка = os.path.dirname(os.path.abspath(a.zadanie)) or "."
        листы = sorted(
            [os.path.join(папка, f) for f in os.listdir(папка)
             if f.startswith("final_sheet") and f.endswith(".jpg")])
        print("ЗАДАНИЕ СВЕЖЕМУ СУБАГЕНТУ (своему, который вёл ролик, НЕЛЬЗЯ):")
        print()
        if листы:
            for l in листы:
                print(f"  лист: {l}")
        else:
            print(f"  листа нет — сделать: python3 final_sheet.py {a.zadanie}")
        print()
        print("  Текст задания:")
        print("  «Посмотри этот контактный лист. Это кадры одного новостного")
        print("   ролика по порядку. Больше ты о нём ничего не знаешь — ни темы,")
        print("   ни текста. Скажи ОДНИМ предложением: о чём этот ролик? Кто")
        print("   главное действующее лицо и что произошло? Если понять нельзя —")
        print("   так и напиши. Ничего не угадывай и не додумывай.»")
        print()
        print("  Ответ вернуть сюда:")
        print(f"  python3 o_chem.py --sverka \"<его ответ>\" --srt <файл.srt>")
        return 0

    if a.sverka:
        if not a.srt or not os.path.exists(a.srt):
            print("нужен --srt с текстом ролика: тема берётся из него")
            return 2
        ключи = тема_из(a.srt)
        попало = совпало(a.sverka, ключи)
        имена = [k for k in ключи[:6]]
        попало_имена = [k for k in имена if k[:5] in a.sverka.lower()]
        print(f"  тема по тексту : {', '.join(ключи[:8])}")
        print(f"  узнал          : {', '.join(попало) if попало else '—'}")
        print()
        if len(попало_имена) >= 2:
            print("СОВПАЛО — видеоряд читается сам, можно сдавать.")
            return 0
        if попало:
            print("БЛИЗКО — тему узнал, но главное лицо или событие из кадров")
            print("не читается. Посмотреть, чем закрыты ключевые сцены: там, где")
            print("звучит имя и событие, в кадре должно быть видно именно это.")
            return 0
        print("МИМО — видеоряд рассказывает НЕ ТО, о чём текст.")
        print("Чинить надо это, а не отдельные кадры: пройти по сценам, где")
        print("названы главное лицо и событие, и закрыть их по существу.")
        return 1

    ap.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
