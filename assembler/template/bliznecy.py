def файлы():
    for подпапка in ГДЕ:
        корень = os.path.join(КОРЕНЬ, подпапка)
        for путь, _, имена in os.walk(корень):
            if any(п in путь for п in ПРОПУСК):
                continue
            for и in имена:
                if not и.endswith((".py", ".sh")):
                    continue
                п = os.path.join(путь, и)
                if any(x in п for x in ПРОПУСК):
                    continue
                yield п


def искать(шаблон, кроме=()):
    рг = re.compile(шаблон, re.M)
    найдено = []
    for ф in файлы():
        if os.path.abspath(ф) in кроме:
            continue
        try:
            текст = io.open(ф, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        for м in рг.finditer(текст):
            строка = текст[:м.start()].count("\n") + 1
            найдено.append((os.path.relpath(ф, КОРЕНЬ), строка,
                            текст.splitlines()[строка - 1].strip()[:90]))
    return найдено


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("fayly", nargs="*", help="файлы, которые правишь")
    ap.add_argument("--obrazec", default="", help="искать свой кусок кода")
    a = ap.parse_args()

    свои = {os.path.abspath(ф) for ф in a.fayly}
    всего = 0

    if a.obrazec:
        п = искать(re.escape(a.obrazec), кроме=свои)
        if п:
            print("ЭТОТ ЖЕ КУСОК ЛЕЖИТ ЕЩЁ ТУТ:")
            for ф, с, т in п[:20]:
                print("  %s:%d  %s" % (ф, с, т))
            всего += len(п)
        else:
            print("такого куска больше нигде нет")

    for шаблон, почему in ПРИЁМЫ:
        п = искать(шаблон, кроме=свои)
        if not п:
            continue
        print("")
        print("ПРИЁМ-БЛИЗНЕЦ: %s" % почему)
        for ф, с, т in п[:12]:
            print("  %s:%d  %s" % (ф, с, т))
        if len(п) > 12:
            print("  … ещё %d мест" % (len(п) - 12))
        всего += len(п)

    print("")
    if всего:
        print("НАЙДЕНО МЕСТ: %d — поправь их ТЕМ ЖЕ заходом, иначе завтра "
              "они выстрелят как новый баг." % всего)
        return 1
    print("близнецов нет")
    return 0


if __name__ == "__main__":
    sys.exit(main())
