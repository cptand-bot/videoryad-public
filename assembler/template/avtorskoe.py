#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""БАЗА АВТОРСКИХ ЗАМЕЧАНИЙ — ЕГО МЫСЛИ ПОВЕРХ ГОТОВОГО ТЕКСТА (08.11.2026).

Его слово: «мы написали статью, сделали ролик, я его прослушал — и вот
некоторые детали, которые я упустил или упустила нейронка. Если я вношу
какую-то свою мысль… это нужно записывать в базу. Для чего? Для накопления
авторского опыта и авторского стиля. И эту базу нужно расширять и на тебя, и
на чат GPT, чтобы в следующий раз это не проскакивало. Может, будут неважные
замечания, а может, фатальные ошибки. В идеале — сбросив тему, вы начали
писать всё сами, полный цикл: я даю тему, даю угол, а вы фигачите по
накопленной базе».

ЧТО КОПИМ. Не правки текста, а АВТОРСКУЮ МЫСЛЬ: чего в тексте не хватило,
какой вывод он добавил бы сам, что прозвучало не так. Пример из его же
объяснения: в тексте сказано «Пашинян заявил, что выйдем из ОДКБ», а он
добавляет комментарий, которого в статье не было, — вот этот комментарий и
есть материал.

    python3 avtorskoe.py --канал "5 МИНУТ" --тема "1-Расплата" \\
        --тип упущение --цитата "Пашинян заявил о выходе из ОДКБ" \\
        --мысль "Надо было сказать, чем он за это заплатит: газ по рыночной цене
                 и очередь к европейской двери длиной в сорок лет"
    python3 avtorskoe.py --список            # всё, что накоплено
    python3 avtorskoe.py --для-задания       # блок, который уходит писателю

ТИПЫ: упущение · уточнение · ошибка · стиль · угол · запрет.
ВАЖНОСТЬ: обычное · важное · фатальное (фатальные идут в задание всегда).

База лежит в `upakovka_lib/avtorskoe.jsonl` и подкладывается в задание
писателю (`rewrite_brief.py`) и в упаковку. Копится общим котлом по всем
каналам: стиль у автора один, каналы различаются подачей, а не головой.
"""

import argparse
import io
import json
import os
import sys
import time

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БАЗА = os.path.join(ЗДЕСЬ, "upakovka_lib", "avtorskoe.jsonl")
ТИПЫ = ("упущение", "уточнение", "ошибка", "стиль", "угол", "запрет")
ВАЖНОСТЬ = ("обычное", "важное", "фатальное")


def читать():
    if not os.path.exists(БАЗА):
        return []
    out = []
    for line in io.open(БАЗА, encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        try:
            out.append(json.loads(line))
        except ValueError:
            continue
    return out


def для_темы(тема):
    """Замечания, сказанные по КОНКРЕТНОЙ теме при прослушивании оригинала.

    Его слово 08.11: «я буду прослушивать только ролики на „5 минут“ и
    „Планету“, остальные рерайты уже не буду — это одно и то же, трата
    времени. Но если в процессе прослушки будут замечания или дополнения,
    которые можно потом перенести и вставить ТОЧЕЧНО в статью — чтобы можно
    было применять и для рерайта этих материалов на другие каналы, на
    масштабируемые».

    То есть мысль, сказанная один раз по оригиналу, обязана доехать до ВСЕХ
    клонов этой темы: он их уже слушать не будет.
    """
    если = (тема or "").strip().lower()
    if не_тема(если):
        return []
    out = []
    for z in читать():
        т = (z.get("тема") or "").strip().lower()
        if не_тема(т):
            continue
        if т == если or т in если or если in т:
            out.append(z)
    return out


def не_тема(x):
    return not x or len(x) < 3


def для_задания(n=20, канал=""):
    """Блок для задания писателю: сначала фатальное, потом важное.

    Канал НЕ фильтруем жёстко: авторский стиль один на все каналы, различается
    подача. Если запись помечена каналом, это видно в строке.
    """
    записи = читать()
    if not записи:
        return ""
    вес = {"фатальное": 0, "важное": 1, "обычное": 2}
    записи.sort(key=lambda z: (вес.get(z.get("важность"), 2), z.get("когда", "")))
    строки = []
    for z in записи[:n]:
        метка = z.get("тип", "замечание")
        если_канал = (" [%s]" % z["канал"]) if z.get("канал") else ""
        цитата = (" · было в тексте: «%s»" % z["цитата"]) if z.get("цитата") else ""
        строки.append("· (%s%s) %s%s" % (метка, если_канал, z.get("мысль", ""), цитата))
    return ("АВТОРСКИЕ ЗАМЕЧАНИЯ ПО ПРОШЛЫМ РОЛИКАМ — ЭТО ЕГО СОБСТВЕННЫЕ\n"
            "МЫСЛИ, ДОБАВЛЕННЫЕ ПОСЛЕ ПРОСЛУШИВАНИЯ. Повторять эти упущения\n"
            "нельзя, а манеру думать — перенимать:\n" + "\n".join(строки))


def main():
    ap = argparse.ArgumentParser(description="база авторских замечаний и стиля")
    ap.add_argument("--канал", default="")
    ap.add_argument("--тема", default="")
    ap.add_argument("--тип", default="упущение", choices=ТИПЫ)
    ap.add_argument("--важность", default="важное", choices=ВАЖНОСТЬ)
    ap.add_argument("--цитата", default="", help="что было в тексте (не обязательно)")
    ap.add_argument("--мысль", default="", help="что он добавил своими словами")
    ap.add_argument("--список", action="store_true", dest="show")
    ap.add_argument("--для-задания", action="store_true", dest="task")
    a = ap.parse_args()

    if a.task:
        блок = для_задания(канал=a.канал)
        print(блок or "(база авторских замечаний пока пуста)")
        return 0

    if a.show or not a.мысль:
        записи = читать()
        if not записи:
            print("база пуста: авторских замечаний ещё не записано")
            return 0
        print("записей: %d" % len(записи))
        for z in записи:
            print("· %s · %s%s · %s"
                  % (z.get("когда", "")[:10], z.get("тип", ""),
                     (" · " + z["важность"]) if z.get("важность") else "",
                     (z.get("канал") or "все каналы")))
            if z.get("цитата"):
                print("   было: «%s»" % z["цитата"][:140])
            print("   мысль: %s" % (z.get("мысль") or "")[:300])
        return 0

    запись = {"когда": time.strftime("%Y-%m-%d %H:%M:%S"), "канал": a.канал,
              "тема": a.тема, "тип": a.тип, "важность": a.важность,
              "цитата": a.цитата, "мысль": " ".join(a.мысль.split())}
    os.makedirs(os.path.dirname(БАЗА), exist_ok=True)
    with io.open(БАЗА, "a", encoding="utf-8") as f:
        f.write(json.dumps(запись, ensure_ascii=False) + "\n")
    print("записано в базу авторских замечаний: %s / %s" % (a.тип, a.важность))
    print("пойдёт в задание писателю при следующем рерайте и в упаковку")
    return 0


if __name__ == "__main__":
    sys.exit(main())
