#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ТЕМА СТАРТУЕТ ЦЕЛИКОМ И СРАЗУ — ВСЁ ПАРАЛЛЕЛЬНО (08.11.2026).

Его слово, сказанное трижды за день: «разумеется, рерайт начинать сразу по
тексту, не дожидаясь готового ролика. Зачем нам готовый ролик? У нас же всё
было готово, текст есть, SRT есть» и следом: «делать сразу и превьюшки, и
описания, и варианты заголовков, и варианты надписей на превью. Всё это можно
делать сразу же, немедленно».

ПОЧЕМУ РАНЬШЕ БЫЛО НЕ ТАК. Мы держали правило «внешний агент на машине ОДИН,
два задания разом не идут» — оно пришло из наблюдения 07.11 и 08.11 НЕ
подтвердилось: три задания, запущенные одновременно, вернули три своих ответа
за десять секунд. Похоже, прежний случай объяснялся не агентом, а обёрткой:
ответ кладётся рядом с брифом, и два задания по ОДНОМУ файлу затирали друг
друга. Теперь одинаковый бриф идёт по очереди, разные — параллельно
(`CODEX_PARALLEL`, по умолчанию три).

ЧТО ЗАПУСКАЕТ ЭТОТ ИНСТРУМЕНТ, получив папку темы и ключ георадара:
  1. задание на РЕРАЙТ второго канала и сам рерайт у агента;
  2. УПАКОВКУ: описание, десять заголовков, десять надписей, паттерн;
  3. ПЯТЬ ПРЕВЬЮ.
Всё тремя параллельными процессами, не дожидаясь ни раскадровки, ни фетча, ни
готового ролика первого канала. Раскадровку в это же время ведёт вкладка
канала — она четвёртая параллельная ветка.

    python3 tema_start.py "<папка темы>" --key ARM_… --channel-2 "ПЛАНЕТА"
    python3 tema_start.py "<папка темы>" --key ARM_… --only upakovka,prevyu

Печатает, что запущено и куда писать логи. Ничего не ждёт: процессы живут
сами, результат проверяется файлами в папке темы.
"""

import argparse
# СЛУЖЕБНОЕ ИМЯ — ОДНА ПРОВЕРКА НА ВЕСЬ СБОРЩИК (15.11, см. sluzhebnye.py):
# слово узнаётся по разделителю, а не по вхождению, иначе тема со словом
# «ответ»/«статья»/«список» в заголовке теряет свой единственный текст.
import importlib.util as _ilu, os as _os
_sp = _ilu.spec_from_file_location(
    "sluzhebnye", _os.path.join(_os.path.dirname(_os.path.abspath(__file__)),
                                "sluzhebnye.py"))
_sl = _ilu.module_from_spec(_sp); _sp.loader.exec_module(_sl)
sluzhebnoe = _sl.sluzhebnoe

import re
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ЛОГИ = "/tmp/videoryad-tema"


def канал_из_пути(path):
    части = os.path.abspath(path).replace("\\", "/").upper().split("/")
    for ч in части:
        for имя in ("5 МИНУТ", "ПЛАНЕТА", "ОЛЬКА НОВОСТИ", "ОЛЬКА",
                    "ДИПЛОМАТИЯ СИЛЫ", "ПЕРЕВОД С ДИПЛОМАТИЧЕСКОГО"):
            if ч == имя or ч.startswith(имя + " "):
                return имя
    return ""


def запустить(имя, argv, лог):
    """Пускаем в фоне и возвращаем pid. Ничего не ждём."""
    os.makedirs(ЛОГИ, exist_ok=True)
    f = open(лог, "w")
    p = subprocess.Popen(argv, stdout=f, stderr=subprocess.STDOUT,
                         stdin=subprocess.DEVNULL, start_new_session=True)
    print("  ✓ %-10s pid %-7d лог: %s" % (имя, p.pid, лог))
    return p.pid


def main():
    ap = argparse.ArgumentParser(description="запустить тему целиком и параллельно")
    ap.add_argument("folder")
    ap.add_argument("--key", required=True, help="ключ георадара (ARM_… / PROD_…)")
    ap.add_argument("--channel-2", default="ПЛАНЕТА", dest="ch2",
                    help="канал, на который делается вторая статья")
    ap.add_argument("--only", default="", help="через запятую: rewrite,upakovka,prevyu")
    a = ap.parse_args()

    if not os.path.isdir(a.folder):
        sys.exit("нет папки: %s" % a.folder)
    ch1 = канал_из_пути(a.folder)
    # СПИСОК СЛУЖЕБНЫХ ИМЁН — ОДИН И ТОТ ЖЕ ВЕЗДЕ (11.11). Здесь не хватало
    # «БРИФ», «СТАТЬЯ», «ДОСЬЕ», «АУДИТ», и строка вывода называла оригиналом
    # `БРИФ-ДЛЯ-CODEX.txt` (он на 64 байта больше текста темы). Само задание
    # `rewrite_brief.py` брал верно — свой список у него полный, — но по
    # выводу это читалось как заказанный рерайт брифа, и по ЭТОМУ ЖЕ списку
    # `razlozhit_rerayt.py` считает имя файла второй статьи.
    тексты = sorted(
        (f for f in os.listdir(a.folder)
         if f.lower().endswith(".txt")
         and not sluzhebnoe(f, ("ЗАДАНИЕ", "УПАКОВКА", "ОТВЕТ", "ГЕОРАДАР",
                                "РЕРАЙТ", "БРИФ", "ПРОМПТ", "ДОСЬЕ", "АУДИТ",
                                "СТАТЬЯ", "СОСТОЯНИЕ", "ССЫЛКИ",
                                "ДЛЯ-ВКЛАДКИ", "СПИСОК"))),
        key=lambda f: os.path.getsize(os.path.join(a.folder, f)), reverse=True)
    if not тексты:
        sys.exit("в папке нет текста озвучки — запускать нечего")

    провал = False
    # ВТОРУЮ СТАТЬЮ ОТСЮДА БОЛЬШЕ НЕ ЗАКАЗЫВАЕМ (14.11, улов `usuario-48` на
    # первой теме дня). Его правило 13.11 прямое: «вторую статью на свой
    # канал заказывает САМА ВКЛАДКА ЭТОГО КАНАЛА… а пишет чат GPT» — и это
    # отменило порядок 12.11. В коде `tema_start` отмена не доехала, поэтому
    # 14.11 статью на ПЛАНЕТУ заказали ДВАЖДЫ: вкладка 5 МИНУТ (ответ лёг в
    # 10:20) и вкладка ПЛАНЕТЫ (в 10:21 ПЕРЕЗАПИСАЛА тот же
    # `ЗАДАНИЕ-РЕРАЙТ.ОТВЕТ.txt` своим ответом). Чужой ответ потерян, папка
    # второго канала осталась пустой — `razlozhit_rerayt` умер на копировании,
    # один заход агента выброшен впустую. Два аккаунта агента на одну статью
    # — это не параллельность, а гонка за один файл.
    # Теперь `rewrite` идёт ТОЛЬКО по явному `--only rewrite,…`: вкладке
    # второго канала он нужен как инструмент, автоматом с первого канала —
    # нет.
    шаги = [s.strip() for s in (a.only or "upakovka,prevyu").split(",") if s.strip()]
    if not a.only:
        print("  вторую статью НЕ заказываю: её заказывает вкладка канала %s "
              "сама (правило 13.11)" % a.ch2)
    метка = time.strftime("%H%M%S")
    база = os.path.basename(os.path.abspath(a.folder))[:28]
    os.makedirs(ЛОГИ, exist_ok=True)

    print("ТЕМА: %s" % база)
    print("  канал-источник: %s → второй канал: %s" % (ch1 or "не определён", a.ch2))
    print("  текст: %s" % тексты[0])
    print("ЗАПУСКАЮ ПАРАЛЛЕЛЬНО (ничего не жду):")

    if "rewrite" in шаги:
        # бриф пишется синхронно (секунды), агент — в фоне
        subprocess.run([sys.executable, os.path.join(HERE, "rewrite_brief.py"),
                        a.folder, "--key", a.key, "--channel", a.ch2],
                       check=False)
        задание = os.path.join(a.folder, "ЗАДАНИЕ-РЕРАЙТ.txt")
        if os.path.isfile(задание):
            запустить("рерайт", ["bash", os.path.join(HERE, "codex_ask.sh"), задание],
                      os.path.join(ЛОГИ, "rewrite-%s-%s.log" % (база, метка)))
            # ГОТОВЫЙ ТЕКСТ САМ ЛОЖИТСЯ В ПАПКУ ВТОРОГО КАНАЛА (11.11,
            # блокер `НА-РАСКАТКУ` п.2). Раньше этого шага в коде не было
            # вовсе — он стоял в ПОРЯДКЕ-ДНЯ как ручной, и вкладка второго
            # канала стояла, пока кто-то не разложит ответ руками (час
            # простоя на каждой теме). Ждёт ответ в своём процессе, нам
            # ждать нечего.
            запустить("раскладка 2-го канала",
                      [sys.executable, os.path.join(HERE, "razlozhit_rerayt.py"),
                       a.folder, "--channel-2", a.ch2],
                      os.path.join(ЛОГИ, "razlozhit-%s-%s.log" % (база, метка)))
        else:
            # МОЛЧАЛИВОГО ПРОВАЛА БОЛЬШЕ НЕТ (правка 10.11): раньше здесь
            # печаталась строка в лог фазы и код возврата оставался НУЛЕВЫМ —
            # вкладка рапортовала «вторая статья запущена в фоне», а статьи не
            # было. Теперь шаг признаётся провалившимся, и `faza.sh` говорит
            # «[СМОТРИ] вторая статья не запустилась» прямо в переписку.
            print("  !! ЗАДАНИЯ НА РЕРАЙТ НЕТ — вторая статья НЕ заказана, "
                  "см. вывод rewrite_brief.py выше")
            провал = True

    # ОЧЕРЁДНОСТЬ У ВНЕШНЕГО АГЕНТА ДЕРЖИТ КОД, А НЕ ТЕКСТ (15.11, его
    # прямой вопрос: «каким образом упаковка и превью уже готовы, почему они
    # пошли в первостепенные задачи, а не в конце»). Его правило 13.11:
    # сперва ВСЕ раскадровки дня, упаковка и превью потом. Здесь же обе
    # ветки уходили в тот же миг, что и тема, и на первой теме 15.11
    # оказались готовы в 09:34-09:41 — раньше раскадровок. Вторая статья
    # этим не ограничена: без неё второй канал стоит целиком.
    # Снять ограничение на один запуск: VIDEORYAD_UPAKOVKA_SRAZU=1.
    # УПАКОВКА — В САМОМ КОНЦЕ ДНЯ (15.11, его прямое слово, зло: «Упаковка
    # должна делаться в самом конце, когда уже сделаны ВСЕ дашборды. Когда
    # уже не надо работать чата GPT ни на одном из аккаунтов. Вот тогда надо
    # делать упаковку и заказывать картинки, а не тормозить процесс
    # дашборда»). Ролик ждёт агента на раскадровке и ключах карточек, и
    # каждая минута, которую агент тратит на описания и превью, — это
    # минута простоя дашборда. Поэтому ветка не уходит, пока ХОТЯ БЫ ОДИН
    # ролик дня не дошёл до дашборда: признак — `overlays.json` в папке
    # проекта (его пишет `build_overlays` перед сборкой страницы).
    # Снять на один запуск: VIDEORYAD_UPAKOVKA_SRAZU=1.
    # ЯВНЫЙ ВЫЗОВ НЕ ОТКЛАДЫВАЕТСЯ (15.11, улов `usuario-55`): отложенный
    # режим писался против АВТОЗАПУСКА из `start`, который тормозил дашборд.
    # Когда упаковку зовут руками ключом `--only upakovka`, значит время
    # пришло — откладывать нечего, и вкладка теряла заход, послушавшись
    # обычной строки вывода.
    _yavno = bool(a.only)
    _srazu = os.environ.get("VIDEORYAD_UPAKOVKA_SRAZU") == "1" or _yavno
    _ne_gotovy = []
    if not _srazu:
        _den = os.path.dirname(os.path.abspath(a.folder.rstrip("/")))
        _proekty = os.path.join(os.path.expanduser("~"), "projects")
        for _t in (sorted(os.listdir(_den)) if os.path.isdir(_den) else []):
            _p = os.path.join(_den, _t)
            if not os.path.isdir(_p) or _t.startswith("_"):
                continue
            if not any(f.lower().endswith(".txt") and not sluzhebnoe(f)
                       for f in os.listdir(_p)):
                continue          # текста ещё нет — тема не в работе
            # ищем проект этой темы среди рабочих папок
            _slova = [w.lower() for w in re.findall(r"[A-Za-zА-Яа-яЁё]{4,}", _t)]
            _dash = False
            for _pr in (os.listdir(_proekty) if os.path.isdir(_proekty) else []):
                _prp = os.path.join(_proekty, _pr)
                if not os.path.isdir(_prp):
                    continue
                if _slova and not any(w[:5] in _pr.lower() for w in _slova):
                    continue
                if os.path.exists(os.path.join(_prp, "overlays.json")):
                    _dash = True
                    break
            if not _dash:
                _ne_gotovy.append(_t)

    if _ne_gotovy and not _srazu:
        print("")
        print("УПАКОВКА И ПРЕВЬЮ ОТЛОЖЕНЫ ДО КОНЦА ДНЯ — его прямое слово "
              "15.11: пока агент нужен видеоряду, он не рисует картинки.")
        print("  Дашборда ещё нет у тем: %s" % ", ".join(_ne_gotovy[:6]))
        print("  Когда ВСЕ дашборды дня собраны, закажи одной командой:")
        print("    python3 %s \"%s\" --only upakovka,prevyu"
              % (os.path.join(HERE, "tema_start.py"), a.folder))
        print("  Нужно прямо сейчас — VIDEORYAD_UPAKOVKA_SRAZU=1.")
    else:
        if "upakovka" in шаги:
            запустить("упаковка", [sys.executable, os.path.join(HERE, "upakovka.py"), a.folder],
                      os.path.join(ЛОГИ, "upakovka-%s-%s.log" % (база, метка)))

        if "prevyu" in шаги:
            запустить("превью", [sys.executable, os.path.join(HERE, "prevyu.py"), a.folder],
                      os.path.join(ЛОГИ, "prevyu-%s-%s.log" % (база, метка)))

    print("")
    if провал:
        print("")
        print("!! ОДНА ИЗ ВЕТОК НЕ ЗАПУСТИЛАСЬ — см. строки с «!!» выше.")
    print("Раскадровку первого канала вкладка ведёт ПАРАЛЛЕЛЬНО этим трём —")
    print("ждать их не нужно, они живут в своих процессах.")
    print("Проверка результата по файлам в папке темы:")
    print("  ЗАДАНИЕ-РЕРАЙТ.ОТВЕТ.txt · УПАКОВКА.json · превью-варианты/ПРЕВЬЮ-*.png")
    return 3 if провал else 0


if __name__ == "__main__":
    sys.exit(main())
