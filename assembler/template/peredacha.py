def main():
    ap = argparse.ArgumentParser(description="собрать передачу смены машиной")
    ap.add_argument("--ot", default=os.environ.get("VIDEORYAD_KTO", "вкладка"))
    ap.add_argument("--slovami", default="", help="две-три строки от себя")
    ap.add_argument("--zapisat", action="store_true",
                    help="записать в ПЕРЕДАЧА-СМЕНЫ-<дата>.md и в состояние")
    ap.add_argument("--bez-proverki", action="store_true", dest="bez",
                    help="записать, НЕ проверяя (только когда так решил ОН)")
    a = ap.parse_args()
    # П.218 (18.11.2026): ПЕРВЫЙ ВЫЗОВ ДНЯ САМОРЕФЕРЕНСНО ПАДАЛ — проверка
    # ниже требует, чтобы файл ПЕРЕДАЧА-*<день>*.md УЖЕ существовал и был
    # тронут сегодня, а создаёт его как раз сам этот вызов при успехе,
    # ДО которого проверка и идёт. Кладём пустую заглушку заранее: если
    # остальные дыры закрыты, она тут же перезапишется настоящим текстом;
    # если нет — останется безобидной пустышкой до следующей попытки.
    if a.zapisat:
        _имя_сегодня = os.path.join(СКИЛЛ, "ПЕРЕДАЧА-СМЕНЫ-%s.md"
                                     % datetime.datetime.now().strftime("%d-%m"))
        if not os.path.isfile(_имя_сегодня):
            io.open(_имя_сегодня, "w", encoding="utf-8").write("")
    # ПРОВЕРКА «ВСЁ ДО НИТОЧКИ» ГОНЯЕТСЯ САМА НА КАЖДОЙ СДАЧЕ (13.11.2026).
    # Его слово: «это надо делать постоянно, а не один раз. Если ты сдаёшь
    # смену, ты должен всё перепроверить. Всё до ниточки, всё до словечка, до
    # копеечки должен сдать». Повод: координатор объявил смену сданной и
    # сказал «перепроверил, сошлось всё» — а на его требование проверить ещё
    # раз нашлись ЧЕТЫРЕ дыры (итог дня, шапка улова, реестр вкладок и
    # невыполненный третий шаг его же приказа). «Перепроверил» означало
    # «сверил то, что сам написал». Поэтому сверяет КОД, а не память.
    if a.zapisat and not a.bez:
        try:
            import sdacha_proverka
            дыры, _ = sdacha_proverka.проверить(a.ot)
        except Exception as e:
            дыры = []
            print("проверка сдачи не отработала (%s) — сдавай глазами" % e)
        if дыры:
            print("=" * 66)
            print("СМЕНА НЕ СДАНА: дыр %d. Передача НЕ записана." % len(дыры))
            for x in дыры:
                print("  ✗ %s" % x)
            print("\nЗакрой и повтори. Подробный отчёт: "
                  "python3 template/sdacha_proverka.py --kto <имя>")
            return 1
    текст = собрать(a.ot, a.slovami)
    print(текст)
    if not a.zapisat:
        return 0
    имя = os.path.join(СКИЛЛ, "ПЕРЕДАЧА-СМЕНЫ-%s.md"
                       % datetime.datetime.now().strftime("%d-%m"))
    # РУЧНЫЕ РАЗДЕЛЫ «ОТ СЕБЯ» ПЕРЕНОСИМ В НОВЫЙ ФАЙЛ (16.11).
    # Пересборка затирала файл целиком, и всё, что координатор написал
    # руками — разбор смены, решения пользователя, опасное, — исчезало без
    # предупреждения. За одну смену это случилось ДВАЖДЫ: сначала на моём же
    # вызове, потом когда файл пересобрала закрывающаяся вкладка. Его слово
    # 16.11: «чтобы ничего не потерялось». Теперь блоки «## ОТ СЕБЯ — …»
    # (и «## ИТОГ …») из прежнего файла дописываются в конец нового, а не
    # пропадают: машинная сводка сверху всегда свежая, рассказ смены цел.
    _ручное = []
    if os.path.isfile(имя):
        _старое = _ч(имя)
        _блоки = re.split(r"(?m)^(?=## (?:ОТ СЕБЯ|ИТОГ))", _старое)
        for _b in _блоки:
            if _b.startswith("## ОТ СЕБЯ") or _b.startswith("## ИТОГ"):
                # обрезаем по следующему машинному разделу
                _b = re.split(r"(?m)^## (?:ТЕМЫ В РАБОТЕ|ЗАМКИ ТРУБ|ПАПКИ ДНЯ|"
                              r"ЖУРНАЛ ПРАВОК|ХВОСТЫ|ЧИТАТЬ ДАЛЬШЕ)", _b)[0]
                if _b.strip() and _b.strip() not in (x.strip() for x in _ручное):
                    _ручное.append(_b.rstrip() + "\n")
    if _ручное:
        текст = текст.rstrip() + "\n\n" + "\n".join(_ручное)
    io.open(имя, "w", encoding="utf-8").write(текст)
    print("\nзаписано: %s%s" % (имя,
          (" (ручных разделов перенесено: %d)" % len(_ручное)) if _ручное else ""))
    # ручная часть файла состояния — та же сводка, коротким хвостом
    s = _ч(СОСТОЯНИЕ)
    i = s.find("СОСТОЯНИЕ НОВОСТНОГО СБОРЩИКА")
    голова = s[:i] if i >= 0 else (s + "\n")
    шапка = ("СОСТОЯНИЕ НОВОСТНОГО СБОРЩИКА — %s (%s)\n"
             "(ручная часть собрана peredacha.py; авто-блок выше сам)\n\n"
             % (datetime.datetime.now().strftime("%d.%m.%Y %H:%M"), a.ot))
    # БЛОК «ОТ СЕБЯ» ТОЖЕ ИДЁТ В СОСТОЯНИЕ (15.11, вечер). Раньше хвост резался
    # от «## ТЕМЫ В РАБОТЕ», то есть всё, что смена написала СЛОВАМИ — что
    # пришло, что разбирать, что погашено и куда убрано, — в файл, объявленный
    # входом новой смены, не попадало вовсе: оно оставалось только в
    # ПЕРЕДАЧА-СМЕНЫ-<дата>.md, а `smena.sh` этот файл не читает (пункт [8б]
    # печатает именно ручную часть состояния). Его слово 15.11: «запиши
    # сначала всё, завтра начнём со смены, чтобы она знала, откуда, где
    # разбирать, что пришло, что ушло, что удалил».
    рез = "## ОТ СЕБЯ" if "## ОТ СЕБЯ" in текст else "## ТЕМЫ В РАБОТЕ"
    io.open(СОСТОЯНИЕ, "w", encoding="utf-8").write(
        голова + шапка + рез + текст.split(рез, 1)[-1])
    print("ручная часть состояния обновлена: %s" % СОСТОЯНИЕ)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
