         # скиллы. Я об этом говорил, оно опять где-то потерялось, блин, на
         # вашей гребаной передаче вкладки»). Держится кодом по той же
         # причине, что и первое: текст теряли при смене вкладок.
         "## СУБАГЕНТЫ ЗОВУТСЯ ПО ИМЕНИ — ОНИ НА ДЕШЁВЫХ МОДЕЛЯХ",
         "",
         "Безымянный субагент наследует модель вкладки, то есть механика идёт",
         "по цене самой дорогой модели. Четыре готовых агента, зови ИМЕНЕМ",
         "в `subagent_type`:",
         "",
         "| имя | модель | что отдаём |",
         "|---|---|---|",
         "| `listy` | Haiku | контактные листы: номера сцен с браком |",
         "| `mehanika` | Haiku | найти, промерить, скопировать, посчитать, опрос прогона |",
         "| `kadry` | Sonnet | осмотр кадров: тот ли человек, надпись, субтитры, повтор |",
         "| `hozyaystvo` | Sonnet | стейджинг, база кадров, георадар-копии, сверка целей, диски |",
         "",
         "Описания — `~/.claude/agents/*.md`, правит их только координатор.",
         "Вспомогательные вкладки (упаковка и превью, добор базы, вечерний",
         "разбор, уборка, раскатка) ведутся на Sonnet. На сильной модели",
         "остаются координатор и смысловые шаги ролика: запросы, наполнение",
         "карточек, разбор его замечаний.",
         "",
         "## ЖЕЛЕЗНОЕ ПРАВИЛО СМЕНЫ — ПРАВИМ ТОЛЬКО КРИТИЧЕСКОЕ",
         "",
         "Его слово 16.11: «мы только критическое можем править, а весь этот",
         "мусор держим в конце, всё, что накопилось. И в конце будем делать",
         "правки» и «ничего не менять — это потом, когда всё соберём».",
         "",
         "- **КРИТИЧЕСКОЕ** = без этого ролик физически не собирается или не",
         "  сдаётся: блокер прогона, отказ двери, упавшая сборка. Только это",
