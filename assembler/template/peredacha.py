         "- **ВСЁ ОСТАЛЬНОЕ — МУСОР ПО ЕГО СЛОВУ** и ждёт конца дня: кривая",
         "  карточка, повтор фразы, не тот человек, выдуманная координата,",
         "  слабый кадр. Оно уедет в ролике и будет исправлено ОДНИМ заходом",
         "  после сдачи ВСЕХ роликов дня, с ОДНОЙ раскаткой, И ТОЛЬКО ПО ЕГО",
